//! Swift 5.9+ target emitter for NVE Hybrid FFI codegen.
//!
//! Emits `<Stem>HybridSpec.generated.swift` targeting direct C interop with `<Stem>HybridAbi.generated.h`:
//! - Zero `@objc`, zero `NSObject`, zero `objc_msgSend`, zero JSON
//! - Native Swift `enum`, `struct`, `public protocol Hybrid<Name>Spec`
//! - `public final class <Name>HybridClient` invoking C vtable function pointers directly
//!   using zero-copy `UnsafeBufferPointer` / `NveStrSlice` / `NveBufferSlice` / `NveValue`
//!   and releasing owned buffers via `vtable.pointee.free_bytes`.

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::hybrid::ir::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::ir::GeneratedFile;
use crate::naming::{
    c_field_ident, escape_c_like_string, format_float_literal, swift_ident, to_camel_case,
    to_pascal_case,
};

/// Emits `<Stem>HybridSpec.generated.swift` targeting direct C interop with `<Stem>HybridAbi.generated.h`.
pub fn generate_hybrid_swift(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_pascal();
    let mut out = String::with_capacity(16 * 1024);

    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Swift 5.9+ direct C-interop target) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(
        out,
        "// Direct C-ABI interop against `{stem}HybridAbi.generated.h`: zero Objective-C runtime bridging, zero JSON."
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#if canImport(NveSwiftUI)").unwrap();
    writeln!(out, "import NveSwiftUI").unwrap();
    writeln!(out, "#endif").unwrap();
    writeln!(out).unwrap();

    emit_swift_common(&mut out, spec);

    for e in &spec.enums {
        emit_swift_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_swift_struct(&mut out, s, spec);
    }

    for m in &spec.modules {
        emit_swift_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_swift_view(&mut out, v, spec);
    }

    out.push_str(swift_optional_unwrap_extension());

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}HybridSpec.generated.swift"),
        content: out,
    }])
}

fn emit_swift_common(out: &mut String, spec: &HybridFileSpec) {
    writeln!(
        out,
        "public let nveHybridAbiVersion: UInt32 = {NVE_HYBRID_ABI_VERSION}"
    )
    .unwrap();
    writeln!(
        out,
        "public let nveHybridFileSchemaHash: UInt64 = 0x{:016X}",
        spec.file_schema_hash()
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        r#"public enum NveHybridError: Error, Equatable {{
    case nullInterfaceResolver
    case interfaceNotFound(UInt32)
    case schemaMismatch(expected: UInt64, actual: UInt64)
    case nullHandle
    case invalidUtf8
    case invalidEnum(String, UInt32)
    case truncatedBinary
    case remoteError(String)
}}

/// Owned dynamic value encoded in NVE's compact binary `NveBinValue` format (zero JSON).
public struct NveHybridDynamicValue: Equatable {{
    public var binBytes: [UInt8]

    public init(binBytes: [UInt8] = [0]) {{
        self.binBytes = binBytes
    }}
}}

/// Compact binary `NveBinValue` encoder matching `nve_abi::encode_bin_value` byte-for-byte.
public struct NveHybridBinWriter {{
    public private(set) var bytes: [UInt8] = []

    public init() {{}}

    public mutating func writeNull() {{
        bytes.append(0)
    }}

    public mutating func writeBool(_ value: Bool) {{
        bytes.append(1)
        bytes.append(value ? 1 : 0)
    }}

    public mutating func writeInt64(_ value: Int64) {{
        bytes.append(2)
        writeLe64(UInt64(bitPattern: value))
    }}

    public mutating func writeDouble(_ value: Double) {{
        bytes.append(3)
        writeLe64(value.bitPattern)
    }}

    public mutating func writeString(_ value: String) {{
        let utf8 = Array(value.utf8)
        bytes.append(4)
        writeLe32(UInt32(utf8.count))
        bytes.append(contentsOf: utf8)
    }}

    public mutating func writeBytes(_ value: [UInt8]) {{
        bytes.append(5)
        writeLe32(UInt32(value.count))
        bytes.append(contentsOf: value)
    }}

    public mutating func writeRaw(_ raw: [UInt8]) {{
        bytes.append(contentsOf: raw)
    }}

    public mutating func writeArray(count: Int, _ body: (inout NveHybridBinWriter) -> Void) {{
        bytes.append(6)
        let lenPos = bytes.count
        writeLe32(0)
        let start = bytes.count
        writeLe32(UInt32(count))
        body(&self)
        patchLe32(at: lenPos, UInt32(bytes.count - start))
    }}

    public mutating func writeMap(count: Int, _ body: (inout NveHybridBinWriter) -> Void) {{
        bytes.append(7)
        let lenPos = bytes.count
        writeLe32(0)
        let start = bytes.count
        writeLe32(UInt32(count))
        body(&self)
        patchLe32(at: lenPos, UInt32(bytes.count - start))
    }}

    public mutating func writeMapKey(_ key: String) {{
        let utf8 = Array(key.utf8)
        writeLe32(UInt32(utf8.count))
        bytes.append(contentsOf: utf8)
    }}

    private mutating func writeLe32(_ v: UInt32) {{
        bytes.append(UInt8(v & 0xFF))
        bytes.append(UInt8((v >> 8) & 0xFF))
        bytes.append(UInt8((v >> 16) & 0xFF))
        bytes.append(UInt8((v >> 24) & 0xFF))
    }}

    private mutating func patchLe32(at pos: Int, _ v: UInt32) {{
        bytes[pos] = UInt8(v & 0xFF)
        bytes[pos + 1] = UInt8((v >> 8) & 0xFF)
        bytes[pos + 2] = UInt8((v >> 16) & 0xFF)
        bytes[pos + 3] = UInt8((v >> 24) & 0xFF)
    }}

    private mutating func writeLe64(_ v: UInt64) {{
        for shift in stride(from: 0, to: 64, by: 8) {{
            bytes.append(UInt8((v >> shift) & 0xFF))
        }}
    }}
}}

/// Bounds-checked reader for compact binary `NveBinValue` payloads.
public struct NveHybridBinReader {{
    private let bytes: [UInt8]
    private var pos: Int = 0

    public init(bytes: [UInt8]) {{
        self.bytes = bytes
    }}

    public func peekTag() throws -> UInt8 {{
        guard pos < bytes.count else {{ throw NveHybridError.truncatedBinary }}
        return bytes[pos]
    }}

    public mutating func readNullIfPresent() throws -> Bool {{
        if try peekTag() == 0 {{
            pos += 1
            return true
        }}
        return false
    }}

    public mutating func readBool() throws -> Bool {{
        try expectTag(1)
        try require(1)
        let v = bytes[pos] != 0
        pos += 1
        return v
    }}

    public mutating func readInt64() throws -> Int64 {{
        try expectTag(2)
        return Int64(bitPattern: try readLe64())
    }}

    public mutating func readDouble() throws -> Double {{
        let tag = try peekTag()
        if tag == 3 {{
            pos += 1
            return Double(bitPattern: try readLe64())
        }}
        if tag == 2 {{
            return Double(try readInt64())
        }}
        throw NveHybridError.truncatedBinary
    }}

    public mutating func readString() throws -> String {{
        try expectTag(4)
        let len = Int(try readLe32())
        try require(len)
        let slice = bytes[pos ..< (pos + len)]
        pos += len
        return String(decoding: slice, as: UTF8.self)
    }}

    public mutating func readBytes() throws -> [UInt8] {{
        try expectTag(5)
        let len = Int(try readLe32())
        try require(len)
        let out = Array(bytes[pos ..< (pos + len)])
        pos += len
        return out
    }}

    public mutating func beginArray() throws -> Int {{
        try expectTag(6)
        let byteLen = Int(try readLe32())
        try require(byteLen)
        return Int(try readLe32())
    }}

    public mutating func beginMap() throws -> Int {{
        try expectTag(7)
        let byteLen = Int(try readLe32())
        try require(byteLen)
        return Int(try readLe32())
    }}

    public mutating func readMapKey() throws -> String {{
        let len = Int(try readLe32())
        try require(len)
        let slice = bytes[pos ..< (pos + len)]
        pos += len
        return String(decoding: slice, as: UTF8.self)
    }}

    public mutating func readRawValue() throws -> [UInt8] {{
        let start = pos
        try skipValue()
        return Array(bytes[start ..< pos])
    }}

    public mutating func skipValue() throws {{
        let tag = try peekTag()
        pos += 1
        switch tag {{
        case 0:
            return
        case 1:
            try require(1)
            pos += 1
        case 2, 3:
            try require(8)
            pos += 8
        case 4, 5, 6, 7:
            let len = Int(try readLe32())
            try require(len)
            pos += len
        default:
            throw NveHybridError.truncatedBinary
        }}
    }}

    private func require(_ n: Int) throws {{
        guard n >= 0, pos + n <= bytes.count else {{ throw NveHybridError.truncatedBinary }}
    }}

    private mutating func expectTag(_ expected: UInt8) throws {{
        guard try peekTag() == expected else {{ throw NveHybridError.truncatedBinary }}
        pos += 1
    }}

    private mutating func readLe32() throws -> UInt32 {{
        try require(4)
        let v = UInt32(bytes[pos])
            | (UInt32(bytes[pos + 1]) << 8)
            | (UInt32(bytes[pos + 2]) << 16)
            | (UInt32(bytes[pos + 3]) << 24)
        pos += 4
        return v
    }}

    private mutating func readLe64() throws -> UInt64 {{
        try require(8)
        var v: UInt64 = 0
        for i in 0 ..< 8 {{
            v |= UInt64(bytes[pos + i]) << (i * 8)
        }}
        pos += 8
        return v
    }}
}}
"#
    )
    .unwrap();
}

fn emit_swift_enum(out: &mut String, e: &HybridEnumSpec) {
    writeln!(out, "public enum {}: UInt32, Equatable, Hashable {{", e.name).unwrap();
    for v in &e.variants {
        let vname = swift_ident(&v.name);
        writeln!(out, "    case {vname} = {}", v.value).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_swift_struct(out: &mut String, s: &HybridStructSpec, spec: &HybridFileSpec) {
    writeln!(out, "public struct {}: Equatable {{", s.name).unwrap();
    for f in &s.fields {
        let fname = swift_ident(&f.name);
        writeln!(out, "    public var {fname}: {}", swift_type(&f.ty)).unwrap();
    }
    writeln!(out).unwrap();

    // Public memberwise init
    write!(out, "    public init(").unwrap();
    for (idx, f) in s.fields.iter().enumerate() {
        if idx > 0 {
            write!(out, ", ").unwrap();
        }
        let fname = swift_ident(&f.name);
        write!(
            out,
            "{fname}: {} = {}",
            swift_type(&f.ty),
            swift_default_value(&f.ty, None, spec)
        )
        .unwrap();
    }
    writeln!(out, ") {{").unwrap();
    for f in &s.fields {
        let fname = swift_ident(&f.name);
        writeln!(out, "        self.{fname} = {fname}").unwrap();
    }
    writeln!(out, "    }}").unwrap();

    if s.is_pod(spec) {
        writeln!(out).unwrap();
        writeln!(out, "    public func toAbi() -> NveHybrid{} {{", s.name).unwrap();
        write!(out, "        NveHybrid{}(", s.name).unwrap();
        for (idx, f) in s.fields.iter().enumerate() {
            if idx > 0 {
                write!(out, ", ").unwrap();
            }
            let cname = c_field_ident(&f.name);
            let fname = swift_ident(&f.name);
            match &f.ty {
                HybridType::Enum(_) => write!(out, "{cname}: {fname}.rawValue").unwrap(),
                HybridType::Struct(_) => write!(out, "{cname}: {fname}.toAbi()").unwrap(),
                _ => write!(out, "{cname}: {fname}").unwrap(),
            }
        }
        writeln!(out, ")").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();

        writeln!(
            out,
            "    public static func fromAbi(_ raw: NveHybrid{}) throws -> {} {{",
            s.name, s.name
        )
        .unwrap();
        write!(out, "        {}(", s.name).unwrap();
        for (idx, f) in s.fields.iter().enumerate() {
            if idx > 0 {
                write!(out, ", ").unwrap();
            }
            let cname = c_field_ident(&f.name);
            let fname = swift_ident(&f.name);
            match &f.ty {
                HybridType::Enum(e) => write!(
                    out,
                    "{fname}: try {e}(rawValue: raw.{cname}).unwrapOrThrow(\"{e}\", raw.{cname})"
                )
                .unwrap(),
                HybridType::Struct(st) => {
                    write!(out, "{fname}: try {st}.fromAbi(raw.{cname})").unwrap()
                }
                _ => write!(out, "{fname}: raw.{cname}").unwrap(),
            }
        }
        writeln!(out, ")").unwrap();
        writeln!(out, "    }}").unwrap();
    }

    // Binary encode/decode
    writeln!(out).unwrap();
    writeln!(out, "    public func encodeBin(into w: inout NveHybridBinWriter) {{").unwrap();
    writeln!(out, "        w.writeMap(count: {}) {{ w in", s.fields.len()).unwrap();
    for f in &s.fields {
        let fname = swift_ident(&f.name);
        let key_lit = escape_c_like_string(&f.name);
        writeln!(out, "            w.writeMapKey(\"{key_lit}\")").unwrap();
        emit_swift_bin_write(out, "            ", "w", &format!("self.{fname}"), &f.ty);
    }
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "    public static func decodeBin(from r: inout NveHybridBinReader) throws -> {} {{",
        s.name
    )
    .unwrap();
    writeln!(out, "        var out = {}()", s.name).unwrap();
    writeln!(out, "        let count = try r.beginMap()").unwrap();
    writeln!(out, "        for _ in 0 ..< count {{").unwrap();
    writeln!(out, "            let key = try r.readMapKey()").unwrap();
    writeln!(out, "            switch key {{").unwrap();
    for f in &s.fields {
        let fname = swift_ident(&f.name);
        let key_lit = escape_c_like_string(&f.name);
        writeln!(out, "            case \"{key_lit}\":").unwrap();
        emit_swift_bin_read(out, "                ", "r", &format!("out.{fname}"), &f.ty);
    }
    writeln!(out, "            default:").unwrap();
    writeln!(out, "                try r.skipValue()").unwrap();
    writeln!(out, "            }}").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        return out").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_swift_module(out: &mut String, m: &HybridModuleSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&m.name);
    writeln!(out, "public protocol Hybrid{pascal}Spec: AnyObject {{").unwrap();
    for method in &m.methods {
        writeln!(out, "    {}", swift_method_sig(method)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_swift_client(out, &pascal, m.interface_id(), m.schema_hash(spec), &m.methods, None, spec);
}

fn emit_swift_view(out: &mut String, v: &HybridViewSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&v.name);

    // Props struct (conforms to `NveDirectEncodable` for zero-alloc stack-slab arena encoding)
    writeln!(out, "public struct {pascal}Props: Equatable, NveDirectEncodable {{").unwrap();
    for p in &v.props {
        let pname = swift_ident(&p.name);
        writeln!(out, "    public var {pname}: {}", swift_type(&p.ty)).unwrap();
    }
    writeln!(out).unwrap();
    write!(out, "    public init(").unwrap();
    for (idx, p) in v.props.iter().enumerate() {
        if idx > 0 {
            write!(out, ", ").unwrap();
        }
        let pname = swift_ident(&p.name);
        let def = swift_default_value(&p.ty, p.default_value.as_ref(), spec);
        write!(out, "{pname}: {} = {def}", swift_type(&p.ty)).unwrap();
    }
    writeln!(out, ") {{").unwrap();
    for p in &v.props {
        let pname = swift_ident(&p.name);
        writeln!(out, "        self.{pname} = {pname}").unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    public var directPropCount: Int {{ {} }}", v.props.len()).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    public func encodeDirect(into builder: inout NveDirectPropsBuilder) throws {{").unwrap();
    for p in &v.props {
        let key_lit = escape_c_like_string(&p.name);
        let pname = swift_ident(&p.name);
        emit_swift_direct_prop_write(out, &key_lit, &format!("self.{pname}"), &p.ty);
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Event structs
    for ev in &v.events {
        let ev_pascal = to_pascal_case(&ev.name);
        writeln!(out, "public struct {pascal}{ev_pascal}Event: Equatable {{").unwrap();
        for param in &ev.params {
            let pname = swift_ident(&param.name);
            writeln!(out, "    public var {pname}: {}", swift_type(&param.ty)).unwrap();
        }
        writeln!(out).unwrap();
        write!(out, "    public init(").unwrap();
        for (idx, param) in ev.params.iter().enumerate() {
            if idx > 0 {
                write!(out, ", ").unwrap();
            }
            let pname = swift_ident(&param.name);
            write!(out, "{pname}: {}", swift_type(&param.ty)).unwrap();
        }
        writeln!(out, ") {{").unwrap();
        for param in &ev.params {
            let pname = swift_ident(&param.name);
            writeln!(out, "        self.{pname} = {pname}").unwrap();
        }
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    writeln!(out, "public protocol Hybrid{pascal}Spec: AnyObject {{").unwrap();
    writeln!(out, "    func setProps(_ props: {pascal}Props) throws").unwrap();
    for method in &v.methods {
        writeln!(out, "    {}", swift_method_sig(method)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_swift_client(out, &pascal, v.interface_id(), v.schema_hash(spec), &v.methods, Some(v), spec);
}

fn emit_swift_client(
    out: &mut String,
    pascal: &str,
    interface_id: u32,
    schema_hash: u64,
    methods: &[HybridMethodSpec],
    view: Option<&HybridViewSpec>,
    spec: &HybridFileSpec,
) {
    writeln!(out, "public final class {pascal}HybridClient: Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, "    public static let interfaceId: UInt32 = 0x{interface_id:08X}").unwrap();
    writeln!(out, "    public static let schemaHash: UInt64 = 0x{schema_hash:016X}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    private let vtable: UnsafePointer<NveHybrid{pascal}VTable>").unwrap();
    writeln!(out, "    private var handle: NveAppHandle?").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "    public static func resolve(getInterface: NveGetInterfaceFn?) throws -> {pascal}HybridClient {{"
    )
    .unwrap();
    writeln!(out, "        guard let resolver = getInterface else {{ throw NveHybridError.nullInterfaceResolver }}").unwrap();
    writeln!(out, "        guard let raw = resolver(interfaceId) else {{ throw NveHybridError.interfaceNotFound(interfaceId) }}").unwrap();
    writeln!(
        out,
        "        return try {pascal}HybridClient(vtable: raw.assumingMemoryBound(to: NveHybrid{pascal}VTable.self))"
    )
    .unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "    public init(vtable: UnsafePointer<NveHybrid{pascal}VTable>) throws {{"
    )
    .unwrap();
    writeln!(out, "        if vtable.pointee.abi_version != nveHybridAbiVersion || vtable.pointee.schema_hash != Self.schemaHash {{").unwrap();
    writeln!(out, "            throw NveHybridError.schemaMismatch(expected: Self.schemaHash, actual: vtable.pointee.schema_hash)").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        guard let createFn = vtable.pointee.create, let h = createFn() else {{").unwrap();
    writeln!(out, "            throw NveHybridError.nullHandle").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        self.vtable = vtable").unwrap();
    writeln!(out, "        self.handle = h").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    deinit {{").unwrap();
    writeln!(out, "        if let h = handle, let destroyFn = vtable.pointee.destroy {{").unwrap();
    writeln!(out, "            destroyFn(h)").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    if let Some(v) = view {
        emit_swift_set_props(out, pascal, v);
    }

    for method in methods {
        emit_swift_client_method(out, method, spec);
    }

    writeln!(out, "    private func takeString(_ raw: NveHybridOwnedBytes) -> String {{").unwrap();
    writeln!(out, "        defer {{ if let freeFn = vtable.pointee.free_bytes {{ freeFn(raw) }} }}").unwrap();
    writeln!(out, "        guard let ptr = raw.ptr, raw.len > 0 else {{ return \"\" }}").unwrap();
    writeln!(out, "        let buf = UnsafeBufferPointer(start: ptr, count: Int(raw.len))").unwrap();
    writeln!(out, "        return String(decoding: buf, as: UTF8.self)").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    private func takeBytes(_ raw: NveHybridOwnedBytes) -> [UInt8] {{").unwrap();
    writeln!(out, "        defer {{ if let freeFn = vtable.pointee.free_bytes {{ freeFn(raw) }} }}").unwrap();
    writeln!(out, "        guard let ptr = raw.ptr, raw.len > 0 else {{ return [] }}").unwrap();
    writeln!(out, "        let buf = UnsafeBufferPointer(start: ptr, count: Int(raw.len))").unwrap();
    writeln!(out, "        return Array(buf)").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_swift_direct_prop_write(out: &mut String, key_lit: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::String
        | HybridType::Bytes => {
            writeln!(out, "        builder.write(\"{key_lit}\", {expr})").unwrap();
        }
        HybridType::Enum(_) => {
            writeln!(out, "        builder.write(\"{key_lit}\", enum: {expr})").unwrap();
        }
        HybridType::Optional(inner) => match inner.as_ref() {
            HybridType::Bool
            | HybridType::U8
            | HybridType::U16
            | HybridType::Usize
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64
            | HybridType::F32
            | HybridType::F64
            | HybridType::String
            | HybridType::Bytes => {
                writeln!(out, "        builder.write(\"{key_lit}\", {expr})").unwrap();
            }
            HybridType::Enum(_) => {
                writeln!(out, "        builder.write(\"{key_lit}\", enum: {expr})").unwrap();
            }
            other => {
                writeln!(out, "        if let _optProp = {expr} {{").unwrap();
                writeln!(out, "            var _w = NveHybridBinWriter()").unwrap();
                emit_swift_bin_write(out, "            ", "_w", "_optProp", other);
                writeln!(out, "            builder.write(\"{key_lit}\", _w.bytes)").unwrap();
                writeln!(out, "        }} else {{").unwrap();
                writeln!(out, "            builder.writeNull(\"{key_lit}\")").unwrap();
                writeln!(out, "        }}").unwrap();
            }
        },
        other => {
            writeln!(out, "        do {{").unwrap();
            writeln!(out, "            var _w = NveHybridBinWriter()").unwrap();
            emit_swift_bin_write(out, "            ", "_w", expr, other);
            writeln!(out, "            builder.write(\"{key_lit}\", _w.bytes)").unwrap();
            writeln!(out, "        }}").unwrap();
        }
    }
}

fn emit_swift_set_props(out: &mut String, pascal: &str, _v: &HybridViewSpec) {
    writeln!(out, "    public func setProps(_ props: {pascal}Props) throws {{").unwrap();
    writeln!(out, "        guard let h = handle, let setFn = vtable.pointee.set_props_direct else {{ throw NveHybridError.nullHandle }}").unwrap();
    writeln!(out, "        let status: Int32 = try NveDirectPropsWriter.withEncodedProps(props) {{ ptr, count in").unwrap();
    writeln!(out, "            setFn(h, ptr, count)").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        if status != Int32(NVE_HYBRID_OK.rawValue) {{").unwrap();
    writeln!(out, "            throw NveHybridError.remoteError(\"setProps failed\")").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();
}

fn emit_swift_client_method(out: &mut String, method: &HybridMethodSpec, spec: &HybridFileSpec) {
    let cname = c_field_ident(&method.name);
    writeln!(out, "    public {} {{", swift_method_sig(method)).unwrap();
    writeln!(
        out,
        "        guard let h = handle, let fnPtr = vtable.pointee.{cname} else {{ throw NveHybridError.nullHandle }}"
    )
    .unwrap();

    // Prepare any binary-encoded or copied UTF-8 buffers before entering nested withUnsafeBufferPointer scopes
    let mut pinned_scopes: Vec<(String, String, bool)> = Vec::new(); // (buffer_var, slice_var, is_str)
    let mut call_args = vec!["h".to_string()];

    for (idx, p) in method.params.iter().enumerate() {
        let pname = swift_ident(&p.name);
        match &p.ty {
            HybridType::Bool
            | HybridType::U8
            | HybridType::U16
            | HybridType::Usize
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64
            | HybridType::F32
            | HybridType::F64 => call_args.push(pname),
            HybridType::Enum(_) => call_args.push(format!("{pname}.rawValue")),
            HybridType::Struct(_) if p.ty.is_pod(spec) => {
                call_args.push(format!("{pname}.toAbi()"));
            }
            HybridType::String => {
                let bvar = format!("_strBuf{idx}");
                let svar = format!("_arg{idx}");
                writeln!(out, "        let {bvar} = Array({pname}.utf8)").unwrap();
                pinned_scopes.push((bvar, svar.clone(), true));
                call_args.push(svar);
            }
            HybridType::Bytes => {
                let svar = format!("_arg{idx}");
                pinned_scopes.push((pname, svar.clone(), false));
                call_args.push(svar);
            }
            HybridType::Value => call_args.push(pname),
            HybridType::Optional(inner) if inner.is_pod(spec) => {
                let suffix = inner.pod_opt_suffix().unwrap();
                let svar = format!("_arg{idx}");
                let zero = swift_c_zero_value(inner, spec);
                let unwrap_expr = match inner.as_ref() {
                    HybridType::Enum(_) => "v.rawValue".to_string(),
                    HybridType::Struct(_) => "v.toAbi()".to_string(),
                    _ => "v".to_string(),
                };
                writeln!(
                    out,
                    "        let {svar}: NveHybridOpt{suffix} = {pname}.map {{ v in NveHybridOpt{suffix}(is_some: true, value: {unwrap_expr}) }} ?? NveHybridOpt{suffix}(is_some: false, value: {zero})"
                )
                .unwrap();
                call_args.push(svar);
            }
            other => {
                let wvar = format!("_w{idx}");
                let bvar = format!("_binBuf{idx}");
                let svar = format!("_arg{idx}");
                writeln!(out, "        var {wvar} = NveHybridBinWriter()").unwrap();
                emit_swift_bin_write(out, "        ", &wvar, &pname, other);
                writeln!(out, "        let {bvar} = {wvar}.bytes").unwrap();
                pinned_scopes.push((bvar, svar.clone(), false));
                call_args.push(svar);
            }
        }
    }

    let mut indent = "        ".to_string();
    let has_ret = !matches!(method.return_type, HybridType::Void)
        && !matches!(&method.return_type, HybridType::Result { ok, .. } if matches!(ok.as_ref(), HybridType::Void));

    for (idx, (bvar, svar, is_str)) in pinned_scopes.iter().enumerate() {
        let ret_prefix = if idx == 0 && has_ret { "return " } else { "" };
        writeln!(
            out,
            "{indent}{ret_prefix}try {bvar}.withUnsafeBufferPointer {{ _p{idx} in"
        )
        .unwrap();
        indent.push_str("    ");
        if *is_str {
            writeln!(
                out,
                "{indent}let {svar} = NveStrSlice(ptr: _p{idx}.baseAddress, len: _p{idx}.count)"
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "{indent}let {svar} = NveBufferSlice(ptr: _p{idx}.baseAddress, len: _p{idx}.count)"
            )
            .unwrap();
        }
    }

    match &method.return_type {
        HybridType::Void => {
            writeln!(out, "{indent}fnPtr({})", call_args.join(", ")).unwrap();
        }
        HybridType::Result { ok, .. } => {
            if !matches!(ok.as_ref(), HybridType::Void) {
                writeln!(
                    out,
                    "{indent}var _rawOk = {}",
                    swift_c_return_zero_value(ok, spec)
                )
                .unwrap();
                call_args.push("&_rawOk".to_string());
            }
            writeln!(
                out,
                "{indent}var _rawErr = NveHybridOwnedBytes(ptr: nil, len: 0, cap: 0)"
            )
            .unwrap();
            call_args.push("&_rawErr".to_string());
            writeln!(
                out,
                "{indent}let _status = fnPtr({})",
                call_args.join(", ")
            )
            .unwrap();
            writeln!(
                out,
                "{indent}if _status != Int32(NVE_HYBRID_OK.rawValue) {{"
            )
            .unwrap();
            writeln!(out, "{indent}    let _msg = self.takeString(_rawErr)").unwrap();
            writeln!(
                out,
                "{indent}    throw NveHybridError.remoteError(_msg.isEmpty ? \"hybrid call failed\" : _msg)"
            )
            .unwrap();
            writeln!(out, "{indent}}}").unwrap();
            if !matches!(ok.as_ref(), HybridType::Void) {
                emit_swift_return_decode(out, &indent, "_rawOk", ok, spec);
            }
        }
        other => {
            writeln!(
                out,
                "{indent}let _rawRet = fnPtr({})",
                call_args.join(", ")
            )
            .unwrap();
            emit_swift_return_decode(out, &indent, "_rawRet", other, spec);
        }
    }

    for _ in 0..pinned_scopes.len() {
        indent.truncate(indent.len() - 4);
        writeln!(out, "{indent}}}").unwrap();
    }

    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();
}

fn emit_swift_return_decode(
    out: &mut String,
    indent: &str,
    var: &str,
    ty: &HybridType,
    spec: &HybridFileSpec,
) {
    match ty {
        HybridType::Void => {}
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64 => {
            writeln!(out, "{indent}return {var}").unwrap();
        }
        HybridType::Enum(e) => {
            writeln!(
                out,
                "{indent}return try {e}(rawValue: {var}).unwrapOrThrow(\"{e}\", {var})"
            )
            .unwrap();
        }
        HybridType::Struct(s) if ty.is_pod(spec) => {
            writeln!(out, "{indent}return try {s}.fromAbi({var})").unwrap();
        }
        HybridType::String => {
            writeln!(out, "{indent}return self.takeString({var})").unwrap();
        }
        HybridType::Bytes => {
            writeln!(out, "{indent}return self.takeBytes({var})").unwrap();
        }
        HybridType::Value => {
            writeln!(
                out,
                "{indent}return NveHybridDynamicValue(binBytes: self.takeBytes({var}))"
            )
            .unwrap();
        }
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            writeln!(out, "{indent}guard {var}.is_some else {{ return nil }}").unwrap();
            match inner.as_ref() {
                HybridType::Enum(e) => {
                    writeln!(
                        out,
                        "{indent}return try {e}(rawValue: {var}.value).unwrapOrThrow(\"{e}\", {var}.value)"
                    )
                    .unwrap();
                }
                HybridType::Struct(s) => {
                    writeln!(out, "{indent}return try {s}.fromAbi({var}.value)").unwrap();
                }
                _ => {
                    writeln!(out, "{indent}return {var}.value").unwrap();
                }
            }
        }
        other => {
            writeln!(out, "{indent}var _r = NveHybridBinReader(bytes: self.takeBytes({var}))").unwrap();
            writeln!(
                out,
                "{indent}var _out: {} = {}",
                swift_type(other),
                swift_default_value(other, None, spec)
            )
            .unwrap();
            emit_swift_bin_read(out, indent, "_r", "_out", other);
            writeln!(out, "{indent}return _out").unwrap();
        }
    }
}

fn swift_method_sig(method: &HybridMethodSpec) -> String {
    let mname = swift_ident(&to_camel_case(&method.name));
    let params: Vec<String> = method
        .params
        .iter()
        .map(|p| format!("{}: {}", swift_ident(&p.name), swift_param_type(&p.ty)))
        .collect();
    let ret = match &method.return_type {
        HybridType::Void => String::new(),
        HybridType::Result { ok, .. } if matches!(ok.as_ref(), HybridType::Void) => String::new(),
        HybridType::Result { ok, .. } => format!(" -> {}", swift_type(ok)),
        other => format!(" -> {}", swift_type(other)),
    };
    format!("func {mname}({}) throws{ret}", params.join(", "))
}

fn swift_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Void => "Void".to_string(),
        HybridType::Bool => "Bool".to_string(),
        HybridType::U8 => "UInt8".to_string(),
        HybridType::U16 => "UInt16".to_string(),
        HybridType::Usize => "Int".to_string(),
        HybridType::I32 => "Int32".to_string(),
        HybridType::U32 => "UInt32".to_string(),
        HybridType::I64 => "Int64".to_string(),
        HybridType::U64 => "UInt64".to_string(),
        HybridType::F32 => "Float".to_string(),
        HybridType::F64 => "Double".to_string(),
        HybridType::String => "String".to_string(),
        HybridType::Bytes => "[UInt8]".to_string(),
        HybridType::Optional(inner) => format!("{}?", swift_type(inner)),
        HybridType::Vec(inner) => format!("[{}]", swift_type(inner)),
        HybridType::Result { ok, .. } => swift_type(ok),
        HybridType::Struct(name) | HybridType::Enum(name) | HybridType::Handle(name) => {
            name.clone()
        }
        HybridType::Value => "NveHybridDynamicValue".to_string(),
        HybridType::ConstPtr(inner) => {
            if matches!(inner.as_ref(), HybridType::Void) {
                "UnsafeRawPointer?".to_string()
            } else {
                format!("UnsafePointer<{}>?", swift_type(inner))
            }
        }
        HybridType::MutPtr(inner) => {
            if matches!(inner.as_ref(), HybridType::Void) {
                "UnsafeMutableRawPointer?".to_string()
            } else {
                format!("UnsafeMutablePointer<{}>?", swift_type(inner))
            }
        }
    }
}

fn swift_param_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Value => "NveValue".to_string(),
        other => swift_type(other),
    }
}

fn swift_default_value(
    ty: &HybridType,
    def: Option<&HybridDefaultValue>,
    spec: &HybridFileSpec,
) -> String {
    if let Some(d) = def {
        if let HybridType::Optional(inner) = ty {
            return match d {
                HybridDefaultValue::None => "nil".to_string(),
                other => swift_default_value(inner, Some(other), spec),
            };
        }
        return match (d, ty) {
            (HybridDefaultValue::Bool(b), _) => b.to_string(),
            (HybridDefaultValue::Int(i), HybridType::F32 | HybridType::F64) => format!("{i}.0"),
            (HybridDefaultValue::Int(i), _) => i.to_string(),
            (HybridDefaultValue::UInt(u), HybridType::F32 | HybridType::F64) => format!("{u}.0"),
            (HybridDefaultValue::UInt(u), _) => u.to_string(),
            (HybridDefaultValue::Float(f), _) => format_float_literal(*f),
            (HybridDefaultValue::String(s), _) => format!("\"{}\"", escape_c_like_string(s)),
            (HybridDefaultValue::EnumVariant { enum_name, variant }, _) => {
                format!("{enum_name}.{}", swift_ident(variant))
            }
            (HybridDefaultValue::None, _) => "nil".to_string(),
        };
    }

    match ty {
        HybridType::Bool => "false".to_string(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => "0".to_string(),
        HybridType::F32 | HybridType::F64 => "0.0".to_string(),
        HybridType::String => "\"\"".to_string(),
        HybridType::Bytes | HybridType::Vec(_) => "[]".to_string(),
        HybridType::Optional(_)
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => "nil".to_string(),
        HybridType::Struct(name) => format!("{name}()"),
        HybridType::Enum(name) => {
            if let Some(e) = spec.find_enum(name) {
                format!("{name}.{}", swift_ident(&e.variants[0].name))
            } else {
                format!("{name}(rawValue: 0)!")
            }
        }
        HybridType::Value => "NveHybridDynamicValue()".to_string(),
        HybridType::Void | HybridType::Result { .. } => "()".to_string(),
    }
}

fn swift_c_zero_value(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Bool => "false".to_string(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::Enum(_) => "0".to_string(),
        HybridType::F32 | HybridType::F64 => "0.0".to_string(),
        HybridType::Struct(name) if ty.is_pod(spec) => format!("{name}().toAbi()"),
        _ => "NveHybridOwnedBytes(ptr: nil, len: 0, cap: 0)".to_string(),
    }
}

fn swift_c_return_zero_value(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            let suffix = inner.pod_opt_suffix().unwrap();
            format!(
                "NveHybridOpt{suffix}(is_some: false, value: {})",
                swift_c_zero_value(inner, spec)
            )
        }
        other => swift_c_zero_value(other, spec),
    }
}

fn emit_swift_bin_write(out: &mut String, indent: &str, w: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{w}.writeBool({expr})").unwrap(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64 => {
            writeln!(out, "{indent}{w}.writeInt64(Int64({expr}))").unwrap();
        }
        HybridType::U64 => {
            writeln!(out, "{indent}{w}.writeInt64(Int64(bitPattern: {expr}))").unwrap();
        }
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "{indent}{w}.writeDouble(Double({expr}))").unwrap();
        }
        HybridType::Enum(_) => {
            writeln!(out, "{indent}{w}.writeInt64(Int64({expr}.rawValue))").unwrap();
        }
        HybridType::String => writeln!(out, "{indent}{w}.writeString({expr})").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{w}.writeBytes({expr})").unwrap(),
        HybridType::Struct(_) => writeln!(out, "{indent}{expr}.encodeBin(into: &{w})").unwrap(),
        HybridType::Value => writeln!(out, "{indent}{w}.writeRaw({expr}.binBytes)").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}if let _optV = {expr} {{").unwrap();
            emit_swift_bin_write(out, &format!("{indent}    "), w, "_optV", inner);
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}    {w}.writeNull()").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}{w}.writeArray(count: {expr}.count) {{ _aw in").unwrap();
            writeln!(out, "{indent}    for _elem in {expr} {{").unwrap();
            emit_swift_bin_write(out, &format!("{indent}        "), "_aw", "_elem", inner);
            writeln!(out, "{indent}    }}").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {
            writeln!(out, "{indent}{w}.writeNull()").unwrap();
        }
    }
}

fn emit_swift_bin_read(out: &mut String, indent: &str, r: &str, dst: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{dst} = try {r}.readBool()").unwrap(),
        HybridType::U8 => writeln!(out, "{indent}{dst} = UInt8(truncatingIfNeeded: try {r}.readInt64())").unwrap(),
        HybridType::U16 => writeln!(out, "{indent}{dst} = UInt16(truncatingIfNeeded: try {r}.readInt64())").unwrap(),
        HybridType::Usize => writeln!(out, "{indent}{dst} = Int(truncatingIfNeeded: try {r}.readInt64())").unwrap(),
        HybridType::I32 => writeln!(out, "{indent}{dst} = Int32(truncatingIfNeeded: try {r}.readInt64())").unwrap(),
        HybridType::U32 => writeln!(out, "{indent}{dst} = UInt32(truncatingIfNeeded: try {r}.readInt64())").unwrap(),
        HybridType::I64 => writeln!(out, "{indent}{dst} = try {r}.readInt64()").unwrap(),
        HybridType::U64 => writeln!(out, "{indent}{dst} = UInt64(bitPattern: try {r}.readInt64())").unwrap(),
        HybridType::F32 => writeln!(out, "{indent}{dst} = Float(try {r}.readDouble())").unwrap(),
        HybridType::F64 => writeln!(out, "{indent}{dst} = try {r}.readDouble()").unwrap(),
        HybridType::Enum(e) => {
            writeln!(out, "{indent}do {{").unwrap();
            writeln!(out, "{indent}    let _raw = UInt32(truncatingIfNeeded: try {r}.readInt64())").unwrap();
            writeln!(out, "{indent}    {dst} = try {e}(rawValue: _raw).unwrapOrThrow(\"{e}\", _raw)").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::String => writeln!(out, "{indent}{dst} = try {r}.readString()").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{dst} = try {r}.readBytes()").unwrap(),
        HybridType::Struct(s) => writeln!(out, "{indent}{dst} = try {s}.decodeBin(from: &{r})").unwrap(),
        HybridType::Value => writeln!(out, "{indent}{dst} = NveHybridDynamicValue(binBytes: try {r}.readRawValue())").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}if try {r}.readNullIfPresent() {{").unwrap();
            writeln!(out, "{indent}    {dst} = nil").unwrap();
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}    let _optVal: {}", swift_type(inner)).unwrap();
            emit_swift_bin_read(out, &format!("{indent}    "), r, "_optVal", inner);
            writeln!(out, "{indent}    {dst} = _optVal").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}do {{").unwrap();
            writeln!(out, "{indent}    let _n = try {r}.beginArray()").unwrap();
            writeln!(out, "{indent}    var _arr: [{}] = []", swift_type(inner)).unwrap();
            writeln!(out, "{indent}    _arr.reserveCapacity(_n)").unwrap();
            writeln!(out, "{indent}    for _ in 0 ..< _n {{").unwrap();
            writeln!(out, "{indent}        let _elem: {}", swift_type(inner)).unwrap();
            emit_swift_bin_read(out, &format!("{indent}        "), r, "_elem", inner);
            writeln!(out, "{indent}        _arr.append(_elem)").unwrap();
            writeln!(out, "{indent}    }}").unwrap();
            writeln!(out, "{indent}    {dst} = _arr").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {}
    }
}

