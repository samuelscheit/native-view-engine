//! Rust target emitter for NVE Hybrid FFI codegen.
//!
//! Emits a self-contained Rust module (`<stem>_hybrid.rs`) with zero JSON dependencies:
//! - `#[repr(u32)]` enums with safe `from_u32` / `to_u32`
//! - `#[repr(C)]` POD structs (passed directly by value) and idiomatic owned Rust structs
//! - Direct C-ABI `NveHybridOwnedBytes`, `NveHybridStatus`, and POD `NveHybridOpt*` structs
//! - Strict `pub trait <Name>Hybrid` contracts
//! - `#[repr(C)] pub struct NveHybrid<Name>VTable` with `abi_version`, `interface_id`,
//!   `schema_hash`, `create`, `destroy`, `alloc_bytes`, `free_bytes`, and direct `extern "C"`
//!   trampolines (`build_<snake>_vtable::<Impl>()`)
//! - For `HybridView`: typed `<Name>Props`, zero-copy `decode_props_direct(&[NveMapEntry])`,
//!   typed event payload structs, zero-copy `NveDirectEvent` emitters, and compact binary
//!   `NveBinValue` encoders (`encode_<event>_bin`).

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::hybrid::ir::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::ir::GeneratedFile;
use crate::naming::{escape_string_literal, format_float_literal, rust_ident, to_pascal_case, to_snake_case};

/// Emits the Rust Hybrid FFI contract, direct C-ABI vtables, and zero-copy prop/event helpers.
pub fn generate_hybrid_rust(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut out = String::with_capacity(16 * 1024);

    writeln!(out, "// @generated by nve-codegen (hybrid Rust target) — DO NOT EDIT.").unwrap();
    writeln!(out, "// Zero-JSON, direct C-ABI vtable bindings backed by `nve_abi`.").unwrap();
    writeln!(out, "#![allow(clippy::too_many_arguments)]").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use nve_abi::{{").unwrap();
    writeln!(out, "    BinValueView, DecodeError, NveAppHandle, NveBufferSlice, NveDirectEvent,").unwrap();
    writeln!(out, "    NveMapEntry, NveMapRef, NveStrSlice, NveValue, NveValueRef, NveValueTag,").unwrap();
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    emit_common_rust_abi(&mut out, spec);

    for e in &spec.enums {
        emit_rust_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_rust_struct(&mut out, s, spec);
    }

    emit_pod_option_structs(&mut out, spec);

    for m in &spec.modules {
        emit_rust_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_rust_view(&mut out, v, spec);
    }

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.rs"),
        content: out,
    }])
}

fn emit_common_rust_abi(out: &mut String, spec: &HybridFileSpec) {
    writeln!(out, "/// Current Hybrid FFI vtable ABI version.").unwrap();
    writeln!(out, "pub const NVE_HYBRID_ABI_VERSION: u32 = {NVE_HYBRID_ABI_VERSION};").unwrap();
    writeln!(
        out,
        "/// File-wide deterministic FNV-1a 64-bit schema hash across all declared hybrid items."
    )
    .unwrap();
    writeln!(
        out,
        "pub const NVE_HYBRID_FILE_SCHEMA_HASH: u64 = 0x{:016X};",
        spec.file_schema_hash()
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        r#"/// Status code returned by fallible Hybrid FFI trampolines.
#[repr(i32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NveHybridStatus {{
    Ok = 0,
    Err = 1,
    InvalidArg = 2,
    SchemaMismatch = 3,
    NullHandle = 4,
}}

/// Rust-allocated owned byte buffer returned across the C ABI.
/// Foreign callers MUST release non-null buffers via the vtable's `free_bytes`.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct NveHybridOwnedBytes {{
    pub ptr: *mut u8,
    pub len: usize,
    pub cap: usize,
}}

impl NveHybridOwnedBytes {{
    pub const EMPTY: Self = Self {{
        ptr: std::ptr::null_mut(),
        len: 0,
        cap: 0,
    }};

    #[inline]
    pub fn from_vec(mut v: Vec<u8>) -> Self {{
        if v.is_empty() {{
            return Self::EMPTY;
        }}
        let ptr = v.as_mut_ptr();
        let len = v.len();
        let cap = v.capacity();
        std::mem::forget(v);
        Self {{ ptr, len, cap }}
    }}

    #[inline]
    pub fn from_string(s: String) -> Self {{
        Self::from_vec(s.into_bytes())
    }}

    /// # Safety
    /// Must only be called once on a buffer previously allocated by `alloc_bytes` / `from_vec`.
    #[inline]
    pub unsafe fn free(self) {{
        if !self.ptr.is_null() && self.cap > 0 {{
            let _ = unsafe {{ Vec::from_raw_parts(self.ptr, self.len, self.cap) }};
        }}
    }}
}}

/// Owned dynamic value crossing Hybrid FFI as compact binary `NveBinValue` (zero JSON).
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct NveHybridValue {{
    pub bin_bytes: Vec<u8>,
}}

impl NveHybridValue {{
    #[inline]
    pub fn null() -> Self {{
        Self {{
            bin_bytes: vec![NveValueTag::Null as u8],
        }}
    }}

    #[inline]
    pub fn from_ffi_ref(value: NveValueRef<'_>) -> Result<Self, DecodeError> {{
        Ok(Self {{
            bin_bytes: nve_abi::encode_bin_value_to_vec(value)?,
        }})
    }}

    #[inline]
    pub fn as_view(&self) -> Result<BinValueView<'_>, DecodeError> {{
        BinValueView::parse(&self.bin_bytes)
    }}
}}

#[inline]
pub unsafe extern "C" fn nve_hybrid_alloc_bytes(len: usize) -> NveHybridOwnedBytes {{
    if len == 0 {{
        return NveHybridOwnedBytes::EMPTY;
    }}
    let buf = vec![0u8; len];
    NveHybridOwnedBytes::from_vec(buf)
}}

#[inline]
pub unsafe extern "C" fn nve_hybrid_free_bytes(buf: NveHybridOwnedBytes) {{
    unsafe {{ buf.free() }};
}}

/// Compact binary `NveBinValue` writer helpers matching `nve_abi::encode_bin_value` byte-for-byte.
pub mod nve_bin_codec {{
    use nve_abi::{{BinValueView, DecodeError, NveValueTag}};

    #[inline]
    pub fn write_null(out: &mut Vec<u8>) {{
        out.push(NveValueTag::Null as u8);
    }}

    #[inline]
    pub fn write_bool(out: &mut Vec<u8>, v: bool) {{
        out.push(NveValueTag::Bool as u8);
        out.push(u8::from(v));
    }}

    #[inline]
    pub fn write_i64(out: &mut Vec<u8>, v: i64) {{
        out.push(NveValueTag::I64 as u8);
        out.extend_from_slice(&v.to_le_bytes());
    }}

    #[inline]
    pub fn write_f64(out: &mut Vec<u8>, v: f64) {{
        out.push(NveValueTag::F64 as u8);
        out.extend_from_slice(&v.to_le_bytes());
    }}

    #[inline]
    pub fn write_str(out: &mut Vec<u8>, s: &str) {{
        let b = s.as_bytes();
        out.push(NveValueTag::Str as u8);
        out.extend_from_slice(&(b.len() as u32).to_le_bytes());
        out.extend_from_slice(b);
    }}

    #[inline]
    pub fn write_bytes(out: &mut Vec<u8>, b: &[u8]) {{
        out.push(NveValueTag::Bytes as u8);
        out.extend_from_slice(&(b.len() as u32).to_le_bytes());
        out.extend_from_slice(b);
    }}

    #[inline]
    pub fn write_array<F: FnOnce(&mut Vec<u8>)>(out: &mut Vec<u8>, count: usize, f: F) {{
        out.push(NveValueTag::Array as u8);
        let len_pos = out.len();
        out.extend_from_slice(&0u32.to_le_bytes());
        let start = out.len();
        out.extend_from_slice(&(count as u32).to_le_bytes());
        f(out);
        let payload_len = (out.len() - start) as u32;
        out[len_pos..len_pos + 4].copy_from_slice(&payload_len.to_le_bytes());
    }}

    #[inline]
    pub fn write_map<F: FnOnce(&mut Vec<u8>)>(out: &mut Vec<u8>, count: usize, f: F) {{
        out.push(NveValueTag::Map as u8);
        let len_pos = out.len();
        out.extend_from_slice(&0u32.to_le_bytes());
        let start = out.len();
        out.extend_from_slice(&(count as u32).to_le_bytes());
        f(out);
        let payload_len = (out.len() - start) as u32;
        out[len_pos..len_pos + 4].copy_from_slice(&payload_len.to_le_bytes());
    }}

    #[inline]
    pub fn write_map_key(out: &mut Vec<u8>, key: &str) {{
        let kb = key.as_bytes();
        out.extend_from_slice(&(kb.len() as u32).to_le_bytes());
        out.extend_from_slice(kb);
    }}

    #[inline]
    pub fn parse_view(bytes: &[u8]) -> Result<BinValueView<'_>, DecodeError> {{
        BinValueView::parse(bytes)
    }}
}}
"#
    )
    .unwrap();
}

fn emit_doc_comments(out: &mut String, indent: &str, doc: Option<&str>) {
    if let Some(d) = doc {
        for line in d.lines() {
            writeln!(out, "{indent}/// {line}").unwrap();
        }
    }
}

fn emit_rust_enum(out: &mut String, e: &HybridEnumSpec) {
    emit_doc_comments(out, "", e.doc.as_deref());
    writeln!(out, "#[repr(u32)]").unwrap();
    writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]").unwrap();
    writeln!(out, "pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        emit_doc_comments(out, "    ", v.doc.as_deref());
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "impl Default for {} {{", e.name).unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    fn default() -> Self {{").unwrap();
    writeln!(out, "        Self::{}", e.variants[0].name).unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "impl {} {{", e.name).unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    pub const fn to_u32(self) -> u32 {{ self as u32 }}").unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    pub const fn from_u32(raw: u32) -> Option<Self> {{").unwrap();
    writeln!(out, "        match raw {{").unwrap();
    for v in &e.variants {
        writeln!(out, "            {} => Some(Self::{}),", v.value, v.name).unwrap();
    }
    writeln!(out, "            _ => None,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_rust_struct(out: &mut String, s: &HybridStructSpec, spec: &HybridFileSpec) {
    let is_pod = s.is_pod(spec);
    emit_doc_comments(out, "", s.doc.as_deref());
    if is_pod {
        writeln!(out, "#[repr(C)]").unwrap();
        writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq, Default)]").unwrap();
    } else {
        writeln!(out, "#[derive(Debug, Clone, PartialEq, Default)]").unwrap();
    }
    writeln!(out, "pub struct {} {{", s.name).unwrap();
    for f in &s.fields {
        emit_doc_comments(out, "    ", f.doc.as_deref());
        let fname = rust_ident(&f.name);
        let fty = rust_owned_type(&f.ty);
        writeln!(out, "    pub {fname}: {fty},").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Emit compact binary `NveBinValue` encode/decode and `NveValueRef` decode helpers on every struct
    // so both non-POD structs and POD structs nested inside Vec/Option/Props/Events work zero-JSON.
    writeln!(out, "impl {} {{", s.name).unwrap();
    writeln!(out, "    pub fn encode_bin(&self, out: &mut Vec<u8>) {{").unwrap();
    writeln!(
        out,
        "        nve_bin_codec::write_map(out, {}, |out| {{",
        s.fields.len()
    )
    .unwrap();
    for f in &s.fields {
        let fname = rust_ident(&f.name);
        let key_lit = escape_string_literal(&f.name);
        writeln!(out, "            nve_bin_codec::write_map_key(out, \"{key_lit}\");").unwrap();
        emit_bin_write_expr(out, "            ", "out", &format!("&self.{fname}"), &f.ty);
    }
    writeln!(out, "        }});").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    pub fn decode_bin(view: BinValueView<'_>) -> Result<Self, DecodeError> {{").unwrap();
    writeln!(out, "        if view.tag() != NveValueTag::Map {{").unwrap();
    writeln!(out, "            return Err(DecodeError::InvalidEnum(\"NveValueTag\", view.tag() as u32));").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        Ok(Self {{").unwrap();
    for f in &s.fields {
        let fname = rust_ident(&f.name);
        let key_lit = escape_string_literal(&f.name);
        let decode_expr = bin_view_decode_expr("fv", &f.ty);
        if matches!(f.ty, HybridType::Optional(_)) {
            writeln!(
                out,
                "            {fname}: match view.get(\"{key_lit}\") {{ Some(fv) => {decode_expr}, None => None }},"
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "            {fname}: {{ let fv = view.get(\"{key_lit}\").ok_or(DecodeError::Truncated)?; {decode_expr} }},"
            )
            .unwrap();
        }
    }
    writeln!(out, "        }})").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    pub fn decode_value_ref(value: NveValueRef<'_>) -> Result<Self, DecodeError> {{").unwrap();
    writeln!(out, "        let map = value.as_map().ok_or(DecodeError::Truncated)?;").unwrap();
    writeln!(out, "        Ok(Self {{").unwrap();
    for f in &s.fields {
        let fname = rust_ident(&f.name);
        let key_lit = escape_string_literal(&f.name);
        let decode_expr = value_ref_decode_expr("fv", &f.ty);
        if matches!(f.ty, HybridType::Optional(_)) {
            writeln!(
                out,
                "            {fname}: match map.get(\"{key_lit}\") {{ Some(fv) => {decode_expr}, None => None }},"
            )
            .unwrap();
        } else {
            writeln!(
                out,
                "            {fname}: {{ let fv = map.get(\"{key_lit}\").ok_or(DecodeError::Truncated)?; {decode_expr} }},"
            )
            .unwrap();
        }
    }
    writeln!(out, "        }})").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_pod_option_structs(out: &mut String, spec: &HybridFileSpec) {
    let opts = spec.collect_pod_option_types();
    for inner in &opts {
        let suffix = inner.pod_opt_suffix().unwrap();
        let ffi_ty = rust_c_abi_pod_type(inner);
        writeln!(out, "#[repr(C)]").unwrap();
        writeln!(out, "#[derive(Debug, Clone, Copy)]").unwrap();
        writeln!(out, "pub struct NveHybridOpt{suffix} {{").unwrap();
        writeln!(out, "    pub is_some: bool,").unwrap();
        writeln!(out, "    pub value: {ffi_ty},").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }
}

fn emit_rust_module(out: &mut String, m: &HybridModuleSpec, spec: &HybridFileSpec) {
    let upper = to_snake_case(&m.name).to_ascii_uppercase();
    let snake = to_snake_case(&m.name);
    let pascal = to_pascal_case(&m.name);
    let iface_id = m.interface_id();
    let schema_hash = m.schema_hash(spec);

    writeln!(out, "// ===========================================================================").unwrap();
    writeln!(out, "// Hybrid Module: {pascal}").unwrap();
    writeln!(out, "// ===========================================================================").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const NVE_HYBRID_{upper}_INTERFACE_ID: u32 = 0x{iface_id:08X};").unwrap();
    writeln!(out, "pub const NVE_HYBRID_{upper}_SCHEMA_HASH: u64 = 0x{schema_hash:016X};").unwrap();
    writeln!(out).unwrap();

    emit_doc_comments(out, "", m.doc.as_deref());
    writeln!(out, "pub trait {pascal}Hybrid {{").unwrap();
    for method in &m.methods {
        emit_doc_comments(out, "    ", method.doc.as_deref());
        emit_rust_trait_method(out, method);
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_rust_vtable_struct(out, &pascal, &m.methods, false, spec);
    emit_rust_vtable_builder(out, &pascal, &snake, &upper, &m.methods, false, spec);
}

fn emit_rust_view(out: &mut String, v: &HybridViewSpec, spec: &HybridFileSpec) {
    let upper = to_snake_case(&v.name).to_ascii_uppercase();
    let snake = to_snake_case(&v.name);
    let pascal = to_pascal_case(&v.name);
    let iface_id = v.interface_id();
    let schema_hash = v.schema_hash(spec);

    writeln!(out, "// ===========================================================================").unwrap();
    writeln!(out, "// Hybrid View: {pascal}").unwrap();
    writeln!(out, "// ===========================================================================").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "pub const NVE_HYBRID_{upper}_INTERFACE_ID: u32 = 0x{iface_id:08X};").unwrap();
    writeln!(out, "pub const NVE_HYBRID_{upper}_SCHEMA_HASH: u64 = 0x{schema_hash:016X};").unwrap();
    writeln!(out).unwrap();

    // Props struct + Default + zero-copy `decode_props_direct(&[NveMapEntry])`
    writeln!(out, "#[derive(Debug, Clone, PartialEq)]").unwrap();
    writeln!(out, "pub struct {pascal}Props {{").unwrap();
    for p in &v.props {
        emit_doc_comments(out, "    ", p.doc.as_deref());
        let pname = rust_ident(&p.name);
        writeln!(out, "    pub {pname}: {},", rust_owned_type(&p.ty)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl Default for {pascal}Props {{").unwrap();
    writeln!(out, "    fn default() -> Self {{").unwrap();
    writeln!(out, "        Self {{").unwrap();
    for p in &v.props {
        let pname = rust_ident(&p.name);
        let def_expr = rust_prop_default_expr(&p.ty, p.default_value.as_ref());
        writeln!(out, "            {pname}: {def_expr},").unwrap();
    }
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {pascal}Props {{").unwrap();
    writeln!(
        out,
        "    /// Zero-copy prop decoder reading directly from FFI `NveMapEntry` slices (no JSON)."
    )
    .unwrap();
    writeln!(
        out,
        "    /// # Safety"
    )
    .unwrap();
    writeln!(
        out,
        "    /// All nested pointers inside `entries` must remain valid for the duration of this call."
    )
    .unwrap();
    writeln!(
        out,
        "    pub unsafe fn decode_props_direct(entries: &[NveMapEntry]) -> Result<Self, DecodeError> {{"
    )
    .unwrap();
    writeln!(out, "        let mut props = Self::default();").unwrap();
    writeln!(out, "        let map = unsafe {{ NveMapRef::from_slice(entries) }};").unwrap();
    writeln!(out, "        for (key, val) in map.iter() {{").unwrap();
    writeln!(out, "            match key {{").unwrap();
    for p in &v.props {
        let pname = rust_ident(&p.name);
        let key_lit = escape_string_literal(&p.name);
        let decode_expr = value_ref_decode_expr("val", &p.ty);
        writeln!(out, "                \"{key_lit}\" => props.{pname} = {decode_expr},").unwrap();
    }
    writeln!(out, "                _ => {{}}").unwrap();
    writeln!(out, "            }}").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "        Ok(props)").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    // Typed events + zero-copy `NveDirectEvent` emitters + compact binary `NveBinValue` encoders
    for ev in &v.events {
        let ev_pascal = to_pascal_case(&ev.name);
        let ev_snake = to_snake_case(&ev.name);
        let ev_struct = format!("{pascal}{ev_pascal}Event");
        emit_doc_comments(out, "", ev.doc.as_deref());
        writeln!(out, "#[derive(Debug, Clone, PartialEq, Default)]").unwrap();
        writeln!(out, "pub struct {ev_struct} {{").unwrap();
        for param in &ev.params {
            let pname = rust_ident(&param.name);
            writeln!(out, "    pub {pname}: {},", rust_owned_type(&param.ty)).unwrap();
        }
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        writeln!(out, "impl {ev_struct} {{").unwrap();
        // Compact binary `NveBinValue` encoder
        writeln!(
            out,
            "    /// Encodes this typed event payload into compact binary `NveBinValue` (zero JSON)."
        )
        .unwrap();
        writeln!(out, "    pub fn encode_bin(&self) -> Vec<u8> {{").unwrap();
        writeln!(out, "        let mut out = Vec::with_capacity(64);").unwrap();
        writeln!(
            out,
            "        nve_bin_codec::write_map(&mut out, {}, |out| {{",
            ev.params.len()
        )
        .unwrap();
        for param in &ev.params {
            let pname = rust_ident(&param.name);
            let key_lit = escape_string_literal(&param.name);
            writeln!(out, "            nve_bin_codec::write_map_key(out, \"{key_lit}\");").unwrap();
            emit_bin_write_expr(out, "            ", "out", &format!("&self.{pname}"), &param.ty);
        }
        writeln!(out, "        }});").unwrap();
        writeln!(out, "        out").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out).unwrap();

        // Zero-copy stack-allocated `NveDirectEvent` emitter
        writeln!(
            out,
            "    /// Emits a zero-copy `NveDirectEvent` backed by stack-allocated `NveMapEntry` values."
        )
        .unwrap();
        writeln!(
            out,
            "    pub fn emit_direct<F: FnOnce(&NveDirectEvent)>(&self, surface_id: u32, node_id: u32, timestamp_us: u64, sink: F) {{"
        )
        .unwrap();
        // Pre-encode any complex event fields into local `Vec<u8>` so stack `NveValue` references stay alive.
        for (idx, param) in ev.params.iter().enumerate() {
            if !is_direct_nve_value_scalar_or_slice(&param.ty) {
                let pname = rust_ident(&param.name);
                writeln!(out, "        let mut _bin_{idx} = Vec::with_capacity(32);").unwrap();
                emit_bin_write_expr(
                    out,
                    "        ",
                    &format!("&mut _bin_{idx}"),
                    &format!("&self.{pname}"),
                    &param.ty,
                );
            }
        }
        writeln!(out, "        let entries: [NveMapEntry; {}] = [", ev.params.len()).unwrap();
        for (idx, param) in ev.params.iter().enumerate() {
            let pname = rust_ident(&param.name);
            let key_lit = escape_string_literal(&param.name);
            let val_expr = direct_nve_value_expr(&format!("self.{pname}"), &param.ty, idx);
            writeln!(out, "            NveMapEntry::new(\"{key_lit}\", {val_expr}),").unwrap();
        }
        writeln!(out, "        ];").unwrap();
        let ev_name_lit = escape_string_literal(&ev.name);
        writeln!(
            out,
            "        let direct = NveDirectEvent::custom(surface_id, node_id, timestamp_us, \"{ev_name_lit}\", NveValue::map(&entries));"
        )
        .unwrap();
        writeln!(out, "        sink(&direct);").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();

        // Convenience top-level `emit_<event>` helper function
        writeln!(
            out,
            "/// Convenience zero-copy `NveDirectEvent` emitter for `{pascal}::{}`.",
            ev.name
        )
        .unwrap();
        write!(
            out,
            "pub fn emit_{snake}_{ev_snake}<F: FnOnce(&NveDirectEvent)>(surface_id: u32, node_id: u32, timestamp_us: u64"
        )
        .unwrap();
        for param in &ev.params {
            let pname = rust_ident(&param.name);
            write!(out, ", {pname}: {}", rust_owned_type(&param.ty)).unwrap();
        }
        writeln!(out, ", sink: F) {{").unwrap();
        write!(out, "    let payload = {ev_struct} {{").unwrap();
        for param in &ev.params {
            let pname = rust_ident(&param.name);
            write!(out, " {pname},").unwrap();
        }
        writeln!(out, " }};").unwrap();
        writeln!(
            out,
            "    payload.emit_direct(surface_id, node_id, timestamp_us, sink);"
        )
        .unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    emit_doc_comments(out, "", v.doc.as_deref());
    writeln!(out, "pub trait {pascal}Hybrid {{").unwrap();
    writeln!(out, "    fn apply_props(&mut self, props: {pascal}Props);").unwrap();
    for method in &v.methods {
        emit_doc_comments(out, "    ", method.doc.as_deref());
        emit_rust_trait_method(out, method);
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_rust_vtable_struct(out, &pascal, &v.methods, true, spec);
    emit_rust_vtable_builder(out, &pascal, &snake, &upper, &v.methods, true, spec);
}

fn emit_rust_trait_method(out: &mut String, method: &HybridMethodSpec) {
    let mname = rust_ident(&method.name);
    write!(out, "    fn {mname}(&mut self").unwrap();
    for p in &method.params {
        let pname = rust_ident(&p.name);
        write!(out, ", {pname}: {}", rust_param_type(&p.ty)).unwrap();
    }
    if method.return_type == HybridType::Void {
        writeln!(out, ");").unwrap();
    } else {
        writeln!(out, ") -> {};", rust_return_type(&method.return_type)).unwrap();
    }
}

fn emit_rust_vtable_struct(
    out: &mut String,
    pascal: &str,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    writeln!(out, "#[repr(C)]").unwrap();
    writeln!(out, "pub struct NveHybrid{pascal}VTable {{").unwrap();
    writeln!(out, "    pub abi_version: u32,").unwrap();
    writeln!(out, "    pub interface_id: u32,").unwrap();
    writeln!(out, "    pub schema_hash: u64,").unwrap();
    writeln!(out, "    pub create: unsafe extern \"C\" fn() -> NveAppHandle,").unwrap();
    writeln!(out, "    pub destroy: unsafe extern \"C\" fn(handle: NveAppHandle),").unwrap();
    writeln!(out, "    pub alloc_bytes: unsafe extern \"C\" fn(len: usize) -> NveHybridOwnedBytes,").unwrap();
    writeln!(out, "    pub free_bytes: unsafe extern \"C\" fn(buf: NveHybridOwnedBytes),").unwrap();
    if is_view {
        writeln!(
            out,
            "    pub set_props_direct: unsafe extern \"C\" fn(handle: NveAppHandle, entries: *const NveMapEntry, count: u32) -> i32,"
        )
        .unwrap();
    }
    for method in methods {
        let mname = rust_ident(&method.name);
        write!(out, "    pub {mname}: unsafe extern \"C\" fn(handle: NveAppHandle").unwrap();
        for p in &method.params {
            let pname = rust_ident(&p.name);
            write!(out, ", {pname}: {}", rust_c_abi_param_type(&p.ty, spec)).unwrap();
        }
        match &method.return_type {
            HybridType::Result { ok, .. } => {
                if !matches!(ok.as_ref(), HybridType::Void) {
                    write!(out, ", out_ok: *mut {}", rust_c_abi_return_type(ok, spec)).unwrap();
                }
                writeln!(out, ", out_err: *mut NveHybridOwnedBytes) -> i32,").unwrap();
            }
            HybridType::Void => writeln!(out, "),").unwrap(),
            other => writeln!(out, ") -> {},", rust_c_abi_return_type(other, spec)).unwrap(),
        }
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_rust_vtable_builder(
    out: &mut String,
    pascal: &str,
    snake: &str,
    upper: &str,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    writeln!(
        out,
        "/// Builds a static C-ABI vtable for any concrete `T: {pascal}Hybrid + Default + 'static`."
    )
    .unwrap();
    writeln!(
        out,
        "pub const fn build_{snake}_vtable<T: {pascal}Hybrid + Default + 'static>() -> NveHybrid{pascal}VTable {{"
    )
    .unwrap();
    writeln!(out, "    unsafe extern \"C\" fn _create<T: {pascal}Hybrid + Default + 'static>() -> NveAppHandle {{").unwrap();
    writeln!(out, "        Box::into_raw(Box::new(T::default())) as NveAppHandle").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    unsafe extern \"C\" fn _destroy<T: {pascal}Hybrid + Default + 'static>(handle: NveAppHandle) {{").unwrap();
    writeln!(out, "        if !handle.is_null() {{").unwrap();
    writeln!(out, "            let _ = unsafe {{ Box::from_raw(handle as *mut T) }};").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();

    if is_view {
        writeln!(
            out,
            "    unsafe extern \"C\" fn _set_props_direct<T: {pascal}Hybrid + Default + 'static>(handle: NveAppHandle, entries: *const NveMapEntry, count: u32) -> i32 {{"
        )
        .unwrap();
        writeln!(out, "        if handle.is_null() {{").unwrap();
        writeln!(out, "            return NveHybridStatus::NullHandle as i32;").unwrap();
        writeln!(out, "        }}").unwrap();
        writeln!(out, "        let slice = if entries.is_null() || count == 0 {{").unwrap();
        writeln!(out, "            &[]").unwrap();
        writeln!(out, "        }} else {{").unwrap();
        writeln!(out, "            unsafe {{ std::slice::from_raw_parts(entries, count as usize) }}").unwrap();
        writeln!(out, "        }};").unwrap();
        writeln!(out, "        match unsafe {{ {pascal}Props::decode_props_direct(slice) }} {{").unwrap();
        writeln!(out, "            Ok(props) => {{").unwrap();
        writeln!(out, "                let instance = unsafe {{ &mut *(handle as *mut T) }};").unwrap();
        writeln!(out, "                instance.apply_props(props);").unwrap();
        writeln!(out, "                NveHybridStatus::Ok as i32").unwrap();
        writeln!(out, "            }}").unwrap();
        writeln!(out, "            Err(_) => NveHybridStatus::InvalidArg as i32,").unwrap();
        writeln!(out, "        }}").unwrap();
        writeln!(out, "    }}").unwrap();
    }

    for method in methods {
        emit_rust_trampoline(out, pascal, method, spec);
    }

    writeln!(out, "    NveHybrid{pascal}VTable {{").unwrap();
    writeln!(out, "        abi_version: NVE_HYBRID_ABI_VERSION,").unwrap();
    writeln!(out, "        interface_id: NVE_HYBRID_{upper}_INTERFACE_ID,").unwrap();
    writeln!(out, "        schema_hash: NVE_HYBRID_{upper}_SCHEMA_HASH,").unwrap();
    writeln!(out, "        create: _create::<T>,").unwrap();
    writeln!(out, "        destroy: _destroy::<T>,").unwrap();
    writeln!(out, "        alloc_bytes: nve_hybrid_alloc_bytes,").unwrap();
    writeln!(out, "        free_bytes: nve_hybrid_free_bytes,").unwrap();
    if is_view {
        writeln!(out, "        set_props_direct: _set_props_direct::<T>,").unwrap();
    }
    for method in methods {
        let mname = rust_ident(&method.name);
        let raw_snake = to_snake_case(&method.name);
        writeln!(out, "        {mname}: _trampoline_{raw_snake}::<T>,").unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_rust_trampoline(
    out: &mut String,
    pascal: &str,
    method: &HybridMethodSpec,
    spec: &HybridFileSpec,
) {
    let mname = rust_ident(&method.name);
    let raw_snake = to_snake_case(&method.name);
    let is_result = method.return_type.is_result();

    write!(
        out,
        "    unsafe extern \"C\" fn _trampoline_{raw_snake}<T: {pascal}Hybrid + Default + 'static>(handle: NveAppHandle"
    )
    .unwrap();
    for p in &method.params {
        let pname = rust_ident(&p.name);
        write!(out, ", {pname}: {}", rust_c_abi_param_type(&p.ty, spec)).unwrap();
    }
    match &method.return_type {
        HybridType::Result { ok, .. } => {
            if !matches!(ok.as_ref(), HybridType::Void) {
                write!(out, ", out_ok: *mut {}", rust_c_abi_return_type(ok, spec)).unwrap();
            }
            writeln!(out, ", out_err: *mut NveHybridOwnedBytes) -> i32 {{").unwrap();
        }
        HybridType::Void => writeln!(out, ") {{").unwrap(),
        other => writeln!(out, ") -> {} {{", rust_c_abi_return_type(other, spec)).unwrap(),
    }

    // Handle null check
    writeln!(out, "        if handle.is_null() {{").unwrap();
    if is_result {
        writeln!(out, "            if !out_err.is_null() {{").unwrap();
        writeln!(
            out,
            "                unsafe {{ *out_err = NveHybridOwnedBytes::from_string(\"null hybrid handle\".to_string()); }}"
        )
        .unwrap();
        writeln!(out, "            }}").unwrap();
        writeln!(out, "            return NveHybridStatus::NullHandle as i32;").unwrap();
    } else if method.return_type == HybridType::Void {
        writeln!(out, "            return;").unwrap();
    } else {
        writeln!(
            out,
            "            return {};",
            rust_c_abi_zero_value(&method.return_type, spec)
        )
        .unwrap();
    }
    writeln!(out, "        }}").unwrap();

    // Decode input params
    let mut call_args = Vec::new();
    for p in &method.params {
        let pname = rust_ident(&p.name);
        let decoded = format!("_arg_{}", to_snake_case(&p.name));
        emit_rust_param_decode(out, &pname, &decoded, &p.ty, &method.return_type, spec);
        call_args.push(decoded);
    }

    writeln!(out, "        let instance = unsafe {{ &mut *(handle as *mut T) }};").unwrap();
    let args_joined = call_args.join(", ");

    match &method.return_type {
        HybridType::Void => {
            writeln!(out, "        instance.{mname}({args_joined});").unwrap();
        }
        HybridType::Result { ok, .. } => {
            writeln!(out, "        match instance.{mname}({args_joined}) {{").unwrap();
            if matches!(ok.as_ref(), HybridType::Void) {
                writeln!(out, "            Ok(()) => {{").unwrap();
                writeln!(out, "                if !out_err.is_null() {{").unwrap();
                writeln!(out, "                    unsafe {{ *out_err = NveHybridOwnedBytes::EMPTY; }}").unwrap();
                writeln!(out, "                }}").unwrap();
                writeln!(out, "                NveHybridStatus::Ok as i32").unwrap();
                writeln!(out, "            }}").unwrap();
            } else {
                writeln!(out, "            Ok(val) => {{").unwrap();
                writeln!(out, "                if !out_ok.is_null() {{").unwrap();
                let encoded = rust_return_encode_expr("val", ok, spec);
                writeln!(out, "                    unsafe {{ *out_ok = {encoded}; }}").unwrap();
                writeln!(out, "                }}").unwrap();
                writeln!(out, "                if !out_err.is_null() {{").unwrap();
                writeln!(out, "                    unsafe {{ *out_err = NveHybridOwnedBytes::EMPTY; }}").unwrap();
                writeln!(out, "                }}").unwrap();
                writeln!(out, "                NveHybridStatus::Ok as i32").unwrap();
                writeln!(out, "            }}").unwrap();
            }
            writeln!(out, "            Err(msg) => {{").unwrap();
            writeln!(out, "                if !out_err.is_null() {{").unwrap();
            writeln!(
                out,
                "                    unsafe {{ *out_err = NveHybridOwnedBytes::from_string(msg); }}"
            )
            .unwrap();
            writeln!(out, "                }}").unwrap();
            writeln!(out, "                NveHybridStatus::Err as i32").unwrap();
            writeln!(out, "            }}").unwrap();
            writeln!(out, "        }}").unwrap();
        }
        other => {
            writeln!(out, "        let _ret = instance.{mname}({args_joined});").unwrap();
            let encoded = rust_return_encode_expr("_ret", other, spec);
            writeln!(out, "        {encoded}").unwrap();
        }
    }

    writeln!(out, "    }}").unwrap();
}

fn emit_rust_param_decode(
    out: &mut String,
    raw_name: &str,
    dst_name: &str,
    ty: &HybridType,
    method_ret: &HybridType,
    spec: &HybridFileSpec,
) {
    let invalid_return = if method_ret.is_result() {
        format!(
            "{{ if !out_err.is_null() {{ unsafe {{ *out_err = NveHybridOwnedBytes::from_string(\"invalid hybrid argument '{raw_name}'\".to_string()); }} }} return NveHybridStatus::InvalidArg as i32; }}"
        )
    } else if *method_ret == HybridType::Void {
        "{ return; }".to_string()
    } else {
        format!("{{ return {}; }}", rust_c_abi_zero_value(method_ret, spec))
    };

    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64 => {
            writeln!(out, "        let {dst_name} = {raw_name};").unwrap();
        }
        HybridType::Enum(e) => {
            writeln!(
                out,
                "        let {dst_name} = match {e}::from_u32({raw_name}) {{ Some(v) => v, None => {invalid_return} }};"
            )
            .unwrap();
        }
        HybridType::Struct(_) if ty.is_pod(spec) => {
            writeln!(out, "        let {dst_name} = {raw_name};").unwrap();
        }
        HybridType::String => {
            writeln!(
                out,
                "        let {dst_name} = match unsafe {{ {raw_name}.as_str() }} {{ Ok(s) => s, Err(_) => {invalid_return} }};"
            )
            .unwrap();
        }
        HybridType::Bytes => {
            writeln!(
                out,
                "        let {dst_name} = unsafe {{ {raw_name}.as_slice() }};"
            )
            .unwrap();
        }
        HybridType::Value => {
            writeln!(
                out,
                "        let {dst_name} = match NveHybridValue::from_ffi_ref(unsafe {{ {raw_name}.as_ref() }}) {{ Ok(v) => v, Err(_) => {invalid_return} }};"
            )
            .unwrap();
        }
        HybridType::Optional(inner) if inner.is_pod(spec) => match inner.as_ref() {
            HybridType::Enum(e) => {
                writeln!(
                    out,
                    "        let {dst_name} = if {raw_name}.is_some {{ match {e}::from_u32({raw_name}.value) {{ Some(v) => Some(v), None => {invalid_return} }} }} else {{ None }};"
                )
                .unwrap();
            }
            _ => {
                writeln!(
                    out,
                    "        let {dst_name} = if {raw_name}.is_some {{ Some({raw_name}.value) }} else {{ None }};"
                )
                .unwrap();
            }
        },
        // Non-POD Struct, Vec<T>, Optional<non-POD>: compact binary NveBinValue slice
        other => {
            writeln!(
                out,
                "        let _{dst_name}_view = match nve_bin_codec::parse_view(unsafe {{ {raw_name}.as_slice() }}) {{ Ok(v) => v, Err(_) => {invalid_return} }};"
            )
            .unwrap();
            let decode_expr = bin_view_decode_expr(&format!("_{dst_name}_view"), other);
            writeln!(
                out,
                "        let {dst_name} = match (|| -> Result<_, DecodeError> {{ Ok({decode_expr}) }})() {{ Ok(v) => v, Err(_) => {invalid_return} }};"
            )
            .unwrap();
        }
    }
}

fn rust_return_encode_expr(expr: &str, ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64 => expr.to_string(),
        HybridType::Enum(_) => format!("{expr}.to_u32()"),
        HybridType::Struct(_) if ty.is_pod(spec) => expr.to_string(),
        HybridType::String => format!("NveHybridOwnedBytes::from_string({expr})"),
        HybridType::Bytes => format!("NveHybridOwnedBytes::from_vec({expr})"),
        HybridType::Value => format!("NveHybridOwnedBytes::from_vec({expr}.bin_bytes)"),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            let suffix = inner.pod_opt_suffix().unwrap();
            match inner.as_ref() {
                HybridType::Enum(_) => format!(
                    "match {expr} {{ Some(v) => NveHybridOpt{suffix} {{ is_some: true, value: v.to_u32() }}, None => NveHybridOpt{suffix} {{ is_some: false, value: 0 }} }}"
                ),
                _ => format!(
                    "match {expr} {{ Some(v) => NveHybridOpt{suffix} {{ is_some: true, value: v }}, None => NveHybridOpt{suffix} {{ is_some: false, value: Default::default() }} }}"
                ),
            }
        }
        other => {
            let mut body = String::new();
            writeln!(body, "{{").unwrap();
            writeln!(body, "            let mut _bin = Vec::with_capacity(64);").unwrap();
            emit_bin_write_expr(&mut body, "            ", "&mut _bin", &format!("&{expr}"), other);
            writeln!(body, "            NveHybridOwnedBytes::from_vec(_bin)").unwrap();
            write!(body, "        }}").unwrap();
            body
        }
    }
}

fn rust_owned_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Void => "()".to_string(),
        HybridType::Bool => "bool".to_string(),
        HybridType::U8 => "u8".to_string(),
        HybridType::U16 => "u16".to_string(),
        HybridType::Usize => "usize".to_string(),
        HybridType::I32 => "i32".to_string(),
        HybridType::U32 => "u32".to_string(),
        HybridType::I64 => "i64".to_string(),
        HybridType::U64 => "u64".to_string(),
        HybridType::F32 => "f32".to_string(),
        HybridType::F64 => "f64".to_string(),
        HybridType::String => "String".to_string(),
        HybridType::Bytes => "Vec<u8>".to_string(),
        HybridType::Optional(inner) => format!("Option<{}>", rust_owned_type(inner)),
        HybridType::Vec(inner) => format!("Vec<{}>", rust_owned_type(inner)),
        HybridType::Result { ok, err } => {
            format!("Result<{}, {}>", rust_owned_type(ok), rust_owned_type(err))
        }
        HybridType::Struct(name) | HybridType::Enum(name) | HybridType::Handle(name) => {
            name.clone()
        }
        HybridType::Value => "NveHybridValue".to_string(),
        HybridType::ConstPtr(inner) => format!(
            "*const {}",
            if matches!(inner.as_ref(), HybridType::Void) {
                "std::ffi::c_void".to_string()
            } else {
                rust_owned_type(inner)
            }
        ),
        HybridType::MutPtr(inner) => format!(
            "*mut {}",
            if matches!(inner.as_ref(), HybridType::Void) {
                "std::ffi::c_void".to_string()
            } else {
                rust_owned_type(inner)
            }
        ),
    }
}

fn rust_param_type(ty: &HybridType) -> String {
    match ty {
        HybridType::String => "&str".to_string(),
        HybridType::Bytes => "&[u8]".to_string(),
        other => rust_owned_type(other),
    }
}

fn rust_return_type(ty: &HybridType) -> String {
    rust_owned_type(ty)
}

fn rust_c_abi_pod_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Bool => "bool".to_string(),
        HybridType::U8 => "u8".to_string(),
        HybridType::U16 => "u16".to_string(),
        HybridType::Usize => "usize".to_string(),
        HybridType::I32 => "i32".to_string(),
        HybridType::U32 => "u32".to_string(),
        HybridType::I64 => "i64".to_string(),
        HybridType::U64 => "u64".to_string(),
        HybridType::F32 => "f32".to_string(),
        HybridType::F64 => "f64".to_string(),
        HybridType::Enum(_) => "u32".to_string(),
        HybridType::Struct(name) => name.clone(),
        _ => unreachable!("non-POD type passed to rust_c_abi_pod_type"),
    }
}

fn rust_c_abi_param_type(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::Enum(_) => rust_c_abi_pod_type(ty),
        HybridType::Struct(_) if ty.is_pod(spec) => rust_c_abi_pod_type(ty),
        HybridType::String => "NveStrSlice".to_string(),
        HybridType::Bytes => "NveBufferSlice".to_string(),
        HybridType::Value => "NveValue".to_string(),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            format!("NveHybridOpt{}", inner.pod_opt_suffix().unwrap())
        }
        _ => "NveBufferSlice".to_string(),
    }
}

fn rust_c_abi_return_type(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Void => "()".to_string(),
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::Enum(_) => rust_c_abi_pod_type(ty),
        HybridType::Struct(_) if ty.is_pod(spec) => rust_c_abi_pod_type(ty),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            format!("NveHybridOpt{}", inner.pod_opt_suffix().unwrap())
        }
        _ => "NveHybridOwnedBytes".to_string(),
    }
}

fn rust_c_abi_zero_value(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Bool => "false".to_string(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::Enum(_) => "0".to_string(),
        HybridType::F32 | HybridType::F64 => "0.0".to_string(),
        HybridType::Struct(name) if ty.is_pod(spec) => format!("{name}::default()"),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            let suffix = inner.pod_opt_suffix().unwrap();
            let zero_inner = rust_c_abi_zero_value(inner, spec);
            format!("NveHybridOpt{suffix} {{ is_some: false, value: {zero_inner} }}")
        }
        _ => "NveHybridOwnedBytes::EMPTY".to_string(),
    }
}

fn emit_bin_write_expr(out: &mut String, indent: &str, buf: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}nve_bin_codec::write_bool({buf}, *{expr});").unwrap(),
        HybridType::U8 | HybridType::U16 | HybridType::Usize | HybridType::I32 | HybridType::U32 | HybridType::U64 => {
            writeln!(out, "{indent}nve_bin_codec::write_i64({buf}, (*{expr}) as i64);").unwrap()
        }
        HybridType::I64 => writeln!(out, "{indent}nve_bin_codec::write_i64({buf}, *{expr});").unwrap(),
        HybridType::F32 => writeln!(out, "{indent}nve_bin_codec::write_f64({buf}, (*{expr}) as f64);").unwrap(),
        HybridType::F64 => writeln!(out, "{indent}nve_bin_codec::write_f64({buf}, *{expr});").unwrap(),
        HybridType::Enum(_) => writeln!(out, "{indent}nve_bin_codec::write_i64({buf}, ({expr}).to_u32() as i64);").unwrap(),
        HybridType::String => writeln!(out, "{indent}nve_bin_codec::write_str({buf}, ({expr}).as_str());").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}nve_bin_codec::write_bytes({buf}, ({expr}).as_slice());").unwrap(),
        HybridType::Struct(_) => writeln!(out, "{indent}({expr}).encode_bin({buf});").unwrap(),
        HybridType::Value => writeln!(out, "{indent}({buf}).extend_from_slice(&({expr}).bin_bytes);").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}match {expr} {{").unwrap();
            writeln!(out, "{indent}    Some(_opt_v) => {{").unwrap();
            emit_bin_write_expr(out, &format!("{indent}        "), buf, "_opt_v", inner);
            writeln!(out, "{indent}    }}").unwrap();
            writeln!(out, "{indent}    None => nve_bin_codec::write_null({buf}),").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}nve_bin_codec::write_array({buf}, ({expr}).len(), |out| {{").unwrap();
            writeln!(out, "{indent}    for _elem in ({expr}).iter() {{").unwrap();
            emit_bin_write_expr(out, &format!("{indent}        "), "out", "_elem", inner);
            writeln!(out, "{indent}    }}").unwrap();
            writeln!(out, "{indent}}});").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {
            writeln!(out, "{indent}nve_bin_codec::write_null({buf});").unwrap();
        }
    }
}

fn bin_view_decode_expr(var: &str, ty: &HybridType) -> String {
    match ty {
        HybridType::Bool => format!("{var}.as_bool().ok_or(DecodeError::Truncated)?"),
        HybridType::U8 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u8"),
        HybridType::U16 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u16"),
        HybridType::Usize => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as usize"),
        HybridType::I32 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as i32"),
        HybridType::U32 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u32"),
        HybridType::I64 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)?"),
        HybridType::U64 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u64"),
        HybridType::F32 => format!("{var}.as_number().ok_or(DecodeError::Truncated)? as f32"),
        HybridType::F64 => format!("{var}.as_number().ok_or(DecodeError::Truncated)?"),
        HybridType::String => format!("{var}.as_str().ok_or(DecodeError::Truncated)?.to_string()"),
        HybridType::Bytes => format!("{var}.as_bytes().ok_or(DecodeError::Truncated)?.to_vec()"),
        HybridType::Enum(name) => format!(
            "{{ let _raw = {var}.as_i64().ok_or(DecodeError::Truncated)? as u32; {name}::from_u32(_raw).ok_or(DecodeError::InvalidEnum(\"{name}\", _raw))? }}"
        ),
        HybridType::Struct(name) => format!("{name}::decode_bin({var})?"),
        HybridType::Value => format!("NveHybridValue {{ bin_bytes: {var}.as_raw_bytes().to_vec() }}"),
        HybridType::Optional(inner) => {
            let inner_expr = bin_view_decode_expr(var, inner);
            format!("if {var}.is_null() {{ None }} else {{ Some({inner_expr}) }}")
        }
        HybridType::Vec(inner) => {
            let elem_expr = bin_view_decode_expr("_item", inner);
            format!(
                "{{ let mut _vec = Vec::new(); for _item in {var}.as_array().ok_or(DecodeError::Truncated)? {{ _vec.push({elem_expr}); }} _vec }}"
            )
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => "()".to_string(),
    }
}

fn value_ref_decode_expr(var: &str, ty: &HybridType) -> String {
    match ty {
        HybridType::Bool => format!("{var}.as_bool().ok_or(DecodeError::Truncated)?"),
        HybridType::U8 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u8"),
        HybridType::U16 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u16"),
        HybridType::Usize => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as usize"),
        HybridType::I32 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as i32"),
        HybridType::U32 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u32"),
        HybridType::I64 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)?"),
        HybridType::U64 => format!("{var}.as_i64().ok_or(DecodeError::Truncated)? as u64"),
        HybridType::F32 => format!("{var}.as_number().ok_or(DecodeError::Truncated)? as f32"),
        HybridType::F64 => format!("{var}.as_number().ok_or(DecodeError::Truncated)?"),
        HybridType::String => format!("{var}.as_str().ok_or(DecodeError::Truncated)?.to_string()"),
        HybridType::Bytes => format!("{var}.as_bytes().ok_or(DecodeError::Truncated)?.to_vec()"),
        HybridType::Enum(name) => format!(
            "{{ let _raw = {var}.as_i64().ok_or(DecodeError::Truncated)? as u32; {name}::from_u32(_raw).ok_or(DecodeError::InvalidEnum(\"{name}\", _raw))? }}"
        ),
        HybridType::Struct(name) => format!(
            "if let Some(_raw) = {var}.as_bytes() {{ {name}::decode_bin(nve_bin_codec::parse_view(_raw)?)? }} else {{ {name}::decode_value_ref({var})? }}"
        ),
        HybridType::Value => format!("NveHybridValue::from_ffi_ref({var})?"),
        HybridType::Optional(inner) => {
            let inner_expr = value_ref_decode_expr(var, inner);
            format!("if {var}.is_null() {{ None }} else {{ Some({inner_expr}) }}")
        }
        HybridType::Vec(inner) => {
            let elem_ref_expr = value_ref_decode_expr("_item", inner);
            let elem_bin_expr = bin_view_decode_expr("_item", inner);
            format!(
                "if let Some(_raw) = {var}.as_bytes() {{ let _bv = nve_bin_codec::parse_view(_raw)?; let mut _vec = Vec::new(); for _item in _bv.as_array().ok_or(DecodeError::Truncated)? {{ _vec.push({elem_bin_expr}); }} _vec }} else {{ let mut _vec = Vec::new(); for _item in {var}.as_array().ok_or(DecodeError::Truncated)?.iter() {{ _vec.push({elem_ref_expr}); }} _vec }}"
            )
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => "()".to_string(),
    }
}

fn is_direct_nve_value_scalar_or_slice(ty: &HybridType) -> bool {
    matches!(
        ty,
        HybridType::Bool
            | HybridType::U8
            | HybridType::U16
            | HybridType::Usize
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64
            | HybridType::F32
            | HybridType::F64
            | HybridType::Enum(_)
            | HybridType::String
            | HybridType::Bytes
    )
}

fn direct_nve_value_expr(expr: &str, ty: &HybridType, idx: usize) -> String {
    match ty {
        HybridType::Bool => format!("NveValue::bool({expr})"),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => {
            format!("NveValue::i64({expr} as i64)")
        }
        HybridType::F32 | HybridType::F64 => format!("NveValue::f64({expr} as f64)"),
        HybridType::Enum(_) => format!("NveValue::i64({expr}.to_u32() as i64)"),
        HybridType::String => format!("NveValue::from_str({expr}.as_str())"),
        HybridType::Bytes => format!("NveValue::from_bytes({expr}.as_slice())"),
        _ => format!("NveValue::from_bytes(_bin_{idx}.as_slice())"),
    }
}

fn rust_prop_default_expr(ty: &HybridType, def: Option<&HybridDefaultValue>) -> String {
    let Some(def) = def else {
        return "Default::default()".to_string();
    };
    if let HybridType::Optional(inner) = ty {
        return match def {
            HybridDefaultValue::None => "None".to_string(),
            other => format!("Some({})", rust_prop_default_expr(inner, Some(other))),
        };
    }
    match (def, ty) {
        (HybridDefaultValue::Bool(b), _) => b.to_string(),
        (HybridDefaultValue::Int(i), HybridType::F32 | HybridType::F64) => format!("{i}.0"),
        (HybridDefaultValue::Int(i), _) => i.to_string(),
        (HybridDefaultValue::UInt(u), HybridType::F32 | HybridType::F64) => format!("{u}.0"),
        (HybridDefaultValue::UInt(u), _) => u.to_string(),
        (HybridDefaultValue::Float(f), _) => format_float_literal(*f),
        (HybridDefaultValue::String(s), _) => {
            format!("\"{}\".to_string()", escape_string_literal(s))
        }
        (HybridDefaultValue::EnumVariant { enum_name, variant }, _) => {
            format!("{enum_name}::{variant}")
        }
        (HybridDefaultValue::None, _) => "Default::default()".to_string(),
    }
}
