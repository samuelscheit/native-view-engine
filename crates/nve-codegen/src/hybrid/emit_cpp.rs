//! C11 & C++20 target emitter for NVE Hybrid FFI codegen.
//!
//! Emits two clean, zero-JSON headers:
//! 1. `<Stem>HybridAbi.h`: pure C11 header including `nve_abi.h`, declaring
//!    `NVE_HYBRID_<NAME>_INTERFACE_ID`, `NVE_HYBRID_<NAME>_SCHEMA_HASH`, `#[repr(C)]` POD
//!    structs/enums, `NveHybridOwnedBytes`, POD `NveHybridOpt*`, and `NveHybrid<Name>VTable`.
//! 2. `<Stem>HybridSpec.hpp`: C++20 `namespace nve::hybrid` with `enum class`, native structs,
//!    compact binary `NveBinValue` reader/writer, Nitro-style abstract `class Hybrid<Name>Spec`,
//!    and zero-overhead RAII `class <Name>Client` resolving `nve_get_interface` + checking
//!    `schema_hash` on construction.

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::hybrid::ir::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::ir::GeneratedFile;
use crate::naming::{
    cpp_ident, escape_string_literal, format_float_literal, to_camel_case, to_pascal_case,
    to_snake_case,
};

/// Emits `<Stem>HybridAbi.h` (pure C11) and `<Stem>HybridSpec.hpp` (C++20).
pub fn generate_hybrid_cpp(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_pascal();
    let header_name = format!("{stem}HybridAbi.h");
    let hpp_name = format!("{stem}HybridSpec.hpp");

    let c_header = emit_c11_header(spec);
    let cpp_header = emit_cpp20_spec(spec, &header_name);

    Ok(vec![
        GeneratedFile {
            relative_path: header_name,
            content: c_header,
        },
        GeneratedFile {
            relative_path: hpp_name,
            content: cpp_header,
        },
    ])
}

fn emit_c11_header(spec: &HybridFileSpec) -> String {
    let mut out = String::with_capacity(8 * 1024);
    writeln!(out, "// @generated by nve-codegen (hybrid C11 ABI header) — DO NOT EDIT.").unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <stdbool.h>").unwrap();
    writeln!(out, "#include <stddef.h>").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    writeln!(out, "#include \"nve_abi.h\"").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#ifdef __cplusplus").unwrap();
    writeln!(out, "extern \"C\" {{").unwrap();
    writeln!(out, "#endif").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "#ifndef NVE_HYBRID_ABI_COMMON_DEFINED").unwrap();
    writeln!(out, "#define NVE_HYBRID_ABI_COMMON_DEFINED 1").unwrap();
    writeln!(out, "#define NVE_HYBRID_ABI_VERSION {NVE_HYBRID_ABI_VERSION}u").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "typedef enum NveHybridStatus {{").unwrap();
    writeln!(out, "  NVE_HYBRID_OK = 0,").unwrap();
    writeln!(out, "  NVE_HYBRID_ERR = 1,").unwrap();
    writeln!(out, "  NVE_HYBRID_ERR_INVALID_ARG = 2,").unwrap();
    writeln!(out, "  NVE_HYBRID_ERR_SCHEMA_MISMATCH = 3,").unwrap();
    writeln!(out, "  NVE_HYBRID_ERR_NULL_HANDLE = 4,").unwrap();
    writeln!(out, "}} NveHybridStatus;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "typedef struct NveHybridOwnedBytes {{").unwrap();
    writeln!(out, "  uint8_t* ptr;").unwrap();
    writeln!(out, "  size_t len;").unwrap();
    writeln!(out, "  size_t cap;").unwrap();
    writeln!(out, "}} NveHybridOwnedBytes;").unwrap();
    writeln!(out, "#endif /* NVE_HYBRID_ABI_COMMON_DEFINED */").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "#define NVE_HYBRID_{}_FILE_SCHEMA_HASH UINT64_C(0x{:016X})",
        to_snake_case(&spec.stem_pascal()).to_ascii_uppercase(),
        spec.file_schema_hash()
    )
    .unwrap();
    writeln!(out).unwrap();

    // Enums (`typedef uint32_t` guarantees exact 4-byte unsigned ABI across C11/C++/Swift/Rust/Dart)
    for e in &spec.enums {
        let e_upper = to_snake_case(&e.name).to_ascii_uppercase();
        writeln!(out, "typedef uint32_t NveHybrid{};", e.name).unwrap();
        writeln!(out, "enum {{").unwrap();
        for v in &e.variants {
            let v_upper = to_snake_case(&v.name).to_ascii_uppercase();
            writeln!(out, "  NVE_HYBRID_{e_upper}_{v_upper} = {}u,", v.value).unwrap();
        }
        writeln!(out, "}};").unwrap();
        writeln!(out).unwrap();
    }

    // POD structs (topological order so embedded POD fields are always complete)
    for s in spec.structs_topological() {
        if !s.is_pod(spec) {
            continue;
        }
        writeln!(out, "typedef struct NveHybrid{} {{", s.name).unwrap();
        for f in &s.fields {
            let fname = c_field_ident(&f.name);
            writeln!(out, "  {} {fname};", c_pod_type(&f.ty)).unwrap();
        }
        writeln!(out, "}} NveHybrid{};", s.name).unwrap();
        if let Some(sz) = s.expected_size {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof(NveHybrid{}) == {sz}u, \"NveHybrid{} size must be {sz}\");",
                s.name, s.name
            )
            .unwrap();
        }
        if let Some(sz64) = s.expected_size_64 {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveHybrid{}) == {sz64}u, \"NveHybrid{} size must be {sz64} on 64-bit\");",
                s.name, s.name
            )
            .unwrap();
        }
        for f in &s.fields {
            let fname = c_field_ident(&f.name);
            if let Some(off) = f.offset {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveHybrid{}, {fname}) == {off}u, \"NveHybrid{}::{fname} offset must be {off}\");",
                    s.name, s.name
                )
                .unwrap();
            }
            if let Some(off64) = f.offset_64 {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 8 || offsetof(NveHybrid{}, {fname}) == {off64}u, \"NveHybrid{}::{fname} offset must be {off64} on 64-bit\");",
                    s.name, s.name
                )
                .unwrap();
            }
        }
        writeln!(out).unwrap();
    }

    // POD Optional<T> structs
    for inner in spec.collect_pod_option_types() {
        let suffix = inner.pod_opt_suffix().unwrap();
        writeln!(out, "typedef struct NveHybridOpt{suffix} {{").unwrap();
        writeln!(out, "  bool is_some;").unwrap();
        writeln!(out, "  {} value;", c_pod_type(&inner)).unwrap();
        writeln!(out, "}} NveHybridOpt{suffix};").unwrap();
        writeln!(out).unwrap();
    }

    // Module vtables
    for m in &spec.modules {
        emit_c11_vtable(
            &mut out,
            &m.name,
            m.interface_id(),
            m.schema_hash(spec),
            &m.methods,
            false,
            spec,
        );
    }

    // View vtables
    for v in &spec.views {
        emit_c11_vtable(
            &mut out,
            &v.name,
            v.interface_id(),
            v.schema_hash(spec),
            &v.methods,
            true,
            spec,
        );
    }

    writeln!(out, "#ifdef __cplusplus").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out, "#endif").unwrap();
    out
}

fn emit_c11_vtable(
    out: &mut String,
    name: &str,
    interface_id: u32,
    schema_hash: u64,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    let pascal = to_pascal_case(name);
    let upper = to_snake_case(name).to_ascii_uppercase();

    writeln!(out, "#define NVE_HYBRID_{upper}_INTERFACE_ID UINT32_C(0x{interface_id:08X})").unwrap();
    writeln!(out, "#define NVE_HYBRID_{upper}_SCHEMA_HASH UINT64_C(0x{schema_hash:016X})").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "typedef struct NveHybrid{pascal}VTable {{").unwrap();
    writeln!(out, "  uint32_t abi_version;").unwrap();
    writeln!(out, "  uint32_t interface_id;").unwrap();
    writeln!(out, "  uint64_t schema_hash;").unwrap();
    writeln!(out, "  NveAppHandle (*create)(void);").unwrap();
    writeln!(out, "  void (*destroy)(NveAppHandle handle);").unwrap();
    writeln!(out, "  NveHybridOwnedBytes (*alloc_bytes)(size_t len);").unwrap();
    writeln!(out, "  void (*free_bytes)(NveHybridOwnedBytes buf);").unwrap();
    if is_view {
        writeln!(
            out,
            "  int32_t (*set_props_direct)(NveAppHandle handle, const NveMapEntry* entries, uint32_t count);"
        )
        .unwrap();
    }
    for m in methods {
        let mname = c_field_ident(&m.name);
        let ret_ty = match &m.return_type {
            HybridType::Result { .. } => "int32_t".to_string(),
            HybridType::Void => "void".to_string(),
            other => c_return_type(other, spec),
        };
        write!(out, "  {ret_ty} (*{mname})(NveAppHandle handle").unwrap();
        for p in &m.params {
            let pname = c_field_ident(&p.name);
            write!(out, ", {} {pname}", c_param_type(&p.ty, spec)).unwrap();
        }
        if let HybridType::Result { ok, .. } = &m.return_type {
            if !matches!(ok.as_ref(), HybridType::Void) {
                write!(out, ", {}* out_ok", c_return_type(ok, spec)).unwrap();
            }
            write!(out, ", NveHybridOwnedBytes* out_err").unwrap();
        }
        writeln!(out, ");").unwrap();
    }
    writeln!(out, "}} NveHybrid{pascal}VTable;").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp20_spec(spec: &HybridFileSpec, abi_header: &str) -> String {
    let mut out = String::with_capacity(16 * 1024);
    writeln!(out, "// @generated by nve-codegen (hybrid C++20 Spec & Client) — DO NOT EDIT.").unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <cstddef>").unwrap();
    writeln!(out, "#include <cstdint>").unwrap();
    writeln!(out, "#include <cstring>").unwrap();
    writeln!(out, "#include <optional>").unwrap();
    writeln!(out, "#include <span>").unwrap();
    writeln!(out, "#include <stdexcept>").unwrap();
    writeln!(out, "#include <string>").unwrap();
    writeln!(out, "#include <string_view>").unwrap();
    writeln!(out, "#include <utility>").unwrap();
    writeln!(out, "#include <vector>").unwrap();
    writeln!(out, "#include \"{abi_header}\"").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace nve::hybrid {{").unwrap();
    writeln!(out).unwrap();

    emit_cpp_bin_codec(&mut out);

    for e in &spec.enums {
        emit_cpp_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_cpp_struct(&mut out, s, spec);
    }

    for m in &spec.modules {
        emit_cpp_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_cpp_view(&mut out, v, spec);
    }

    writeln!(out, "}} // namespace nve::hybrid").unwrap();
    out
}

fn emit_cpp_bin_codec(out: &mut String) {
    writeln!(
        out,
        r#"#ifndef NVE_HYBRID_CPP_COMMON_DEFINED
#define NVE_HYBRID_CPP_COMMON_DEFINED 1

/// Owned dynamic value encoded in NVE's compact binary `NveBinValue` format (zero JSON).
struct DynamicValue {{
  std::vector<uint8_t> bin_bytes;
}};

/// Compact binary `NveBinValue` encoder matching `nve_abi::encode_bin_value` byte-for-byte.
class BinWriter {{
 public:
  void write_null() {{ buf_.push_back(static_cast<uint8_t>(NVE_VAL_NULL)); }}

  void write_bool(bool v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_BOOL));
    buf_.push_back(v ? 1u : 0u);
  }}

  void write_i64(int64_t v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_I64));
    write_le64(static_cast<uint64_t>(v));
  }}

  void write_f64(double v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_F64));
    uint64_t bits = 0;
    std::memcpy(&bits, &v, sizeof(bits));
    write_le64(bits);
  }}

  void write_str(std::string_view s) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_STR));
    write_le32(static_cast<uint32_t>(s.size()));
    const auto* p = reinterpret_cast<const uint8_t*>(s.data());
    buf_.insert(buf_.end(), p, p + s.size());
  }}

  void write_bytes(std::span<const uint8_t> b) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_BYTES));
    write_le32(static_cast<uint32_t>(b.size()));
    buf_.insert(buf_.end(), b.begin(), b.end());
  }}

  void write_raw(std::span<const uint8_t> raw) {{
    buf_.insert(buf_.end(), raw.begin(), raw.end());
  }}

  template <typename Fn>
  void write_array(uint32_t count, Fn&& fn) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_ARRAY));
    const size_t len_pos = buf_.size();
    write_le32(0);
    const size_t start = buf_.size();
    write_le32(count);
    fn(*this);
    patch_le32(len_pos, static_cast<uint32_t>(buf_.size() - start));
  }}

  template <typename Fn>
  void write_map(uint32_t count, Fn&& fn) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_MAP));
    const size_t len_pos = buf_.size();
    write_le32(0);
    const size_t start = buf_.size();
    write_le32(count);
    fn(*this);
    patch_le32(len_pos, static_cast<uint32_t>(buf_.size() - start));
  }}

  void write_map_key(std::string_view key) {{
    write_le32(static_cast<uint32_t>(key.size()));
    const auto* p = reinterpret_cast<const uint8_t*>(key.data());
    buf_.insert(buf_.end(), p, p + key.size());
  }}

  const std::vector<uint8_t>& bytes() const noexcept {{ return buf_; }}
  NveBufferSlice slice() const noexcept {{ return NveBufferSlice{{buf_.data(), buf_.size()}}; }}

 private:
  void write_le32(uint32_t v) {{
    buf_.push_back(static_cast<uint8_t>(v & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 8) & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 16) & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 24) & 0xFFu));
  }}

  void patch_le32(size_t pos, uint32_t v) {{
    buf_[pos] = static_cast<uint8_t>(v & 0xFFu);
    buf_[pos + 1] = static_cast<uint8_t>((v >> 8) & 0xFFu);
    buf_[pos + 2] = static_cast<uint8_t>((v >> 16) & 0xFFu);
    buf_[pos + 3] = static_cast<uint8_t>((v >> 24) & 0xFFu);
  }}

  void write_le64(uint64_t v) {{
    for (int i = 0; i < 8; ++i) {{
      buf_.push_back(static_cast<uint8_t>((v >> (i * 8)) & 0xFFu));
    }}
  }}

  std::vector<uint8_t> buf_;
}};

/// Bounds-checked zero-copy reader for compact binary `NveBinValue` payloads.
class BinReader {{
 public:
  explicit BinReader(std::span<const uint8_t> data) noexcept : data_(data) {{}}

  uint8_t peek_tag() const {{
    if (pos_ >= data_.size()) {{
      throw std::runtime_error("truncated NveBinValue");
    }}
    return data_[pos_];
  }}

  bool read_null_if_present() {{
    if (peek_tag() == static_cast<uint8_t>(NVE_VAL_NULL)) {{
      ++pos_;
      return true;
    }}
    return false;
  }}

  bool read_bool() {{
    expect_tag(NVE_VAL_BOOL);
    require(1);
    return data_[pos_++] != 0;
  }}

  int64_t read_i64() {{
    expect_tag(NVE_VAL_I64);
    return static_cast<int64_t>(read_le64());
  }}

  double read_f64() {{
    const uint8_t tag = peek_tag();
    if (tag == static_cast<uint8_t>(NVE_VAL_F64)) {{
      ++pos_;
      const uint64_t bits = read_le64();
      double out = 0.0;
      std::memcpy(&out, &bits, sizeof(out));
      return out;
    }}
    if (tag == static_cast<uint8_t>(NVE_VAL_I64)) {{
      return static_cast<double>(read_i64());
    }}
    throw std::runtime_error("expected NveBinValue number");
  }}

  std::string read_str() {{
    expect_tag(NVE_VAL_STR);
    const uint32_t len = read_le32();
    require(len);
    std::string out(reinterpret_cast<const char*>(data_.data() + pos_), len);
    pos_ += len;
    return out;
  }}

  std::vector<uint8_t> read_bytes() {{
    expect_tag(NVE_VAL_BYTES);
    const uint32_t len = read_le32();
    require(len);
    std::vector<uint8_t> out(data_.begin() + static_cast<std::ptrdiff_t>(pos_),
                             data_.begin() + static_cast<std::ptrdiff_t>(pos_ + len));
    pos_ += len;
    return out;
  }}

  uint32_t begin_array() {{
    expect_tag(NVE_VAL_ARRAY);
    const uint32_t byte_len = read_le32();
    require(byte_len);
    return read_le32();
  }}

  uint32_t begin_map() {{
    expect_tag(NVE_VAL_MAP);
    const uint32_t byte_len = read_le32();
    require(byte_len);
    return read_le32();
  }}

  std::string_view read_map_key() {{
    const uint32_t len = read_le32();
    require(len);
    std::string_view key(reinterpret_cast<const char*>(data_.data() + pos_), len);
    pos_ += len;
    return key;
  }}

  std::vector<uint8_t> read_raw_value() {{
    const size_t start = pos_;
    skip_value();
    return std::vector<uint8_t>(data_.begin() + static_cast<std::ptrdiff_t>(start),
                                data_.begin() + static_cast<std::ptrdiff_t>(pos_));
  }}

  void skip_value() {{
    const uint8_t tag = peek_tag();
    ++pos_;
    switch (tag) {{
      case NVE_VAL_NULL:
        return;
      case NVE_VAL_BOOL:
        require(1);
        pos_ += 1;
        return;
      case NVE_VAL_I64:
      case NVE_VAL_F64:
        require(8);
        pos_ += 8;
        return;
      case NVE_VAL_STR:
      case NVE_VAL_BYTES:
      case NVE_VAL_ARRAY:
      case NVE_VAL_MAP: {{
        const uint32_t len = read_le32();
        require(len);
        pos_ += len;
        return;
      }}
      default:
        throw std::runtime_error("invalid NveBinValue tag");
    }}
  }}

 private:
  void require(size_t n) const {{
    if (n > data_.size() - pos_) {{
      throw std::runtime_error("truncated NveBinValue");
    }}
  }}

  void expect_tag(NveValueTag tag) {{
    if (peek_tag() != static_cast<uint8_t>(tag)) {{
      throw std::runtime_error("unexpected NveBinValue tag");
    }}
    ++pos_;
  }}

  uint32_t read_le32() {{
    require(4);
    const uint32_t v = static_cast<uint32_t>(data_[pos_]) |
                       (static_cast<uint32_t>(data_[pos_ + 1]) << 8) |
                       (static_cast<uint32_t>(data_[pos_ + 2]) << 16) |
                       (static_cast<uint32_t>(data_[pos_ + 3]) << 24);
    pos_ += 4;
    return v;
  }}

  uint64_t read_le64() {{
    require(8);
    uint64_t v = 0;
    for (int i = 0; i < 8; ++i) {{
      v |= static_cast<uint64_t>(data_[pos_ + static_cast<size_t>(i)]) << (i * 8);
    }}
    pos_ += 8;
    return v;
  }}

  std::span<const uint8_t> data_;
  size_t pos_ = 0;
}};

#endif // NVE_HYBRID_CPP_COMMON_DEFINED
"#
    )
    .unwrap();
}

fn emit_cpp_enum(out: &mut String, e: &HybridEnumSpec) {
    writeln!(out, "enum class {} : uint32_t {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "  {} = {}u,", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp_struct(out: &mut String, s: &HybridStructSpec, spec: &HybridFileSpec) {
    writeln!(out, "struct {} {{", s.name).unwrap();
    for f in &s.fields {
        let fname = cpp_ident(&f.name);
        writeln!(out, "  {} {fname}{{}};", cpp_owned_type(&f.ty)).unwrap();
    }
    writeln!(out).unwrap();

    if s.is_pod(spec) {
        writeln!(out, "  NveHybrid{} to_abi() const noexcept {{", s.name).unwrap();
        writeln!(out, "    NveHybrid{} raw{{}};", s.name).unwrap();
        for f in &s.fields {
            let fname = cpp_ident(&f.name);
            let cname = c_field_ident(&f.name);
            match &f.ty {
                HybridType::Enum(_) => {
                    writeln!(out, "    raw.{cname} = static_cast<uint32_t>({fname});").unwrap();
                }
                HybridType::Struct(_) => {
                    writeln!(out, "    raw.{cname} = {fname}.to_abi();").unwrap();
                }
                _ => {
                    writeln!(out, "    raw.{cname} = {fname};").unwrap();
                }
            }
        }
        writeln!(out, "    return raw;").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();

        writeln!(out, "  static {} from_abi(const NveHybrid{}& raw) noexcept {{", s.name, s.name).unwrap();
        writeln!(out, "    {} out{{}};", s.name).unwrap();
        for f in &s.fields {
            let fname = cpp_ident(&f.name);
            let cname = c_field_ident(&f.name);
            match &f.ty {
                HybridType::Enum(e) => {
                    writeln!(out, "    out.{fname} = static_cast<{e}>(raw.{cname});").unwrap();
                }
                HybridType::Struct(st) => {
                    writeln!(out, "    out.{fname} = {st}::from_abi(raw.{cname});").unwrap();
                }
                _ => {
                    writeln!(out, "    out.{fname} = raw.{cname};").unwrap();
                }
            }
        }
        writeln!(out, "    return out;").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    }

    // Compact binary NveBinValue encode/decode for every struct
    writeln!(out, "  void encode_bin(BinWriter& w) const {{").unwrap();
    writeln!(out, "    w.write_map({}u, [&](BinWriter& w) {{", s.fields.len()).unwrap();
    for f in &s.fields {
        let fname = cpp_ident(&f.name);
        let key_lit = escape_string_literal(&f.name);
        writeln!(out, "      w.write_map_key(\"{key_lit}\");").unwrap();
        emit_cpp_bin_write(out, "      ", "w", &fname, &f.ty);
    }
    writeln!(out, "    }});").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  static {} decode_bin(BinReader& r) {{", s.name).unwrap();
    writeln!(out, "    {} out{{}};", s.name).unwrap();
    writeln!(out, "    const uint32_t count = r.begin_map();").unwrap();
    writeln!(out, "    for (uint32_t i = 0; i < count; ++i) {{").unwrap();
    writeln!(out, "      const auto key = r.read_map_key();").unwrap();
    for (idx, f) in s.fields.iter().enumerate() {
        let fname = cpp_ident(&f.name);
        let key_lit = escape_string_literal(&f.name);
        let cond = if idx == 0 { "if" } else { "else if" };
        writeln!(out, "      {cond} (key == \"{key_lit}\") {{").unwrap();
        emit_cpp_bin_read(out, "        ", "r", &format!("out.{fname}"), &f.ty);
        writeln!(out, "      }}").unwrap();
    }
    writeln!(out, "      else {{").unwrap();
    writeln!(out, "        r.skip_value();").unwrap();
    writeln!(out, "      }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    return out;").unwrap();
    writeln!(out, "  }}").unwrap();

    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp_module(out: &mut String, m: &HybridModuleSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&m.name);
    let upper = to_snake_case(&m.name).to_ascii_uppercase();

    // Nitro-style abstract Spec base class
    writeln!(out, "/// Nitro-style compile-time-enforced C++20 contract for `{pascal}`.").unwrap();
    writeln!(out, "class Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, " public:").unwrap();
    writeln!(out, "  virtual ~Hybrid{pascal}Spec() = default;").unwrap();
    for method in &m.methods {
        writeln!(out, "  virtual {} = 0;", cpp_method_signature(method)).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    emit_cpp_client(out, &pascal, &upper, &m.methods, None, spec);
}

fn emit_cpp_view(out: &mut String, v: &HybridViewSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&v.name);
    let upper = to_snake_case(&v.name).to_ascii_uppercase();

    // Props struct
    writeln!(out, "struct {pascal}Props {{").unwrap();
    for p in &v.props {
        let pname = cpp_ident(&p.name);
        let def = cpp_prop_default_initializer(&p.ty, p.default_value.as_ref());
        writeln!(out, "  {} {pname} = {def};", cpp_owned_type(&p.ty)).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    // Event structs
    for ev in &v.events {
        let ev_pascal = to_pascal_case(&ev.name);
        writeln!(out, "struct {pascal}{ev_pascal}Event {{").unwrap();
        for param in &ev.params {
            let pname = cpp_ident(&param.name);
            writeln!(out, "  {} {pname}{{}};", cpp_owned_type(&param.ty)).unwrap();
        }
        writeln!(out, "}};").unwrap();
        writeln!(out).unwrap();
    }

    // Nitro-style abstract Spec base class
    writeln!(out, "/// Nitro-style compile-time-enforced C++20 view contract for `{pascal}`.").unwrap();
    writeln!(out, "class Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, " public:").unwrap();
    writeln!(out, "  virtual ~Hybrid{pascal}Spec() = default;").unwrap();
    writeln!(out, "  virtual void setProps(const {pascal}Props& props) = 0;").unwrap();
    for method in &v.methods {
        writeln!(out, "  virtual {} = 0;", cpp_method_signature(method)).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    emit_cpp_client(out, &pascal, &upper, &v.methods, Some(v), spec);
}

fn emit_cpp_client(
    out: &mut String,
    pascal: &str,
    upper: &str,
    methods: &[HybridMethodSpec],
    view: Option<&HybridViewSpec>,
    spec: &HybridFileSpec,
) {
    writeln!(
        out,
        "/// Zero-overhead RAII C++20 client wrapping `const NveHybrid{pascal}VTable*`."
    )
    .unwrap();
    writeln!(out, "class {pascal}Client final : public Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, " public:").unwrap();
    writeln!(out, "  static constexpr uint32_t kInterfaceId = NVE_HYBRID_{upper}_INTERFACE_ID;").unwrap();
    writeln!(out, "  static constexpr uint64_t kSchemaHash = NVE_HYBRID_{upper}_SCHEMA_HASH;").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        "  static {pascal}Client resolve(NveGetInterfaceFn get_iface) {{"
    )
    .unwrap();
    writeln!(out, "    if (!get_iface) {{").unwrap();
    writeln!(out, "      throw std::runtime_error(\"nve_get_interface pointer is null\");").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(
        out,
        "    const auto* vt = static_cast<const NveHybrid{pascal}VTable*>(get_iface(kInterfaceId));"
    )
    .unwrap();
    writeln!(out, "    return {pascal}Client(vt);").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  explicit {pascal}Client(const NveHybrid{pascal}VTable* vtable) : vtable_(vtable) {{").unwrap();
    writeln!(out, "    if (!vtable_) {{").unwrap();
    writeln!(out, "      throw std::runtime_error(\"hybrid vtable for {pascal} is null\");").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    if (vtable_->abi_version != NVE_HYBRID_ABI_VERSION || vtable_->schema_hash != kSchemaHash) {{").unwrap();
    writeln!(out, "      throw std::runtime_error(\"hybrid schema hash mismatch for {pascal}\");").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    handle_ = vtable_->create();").unwrap();
    writeln!(out, "    if (!handle_) {{").unwrap();
    writeln!(out, "      throw std::runtime_error(\"failed to create {pascal} hybrid instance\");").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  {pascal}Client(const {pascal}Client&) = delete;").unwrap();
    writeln!(out, "  {pascal}Client& operator=(const {pascal}Client&) = delete;").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  {pascal}Client({pascal}Client&& other) noexcept : vtable_(other.vtable_), handle_(other.handle_) {{").unwrap();
    writeln!(out, "    other.vtable_ = nullptr;").unwrap();
    writeln!(out, "    other.handle_ = nullptr;").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  {pascal}Client& operator=({pascal}Client&& other) noexcept {{").unwrap();
    writeln!(out, "    if (this != &other) {{").unwrap();
    writeln!(out, "      reset();").unwrap();
    writeln!(out, "      vtable_ = other.vtable_;").unwrap();
    writeln!(out, "      handle_ = other.handle_;").unwrap();
    writeln!(out, "      other.vtable_ = nullptr;").unwrap();
    writeln!(out, "      other.handle_ = nullptr;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    return *this;").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  ~{pascal}Client() override {{ reset(); }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  void reset() noexcept {{").unwrap();
    writeln!(out, "    if (vtable_ && handle_) {{").unwrap();
    writeln!(out, "      vtable_->destroy(handle_);").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    handle_ = nullptr;").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  const NveHybrid{pascal}VTable* vtable() const noexcept {{ return vtable_; }}").unwrap();
    writeln!(out, "  NveAppHandle handle() const noexcept {{ return handle_; }}").unwrap();
    writeln!(out).unwrap();

    if let Some(v) = view {
        emit_cpp_set_props(out, pascal, v);
    }

    for method in methods {
        emit_cpp_client_method(out, method, spec);
    }

    writeln!(out, " private:").unwrap();
    writeln!(out, "  std::string take_string(NveHybridOwnedBytes raw) const {{").unwrap();
    writeln!(out, "    if (!raw.ptr || raw.len == 0) {{").unwrap();
    writeln!(out, "      if (raw.ptr) {{ vtable_->free_bytes(raw); }}").unwrap();
    writeln!(out, "      return {{}};").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    std::string out(reinterpret_cast<const char*>(raw.ptr), raw.len);").unwrap();
    writeln!(out, "    vtable_->free_bytes(raw);").unwrap();
    writeln!(out, "    return out;").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  std::vector<uint8_t> take_bytes(NveHybridOwnedBytes raw) const {{").unwrap();
    writeln!(out, "    if (!raw.ptr || raw.len == 0) {{").unwrap();
    writeln!(out, "      if (raw.ptr) {{ vtable_->free_bytes(raw); }}").unwrap();
    writeln!(out, "      return {{}};").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    std::vector<uint8_t> out(raw.ptr, raw.ptr + raw.len);").unwrap();
    writeln!(out, "    vtable_->free_bytes(raw);").unwrap();
    writeln!(out, "    return out;").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  const NveHybrid{pascal}VTable* vtable_ = nullptr;").unwrap();
    writeln!(out, "  NveAppHandle handle_ = nullptr;").unwrap();
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp_set_props(out: &mut String, pascal: &str, v: &HybridViewSpec) {
    writeln!(out, "  void setProps(const {pascal}Props& props) override {{").unwrap();
    if v.props.is_empty() {
        writeln!(out, "    (void)props;").unwrap();
        writeln!(out, "    vtable_->set_props_direct(handle_, nullptr, 0u);").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
        return;
    }
    writeln!(out, "    std::vector<NveMapEntry> entries;").unwrap();
    writeln!(out, "    entries.reserve({}u);", v.props.len()).unwrap();
    // Keep any scratch BinWriters alive for the duration of set_props_direct.
    for (idx, p) in v.props.iter().enumerate() {
        if !cpp_prop_is_direct_nve_value(&p.ty) {
            let pname = cpp_ident(&p.name);
            let wname = format!("_prop_bin_{idx}");
            writeln!(out, "    BinWriter {wname};").unwrap();
            emit_cpp_bin_write(out, "    ", &wname, &format!("props.{pname}"), &p.ty);
        }
    }
    for (idx, p) in v.props.iter().enumerate() {
        let pname = cpp_ident(&p.name);
        let key_lit = escape_string_literal(&p.name);
        writeln!(out, "    {{").unwrap();
        writeln!(out, "      NveMapEntry entry{{}};").unwrap();
        writeln!(
            out,
            "      entry.key = NveStrSlice{{reinterpret_cast<const uint8_t*>(\"{key_lit}\"), {}u}};",
            p.name.len()
        )
        .unwrap();
        emit_cpp_fill_nve_value(out, "      ", "entry.value", &format!("props.{pname}"), &p.ty, idx);
        writeln!(out, "      entries.push_back(entry);").unwrap();
        writeln!(out, "    }}").unwrap();
    }
    writeln!(
        out,
        "    const int32_t status = vtable_->set_props_direct(handle_, entries.data(), static_cast<uint32_t>(entries.size()));"
    )
    .unwrap();
    writeln!(out, "    if (status != NVE_HYBRID_OK) {{").unwrap();
    writeln!(out, "      throw std::runtime_error(\"setProps failed on {pascal}\");").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp_client_method(out: &mut String, method: &HybridMethodSpec, spec: &HybridFileSpec) {
    let cname = c_field_ident(&method.name);
    writeln!(out, "  {} override {{", cpp_method_signature(method)).unwrap();

    // Prepare arguments
    let mut call_args = vec!["handle_".to_string()];
    for (idx, p) in method.params.iter().enumerate() {
        let pname = cpp_ident(&p.name);
        match &p.ty {
            HybridType::Bool
            | HybridType::U8
            | HybridType::U16
            | HybridType::Usize
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64
            | HybridType::F32
            | HybridType::F64 => call_args.push(pname),
            HybridType::Enum(_) => call_args.push(format!("static_cast<uint32_t>({pname})")),
            HybridType::Struct(_) if p.ty.is_pod(spec) => {
                call_args.push(format!("{pname}.to_abi()"));
            }
            HybridType::String => {
                writeln!(
                    out,
                    "    const NveStrSlice _arg_{idx}{{reinterpret_cast<const uint8_t*>({pname}.data()), {pname}.size()}};"
                )
                .unwrap();
                call_args.push(format!("_arg_{idx}"));
            }
            HybridType::Bytes => {
                writeln!(
                    out,
                    "    const NveBufferSlice _arg_{idx}{{{pname}.data(), {pname}.size()}};"
                )
                .unwrap();
                call_args.push(format!("_arg_{idx}"));
            }
            HybridType::Value => call_args.push(pname),
            HybridType::Optional(inner) if inner.is_pod(spec) => {
                let suffix = inner.pod_opt_suffix().unwrap();
                writeln!(out, "    NveHybridOpt{suffix} _arg_{idx}{{false, {{}}}};").unwrap();
                writeln!(out, "    if ({pname}.has_value()) {{").unwrap();
                writeln!(out, "      _arg_{idx}.is_some = true;").unwrap();
                match inner.as_ref() {
                    HybridType::Enum(_) => {
                        writeln!(out, "      _arg_{idx}.value = static_cast<uint32_t>(*{pname});").unwrap();
                    }
                    HybridType::Struct(_) => {
                        writeln!(out, "      _arg_{idx}.value = {pname}->to_abi();").unwrap();
                    }
                    _ => {
                        writeln!(out, "      _arg_{idx}.value = *{pname};").unwrap();
                    }
                }
                writeln!(out, "    }}").unwrap();
                call_args.push(format!("_arg_{idx}"));
            }
            other => {
                let wname = format!("_arg_w_{idx}");
                writeln!(out, "    BinWriter {wname};").unwrap();
                emit_cpp_bin_write(out, "    ", &wname, &pname, other);
                call_args.push(format!("{wname}.slice()"));
            }
        }
    }

    match &method.return_type {
        HybridType::Void => {
            writeln!(out, "    vtable_->{cname}({});", call_args.join(", ")).unwrap();
        }
        HybridType::Result { ok, .. } => {
            if !matches!(ok.as_ref(), HybridType::Void) {
                writeln!(out, "    {} _raw_ok{{}};", c_return_type(ok, spec)).unwrap();
                call_args.push("&_raw_ok".to_string());
            }
            writeln!(out, "    NveHybridOwnedBytes _raw_err{{nullptr, 0, 0}};").unwrap();
            call_args.push("&_raw_err".to_string());
            writeln!(
                out,
                "    const int32_t _status = vtable_->{cname}({});",
                call_args.join(", ")
            )
            .unwrap();
            writeln!(out, "    if (_status != NVE_HYBRID_OK) {{").unwrap();
            writeln!(out, "      const std::string _msg = take_string(_raw_err);").unwrap();
            writeln!(
                out,
                "      throw std::runtime_error(_msg.empty() ? \"hybrid call failed\" : _msg);"
            )
            .unwrap();
            writeln!(out, "    }}").unwrap();
            if !matches!(ok.as_ref(), HybridType::Void) {
                emit_cpp_return_decode(out, "    ", "_raw_ok", ok, spec);
            }
        }
        other => {
            writeln!(
                out,
                "    const auto _raw_ret = vtable_->{cname}({});",
                call_args.join(", ")
            )
            .unwrap();
            emit_cpp_return_decode(out, "    ", "_raw_ret", other, spec);
        }
    }

    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();
}

fn emit_cpp_return_decode(
    out: &mut String,
    indent: &str,
    var: &str,
    ty: &HybridType,
    spec: &HybridFileSpec,
) {
    match ty {
        HybridType::Void => {}
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64 => {
            writeln!(out, "{indent}return {var};").unwrap();
        }
        HybridType::Enum(e) => {
            writeln!(out, "{indent}return static_cast<{e}>({var});").unwrap();
        }
        HybridType::Struct(s) if ty.is_pod(spec) => {
            writeln!(out, "{indent}return {s}::from_abi({var});").unwrap();
        }
        HybridType::String => {
            writeln!(out, "{indent}return take_string({var});").unwrap();
        }
        HybridType::Bytes => {
            writeln!(out, "{indent}return take_bytes({var});").unwrap();
        }
        HybridType::Value => {
            writeln!(out, "{indent}return DynamicValue{{take_bytes({var})}};").unwrap();
        }
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            writeln!(out, "{indent}if (!{var}.is_some) {{ return std::nullopt; }}").unwrap();
            match inner.as_ref() {
                HybridType::Enum(e) => {
                    writeln!(out, "{indent}return static_cast<{e}>({var}.value);").unwrap();
                }
                HybridType::Struct(s) => {
                    writeln!(out, "{indent}return {s}::from_abi({var}.value);").unwrap();
                }
                _ => {
                    writeln!(out, "{indent}return {var}.value;").unwrap();
                }
            }
        }
        other => {
            writeln!(out, "{indent}const auto _bytes = take_bytes({var});").unwrap();
            writeln!(out, "{indent}BinReader _r(_bytes);").unwrap();
            writeln!(out, "{indent}{} _out{{}};", cpp_owned_type(other)).unwrap();
            emit_cpp_bin_read(out, indent, "_r", "_out", other);
            writeln!(out, "{indent}return _out;").unwrap();
        }
    }
}

fn cpp_method_signature(method: &HybridMethodSpec) -> String {
    let mname = cpp_ident(&to_camel_case(&method.name));
    let ret = match &method.return_type {
        HybridType::Result { ok, .. } => cpp_owned_type(ok),
        other => cpp_owned_type(other),
    };
    let params: Vec<String> = method
        .params
        .iter()
        .map(|p| format!("{} {}", cpp_param_type(&p.ty), cpp_ident(&p.name)))
        .collect();
    format!("{ret} {mname}({})", params.join(", "))
}

fn cpp_owned_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Void => "void".to_string(),
        HybridType::Bool => "bool".to_string(),
        HybridType::U8 => "uint8_t".to_string(),
        HybridType::U16 => "uint16_t".to_string(),
        HybridType::Usize => "size_t".to_string(),
        HybridType::I32 => "int32_t".to_string(),
        HybridType::U32 => "uint32_t".to_string(),
        HybridType::I64 => "int64_t".to_string(),
        HybridType::U64 => "uint64_t".to_string(),
        HybridType::F32 => "float".to_string(),
        HybridType::F64 => "double".to_string(),
        HybridType::String => "std::string".to_string(),
        HybridType::Bytes => "std::vector<uint8_t>".to_string(),
        HybridType::Optional(inner) => format!("std::optional<{}>", cpp_owned_type(inner)),
        HybridType::Vec(inner) => format!("std::vector<{}>", cpp_owned_type(inner)),
        HybridType::Result { ok, .. } => cpp_owned_type(ok),
        HybridType::Struct(name) | HybridType::Enum(name) | HybridType::Handle(name) => {
            name.clone()
        }
        HybridType::Value => "DynamicValue".to_string(),
        HybridType::ConstPtr(inner) => format!("const {}*", cpp_owned_type(inner)),
        HybridType::MutPtr(inner) => format!("{}*", cpp_owned_type(inner)),
    }
}

fn cpp_param_type(ty: &HybridType) -> String {
    match ty {
        HybridType::String => "std::string_view".to_string(),
        HybridType::Bytes => "std::span<const uint8_t>".to_string(),
        HybridType::Value => "NveValue".to_string(),
        HybridType::Struct(name) => format!("const {name}&"),
        HybridType::Optional(inner) => format!("const std::optional<{}>&", cpp_owned_type(inner)),
        HybridType::Vec(inner) => format!("const std::vector<{}>&", cpp_owned_type(inner)),
        other => cpp_owned_type(other),
    }
}

fn c_field_ident(raw: &str) -> String {
    let s = to_snake_case(raw);
    match s.as_str() {
        "auto" | "break" | "case" | "char" | "const" | "continue" | "default" | "do" | "double"
        | "else" | "enum" | "extern" | "float" | "for" | "goto" | "if" | "inline" | "int"
        | "long" | "register" | "restrict" | "return" | "short" | "signed" | "sizeof"
        | "static" | "struct" | "switch" | "typedef" | "union" | "unsigned" | "void"
        | "volatile" | "while" | "class" | "delete" | "new" | "namespace" | "template" => {
            format!("{s}_")
        }
        _ => s,
    }
}

fn c_pod_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Bool => "bool".to_string(),
        HybridType::U8 => "uint8_t".to_string(),
        HybridType::U16 => "uint16_t".to_string(),
        HybridType::Usize => "size_t".to_string(),
        HybridType::I32 => "int32_t".to_string(),
        HybridType::U32 => "uint32_t".to_string(),
        HybridType::I64 => "int64_t".to_string(),
        HybridType::U64 => "uint64_t".to_string(),
        HybridType::F32 => "float".to_string(),
        HybridType::F64 => "double".to_string(),
        HybridType::Enum(name) | HybridType::Struct(name) => format!("NveHybrid{name}"),
        _ => unreachable!("non-POD type in c_pod_type"),
    }
}

fn c_param_type(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::Enum(_) => c_pod_type(ty),
        HybridType::Struct(_) if ty.is_pod(spec) => c_pod_type(ty),
        HybridType::String => "NveStrSlice".to_string(),
        HybridType::Bytes => "NveBufferSlice".to_string(),
        HybridType::Value => "NveValue".to_string(),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            format!("NveHybridOpt{}", inner.pod_opt_suffix().unwrap())
        }
        _ => "NveBufferSlice".to_string(),
    }
}

fn c_return_type(ty: &HybridType, spec: &HybridFileSpec) -> String {
    match ty {
        HybridType::Void => "void".to_string(),
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::Enum(_) => c_pod_type(ty),
        HybridType::Struct(_) if ty.is_pod(spec) => c_pod_type(ty),
        HybridType::Optional(inner) if inner.is_pod(spec) => {
            format!("NveHybridOpt{}", inner.pod_opt_suffix().unwrap())
        }
        _ => "NveHybridOwnedBytes".to_string(),
    }
}

fn emit_cpp_bin_write(out: &mut String, indent: &str, w: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{w}.write_bool({expr});").unwrap(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => {
            writeln!(out, "{indent}{w}.write_i64(static_cast<int64_t>({expr}));").unwrap();
        }
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "{indent}{w}.write_f64(static_cast<double>({expr}));").unwrap();
        }
        HybridType::Enum(_) => {
            writeln!(out, "{indent}{w}.write_i64(static_cast<int64_t>(static_cast<uint32_t>({expr})));").unwrap();
        }
        HybridType::String => writeln!(out, "{indent}{w}.write_str({expr});").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{w}.write_bytes({expr});").unwrap(),
        HybridType::Struct(_) => writeln!(out, "{indent}{expr}.encode_bin({w});").unwrap(),
        HybridType::Value => writeln!(out, "{indent}{w}.write_raw({expr}.bin_bytes);").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}if ({expr}.has_value()) {{").unwrap();
            emit_cpp_bin_write(out, &format!("{indent}  "), w, &format!("(*{expr})"), inner);
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}  {w}.write_null();").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}{w}.write_array(static_cast<uint32_t>({expr}.size()), [&](BinWriter& _aw) {{").unwrap();
            writeln!(out, "{indent}  for (const auto& _elem : {expr}) {{").unwrap();
            emit_cpp_bin_write(out, &format!("{indent}    "), "_aw", "_elem", inner);
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}}});").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {
            writeln!(out, "{indent}{w}.write_null();").unwrap();
        }
    }
}

fn emit_cpp_bin_read(out: &mut String, indent: &str, r: &str, dst: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{dst} = {r}.read_bool();").unwrap(),
        HybridType::U8 => writeln!(out, "{indent}{dst} = static_cast<uint8_t>({r}.read_i64());").unwrap(),
        HybridType::U16 => writeln!(out, "{indent}{dst} = static_cast<uint16_t>({r}.read_i64());").unwrap(),
        HybridType::Usize => writeln!(out, "{indent}{dst} = static_cast<size_t>({r}.read_i64());").unwrap(),
        HybridType::I32 => writeln!(out, "{indent}{dst} = static_cast<int32_t>({r}.read_i64());").unwrap(),
        HybridType::U32 => writeln!(out, "{indent}{dst} = static_cast<uint32_t>({r}.read_i64());").unwrap(),
        HybridType::I64 => writeln!(out, "{indent}{dst} = {r}.read_i64();").unwrap(),
        HybridType::U64 => writeln!(out, "{indent}{dst} = static_cast<uint64_t>({r}.read_i64());").unwrap(),
        HybridType::F32 => writeln!(out, "{indent}{dst} = static_cast<float>({r}.read_f64());").unwrap(),
        HybridType::F64 => writeln!(out, "{indent}{dst} = {r}.read_f64();").unwrap(),
        HybridType::Enum(e) => {
            writeln!(out, "{indent}{dst} = static_cast<{e}>(static_cast<uint32_t>({r}.read_i64()));").unwrap();
        }
        HybridType::String => writeln!(out, "{indent}{dst} = {r}.read_str();").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{dst} = {r}.read_bytes();").unwrap(),
        HybridType::Struct(s) => writeln!(out, "{indent}{dst} = {s}::decode_bin({r});").unwrap(),
        HybridType::Value => writeln!(out, "{indent}{dst} = DynamicValue{{{r}.read_raw_value()}};").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}if ({r}.read_null_if_present()) {{").unwrap();
            writeln!(out, "{indent}  {dst} = std::nullopt;").unwrap();
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}  {} _opt_v{{}};", cpp_owned_type(inner)).unwrap();
            emit_cpp_bin_read(out, &format!("{indent}  "), r, "_opt_v", inner);
            writeln!(out, "{indent}  {dst} = std::move(_opt_v);").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}{{").unwrap();
            writeln!(out, "{indent}  const uint32_t _n = {r}.begin_array();").unwrap();
            writeln!(out, "{indent}  {dst}.clear();").unwrap();
            writeln!(out, "{indent}  {dst}.reserve(_n);").unwrap();
            writeln!(out, "{indent}  for (uint32_t _i = 0; _i < _n; ++_i) {{").unwrap();
            writeln!(out, "{indent}    {} _elem{{}};", cpp_owned_type(inner)).unwrap();
            emit_cpp_bin_read(out, &format!("{indent}    "), r, "_elem", inner);
            writeln!(out, "{indent}    {dst}.push_back(std::move(_elem));").unwrap();
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {}
    }
}

fn cpp_prop_is_direct_nve_value(ty: &HybridType) -> bool {
    match ty {
        HybridType::Bool
        | HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64
        | HybridType::F32
        | HybridType::F64
        | HybridType::Enum(_)
        | HybridType::String
        | HybridType::Bytes => true,
        HybridType::Optional(inner) => cpp_prop_is_direct_nve_value(inner),
        _ => false,
    }
}

fn emit_cpp_fill_nve_value(
    out: &mut String,
    indent: &str,
    dst: &str,
    expr: &str,
    ty: &HybridType,
    idx: usize,
) {
    match ty {
        HybridType::Optional(inner) if cpp_prop_is_direct_nve_value(inner) => {
            writeln!(out, "{indent}if ({expr}.has_value()) {{").unwrap();
            emit_cpp_fill_nve_value(out, &format!("{indent}  "), dst, &format!("(*{expr})"), inner, idx);
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}  {dst}.tag = NVE_VAL_NULL;").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Bool => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_BOOL;").unwrap();
            writeln!(out, "{indent}{dst}.data.bool_val = {expr} ? 1u : 0u;").unwrap();
        }
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_I64;").unwrap();
            writeln!(out, "{indent}{dst}.data.i64_val = static_cast<int64_t>({expr});").unwrap();
        }
        HybridType::Enum(_) => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_I64;").unwrap();
            writeln!(out, "{indent}{dst}.data.i64_val = static_cast<int64_t>(static_cast<uint32_t>({expr}));").unwrap();
        }
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_F64;").unwrap();
            writeln!(out, "{indent}{dst}.data.f64_val = static_cast<double>({expr});").unwrap();
        }
        HybridType::String => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_STR;").unwrap();
            writeln!(
                out,
                "{indent}{dst}.data.str_val = NveStrSlice{{reinterpret_cast<const uint8_t*>({expr}.data()), {expr}.size()}};"
            )
            .unwrap();
        }
        HybridType::Bytes => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_BYTES;").unwrap();
            writeln!(
                out,
                "{indent}{dst}.data.bytes_val = NveBufferSlice{{{expr}.data(), {expr}.size()}};"
            )
            .unwrap();
        }
        _ => {
            writeln!(out, "{indent}{dst}.tag = NVE_VAL_BYTES;").unwrap();
            writeln!(out, "{indent}{dst}.data.bytes_val = _prop_bin_{idx}.slice();").unwrap();
        }
    }
}

fn cpp_prop_default_initializer(ty: &HybridType, def: Option<&HybridDefaultValue>) -> String {
    let Some(def) = def else {
        return "{}".to_string();
    };
    if let HybridType::Optional(inner) = ty {
        return match def {
            HybridDefaultValue::None => "std::nullopt".to_string(),
            other => cpp_prop_default_initializer(inner, Some(other)),
        };
    }
    match (def, ty) {
        (HybridDefaultValue::Bool(b), _) => b.to_string(),
        (HybridDefaultValue::Int(i), HybridType::F32) => format!("{i}.0f"),
        (HybridDefaultValue::Int(i), HybridType::F64) => format!("{i}.0"),
        (HybridDefaultValue::Int(i), _) => i.to_string(),
        (HybridDefaultValue::UInt(u), HybridType::F32) => format!("{u}.0f"),
        (HybridDefaultValue::UInt(u), HybridType::F64) => format!("{u}.0"),
        (HybridDefaultValue::UInt(u), HybridType::U64) => format!("{u}ULL"),
        (HybridDefaultValue::UInt(u), _) => format!("{u}u"),
        (HybridDefaultValue::Float(f), HybridType::F32) => format!("{}f", format_float_literal(*f)),
        (HybridDefaultValue::Float(f), _) => format_float_literal(*f),
        (HybridDefaultValue::String(s), _) => format!("\"{}\"", escape_string_literal(s)),
        (HybridDefaultValue::EnumVariant { enum_name, variant }, _) => {
            format!("{enum_name}::{variant}")
        }
        (HybridDefaultValue::None, _) => "{}".to_string(),
    }
}
