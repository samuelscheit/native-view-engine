//! Flutter / Dart (`dart:ffi`) target emitter for NVE Hybrid FFI codegen.
//!
//! Emits a standalone, zero-JSON, zero-external-package Dart file (`<stem>_hybrid.dart`):
//! - Uses only Dart SDK (`dart:convert` UTF-8, `dart:ffi`, `dart:typed_data`)
//! - Exact `ffi.Struct` definitions for `NveStrSlice`, `NveBufferSlice`, `NveHybridOwnedBytes`,
//!   `NveValue`, `NveMapEntry`, POD structs, POD `NveHybridOpt*`, and `NveHybrid<Name>VTable`
//! - `abstract interface class Hybrid<Name>Spec`
//! - `class <Name>HybridClient` resolving `nve_get_interface`, verifying `schemaHash`,
//!   and managing transient scratch buffers via the vtable's `allocBytes` / `freeBytes`.

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::hybrid::ir::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::ir::GeneratedFile;
use crate::naming::{
    dart_ident, escape_dart_single_quoted_string, format_float_literal, to_camel_case,
    to_pascal_case,
};

/// Emits `<stem>_hybrid.dart` using `dart:ffi` and the shared `package:nve_flutter/nve_hybrid_runtime.dart`.
pub fn generate_hybrid_dart(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut body = String::with_capacity(16 * 1024);

    emit_dart_common(&mut body, spec);

    for e in &spec.enums {
        emit_dart_enum(&mut body, e);
    }

    for s in spec.structs_topological() {
        emit_dart_struct(&mut body, s, spec);
    }

    // POD Option FFI structs
    for inner in spec.collect_pod_option_types() {
        let suffix = inner.pod_opt_suffix().unwrap();
        writeln!(body, "final class NveHybridOpt{suffix} extends ffi.Struct {{").unwrap();
        writeln!(body, "  @ffi.Bool()").unwrap();
        writeln!(body, "  external bool isSome;").unwrap();
        if let Some(ann) = dart_ffi_field_annotation(&inner) {
            writeln!(body, "  {ann}").unwrap();
        }
        writeln!(body, "  external {} value;", dart_ffi_struct_field_type(&inner)).unwrap();
        writeln!(body, "}}").unwrap();
        writeln!(body).unwrap();
    }

    for m in &spec.modules {
        emit_dart_module(&mut body, m, spec);
    }

    for v in &spec.views {
        emit_dart_view(&mut body, v, spec);
    }

    let mut out = String::with_capacity(body.len() + 512);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Flutter/Dart dart:ffi target) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(
        out,
        "// Zero-JSON direct dart:ffi vtable bindings sharing `package:nve_flutter/nve_hybrid_runtime.dart`."
    )
    .unwrap();
    writeln!(out).unwrap();
    if body.contains("utf8.") {
        writeln!(out, "import 'dart:convert' show utf8;").unwrap();
    }
    writeln!(out, "import 'dart:ffi' as ffi;").unwrap();
    if body.contains("Uint8List") {
        writeln!(out, "import 'dart:typed_data';").unwrap();
    }
    writeln!(out).unwrap();
    writeln!(out, "import 'package:nve_flutter/nve_hybrid_runtime.dart';").unwrap();
    writeln!(out).unwrap();
    out.push_str(&body);

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.dart"),
        content: out,
    }])
}

fn emit_dart_common(out: &mut String, spec: &HybridFileSpec) {
    writeln!(out, "const int nveHybridAbiVersion = {NVE_HYBRID_ABI_VERSION};").unwrap();
    writeln!(
        out,
        "const int nveHybridFileSchemaHash = {};",
        dart_u64_const(spec.file_schema_hash())
    )
    .unwrap();
    writeln!(out, "const int nveHybridOk = 0;").unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        r#"typedef _NveGetInterfaceNative = ffi.Pointer<ffi.Void> Function(ffi.Uint32);
typedef _NveGetInterfaceDart = ffi.Pointer<ffi.Void> Function(int);
typedef _NveCreateNative = ffi.Pointer<ffi.Void> Function();
typedef _NveCreateDart = ffi.Pointer<ffi.Void> Function();
typedef _NveDestroyNative = ffi.Void Function(ffi.Pointer<ffi.Void>);
typedef _NveDestroyDart = void Function(ffi.Pointer<ffi.Void>);
typedef _NveAllocBytesNative = NveHybridOwnedBytes Function(ffi.Size);
typedef _NveAllocBytesDart = NveHybridOwnedBytes Function(int);
typedef _NveFreeBytesNative = ffi.Void Function(NveHybridOwnedBytes);
typedef _NveFreeBytesDart = void Function(NveHybridOwnedBytes);
typedef _NveSetPropsDirectNative = ffi.Int32 Function(
  ffi.Pointer<ffi.Void>,
  ffi.Pointer<NveMapEntry>,
  ffi.Uint32,
);
typedef _NveSetPropsDirectDart = int Function(
  ffi.Pointer<ffi.Void>,
  ffi.Pointer<NveMapEntry>,
  int,
);
"#
    )
    .unwrap();
}

fn emit_dart_enum(out: &mut String, e: &HybridEnumSpec) {
    writeln!(out, "enum {} {{", e.name).unwrap();
    for (idx, v) in e.variants.iter().enumerate() {
        let vname = dart_ident(&v.name);
        let sep = if idx + 1 == e.variants.len() { ";" } else { "," };
        writeln!(out, "  {vname}({}){sep}", v.value).unwrap();
    }
    writeln!(out, "  final int rawValue;").unwrap();
    writeln!(out, "  const {}(this.rawValue);", e.name).unwrap();
    writeln!(out, "  static {} fromRaw(int raw) => switch (raw) {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "    {} => {}.{},", v.value, e.name, dart_ident(&v.name)).unwrap();
    }
    writeln!(
        out,
        "    _ => throw ArgumentError('invalid {} discriminant: $raw'),",
        e.name
    )
    .unwrap();
    writeln!(out, "  }};").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_dart_struct(out: &mut String, s: &HybridStructSpec, spec: &HybridFileSpec) {
    if s.is_pod(spec) {
        writeln!(out, "final class NveHybrid{} extends ffi.Struct {{", s.name).unwrap();
        for f in &s.fields {
            if let Some(ann) = dart_ffi_field_annotation(&f.ty) {
                writeln!(out, "  {ann}").unwrap();
            }
            let fname = dart_ident(&f.name);
            writeln!(out, "  external {} {fname};", dart_ffi_struct_field_type(&f.ty)).unwrap();
        }
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    writeln!(out, "class {} {{", s.name).unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        writeln!(out, "  final {} {fname};", dart_type(&f.ty)).unwrap();
    }
    writeln!(out).unwrap();
    write!(out, "  const {}({{", s.name).unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        write!(out, "required this.{fname}, ").unwrap();
    }
    writeln!(out, "}});").unwrap();

    if s.is_pod(spec) {
        writeln!(out).unwrap();
        writeln!(out, "  NveHybrid{} toAbi() {{", s.name).unwrap();
        writeln!(out, "    final raw = ffi.Struct.create<NveHybrid{}>();", s.name).unwrap();
        for f in &s.fields {
            let fname = dart_ident(&f.name);
            match &f.ty {
                HybridType::Enum(_) => writeln!(out, "    raw.{fname} = {fname}.rawValue;").unwrap(),
                HybridType::Struct(_) => writeln!(out, "    raw.{fname} = {fname}.toAbi();").unwrap(),
                _ => writeln!(out, "    raw.{fname} = {fname};").unwrap(),
            }
        }
        writeln!(out, "    return raw;").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
        writeln!(out, "  factory {}.fromAbi(NveHybrid{} raw) => {}(", s.name, s.name, s.name).unwrap();
        for f in &s.fields {
            let fname = dart_ident(&f.name);
            match &f.ty {
                HybridType::Enum(e) => writeln!(out, "    {fname}: {e}.fromRaw(raw.{fname}),").unwrap(),
                HybridType::Struct(st) => writeln!(out, "    {fname}: {st}.fromAbi(raw.{fname}),").unwrap(),
                _ => writeln!(out, "    {fname}: raw.{fname},").unwrap(),
            }
        }
        writeln!(out, "  );").unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "  void encodeBin(NveBinWriter w) {{").unwrap();
    writeln!(out, "    w.writeMap({}, (mw) {{", s.fields.len()).unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let key_lit = escape_dart_single_quoted_string(&f.name);
        writeln!(out, "      mw.writeMapKey('{key_lit}');").unwrap();
        emit_dart_bin_write(out, "      ", "mw", &fname, &f.ty);
    }
    writeln!(out, "    }});").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  factory {}.decodeBin(NveBinReader r) {{", s.name).unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let def = dart_default_value(&f.ty, None, spec);
        writeln!(out, "    {} _{fname} = {def};", dart_type(&f.ty)).unwrap();
    }
    writeln!(out, "    final count = r.beginMap();").unwrap();
    writeln!(out, "    for (var i = 0; i < count; i++) {{").unwrap();
    writeln!(out, "      switch (r.readMapKey()) {{").unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let key_lit = escape_dart_single_quoted_string(&f.name);
        writeln!(out, "        case '{key_lit}':").unwrap();
        emit_dart_bin_read(out, "          ", "r", &format!("_{fname}"), &f.ty);
    }
    writeln!(out, "        default:").unwrap();
    writeln!(out, "          r.skipValue();").unwrap();
    writeln!(out, "      }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    return {}(", s.name).unwrap();
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        writeln!(out, "      {fname}: _{fname},").unwrap();
    }
    writeln!(out, "    );").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_dart_module(out: &mut String, m: &HybridModuleSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&m.name);
    emit_dart_vtable_struct(out, &pascal, &m.methods, false, spec);

    writeln!(out, "abstract interface class Hybrid{pascal}Spec {{").unwrap();
    for method in &m.methods {
        writeln!(out, "  {};", dart_method_sig(method)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_dart_client(out, &pascal, m.interface_id(), m.schema_hash(spec), &m.methods, None, spec);
}

fn emit_dart_view(out: &mut String, v: &HybridViewSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&v.name);

    writeln!(out, "class {pascal}Props implements NveDirectEncodable {{").unwrap();
    for p in &v.props {
        let pname = dart_ident(&p.name);
        writeln!(out, "  final {} {pname};", dart_type(&p.ty)).unwrap();
    }
    writeln!(out).unwrap();
    write!(out, "  {pascal}Props({{").unwrap();
    for p in &v.props {
        let pname = dart_ident(&p.name);
        let def = dart_default_value(&p.ty, p.default_value.as_ref(), spec);
        if dart_is_const_expr(&p.ty, p.default_value.as_ref()) {
            write!(out, "this.{pname} = {def}, ").unwrap();
        } else {
            write!(out, "{}? {pname}, ", dart_type_non_nullable(&p.ty)).unwrap();
        }
    }
    writeln!(out, "}})").unwrap();
    let non_const_inits: Vec<String> = v
        .props
        .iter()
        .filter(|p| !dart_is_const_expr(&p.ty, p.default_value.as_ref()))
        .map(|p| {
            let pname = dart_ident(&p.name);
            let def = dart_default_value(&p.ty, p.default_value.as_ref(), spec);
            format!("{pname} = {pname} ?? {def}")
        })
        .collect();
    if !non_const_inits.is_empty() {
        writeln!(out, "      : {};", non_const_inits.join(",\n        ")).unwrap();
    } else {
        writeln!(out, "      ;").unwrap();
    }
    writeln!(out).unwrap();
    writeln!(out, "  @override").unwrap();
    writeln!(out, "  int get directPropCount => {};", v.props.len()).unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  @override").unwrap();
    writeln!(out, "  void encodeDirect(NveDirectPropsBuilder builder) {{").unwrap();
    for p in &v.props {
        let pname = dart_ident(&p.name);
        let key_lit = escape_dart_single_quoted_string(&p.name);
        emit_dart_direct_prop_write(out, &key_lit, &pname, &p.ty);
    }
    writeln!(out, "  }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    for ev in &v.events {
        let ev_pascal = to_pascal_case(&ev.name);
        writeln!(out, "class {pascal}{ev_pascal}Event {{").unwrap();
        for param in &ev.params {
            let pname = dart_ident(&param.name);
            writeln!(out, "  final {} {pname};", dart_type(&param.ty)).unwrap();
        }
        writeln!(out).unwrap();
        write!(out, "  const {pascal}{ev_pascal}Event({{").unwrap();
        for param in &ev.params {
            let pname = dart_ident(&param.name);
            write!(out, "required this.{pname}, ").unwrap();
        }
        writeln!(out, "}});").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    emit_dart_vtable_struct(out, &pascal, &v.methods, true, spec);

    writeln!(out, "abstract interface class Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, "  void setProps({pascal}Props props);").unwrap();
    for method in &v.methods {
        writeln!(out, "  {};", dart_method_sig(method)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    emit_dart_client(out, &pascal, v.interface_id(), v.schema_hash(spec), &v.methods, Some(v), spec);
}

fn emit_dart_vtable_struct(
    out: &mut String,
    pascal: &str,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    for m in methods {
        let mp = to_pascal_case(&m.name);
        let native_ret = dart_native_return_type(&m.return_type, spec);
        let dart_ret = dart_ffi_call_return_type(&m.return_type, spec);
        let mut native_params = vec!["ffi.Pointer<ffi.Void>".to_string()];
        let mut dart_params = vec!["ffi.Pointer<ffi.Void>".to_string()];
        for p in &m.params {
            native_params.push(dart_native_param_type(&p.ty, spec));
            dart_params.push(dart_ffi_call_param_type(&p.ty, spec));
        }
        if let HybridType::Result { ok, .. } = &m.return_type {
            if !matches!(ok.as_ref(), HybridType::Void) {
                let ptr_ty = format!("ffi.Pointer<{}>", dart_native_value_type(ok, spec));
                native_params.push(ptr_ty.clone());
                dart_params.push(ptr_ty);
            }
            native_params.push("ffi.Pointer<NveHybridOwnedBytes>".to_string());
            dart_params.push("ffi.Pointer<NveHybridOwnedBytes>".to_string());
        }
        writeln!(
            out,
            "typedef _{pascal}{mp}Native = {native_ret} Function({});",
            native_params.join(", ")
        )
        .unwrap();
        writeln!(
            out,
            "typedef _{pascal}{mp}Dart = {dart_ret} Function({});",
            dart_params.join(", ")
        )
        .unwrap();
    }
    writeln!(out).unwrap();

    writeln!(out, "final class NveHybrid{pascal}VTable extends ffi.Struct {{").unwrap();
    writeln!(out, "  @ffi.Uint32()").unwrap();
    writeln!(out, "  external int abiVersion;").unwrap();
    writeln!(out, "  @ffi.Uint32()").unwrap();
    writeln!(out, "  external int interfaceId;").unwrap();
    writeln!(out, "  @ffi.Uint64()").unwrap();
    writeln!(out, "  external int schemaHash;").unwrap();
    writeln!(out, "  external ffi.Pointer<ffi.NativeFunction<_NveCreateNative>> create;").unwrap();
    writeln!(out, "  external ffi.Pointer<ffi.NativeFunction<_NveDestroyNative>> destroy;").unwrap();
    writeln!(out, "  external ffi.Pointer<ffi.NativeFunction<_NveAllocBytesNative>> allocBytes;").unwrap();
    writeln!(out, "  external ffi.Pointer<ffi.NativeFunction<_NveFreeBytesNative>> freeBytes;").unwrap();
    if is_view {
        writeln!(
            out,
            "  external ffi.Pointer<ffi.NativeFunction<_NveSetPropsDirectNative>> setPropsDirect;"
        )
        .unwrap();
    }
    for m in methods {
        let mp = to_pascal_case(&m.name);
        let mfield = dart_ident(&m.name);
        writeln!(
            out,
            "  external ffi.Pointer<ffi.NativeFunction<_{pascal}{mp}Native>> {mfield};"
        )
        .unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_dart_client(
    out: &mut String,
    pascal: &str,
    interface_id: u32,
    schema_hash: u64,
    methods: &[HybridMethodSpec],
    view: Option<&HybridViewSpec>,
    spec: &HybridFileSpec,
) {
    writeln!(out, "class {pascal}HybridClient implements Hybrid{pascal}Spec {{").unwrap();
    writeln!(out, "  static const int interfaceId = 0x{interface_id:08X};").unwrap();
    writeln!(
        out,
        "  static const int schemaHash = {};",
        dart_u64_const(schema_hash)
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "  final ffi.Pointer<NveHybrid{pascal}VTable> _vtable;").unwrap();
    writeln!(out, "  ffi.Pointer<ffi.Void> _handle;").unwrap();
    writeln!(out, "  final _NveDestroyDart _destroy;").unwrap();
    writeln!(out, "  final _NveAllocBytesDart _allocBytes;").unwrap();
    writeln!(out, "  final _NveFreeBytesDart _freeBytes;").unwrap();
    if view.is_some() {
        writeln!(out, "  final _NveSetPropsDirectDart _setPropsDirect;").unwrap();
    }
    writeln!(out).unwrap();

    writeln!(
        out,
        "  static {pascal}HybridClient resolve(ffi.DynamicLibrary library) {{"
    )
    .unwrap();
    writeln!(
        out,
        "    final getIface = library.lookupFunction<_NveGetInterfaceNative, _NveGetInterfaceDart>('nve_get_interface');"
    )
    .unwrap();
    writeln!(out, "    final raw = getIface(interfaceId);").unwrap();
    writeln!(out, "    if (raw == ffi.nullptr) {{").unwrap();
    writeln!(
        out,
        "      throw StateError('NVE hybrid interface {pascal} (0x{interface_id:08X}) not found');"
    )
    .unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(
        out,
        "    return {pascal}HybridClient._(raw.cast<NveHybrid{pascal}VTable>());"
    )
    .unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  {pascal}HybridClient._(this._vtable)").unwrap();
    writeln!(out, "      : _handle = ffi.nullptr,").unwrap();
    writeln!(out, "        _destroy = _vtable.ref.destroy.asFunction<_NveDestroyDart>(),")
        .unwrap();
    writeln!(
        out,
        "        _allocBytes = _vtable.ref.allocBytes.asFunction<_NveAllocBytesDart>(),"
    )
    .unwrap();
    writeln!(
        out,
        "        _freeBytes = _vtable.ref.freeBytes.asFunction<_NveFreeBytesDart>()"
    )
    .unwrap();
    if view.is_some() {
        writeln!(
            out,
            "        , _setPropsDirect = _vtable.ref.setPropsDirect.asFunction<_NveSetPropsDirectDart>()"
        )
        .unwrap();
    }
    writeln!(out, "  {{").unwrap();
    writeln!(
        out,
        "    if (_vtable.ref.abiVersion != nveHybridAbiVersion || _vtable.ref.schemaHash != schemaHash) {{"
    )
    .unwrap();
    writeln!(
        out,
        "      throw StateError('NVE hybrid schema hash mismatch for {pascal}');"
    )
    .unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    final createFn = _vtable.ref.create.asFunction<_NveCreateDart>();").unwrap();
    writeln!(out, "    _handle = createFn();").unwrap();
    writeln!(out, "    if (_handle == ffi.nullptr) {{").unwrap();
    writeln!(out, "      throw StateError('failed to create {pascal} hybrid instance');").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "  void dispose() {{").unwrap();
    writeln!(out, "    if (_handle != ffi.nullptr) {{").unwrap();
    writeln!(out, "      _destroy(_handle);").unwrap();
    writeln!(out, "      _handle = ffi.nullptr;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out).unwrap();

    let mut methods_body = String::new();
    if let Some(v) = view {
        emit_dart_set_props(&mut methods_body, pascal, v);
    }

    for m in methods {
        emit_dart_client_method(&mut methods_body, pascal, m, spec);
    }

    out.push_str(&methods_body);

    if methods_body.contains("_copyToNative(") {
        writeln!(out, "  NveHybridOwnedBytes _copyToNative(List<int> bytes) {{").unwrap();
        writeln!(out, "    if (bytes.isEmpty) return ffi.Struct.create<NveHybridOwnedBytes>();").unwrap();
        writeln!(out, "    final buf = _allocBytes(bytes.length);").unwrap();
        writeln!(out, "    buf.ptr.asTypedList(bytes.length).setAll(0, bytes);").unwrap();
        writeln!(out, "    return buf;").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    }

    if methods_body.contains("_takeString(") {
        writeln!(out, "  String _takeString(NveHybridOwnedBytes raw) {{").unwrap();
        writeln!(out, "    try {{").unwrap();
        writeln!(out, "      if (raw.ptr == ffi.nullptr || raw.len == 0) return '';").unwrap();
        writeln!(out, "      return utf8.decode(raw.ptr.asTypedList(raw.len));").unwrap();
        writeln!(out, "    }} finally {{").unwrap();
        writeln!(out, "      if (raw.ptr != ffi.nullptr) _freeBytes(raw);").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "  }}").unwrap();
        writeln!(out).unwrap();
    }

    if methods_body.contains("_takeBytes(") {
        writeln!(out, "  Uint8List _takeBytes(NveHybridOwnedBytes raw) {{").unwrap();
        writeln!(out, "    try {{").unwrap();
        writeln!(out, "      if (raw.ptr == ffi.nullptr || raw.len == 0) return Uint8List(0);").unwrap();
        writeln!(out, "      return Uint8List.fromList(raw.ptr.asTypedList(raw.len));").unwrap();
        writeln!(out, "    }} finally {{").unwrap();
        writeln!(out, "      if (raw.ptr != ffi.nullptr) _freeBytes(raw);").unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "  }}").unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_dart_direct_prop_write(out: &mut String, key_lit: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "    builder.writeBool('{key_lit}', {expr});").unwrap(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => writeln!(out, "    builder.writeInt64('{key_lit}', {expr});").unwrap(),
        HybridType::Enum(_) => {
            writeln!(out, "    builder.writeInt64('{key_lit}', {expr}.rawValue);").unwrap()
        }
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "    builder.writeDouble('{key_lit}', {expr});").unwrap()
        }
        HybridType::String => {
            writeln!(out, "    builder.writeString('{key_lit}', {expr});").unwrap()
        }
        HybridType::Bytes => writeln!(out, "    builder.writeBytes('{key_lit}', {expr});").unwrap(),
        HybridType::Optional(inner) => match inner.as_ref() {
            HybridType::Bool => {
                writeln!(out, "    builder.writeBool('{key_lit}', {expr});").unwrap()
            }
            HybridType::U8
            | HybridType::U16
            | HybridType::Usize
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64 => {
                writeln!(out, "    builder.writeInt64('{key_lit}', {expr});").unwrap()
            }
            HybridType::Enum(_) => {
                writeln!(out, "    builder.writeInt64('{key_lit}', {expr}?.rawValue);").unwrap()
            }
            HybridType::F32 | HybridType::F64 => {
                writeln!(out, "    builder.writeDouble('{key_lit}', {expr});").unwrap()
            }
            HybridType::String => {
                writeln!(out, "    builder.writeString('{key_lit}', {expr});").unwrap()
            }
            HybridType::Bytes => {
                writeln!(out, "    builder.writeBytes('{key_lit}', {expr});").unwrap()
            }
            other => {
                writeln!(out, "    final _opt_{expr} = {expr};").unwrap();
                writeln!(out, "    if (_opt_{expr} == null) {{").unwrap();
                writeln!(out, "      builder.writeNull('{key_lit}');").unwrap();
                writeln!(out, "    }} else {{").unwrap();
                writeln!(out, "      final _bw = NveBinWriter();").unwrap();
                emit_dart_bin_write(out, "      ", "_bw", &format!("_opt_{expr}"), other);
                writeln!(out, "      builder.writeBytes('{key_lit}', _bw.takeBytes());").unwrap();
                writeln!(out, "    }}").unwrap();
            }
        },
        other => {
            writeln!(out, "    {{").unwrap();
            writeln!(out, "      final _bw = NveBinWriter();").unwrap();
            emit_dart_bin_write(out, "      ", "_bw", expr, other);
            writeln!(out, "      builder.writeBytes('{key_lit}', _bw.takeBytes());").unwrap();
            writeln!(out, "    }}").unwrap();
        }
    }
}

