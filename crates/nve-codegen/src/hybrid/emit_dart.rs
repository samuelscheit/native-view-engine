fn dart_u64_const(v: u64) -> String {
    // Dart signed 64-bit int literal syntax: represent values >= 2^63 cleanly using signed two's complement.
    let signed = v as i64;
    if signed < 0 {
        format!("{signed} /* 0x{v:016X} */")
    } else {
        format!("0x{v:016X}")
    }
}

fn dart_is_const_expr(ty: &HybridType, def: Option<&HybridDefaultValue>) -> bool {
    if matches!(ty, HybridType::Optional(_)) {
        return match def {
            None | Some(HybridDefaultValue::None) => true,
            Some(_) => matches!(
                ty,
                HybridType::Optional(inner) if dart_is_const_expr(inner, def)
            ),
        };
    }
    matches!(
        ty,
        HybridType::Bool
            | HybridType::I32
            | HybridType::U32
            | HybridType::I64
            | HybridType::U64
            | HybridType::F32
            | HybridType::F64
            | HybridType::String
            | HybridType::Enum(_)
    )
}

fn dart_default_value(
    ty: &HybridType,
    def: Option<&HybridDefaultValue>,
    spec: &HybridFileSpec,
) -> String {
    if let Some(d) = def {
        if let HybridType::Optional(inner) = ty {
            return match d {
                HybridDefaultValue::None => "null".to_string(),
                other => dart_default_value(inner, Some(other), spec),
            };
        }
        return match (d, ty) {
            (HybridDefaultValue::Bool(b), _) => b.to_string(),
            (HybridDefaultValue::Int(i), HybridType::F32 | HybridType::F64) => format!("{i}.0"),
            (HybridDefaultValue::Int(i), _) => i.to_string(),
            (HybridDefaultValue::UInt(u), HybridType::F32 | HybridType::F64) => format!("{u}.0"),
            (HybridDefaultValue::UInt(u), _) => u.to_string(),
            (HybridDefaultValue::Float(f), _) => format_float_literal(*f),
            (HybridDefaultValue::String(s), _) => format!("'{}'", escape_dart_single_quoted_string(s)),
            (HybridDefaultValue::EnumVariant { enum_name, variant }, _) => {
                format!("{enum_name}.{}", dart_ident(variant))
            }
            (HybridDefaultValue::None, _) => "null".to_string(),
        };
    }

    match ty {
        HybridType::Bool => "false".to_string(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => "0".to_string(),
        HybridType::F32 | HybridType::F64 => "0.0".to_string(),
        HybridType::String => "''".to_string(),
        HybridType::Bytes => "Uint8List(0)".to_string(),
        HybridType::Optional(_) => "null".to_string(),
        HybridType::Vec(inner) => format!("<{}>[]", dart_type(inner)),
        HybridType::Struct(name) => {
            if let Some(s) = spec.find_struct(name) {
                let args: Vec<String> = s
                    .fields
                    .iter()
                    .map(|f| {
                        format!(
                            "{}: {}",
                            dart_ident(&f.name),
                            dart_default_value(&f.ty, None, spec)
                        )
                    })
                    .collect();
                format!("{name}({})", args.join(", "))
            } else {
                format!("{name}()")
            }
        }
        HybridType::Enum(name) => {
            if let Some(e) = spec.find_enum(name) {
                format!("{name}.{}", dart_ident(&e.variants[0].name))
            } else {
                format!("{name}.fromRaw(0)")
            }
        }
        HybridType::Value => "NveHybridDynamicValue()".to_string(),
        HybridType::ConstPtr(_) | HybridType::MutPtr(_) | HybridType::Handle(_) => {
            "ffi.nullptr".to_string()
        }
        HybridType::Void | HybridType::Result { .. } => "null".to_string(),
    }
}

fn emit_dart_bin_write(out: &mut String, indent: &str, w: &str, expr: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{w}.writeBool({expr});").unwrap(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => writeln!(out, "{indent}{w}.writeInt64({expr});").unwrap(),
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "{indent}{w}.writeDouble({expr});").unwrap()
        }
        HybridType::Enum(_) => writeln!(out, "{indent}{w}.writeInt64({expr}.rawValue);").unwrap(),
        HybridType::String => writeln!(out, "{indent}{w}.writeString({expr});").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{w}.writeBytes({expr});").unwrap(),
        HybridType::Struct(_) => writeln!(out, "{indent}{expr}.encodeBin({w});").unwrap(),
        HybridType::Value => writeln!(out, "{indent}{w}.writeRaw({expr}.binBytes);").unwrap(),
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}final _ov = {expr};").unwrap();
            writeln!(out, "{indent}if (_ov != null) {{").unwrap();
            emit_dart_bin_write(out, &format!("{indent}  "), w, "_ov", inner);
            writeln!(out, "{indent}}} else {{ {w}.writeNull(); }}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}{w}.writeArray({expr}.length, (aw) {{").unwrap();
            writeln!(out, "{indent}  for (final _el in {expr}) {{").unwrap();
            emit_dart_bin_write(out, &format!("{indent}    "), "aw", "_el", inner);
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}}});").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {}
    }
}

fn emit_dart_bin_read(out: &mut String, indent: &str, r: &str, dst: &str, ty: &HybridType) {
    match ty {
        HybridType::Bool => writeln!(out, "{indent}{dst} = {r}.readBool();").unwrap(),
        HybridType::U8
        | HybridType::U16
        | HybridType::Usize
        | HybridType::I32
        | HybridType::U32
        | HybridType::I64
        | HybridType::U64 => writeln!(out, "{indent}{dst} = {r}.readInt64();").unwrap(),
        HybridType::F32 | HybridType::F64 => {
            writeln!(out, "{indent}{dst} = {r}.readDouble();").unwrap()
        }
        HybridType::Enum(e) => {
            writeln!(out, "{indent}{dst} = {e}.fromRaw({r}.readInt64());").unwrap()
        }
        HybridType::String => writeln!(out, "{indent}{dst} = {r}.readString();").unwrap(),
        HybridType::Bytes => writeln!(out, "{indent}{dst} = {r}.readBytes();").unwrap(),
        HybridType::Struct(s) => writeln!(out, "{indent}{dst} = {s}.decodeBin({r});").unwrap(),
        HybridType::Value => {
            writeln!(out, "{indent}{dst} = NveHybridDynamicValue({r}.readRawValue());").unwrap()
        }
        HybridType::Optional(inner) => {
            writeln!(out, "{indent}if ({r}.readNullIfPresent()) {{").unwrap();
            writeln!(out, "{indent}  {dst} = null;").unwrap();
            writeln!(out, "{indent}}} else {{").unwrap();
            writeln!(out, "{indent}  late final {} _ov;", dart_type(inner)).unwrap();
            emit_dart_bin_read(out, &format!("{indent}  "), r, "_ov", inner);
            writeln!(out, "{indent}  {dst} = _ov;").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Vec(inner) => {
            writeln!(out, "{indent}{{").unwrap();
            writeln!(out, "{indent}  final _n = {r}.beginArray();").unwrap();
            writeln!(out, "{indent}  final _list = <{}>[];", dart_type(inner)).unwrap();
            writeln!(out, "{indent}  for (var _i = 0; _i < _n; _i++) {{").unwrap();
            writeln!(out, "{indent}    late final {} _el;", dart_type(inner)).unwrap();
            emit_dart_bin_read(out, &format!("{indent}    "), r, "_el", inner);
            writeln!(out, "{indent}    _list.add(_el);").unwrap();
            writeln!(out, "{indent}  }}").unwrap();
            writeln!(out, "{indent}  {dst} = _list;").unwrap();
            writeln!(out, "{indent}}}").unwrap();
        }
        HybridType::Void
        | HybridType::Result { .. }
        | HybridType::ConstPtr(_)
        | HybridType::MutPtr(_)
        | HybridType::Handle(_) => {}
    }
}
