fn export_cpp_prop_type(ty: &PropType) -> &'static str {
    match ty {
        PropType::Bool => "bool",
        PropType::Int32 | PropType::IntEnum { .. } => "int32_t",
        PropType::Float => "float",
        PropType::Double => "double",
        PropType::String
        | PropType::Color
        | PropType::ImageSource
        | PropType::Point
        | PropType::EdgeInsets
        | PropType::Dimension
        | PropType::StringEnum { .. }
        | PropType::Array { .. }
        | PropType::Object { .. }
        | PropType::Mixed
        | PropType::Void
        | PropType::Promise { .. }
        | PropType::Callback { .. } => "std::string",
    }
}

fn export_cpp_default(prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32 | PropType::IntEnum { .. }, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float, DefaultValue::Int(i)) => Some(format!("{i}.0f")),
        (PropType::Float, DefaultValue::Float(f)) => {
            Some(format!("{}f", format_float_literal(*f)))
        }
        (PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Double, DefaultValue::Float(f)) => Some(format_float_literal(*f)),
        (PropType::String | PropType::StringEnum { .. } | PropType::Color, DefaultValue::String(s)) => {
            Some(format!("\"{}\"", escape_string_literal(s)))
        }
        _ => None,
    }
}

fn cpp_prop_to_variant(expr: &str, ty: &PropType) -> String {
    match ty {
        PropType::Bool => format!("nve::PropValue{{{expr}}}"),
        PropType::Int32 | PropType::IntEnum { .. } => {
            format!("nve::PropValue{{static_cast<int64_t>({expr})}}")
        }
        PropType::Float | PropType::Double => {
            format!("nve::PropValue{{static_cast<double>({expr})}}")
        }
        _ => format!("nve::PropValue{{{expr}}}"),
    }
}

