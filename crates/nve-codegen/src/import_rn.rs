//! Direction 1 (`import_rn`): React Native Fabric Component / TurboModule spec ->
//! Zero-JS typed Rust `nve-dioxus` module + thin C++20 Fabric adapter (`cxx/nve-fabric-bridge`).

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::ir::{
    DefaultValue, EventBubbling, EventSpec, GeneratedFile, ImportRnOutput, ObjectField,
    ParsedRnSpec, PropSpec, PropType, RnComponentSpec, TurboModuleSpec,
};
use crate::naming::{
    cpp_ident, escape_string_literal, format_float_literal, rust_ident, strip_on_prefix,
    to_pascal_case, to_snake_case,
};

/// Generates zero-JS Rust `nve-dioxus` bindings and a thin C++20 Fabric adapter from a parsed RN spec.
pub fn generate_import_rn(spec: &ParsedRnSpec) -> Result<ImportRnOutput, CodegenError> {
    match spec {
        ParsedRnSpec::Component(comp) => generate_component_import(comp),
        ParsedRnSpec::TurboModule(tm) => generate_turbomodule_import(tm),
    }
}

fn generate_component_import(spec: &RnComponentSpec) -> Result<ImportRnOutput, CodegenError> {
    let mod_name = to_snake_case(&spec.component_name);
    let rust_source = emit_component_rust(spec, &mod_name);
    let cpp_source = emit_component_cpp(spec);

    Ok(ImportRnOutput {
        spec: ParsedRnSpec::Component(spec.clone()),
        rust_module: GeneratedFile {
            relative_path: format!("{mod_name}.rs"),
            content: rust_source,
        },
        cpp_adapter: GeneratedFile {
            relative_path: format!("{mod_name}_fabric_adapter.hpp"),
            content: cpp_source,
        },
    })
}

fn generate_turbomodule_import(spec: &TurboModuleSpec) -> Result<ImportRnOutput, CodegenError> {
    let mod_name = to_snake_case(&spec.module_name);
    let rust_source = emit_turbomodule_rust(spec, &mod_name);
    let cpp_source = emit_turbomodule_cpp(spec);

    Ok(ImportRnOutput {
        spec: ParsedRnSpec::TurboModule(spec.clone()),
        rust_module: GeneratedFile {
            relative_path: format!("{mod_name}_module.rs"),
            content: rust_source,
        },
        cpp_adapter: GeneratedFile {
            relative_path: format!("{mod_name}_turbomodule_adapter.hpp"),
            content: cpp_source,
        },
    })
}

// ===========================================================================
// Rust `nve-dioxus` Component Emitter
// ===========================================================================

fn emit_component_rust(spec: &RnComponentSpec, mod_name: &str) -> String {
    let pascal = to_pascal_case(&spec.component_name);
    let mut out = String::with_capacity(4096);

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native Fabric component `{}`.",
        spec.component_name
    );
    let _ = writeln!(out, "// Zero-JS typed Rust `nve-dioxus` bindings + `nve-abi` prop builders.");
    let _ = writeln!(out);
    let _ = writeln!(out, "#![allow(dead_code, clippy::all)]");
    let _ = writeln!(out);
    let _ = writeln!(out, "pub mod {mod_name} {{");
    let _ = writeln!(
        out,
        "    use nve_abi::{{ColorRgba, CommandBufferBuilder, ComponentKind, EventMask, EventPayload, NativeEvent, NativeEventKind, NodeId, RawPropValue}};"
    );
    let _ = writeln!(
        out,
        "    use nve_dioxus::elements::AttributeDescription;"
    );
    let _ = writeln!(out, "    use serde::{{Deserialize, Serialize}};");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    /// React Native Fabric component name registered in the native host."
    );
    let _ = writeln!(
        out,
        "    pub const COMPONENT_NAME: &str = \"{}\";",
        escape_string_literal(&spec.component_name)
    );
    let _ = writeln!(
        out,
        "    pub const TAG_NAME: &'static str = COMPONENT_NAME;"
    );
    let _ = writeln!(
        out,
        "    pub const NAME_SPACE: Option<&'static str> = None;"
    );
    if let Some(paper) = &spec.options.paper_component_name {
        let _ = writeln!(
            out,
            "    pub const PAPER_COMPONENT_NAME: &str = \"{}\";",
            escape_string_literal(paper)
        );
    }
    let _ = writeln!(out);

    // 1. Emit auxiliary enums/structs for enum & object props
    for prop in &spec.props {
        emit_rust_aux_types(&mut out, &pascal, &prop.name, &prop.prop_type, prop.default_value.as_ref());
    }

    // 2. Emit typed event payload structs + unified component event enum
    for ev in &spec.events {
        emit_rust_event_payload(&mut out, &pascal, ev);
    }

    if !spec.events.is_empty() {
        let _ = writeln!(out, "    #[derive(Debug, Clone, PartialEq)]");
        let _ = writeln!(out, "    pub enum {pascal}Event {{");
        for ev in &spec.events {
            let variant = to_pascal_case(&strip_on_prefix(&ev.name));
            if ev.payload.is_empty() {
                let _ = writeln!(out, "        {variant},");
            } else {
                let payload_ty = format!("{pascal}{}Event", variant);
                let _ = writeln!(out, "        {variant}({payload_ty}),");
            }
        }
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);

        let _ = writeln!(
            out,
            "    /// Decodes a `NativeEventKind::Custom` event emitted by `{}` into a typed `{pascal}Event`.",
            spec.component_name
        );
        let _ = writeln!(
            out,
            "    pub fn decode_event(event: &NativeEvent) -> Option<{pascal}Event> {{"
        );
        let _ = writeln!(
            out,
            "        if event.kind != NativeEventKind::Custom {{"
        );
        let _ = writeln!(out, "            return None;");
        let _ = writeln!(out, "        }}");
        let _ = writeln!(
            out,
            "        let EventPayload::Custom {{ name, data }} = &event.payload else {{"
        );
        let _ = writeln!(out, "            return None;");
        let _ = writeln!(out, "        }};");
        let _ = writeln!(out, "        match name.as_str() {{");
        for ev in &spec.events {
            let variant = to_pascal_case(&strip_on_prefix(&ev.name));
            let short_name = strip_on_prefix(&ev.name);
            let pattern = if let Some(paper) = &ev.paper_top_level_name {
                format!(
                    "\"{}\" | \"{}\" | \"{}\"",
                    escape_string_literal(&ev.name),
                    escape_string_literal(&short_name),
                    escape_string_literal(paper)
                )
            } else {
                format!(
                    "\"{}\" | \"{}\"",
                    escape_string_literal(&ev.name),
                    escape_string_literal(&short_name)
                )
            };
            if ev.payload.is_empty() {
                let _ = writeln!(
                    out,
                    "            {pattern} => Some({pascal}Event::{variant}),"
                );
            } else {
                let payload_ty = format!("{pascal}{}Event", variant);
                let _ = writeln!(
                    out,
                    "            {pattern} => serde_json::from_slice::<{payload_ty}>(data).ok().map({pascal}Event::{variant}),"
                );
            }
        }
        let _ = writeln!(out, "            _ => None,");
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
    }

    // 3. Emit `dioxus_elements` attribute constants
    let _ = writeln!(out, "    /// Attribute descriptors for Dioxus `rsx!{{}}` templates.");
    let _ = writeln!(out, "    pub mod attrs {{");
    let _ = writeln!(out, "        use super::AttributeDescription;");
    if spec.extends_view_props {
        let _ = writeln!(out, "        pub const style: AttributeDescription = (\"style\", None, false);");
        let _ = writeln!(out, "        pub const test_id: AttributeDescription = (\"testID\", None, false);");
    }
    for prop in &spec.props {
        let ident = rust_ident(&prop.name);
        let _ = writeln!(
            out,
            "        #[allow(non_upper_case_globals)]\n        pub const {ident}: AttributeDescription = (\"{}\", None, false);",
            escape_string_literal(&prop.name)
        );
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    // 4. Emit typed Dioxus event listener helpers
    if !spec.events.is_empty() {
        let _ = writeln!(out, "    /// Typed Dioxus event attribute constructors.");
        let _ = writeln!(out, "    pub mod events {{");
        let _ = writeln!(out, "        use super::*;");
        let _ = writeln!(
            out,
            "        use nve_dioxus::prelude::dioxus_core::{{Attribute, AttributeValue, Event}};"
        );
        for ev in &spec.events {
            let fn_name = rust_ident(&ev.name);
            let variant = to_pascal_case(&strip_on_prefix(&ev.name));
            let event_ty = if ev.payload.is_empty() {
                "Event<()>".to_owned()
            } else {
                format!("Event<{pascal}{variant}Event>")
            };
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "        pub fn {fn_name}(handler: impl FnMut({event_ty}) + 'static) -> Attribute {{"
            );
            let _ = writeln!(
                out,
                "            Attribute::new(\"{}\", AttributeValue::listener(handler), None, false)",
                escape_string_literal(&ev.name)
            );
            let _ = writeln!(out, "        }}");
        }
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
    }

    // 5. Emit typed Props struct + builder methods + CommandBufferBuilder encoder
    let _ = writeln!(out, "    #[derive(Debug, Clone, PartialEq, Default)]");
    let _ = writeln!(out, "    pub struct {pascal}Props {{");
    for prop in &spec.props {
        if let Some(doc) = &prop.doc {
            for line in doc.lines() {
                let _ = writeln!(out, "        /// {line}");
            }
        }
        let field = rust_ident(&prop.name);
        let ty = rust_prop_type(&pascal, &prop.name, &prop.prop_type);
        if prop.optional || prop.nullable {
            let _ = writeln!(out, "        pub {field}: Option<{ty}>,");
        } else {
            let _ = writeln!(out, "        pub {field}: {ty},");
        }
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    let _ = writeln!(out, "    impl {pascal}Props {{");
    let _ = writeln!(out, "        pub fn new() -> Self {{");
    let _ = writeln!(out, "            Self::default()");
    let _ = writeln!(out, "        }}");

    for prop in &spec.props {
        let field = rust_ident(&prop.name);
        let method = format!("with_{}", to_snake_case(&prop.name));
        let ty = rust_prop_type(&pascal, &prop.name, &prop.prop_type);
        let _ = writeln!(out);
        if prop.optional || prop.nullable {
            let _ = writeln!(
                out,
                "        pub fn {method}(mut self, value: impl Into<{ty}>) -> Self {{"
            );
            let _ = writeln!(out, "            self.{field} = Some(value.into());");
            let _ = writeln!(out, "            self");
            let _ = writeln!(out, "        }}");
        } else {
            let _ = writeln!(
                out,
                "        pub fn {method}(mut self, value: impl Into<{ty}>) -> Self {{"
            );
            let _ = writeln!(out, "            self.{field} = value.into();");
            let _ = writeln!(out, "            self");
            let _ = writeln!(out, "        }}");
        }
    }

    // Create node + encode all typed props directly into binary `CommandBufferBuilder`
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "        /// Emits `CreateNode(ComponentKind::Custom, Some(\"{}\"))` and all typed raw props.",
        spec.component_name
    );
    let _ = writeln!(
        out,
        "        pub fn mount(&self, builder: &mut CommandBufferBuilder, node_id: NodeId) {{"
    );
    let _ = writeln!(
        out,
        "            builder.create_node(node_id, ComponentKind::Custom, Some(COMPONENT_NAME));"
    );
    let _ = writeln!(out, "            self.encode_props(builder, node_id);");
    if !spec.events.is_empty() {
        let _ = writeln!(out, "            builder.set_event_mask(node_id, EventMask::CUSTOM);");
    }
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "        /// Writes all configured props into `builder` via `RawPropValue` without JS/JSON overhead."
    );
    let _ = writeln!(
        out,
        "        pub fn encode_props(&self, builder: &mut CommandBufferBuilder, node_id: NodeId) {{"
    );
    for prop in &spec.props {
        let field = rust_ident(&prop.name);
        let key = escape_string_literal(&prop.name);
        if prop.optional || prop.nullable {
            let _ = writeln!(out, "            if let Some(ref val) = self.{field} {{");
            let expr = rust_to_raw_prop_expr("val", &prop.prop_type, true);
            let _ = writeln!(
                out,
                "                builder.set_raw_prop(node_id, \"{key}\", &{expr});"
            );
            let _ = writeln!(out, "            }}");
        } else {
            let expr = rust_to_raw_prop_expr(&format!("self.{field}"), &prop.prop_type, false);
            let _ = writeln!(
                out,
                "            builder.set_raw_prop(node_id, \"{key}\", &{expr});"
            );
        }
    }
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");

    // 6. Native Commands
    if !spec.commands.is_empty() {
        let _ = writeln!(out);
        let _ = writeln!(out, "    /// Imperative native commands (`codegenNativeCommands`).");
        let _ = writeln!(out, "    pub mod commands {{");
        let _ = writeln!(out, "        use super::*;");
        for cmd in &spec.commands {
            let fn_name = rust_ident(&cmd.name);
            let mut sig = String::from("builder: &mut CommandBufferBuilder, node_id: NodeId");
            for p in &cmd.params {
                let pname = rust_ident(&p.name);
                let pty = rust_simple_type(&p.param_type);
                let _ = write!(sig, ", {pname}: {pty}");
            }
            let _ = writeln!(out);
            let _ = writeln!(out, "        pub fn {fn_name}({sig}) {{");
            if cmd.params.is_empty() {
                let _ = writeln!(
                    out,
                    "            builder.dispatch_command(node_id, \"{}\", &[]);",
                    escape_string_literal(&cmd.name)
                );
            } else {
                let _ = writeln!(out, "            let payload = serde_json::json!({{");
                for p in &cmd.params {
                    let pname = rust_ident(&p.name);
                    let _ = writeln!(
                        out,
                        "                \"{}\": {pname},",
                        escape_string_literal(&p.name)
                    );
                }
                let _ = writeln!(out, "            }}).to_string();");
                let _ = writeln!(
                    out,
                    "            builder.dispatch_command(node_id, \"{}\", payload.as_bytes());",
                    escape_string_literal(&cmd.name)
                );
            }
            let _ = writeln!(out, "        }}");
        }
        let _ = writeln!(out, "    }}");
    }

    let _ = writeln!(out, "}}");
    out
}

fn emit_rust_aux_types(
    out: &mut String,
    comp_pascal: &str,
    prop_name: &str,
    prop_type: &PropType,
    default_val: Option<&DefaultValue>,
) {
    match prop_type {
        PropType::StringEnum { variants } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(prop_name));
            let _ = writeln!(
                out,
                "    #[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]"
            );
            let _ = writeln!(out, "    pub enum {enum_name} {{");
            for v in variants {
                let v_ident = to_pascal_case(v);
                let _ = writeln!(
                    out,
                    "        #[serde(rename = \"{}\")]",
                    escape_string_literal(v)
                );
                let _ = writeln!(out, "        {v_ident},");
            }
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out);
            let _ = writeln!(out, "    impl {enum_name} {{");
            let _ = writeln!(out, "        pub const fn as_str(self) -> &'static str {{");
            let _ = writeln!(out, "            match self {{");
            for v in variants {
                let v_ident = to_pascal_case(v);
                let _ = writeln!(
                    out,
                    "                Self::{v_ident} => \"{}\",",
                    escape_string_literal(v)
                );
            }
            let _ = writeln!(out, "            }}");
            let _ = writeln!(out, "        }}");
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out);
            if let Some(first) = variants.first() {
                let def_variant = match default_val {
                    Some(DefaultValue::String(s)) if variants.contains(s) => to_pascal_case(s),
                    _ => to_pascal_case(first),
                };
                let _ = writeln!(out, "    impl Default for {enum_name} {{");
                let _ = writeln!(out, "        fn default() -> Self {{ Self::{def_variant} }}");
                let _ = writeln!(out, "    }}");
                let _ = writeln!(out);
            }
            let _ = writeln!(out, "    impl From<{enum_name}> for RawPropValue {{");
            let _ = writeln!(
                out,
                "        fn from(v: {enum_name}) -> Self {{ RawPropValue::String(v.as_str().to_owned()) }}"
            );
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out);
        }
        PropType::IntEnum { variants } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(prop_name));
            let _ = writeln!(
                out,
                "    #[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]"
            );
            let _ = writeln!(out, "    pub enum {enum_name} {{");
            for v in variants {
                let v_ident = int_enum_variant_name(*v);
                let _ = writeln!(out, "        {v_ident} = {v},");
            }
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out);
            if let Some(first) = variants.first() {
                let def_v = match default_val {
                    Some(DefaultValue::Int(i)) if variants.contains(&(*i as i32)) => {
                        int_enum_variant_name(*i as i32)
                    }
                    _ => int_enum_variant_name(*first),
                };
                let _ = writeln!(out, "    impl Default for {enum_name} {{");
                let _ = writeln!(out, "        fn default() -> Self {{ Self::{def_v} }}");
                let _ = writeln!(out, "    }}");
                let _ = writeln!(out);
            }
            let _ = writeln!(out, "    impl From<{enum_name}> for RawPropValue {{");
            let _ = writeln!(
                out,
                "        fn from(v: {enum_name}) -> Self {{ RawPropValue::I64(v as i64) }}"
            );
            let _ = writeln!(out, "    }}");
            let _ = writeln!(out);
        }
        PropType::Array { item } => {
            emit_rust_aux_types(out, comp_pascal, &format!("{prop_name}Item"), item, default_val);
        }
        PropType::Object { fields } => {
            let struct_name = format!("{comp_pascal}{}", to_pascal_case(prop_name));
            emit_rust_object_struct(out, &struct_name, fields);
        }
        _ => {}
    }
}

fn emit_rust_event_payload(out: &mut String, comp_pascal: &str, ev: &EventSpec) {
    if ev.payload.is_empty() {
        return;
    }
    let variant = to_pascal_case(&strip_on_prefix(&ev.name));
    let struct_name = format!("{comp_pascal}{variant}Event");
    emit_rust_object_struct(out, &struct_name, &ev.payload);
}

fn emit_rust_object_struct(out: &mut String, struct_name: &str, fields: &[ObjectField]) {
    let _ = writeln!(
        out,
        "    #[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]"
    );
    let _ = writeln!(out, "    pub struct {struct_name} {{");
    for f in fields {
        let fname = rust_ident(&f.name);
        let fty = rust_simple_type(&f.field_type);
        let _ = writeln!(
            out,
            "        #[serde(rename = \"{}\")]",
            escape_string_literal(&f.name)
        );
        if f.optional || f.nullable {
            let _ = writeln!(out, "        pub {fname}: Option<{fty}>,");
        } else {
            let _ = writeln!(out, "        pub {fname}: {fty},");
        }
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
}

fn rust_prop_type(comp_pascal: &str, prop_name: &str, ty: &PropType) -> String {
    match ty {
        PropType::StringEnum { .. } | PropType::IntEnum { .. } | PropType::Object { .. } => {
            format!("{comp_pascal}{}", to_pascal_case(prop_name))
        }
        PropType::Array { item } => {
            let inner = rust_prop_type(comp_pascal, &format!("{prop_name}Item"), item);
            format!("Vec<{inner}>")
        }
        other => rust_simple_type(other),
    }
}

fn rust_simple_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 => "i32".to_owned(),
        PropType::Float => "f32".to_owned(),
        PropType::Double => "f64".to_owned(),
        PropType::String => "String".to_owned(),
        PropType::Color => "ColorRgba".to_owned(),
        PropType::ImageSource | PropType::Dimension | PropType::Mixed => "String".to_owned(),
        PropType::Point => "(f32, f32)".to_owned(),
        PropType::EdgeInsets => "(f32, f32, f32, f32)".to_owned(),
        PropType::StringEnum { .. } => "String".to_owned(),
        PropType::IntEnum { .. } => "i32".to_owned(),
        PropType::Array { item } => format!("Vec<{}>", rust_simple_type(item)),
        PropType::Object { .. } => "serde_json::Value".to_owned(),
        PropType::Void => "()".to_owned(),
        PropType::Promise { inner } => rust_simple_type(inner),
        PropType::Callback { .. } => "String".to_owned(),
    }
}

fn rust_to_raw_prop_expr(var: &str, ty: &PropType, is_ref: bool) -> String {
    let deref = if is_ref { format!("*{var}") } else { var.to_owned() };
    let clone = format!("{var}.clone()");
    match ty {
        PropType::Bool => format!("RawPropValue::Bool({deref})"),
        PropType::Int32 => format!("RawPropValue::I64({deref} as i64)"),
        PropType::Float => format!("RawPropValue::F64({deref} as f64)"),
        PropType::Double => format!("RawPropValue::F64({deref})"),
        PropType::String | PropType::ImageSource | PropType::Dimension | PropType::Mixed => {
            format!("RawPropValue::String({clone})")
        }
        PropType::Color => format!("RawPropValue::I64({deref}.to_u32() as i64)"),
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("RawPropValue::from({deref})")
        }
        PropType::Array { .. }
        | PropType::Object { .. }
        | PropType::Point
        | PropType::EdgeInsets => {
            format!(
                "RawPropValue::Bytes(serde_json::to_vec({ref_expr}).unwrap_or_default())",
                ref_expr = if is_ref { var.to_owned() } else { format!("&{var}") }
            )
        }
        PropType::Void | PropType::Promise { .. } | PropType::Callback { .. } => {
            "RawPropValue::Null".to_owned()
        }
    }
}

fn int_enum_variant_name(v: i32) -> String {
    if v < 0 {
        format!("Neg{}", v.unsigned_abs())
    } else {
        format!("V{v}")
    }
}

