fn emit_turbomodule_rust(spec: &TurboModuleSpec, mod_name: &str) -> String {
    let pascal = to_pascal_case(&spec.module_name);
    let mut out = String::with_capacity(2048);

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native TurboModule `{}`.",
        spec.module_name
    );
    let _ = writeln!(out, "#![allow(dead_code, clippy::all)]");
    let _ = writeln!(out);
    let _ = writeln!(out, "pub mod {mod_name} {{");
    let _ = writeln!(
        out,
        "    use nve_abi::{{CommandBufferBuilder, NodeId}};"
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    pub const MODULE_NAME: &str = \"{}\";",
        escape_string_literal(&spec.module_name)
    );
    let _ = writeln!(out, "    pub const ENFORCING: bool = {};", spec.enforcing);
    let _ = writeln!(out);

    let _ = writeln!(out, "    /// Typed zero-JS host interface for TurboModule `{}`.", spec.module_name);
    let _ = writeln!(out, "    pub trait {pascal}Module {{");
    for method in &spec.methods {
        if let Some(doc) = &method.doc {
            for line in doc.lines() {
                let _ = writeln!(out, "        /// {line}");
            }
        }
        let mname = rust_ident(&method.name);
        let mut params = String::from("&self");
        for p in &method.params {
            let pname = rust_ident(&p.name);
            let pty = rust_simple_type(&p.param_type);
            if p.optional {
                let _ = write!(params, ", {pname}: Option<{pty}>");
            } else {
                let _ = write!(params, ", {pname}: {pty}");
            }
        }
        let ret = rust_simple_type(&method.return_type);
        if ret == "()" {
            let _ = writeln!(out, "        fn {mname}({params});");
        } else {
            let _ = writeln!(out, "        fn {mname}({params}) -> {ret};");
        }
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "    /// Command-buffer bridge client dispatching TurboModule calls via `Command::DispatchCommand`."
    );
    let _ = writeln!(out, "    pub struct {pascal}Bridge;");
    let _ = writeln!(out);
    let _ = writeln!(out, "    impl {pascal}Bridge {{");
    for method in &spec.methods {
        let mname = rust_ident(&method.name);
        let mut params = String::from("builder: &mut CommandBufferBuilder, node_id: NodeId");
        for p in &method.params {
            let pname = rust_ident(&p.name);
            let pty = rust_simple_type(&p.param_type);
            if p.optional {
                let _ = write!(params, ", {pname}: Option<{pty}>");
            } else {
                let _ = write!(params, ", {pname}: {pty}");
            }
        }
        let _ = writeln!(out, "        pub fn {mname}({params}) {{");
        if method.params.is_empty() {
            let _ = writeln!(
                out,
                "            builder.dispatch_command(node_id, \"{}.{}\", &[]);",
                escape_string_literal(&spec.module_name),
                escape_string_literal(&method.name)
            );
        } else {
            let _ = writeln!(out, "            let payload = serde_json::json!({{");
            for p in &method.params {
                let pname = rust_ident(&p.name);
                let _ = writeln!(
                    out,
                    "                \"{}\": {pname},",
                    escape_string_literal(&p.name)
                );
            }
            let _ = writeln!(out, "            }}).to_string();");
            let _ = writeln!(
                out,
                "            builder.dispatch_command(node_id, \"{}.{}\", payload.as_bytes());",
                escape_string_literal(&spec.module_name),
                escape_string_literal(&method.name)
            );
        }
        let _ = writeln!(out, "        }}");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    out
}

fn emit_turbomodule_cpp(spec: &TurboModuleSpec) -> String {
    let pascal = to_pascal_case(&spec.module_name);
    let mut out = String::with_capacity(2048);

    let _ = writeln!(out, "#pragma once");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native TurboModule `{}`.",
        spec.module_name
    );
    let _ = writeln!(out, "#include \"nve_abi.h\"");
    let _ = writeln!(out, "#include \"nve_rn_component.hpp\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <cstdint>");
    let _ = writeln!(out, "#include <optional>");
    let _ = writeln!(out, "#include <string>");
    let _ = writeln!(out, "#include <string_view>");
    let _ = writeln!(out, "#include <vector>");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace nve::generated {{");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "inline constexpr std::string_view k{pascal}ModuleName = \"{}\";",
        escape_string_literal(&spec.module_name)
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "class {pascal}TurboModuleHost {{");
    let _ = writeln!(out, " public:");
    let _ = writeln!(out, "  virtual ~{pascal}TurboModuleHost() = default;");
    for method in &spec.methods {
        let mname = cpp_ident(&method.name);
        let ret = cpp_tm_type(&method.return_type);
        let mut params = String::new();
        for (i, p) in method.params.iter().enumerate() {
            if i > 0 {
                params.push_str(", ");
            }
            let pty = cpp_tm_type(&p.param_type);
            let pname = cpp_ident(&p.name);
            if p.optional {
                let _ = write!(params, "std::optional<{pty}> {pname}");
            } else {
                let _ = write!(params, "{pty} {pname}");
            }
        }
        let _ = writeln!(out, "  virtual {ret} {mname}({params}) = 0;");
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace nve::generated");
    out
}

fn cpp_tm_type(ty: &PropType) -> String {
    match ty {
        PropType::Void => "void".to_owned(),
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 => "int32_t".to_owned(),
        PropType::Float => "float".to_owned(),
        PropType::Double => "double".to_owned(),
        PropType::String | PropType::StringEnum { .. } | PropType::Mixed => {
            "std::string".to_owned()
        }
        PropType::IntEnum { .. } => "int32_t".to_owned(),
        PropType::Array { item } => format!("std::vector<{}>", cpp_tm_type(item)),
        PropType::Promise { inner } => cpp_tm_type(inner),
        _ => "std::string".to_owned(),
    }
}
