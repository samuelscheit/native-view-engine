//! Deterministic Rust / Dioxus source code generator for compiled documentation sites.

use std::fmt::Write as _;

use crate::ast::CompiledSite;
use crate::nav::NavNode;

/// Configuration options for [`generate_rust_module`].
#[derive(Debug, Clone)]
pub struct SiteCodegenOptions {
    /// Emit `pub const SEARCH_INDEX_BYTES: &[u8]`.
    pub include_search_bytes: bool,
    /// Emit `pub const LIVE_BLOCKS: &[GeneratedLiveBlock]`.
    pub include_live_blocks: bool,
    /// Emit `pub const NAV_NODES: &[GeneratedNavEntry]`.
    pub include_nav: bool,
}

impl Default for SiteCodegenOptions {
    fn default() -> Self {
        Self {
            include_search_bytes: true,
            include_live_blocks: true,
            include_nav: true,
        }
    }
}

/// Emit a deterministic, zero-runtime-parse Rust module for a [`CompiledSite`].
///
/// Designed to be written out by `build.rs` or `cargo nve docs build` and `include!`d
/// directly into an `nve-docs` / Dioxus application.
pub fn generate_rust_module(site: &CompiledSite, opts: &SiteCodegenOptions) -> String {
    let mut out = String::with_capacity(4096);
    out.push_str("// @generated by nve-mdx — DO NOT EDIT BY HAND.\n");
    out.push_str("#![allow(dead_code, clippy::all)]\n\n");

    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    out.push_str("pub struct GeneratedTocEntry {\n");
    out.push_str("    pub level: u8,\n");
    out.push_str("    pub id: &'static str,\n");
    out.push_str("    pub text: &'static str,\n");
    out.push_str("    pub line: usize,\n");
    out.push_str("}\n\n");

    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
    out.push_str("pub struct GeneratedPageMeta {\n");
    out.push_str("    pub route: &'static str,\n");
    out.push_str("    pub source_path: &'static str,\n");
    out.push_str("    pub title: &'static str,\n");
    out.push_str("    pub description: &'static str,\n");
    out.push_str("    pub badge: Option<&'static str>,\n");
    out.push_str("    pub icon: Option<&'static str>,\n");
    out.push_str("    pub toc_enabled: bool,\n");
    out.push_str("    pub toc: &'static [GeneratedTocEntry],\n");
    out.push_str("    pub prev_route: Option<&'static str>,\n");
    out.push_str("    pub next_route: Option<&'static str>,\n");
    out.push_str("}\n\n");

    if opts.include_live_blocks {
        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
        out.push_str("pub struct GeneratedLiveBlock {\n");
        out.push_str("    pub id: &'static str,\n");
        out.push_str("    pub route: &'static str,\n");
        out.push_str("    pub lang: &'static str,\n");
        out.push_str("    pub title: Option<&'static str>,\n");
        out.push_str("    pub code: &'static str,\n");
        out.push_str("    pub line: usize,\n");
        out.push_str("}\n\n");
    }

    if opts.include_nav {
        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
        out.push_str("pub enum GeneratedNavKind {\n");
        out.push_str("    Page,\n");
        out.push_str("    Folder,\n");
        out.push_str("    Separator,\n");
        out.push_str("    ExternalLink,\n");
        out.push_str("}\n\n");

        out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n");
        out.push_str("pub struct GeneratedNavEntry {\n");
        out.push_str("    pub depth: usize,\n");
        out.push_str("    pub kind: GeneratedNavKind,\n");
        out.push_str("    pub title: &'static str,\n");
        out.push_str("    pub target: Option<&'static str>,\n");
        out.push_str("    pub badge: Option<&'static str>,\n");
        out.push_str("    pub collapsed: bool,\n");
        out.push_str("}\n\n");
    }

    // Emit PAGES table.
    out.push_str("pub const PAGES: &[GeneratedPageMeta] = &[\n");
    for page in &site.pages {
        let pn = site.prev_next.get(&page.route);
        let prev = pn.and_then(|p| p.prev.as_ref()).map(|l| l.route.as_str());
        let next = pn.and_then(|p| p.next.as_ref()).map(|l| l.route.as_str());

        out.push_str("    GeneratedPageMeta {\n");
        let _ = writeln!(out, "        route: {:?},", page.route);
        let _ = writeln!(out, "        source_path: {:?},", page.source_path);
        let _ = writeln!(out, "        title: {:?},", page.title);
        let _ = writeln!(out, "        description: {:?},", page.description);
        let _ = writeln!(out, "        badge: {},", fmt_opt_str(page.frontmatter.badge.as_deref()));
        let _ = writeln!(out, "        icon: {},", fmt_opt_str(page.frontmatter.icon.as_deref()));
        let _ = writeln!(out, "        toc_enabled: {},", page.frontmatter.toc);
        out.push_str("        toc: &[\n");
        for h in &page.toc {
            let _ = writeln!(
                out,
                "            GeneratedTocEntry {{ level: {}, id: {:?}, text: {:?}, line: {} }},",
                h.level, h.id, h.text, h.line
            );
        }
        out.push_str("        ],\n");
        let _ = writeln!(out, "        prev_route: {},", fmt_opt_str(prev));
        let _ = writeln!(out, "        next_route: {},", fmt_opt_str(next));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    if opts.include_live_blocks {
        out.push_str("pub const LIVE_BLOCKS: &[GeneratedLiveBlock] = &[\n");
        for page in &site.pages {
            for lb in &page.live_blocks {
                out.push_str("    GeneratedLiveBlock {\n");
                let _ = writeln!(out, "        id: {:?},", lb.id);
                let _ = writeln!(out, "        route: {:?},", page.route);
                let _ = writeln!(out, "        lang: {:?},", lb.lang);
                let _ = writeln!(out, "        title: {},", fmt_opt_str(lb.title.as_deref()));
                let _ = writeln!(out, "        code: {:?},", lb.code);
                let _ = writeln!(out, "        line: {},", lb.line);
                out.push_str("    },\n");
            }
        }
        out.push_str("];\n\n");
    }

    if opts.include_nav {
        out.push_str("pub const NAV_ENTRIES: &[GeneratedNavEntry] = &[\n");
        emit_nav_entries(&site.nav.items, 0, &mut out);
        out.push_str("];\n\n");
    }

    if opts.include_search_bytes {
        let bytes = site.search_index.encode();
        out.push_str("pub const SEARCH_INDEX_BYTES: &[u8] = &[\n");
        for chunk in bytes.chunks(16) {
            out.push_str("    ");
            for (i, b) in chunk.iter().enumerate() {
                if i > 0 {
                    out.push(' ');
                }
                let _ = write!(out, "0x{b:02x},");
            }
            out.push('\n');
        }
        out.push_str("];\n\n");
    }

    out.push_str("pub fn find_page(route: &str) -> Option<&'static GeneratedPageMeta> {\n");
    out.push_str("    PAGES.iter().find(|p| p.route == route)\n");
    out.push_str("}\n\n");

    out.push_str("pub fn prev_next(route: &str) -> (Option<&'static str>, Option<&'static str>) {\n");
    out.push_str("    match find_page(route) {\n");
    out.push_str("        Some(p) => (p.prev_route, p.next_route),\n");
    out.push_str("        None => (None, None),\n");
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}

fn emit_nav_entries(nodes: &[NavNode], depth: usize, out: &mut String) {
    for node in nodes {
        match node {
            NavNode::Page {
                title,
                route,
                badge,
                ..
            } => {
                let _ = writeln!(
                    out,
                    "    GeneratedNavEntry {{ depth: {depth}, kind: GeneratedNavKind::Page, title: {title:?}, target: Some({route:?}), badge: {}, collapsed: false }},",
                    fmt_opt_str(badge.as_deref())
                );
            }
            NavNode::Folder {
                title,
                index_route,
                collapsed,
                badge,
                children,
                ..
            } => {
                let _ = writeln!(
                    out,
                    "    GeneratedNavEntry {{ depth: {depth}, kind: GeneratedNavKind::Folder, title: {title:?}, target: {}, badge: {}, collapsed: {collapsed} }},",
                    fmt_opt_str(index_route.as_deref()),
                    fmt_opt_str(badge.as_deref())
                );
                emit_nav_entries(children, depth + 1, out);
            }
            NavNode::Separator { title } => {
                let label = title.as_deref().unwrap_or("");
                let _ = writeln!(
                    out,
                    "    GeneratedNavEntry {{ depth: {depth}, kind: GeneratedNavKind::Separator, title: {label:?}, target: None, badge: None, collapsed: false }},"
                );
            }
            NavNode::ExternalLink {
                title, href, badge, ..
            } => {
                let _ = writeln!(
                    out,
                    "    GeneratedNavEntry {{ depth: {depth}, kind: GeneratedNavKind::ExternalLink, title: {title:?}, target: Some({href:?}), badge: {}, collapsed: false }},",
                    fmt_opt_str(badge.as_deref())
                );
            }
        }
    }
}

fn fmt_opt_str(opt: Option<&str>) -> String {
    match opt {
        Some(s) => format!("Some({s:?})"),
        None => "None".to_string(),
    }
}
