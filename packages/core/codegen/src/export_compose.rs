//! `export_compose`: `NveExportSpec` -> typed zero-JSON Kotlin `@Composable` wrapping
//! `dev.nve.compose.NveSurface` via binary `NveBinValue` / `NveBinValueView` direct FFI encoding.

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::ir::{
    DefaultValue, EventSpec, ExportBackend, ExportComposeOutput, GeneratedFile, NveExportSpec,
    ObjectField, PropSpec, PropType,
};
use crate::naming::{
    escape_kotlin_string, format_float_literal, int_enum_variant_pascal, kotlin_ident,
    sanitize_block_comment, strip_on_prefix, to_pascal_case,
};

/// Generates a typed zero-JSON Jetpack Compose `@Composable` wrapper targeting `dev.nve.compose.NveSurface`.
pub fn generate_export_compose(spec: &NveExportSpec) -> Result<ExportComposeOutput, CodegenError> {
    spec.validate()?;
    let content = emit_compose_kotlin(spec);

    Ok(ExportComposeOutput {
        spec: spec.clone(),
        compose_kt: GeneratedFile {
            relative_path: format!("{}Composable.generated.kt", spec.name),
            content,
        },
    })
}

fn emit_compose_kotlin(spec: &NveExportSpec) -> String {
    let name = &spec.name;
    let pkg = spec.android_package_name();
    let vtable_sym = spec.vtable_symbol();
    let backend_enum = match spec.backend {
        ExportBackend::Fabric => "NveRenderBackend.FABRIC",
        ExportBackend::Skia => "NveRenderBackend.SKIA",
    };

    let mut out = String::with_capacity(4096);
    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_compose`) — backend: {}",
        spec.backend.as_str()
    );
    let _ = writeln!(
        out,
        "// Zero-JSON typed Jetpack Compose @Composable wrapping `dev.nve.compose.NveSurface`."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "package {pkg}");
    let _ = writeln!(out);
    let _ = writeln!(out, "import androidx.compose.runtime.Composable");
    let _ = writeln!(out, "import androidx.compose.runtime.Immutable");
    let _ = writeln!(out, "import androidx.compose.runtime.LaunchedEffect");
    let _ = writeln!(out, "import androidx.compose.runtime.remember");
    let _ = writeln!(out, "import androidx.compose.ui.Modifier");
    let _ = writeln!(out, "import dev.nve.compose.NveBinValue");
    let _ = writeln!(out, "import dev.nve.compose.NveBinValueView");
    let _ = writeln!(out, "import dev.nve.compose.NveEvent");
    let _ = writeln!(out, "import dev.nve.compose.NveEventKind");
    let _ = writeln!(out, "import dev.nve.compose.NveRenderBackend");
    let _ = writeln!(out, "import dev.nve.compose.NveSurface");
    let _ = writeln!(out, "import dev.nve.compose.NveSurfaceController");
    let _ = writeln!(out, "import dev.nve.compose.rememberNveSurfaceController");
    let _ = writeln!(out);

    // 1. Typed Kotlin enums
    for prop in &spec.props {
        emit_kotlin_aux_enum(&mut out, name, prop);
    }

    // 2. Typed @Immutable binary event payload data classes
    for ev in &spec.events {
        emit_kotlin_event_data_class(&mut out, name, ev);
    }

    // 3. Zero-boxing binary direct props writer
    emit_kotlin_direct_props_writer(&mut out, spec);

    // 4. Typed imperative controller + remember helper
    let _ = writeln!(
        out,
        "/** Imperative binary command controller for `{}` backed by `NveSurfaceController`. */",
        sanitize_block_comment(name)
    );
    let _ = writeln!(
        out,
        "class {name}Controller(val inner: NveSurfaceController) {{"
    );
    for cmd in &spec.commands {
        let mname = kotlin_ident(&cmd.name);
        let mut params = Vec::new();
        for p in &cmd.params {
            let pname = kotlin_ident(&p.name);
            let pty = kotlin_simple_type(&p.param_type);
            if p.optional {
                params.push(format!("{pname}: {pty}? = null"));
            } else {
                params.push(format!("{pname}: {pty}"));
            }
        }
        let _ = writeln!(out);
        let _ = writeln!(out, "    fun {mname}({}) {{", params.join(", "));
        if cmd.params.is_empty() {
            let _ = writeln!(
                out,
                "        inner.dispatchCommandBinary(\"{}\", NveBinValue.Null.encode())",
                escape_kotlin_string(&cmd.name)
            );
        } else {
            let _ = writeln!(
                out,
                "        val entries = ArrayList<Pair<String, NveBinValue>>({})",
                cmd.params.len()
            );
            for p in &cmd.params {
                let pname = kotlin_ident(&p.name);
                let key = escape_kotlin_string(&p.name);
                if p.optional {
                    let expr = kotlin_bin_value_expr("v", &p.param_type);
                    let _ = writeln!(
                        out,
                        "        {pname}?.let {{ v -> entries.add(\"{key}\" to {expr}) }}"
                    );
                } else {
                    let expr = kotlin_bin_value_expr(&pname, &p.param_type);
                    let _ = writeln!(out, "        entries.add(\"{key}\" to {expr})");
                }
            }
            let _ = writeln!(
                out,
                "        inner.dispatchCommandBinary(\"{}\", NveBinValue.Map(entries).encode())",
                escape_kotlin_string(&cmd.name)
            );
        }
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(out, "@Composable");
    let _ = writeln!(out, "fun remember{name}Controller(): {name}Controller {{");
    let _ = writeln!(out, "    val inner = rememberNveSurfaceController(");
    let _ = writeln!(
        out,
        "        componentName = \"{}\",",
        escape_kotlin_string(name)
    );
    let _ = writeln!(
        out,
        "        vtableSymbol = \"{}\",",
        escape_kotlin_string(vtable_sym)
    );
    let _ = writeln!(out, "        backend = {backend_enum},");
    let _ = writeln!(out, "    )");
    let _ = writeln!(out, "    return remember(inner) {{ {name}Controller(inner) }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    // 5. Typed `@Composable` function
    if let Some(doc) = &spec.doc {
        let _ = writeln!(out, "/**");
        for line in sanitize_block_comment(doc).lines() {
            let _ = writeln!(out, " * {line}");
        }
        let _ = writeln!(out, " */");
    }
    let _ = writeln!(out, "@Composable");
    let _ = writeln!(out, "fun {name}(");
    for prop in &spec.props {
        let param = kotlin_ident(&prop.name);
        let ty = compose_prop_type(name, prop);
        if let Some(def) = compose_default_expr(name, prop) {
            let _ = writeln!(out, "    {param}: {ty} = {def},");
        } else if compose_prop_is_nullable(prop) {
            let _ = writeln!(out, "    {param}: {ty} = null,");
        } else {
            let _ = writeln!(out, "    {param}: {ty},");
        }
    }
    for ev in &spec.events {
        let cb = kotlin_ident(&ev.name);
        let cb_ty = compose_event_lambda_type(name, ev);
        let _ = writeln!(out, "    {cb}: ({cb_ty})? = null,");
    }
    let _ = writeln!(out, "    modifier: Modifier = Modifier,");
    let _ = writeln!(out, "    controller: {name}Controller? = null,");
    let _ = writeln!(out, ") {{");

    let _ = writeln!(
        out,
        "    val activeController = controller ?: remember{name}Controller()"
    );
    let prop_args: Vec<String> = spec.props.iter().map(|p| kotlin_ident(&p.name)).collect();
    let _ = writeln!(
        out,
        "    val encodedPropsBin = {name}DirectPropsWriter.encode({})",
        prop_args.join(", ")
    );
    let _ = writeln!(
        out,
        "    LaunchedEffect(activeController, encodedPropsBin.contentHashCode()) {{"
    );
    let _ = writeln!(
        out,
        "        activeController.inner.updatePropsBinary(encodedPropsBin)"
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    // Invoke `dev.nve.compose.NveSurface`
    let _ = writeln!(out, "    NveSurface(");
    let _ = writeln!(
        out,
        "        componentName = \"{}\",",
        escape_kotlin_string(name)
    );
    let _ = writeln!(out, "        modifier = modifier,");
    let _ = writeln!(
        out,
        "        vtableSymbol = \"{}\",",
        escape_kotlin_string(vtable_sym)
    );
    let _ = writeln!(out, "        backend = {backend_enum},");
    let _ = writeln!(out, "        controller = activeController.inner,");
    let _ = writeln!(out, "        onEvent = {{ event: NveEvent ->");
    let _ = writeln!(
        out,
        "            if (event.kind == NveEventKind.CUSTOM && event.name != null) {{"
    );
    let _ = writeln!(out, "                when (event.name) {{");
    for ev in &spec.events {
        let cb = kotlin_ident(&ev.name);
        let short = strip_on_prefix(&ev.name);
        let _ = writeln!(
            out,
            "                    \"{}\", \"{}\" -> {{",
            escape_kotlin_string(&ev.name),
            escape_kotlin_string(&short)
        );
        if ev.payload.is_empty() {
            let _ = writeln!(out, "                        {cb}?.invoke()");
        } else {
            let ev_cls = compose_event_class_name(name, ev);
            let _ = writeln!(
                out,
                "                        {ev_cls}.fromBinBytes(event.payloadBytes)?.let {{ {cb}?.invoke(it) }}"
            );
        }
        let _ = writeln!(out, "                    }}");
    }
    let _ = writeln!(out, "                }}");
    let _ = writeln!(out, "            }}");
    let _ = writeln!(out, "        }},");
    let _ = writeln!(out, "    )");
    let _ = writeln!(out, "}}");

    out
}

fn emit_kotlin_direct_props_writer(out: &mut String, spec: &NveExportSpec) {
    let name = &spec.name;
    let _ = writeln!(
        out,
        "/** Typed zero-JSON binary encoder writing `{}` props directly into `NveBinValue` bytes. */",
        sanitize_block_comment(name)
    );
    let _ = writeln!(out, "object {name}DirectPropsWriter {{");
    let params: Vec<String> = spec
        .props
        .iter()
        .map(|p| format!("{}: {}", kotlin_ident(&p.name), compose_prop_type(name, p)))
        .collect();
    let _ = writeln!(out, "    fun encode({}): ByteArray {{", params.join(", "));
    let _ = writeln!(
        out,
        "        val entries = ArrayList<Pair<String, NveBinValue>>({})",
        spec.props.len()
    );
    for prop in &spec.props {
        let key = escape_kotlin_string(&prop.name);
        let param = kotlin_ident(&prop.name);
        let nullable = compose_prop_is_nullable(prop);
        if nullable {
            let expr = compose_bin_value_expr("v", prop);
            let _ = writeln!(
                out,
                "        {param}?.let {{ v -> entries.add(\"{key}\" to {expr}) }}"
            );
        } else {
            let expr = compose_bin_value_expr(&param, prop);
            let _ = writeln!(out, "        entries.add(\"{key}\" to {expr})");
        }
    }
    let _ = writeln!(out, "        return NveBinValue.Map(entries).encode()");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
}

fn compose_bin_value_expr(var: &str, prop: &PropSpec) -> String {
    match &prop.prop_type {
        PropType::StringEnum { .. } => format!("NveBinValue.Str({var}.wireValue)"),
        PropType::IntEnum { .. } => format!("NveBinValue.I64({var}.wireValue.toLong())"),
        other => kotlin_bin_value_expr(var, other),
    }
}

fn kotlin_bin_value_expr(var: &str, ty: &PropType) -> String {
    match ty {
        PropType::Bool => format!("NveBinValue.Bool({var})"),
        PropType::Int32 | PropType::IntEnum { .. } => format!("NveBinValue.I64({var}.toLong())"),
        PropType::Float => format!("NveBinValue.F64({var}.toDouble())"),
        PropType::Double => format!("NveBinValue.F64({var})"),
        PropType::Array { item } => format!(
            "NveBinValue.Array({var}.map {{ item -> {} }})",
            kotlin_bin_value_expr("item", item)
        ),
        PropType::Object { .. } => var.to_owned(),
        _ => format!("NveBinValue.Str({var})"),
    }
}

fn emit_kotlin_aux_enum(out: &mut String, comp_name: &str, prop: &PropSpec) {
    match &prop.prop_type {
        PropType::StringEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            let _ = writeln!(out, "enum class {enum_name}(val wireValue: String) {{");
            for (i, v) in variants.iter().enumerate() {
                let sep = if i + 1 == variants.len() { ";" } else { "," };
                let _ = writeln!(
                    out,
                    "    {}(\"{}\"){sep}",
                    to_pascal_case(v),
                    escape_kotlin_string(v)
                );
            }
            let _ = writeln!(out, "}}");
            let _ = writeln!(out);
        }
        PropType::IntEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            let _ = writeln!(out, "enum class {enum_name}(val wireValue: Int) {{");
            for (i, v) in variants.iter().enumerate() {
                let sep = if i + 1 == variants.len() { ";" } else { "," };
                let vname = int_enum_variant_pascal(*v);
                let _ = writeln!(out, "    {vname}({v}){sep}");
            }
            let _ = writeln!(out, "}}");
            let _ = writeln!(out);
        }
        _ => {}
    }
}

fn compose_event_class_name(comp_name: &str, ev: &EventSpec) -> String {
    format!("{comp_name}{}Event", to_pascal_case(&strip_on_prefix(&ev.name)))
}

fn emit_kotlin_event_data_class(out: &mut String, comp_name: &str, ev: &EventSpec) {
    if ev.payload.is_empty() {
        return;
    }
    let cls = compose_event_class_name(comp_name, ev);
    let _ = writeln!(out, "@Immutable");
    let _ = writeln!(out, "data class {cls}(");
    for f in &ev.payload {
        let fname = kotlin_ident(&f.name);
        let fty = kotlin_simple_type(&f.field_type);
        let q = if f.optional || f.nullable { "?" } else { "" };
        let _ = writeln!(out, "    val {fname}: {fty}{q},");
    }
    let _ = writeln!(out, ") {{");
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(out, "        fun fromBinView(view: NveBinValueView): {cls} = {cls}(");
    for f in &ev.payload {
        let fname = kotlin_ident(&f.name);
        let key = escape_kotlin_string(&f.name);
        let expr = kotlin_from_bin_view_expr(&key, f);
        let _ = writeln!(out, "            {fname} = {expr},");
    }
    let _ = writeln!(out, "        )");
    let _ = writeln!(out);
    let _ = writeln!(out, "        fun fromBinBytes(bytes: ByteArray): {cls}? {{");
    let _ = writeln!(out, "            if (bytes.isEmpty()) return null");
    let _ = writeln!(out, "            return runCatching {{");
    let _ = writeln!(out, "                fromBinView(NveBinValueView.parse(bytes))");
    let _ = writeln!(out, "            }}.getOrNull()");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
}

fn kotlin_from_bin_view_expr(key: &str, f: &ObjectField) -> String {
    let opt = f.optional || f.nullable;
    match &f.field_type {
        PropType::Bool => {
            if opt {
                format!("view.mapValue(\"{key}\")?.boolValue")
            } else {
                format!("view.mapValue(\"{key}\")?.boolValue ?: false")
            }
        }
        PropType::Int32 | PropType::IntEnum { .. } => {
            if opt {
                format!("view.mapValue(\"{key}\")?.int64Value?.toInt()")
            } else {
                format!("view.mapValue(\"{key}\")?.int64Value?.toInt() ?: 0")
            }
        }
        PropType::Float => {
            if opt {
                format!("view.mapValue(\"{key}\")?.numberValue?.toFloat()")
            } else {
                format!("view.mapValue(\"{key}\")?.numberValue?.toFloat() ?: 0.0f")
            }
        }
        PropType::Double => {
            if opt {
                format!("view.mapValue(\"{key}\")?.numberValue")
            } else {
                format!("view.mapValue(\"{key}\")?.numberValue ?: 0.0")
            }
        }
        PropType::Object { .. } => {
            if opt {
                format!("view.mapValue(\"{key}\")?.toOwned()")
            } else {
                format!("view.mapValue(\"{key}\")?.toOwned() ?: NveBinValue.Null")
            }
        }
        _ => {
            if opt {
                format!("view.mapValue(\"{key}\")?.stringValue")
            } else {
                format!("view.mapValue(\"{key}\")?.stringValue ?: \"\"")
            }
        }
    }
}

fn compose_event_lambda_type(comp_name: &str, ev: &EventSpec) -> String {
    if ev.payload.is_empty() {
        "() -> Unit".to_owned()
    } else {
        format!("({}) -> Unit", compose_event_class_name(comp_name, ev))
    }
}

fn compose_prop_is_nullable(prop: &PropSpec) -> bool {
    (prop.optional || prop.nullable) && compose_default_expr("_", prop).is_none()
}

fn compose_prop_type(comp_name: &str, prop: &PropSpec) -> String {
    let base = match &prop.prop_type {
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("{comp_name}{}", to_pascal_case(&prop.name))
        }
        other => kotlin_simple_type(other),
    };
    if compose_prop_is_nullable(prop) {
        format!("{base}?")
    } else {
        base
    }
}

fn kotlin_simple_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "Boolean".to_owned(),
        PropType::Int32 | PropType::IntEnum { .. } => "Int".to_owned(),
        PropType::Float => "Float".to_owned(),
        PropType::Double => "Double".to_owned(),
        PropType::Array { item } => format!("List<{}>", kotlin_simple_type(item)),
        PropType::Object { .. } => "NveBinValue".to_owned(),
        _ => "String".to_owned(),
    }
}

fn compose_default_expr(comp_name: &str, prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float, DefaultValue::Int(i)) => Some(format!("{i}.0f")),
        (PropType::Float, DefaultValue::Float(f)) => {
            Some(format!("{}f", format_float_literal(*f)))
        }
        (PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Double, DefaultValue::Float(f)) => Some(format_float_literal(*f)),
        (PropType::String | PropType::Color, DefaultValue::String(s)) => {
            Some(format!("\"{}\"", escape_kotlin_string(s)))
        }
        (PropType::StringEnum { variants }, DefaultValue::String(s)) if variants.contains(s) => {
            Some(format!(
                "{comp_name}{}.{}",
                to_pascal_case(&prop.name),
                to_pascal_case(s)
            ))
        }
        (PropType::IntEnum { variants }, DefaultValue::Int(i))
            if variants.contains(&(*i as i32)) =>
        {
            let vname = int_enum_variant_pascal(*i as i32);
            Some(format!("{comp_name}{}.{vname}", to_pascal_case(&prop.name)))
        }
        _ => None,
    }
}
