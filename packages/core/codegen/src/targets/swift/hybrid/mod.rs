//! Swift target emitter for NVE Hybrid FFI codegen.
//!
//! Emits `<Stem>HybridSpec.generated.swift` against `<Stem>HybridAbi.generated.h` (imported by the
//! consumer, e.g. as its bridging header) and the static runtime in `packages/core/host-swift`:
//! - `NveHost`: `HybridError`, `HybridStatus`, `HybridEnum`, `DynamicValue`, `BinReader` /
//!   `BinWriter` (no codec is copied into generated code)
//! - `NveHostAbi`: `NveValueTree`, the C `NveValue` graphs `set_props_direct` and `NveValue`
//!   parameters borrow (dynamic values keep their true tags, never wrapped as `Bytes`)
//!
//! Zero `@objc`, zero `NSObject`: native Swift `enum` / `struct`, `protocol Hybrid<Name>Spec`, and
//! `final class <Name>HybridClient` calling the C vtable directly with zero-copy pinned slices,
//! releasing owned buffers through the peer's `free_bytes`.

