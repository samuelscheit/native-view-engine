    writeln!(
        s,
        "        public static let entryPayloadTagOffset: Int = {EVENT_ENTRY_PAYLOAD_TAG_OFFSET}"
    );
    writeln!(s, "    }}\n");

    writeln!(s, "    public enum KeyModifiers {{");
    writeln!(s, "        public static let meta: UInt8 = 0x{KEY_MOD_META:02X}");
    writeln!(s, "        public static let ctrl: UInt8 = 0x{KEY_MOD_CTRL:02X}");
    writeln!(s, "        public static let shift: UInt8 = 0x{KEY_MOD_SHIFT:02X}");
