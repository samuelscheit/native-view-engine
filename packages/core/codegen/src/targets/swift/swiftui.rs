//! `export_swiftui`: `NveExportSpec` -> typed zero-boxing SwiftUI `View` wrapping
//! `NveSwiftUI`'s `NveSurfaceRepresentable` via `NveDirectEncodable` + `NveDirectPropsBuilder`.

use crate::writer::CodeWriter;

use crate::error::CodegenError;
use crate::schema::export::{
    DefaultValue, EventSpec, ExportBackend, ExportSwiftUiOutput, GeneratedFile, NveExportSpec,
    ObjectField, PropSpec, PropType,
};
use crate::naming::{
    escape_c_like_string, format_float_literal, int_enum_variant_camel,
    sanitize_single_line_comment, strip_on_prefix, swift_ident, to_pascal_case,
};

/// Generates a typed zero-boxing SwiftUI `View` wrapping `NveSwiftUI.NveSurfaceRepresentable`.
pub fn generate_export_swiftui(spec: &NveExportSpec) -> Result<ExportSwiftUiOutput, CodegenError> {
    spec.validate()?;
    let content = emit_swiftui_view(spec);

    Ok(ExportSwiftUiOutput {
        spec: spec.clone(),
        swift_view: GeneratedFile {
            relative_path: format!("{}View.generated.swift", spec.name),
            content,
        },
    })
}

fn emit_swiftui_view(spec: &NveExportSpec) -> String {
    let name = &spec.name;
    let vtable_sym = spec.vtable_symbol();
    let backend_case = match spec.backend {
        ExportBackend::Fabric => ".fabric",
        ExportBackend::Skia => ".skia",
    };

    let mut out = CodeWriter::with_capacity(4096);
    writeln!(
        out,
        "// @generated by nve-codegen (`export_swiftui`) — backend: {}",
        spec.backend.as_str()
    );
    writeln!(
        out,
        "// Zero-boxing SwiftUI View wrapping `NveSwiftUI.NveSurfaceRepresentable` via `NveDirectEncodable`."
    );
    writeln!(out);
    writeln!(out, "import Foundation");
    writeln!(out, "import SwiftUI");
    writeln!(out, "import NveSwiftUI");
    writeln!(out);

    // 1. Typed Swift enums for StringEnum / IntEnum props
    for prop in &spec.props {
        emit_swift_aux_enum(&mut out, name, prop);
    }

    // 2. Binary event payload structs (`NveBinValueView`)
    for ev in &spec.events {
        emit_swift_event_struct(&mut out, name, ev);
    }

    // 3. Zero-boxing `NveDirectEncodable` props struct
    emit_swift_direct_props_struct(&mut out, spec);

    // 4. ObservableObject Controller wrapping `NveSurfaceController`
    writeln!(
        out,
        "/// Imperative command controller for `{}` wrapping `NveSwiftUI.NveSurfaceController`.",
        sanitize_single_line_comment(name)
    );
    writeln!(out, "public final class {name}Controller: ObservableObject {{");
    writeln!(out, "    public let inner: NveSurfaceController");
    writeln!(out);
    writeln!(
        out,
        "    public init(inner: NveSurfaceController = NveSurfaceController()) {{"
    );
    writeln!(out, "        self.inner = inner");
    writeln!(out, "    }}");
    for cmd in &spec.commands {
        let mname = swift_ident(&cmd.name);
        let mut params = Vec::new();
        for p in &cmd.params {
            let pname = swift_ident(&p.name);
            let pty = swift_simple_type(&p.param_type);
            if p.optional {
                params.push(format!("{pname}: {pty}? = nil"));
            } else {
                params.push(format!("{pname}: {pty}"));
            }
        }
        writeln!(out);
        writeln!(out, "    public func {mname}({}) {{", params.join(", "));
        if cmd.params.is_empty() {
            writeln!(
                out,
                "        inner.dispatchCommand(name: \"{}\", value: .null)",
                escape_c_like_string(&cmd.name)
            );
        } else {
            writeln!(out, "        var entries: [(String, NveBinValue)] = []");
            writeln!(out, "        entries.reserveCapacity({})", cmd.params.len());
            for p in &cmd.params {
                let pname = swift_ident(&p.name);
                let key = escape_c_like_string(&p.name);
                if p.optional {
                    let expr = swift_bin_value_expr("val", &p.param_type);
                    writeln!(
                        out,
                        "        if let val = {pname} {{ entries.append((\"{key}\", {expr})) }}"
                    );
                } else {
                    let expr = swift_bin_value_expr(&pname, &p.param_type);
                    writeln!(out, "        entries.append((\"{key}\", {expr}))");
                }
            }
            writeln!(
                out,
                "        inner.dispatchCommand(name: \"{}\", value: .map(entries))",
                escape_c_like_string(&cmd.name)
            );
        }
        writeln!(out, "    }}");
    }
    writeln!(out, "}}");
    writeln!(out);

    // 5. Typed SwiftUI View struct
    if let Some(doc) = &spec.doc {
        for line in doc.lines() {
            writeln!(out, "/// {}", sanitize_single_line_comment(line));
        }
    }
    writeln!(out, "public struct {name}View: View {{");
    for prop in &spec.props {
        if let Some(doc) = &prop.doc {
            for line in doc.lines() {
                writeln!(out, "    /// {}", sanitize_single_line_comment(line));
            }
        }
        let field = swift_ident(&prop.name);
        let ty = swift_prop_type(name, prop);
        writeln!(out, "    public var {field}: {ty}");
    }
    for ev in &spec.events {
        let cb = swift_ident(&ev.name);
        let cb_ty = swift_event_closure_type(name, ev);
        writeln!(out, "    public var {cb}: ({cb_ty})?");
    }
    writeln!(out, "    public var controller: {name}Controller?");
    writeln!(out);

    // Public initializer
    let mut init_params = Vec::new();
    for prop in &spec.props {
        let field = swift_ident(&prop.name);
        let ty = swift_prop_type(name, prop);
        if let Some(def) = swift_default_expr(name, prop) {
            init_params.push(format!("{field}: {ty} = {def}"));
        } else if swift_prop_is_optional(prop) {
            init_params.push(format!("{field}: {ty} = nil"));
        } else {
            init_params.push(format!("{field}: {ty}"));
        }
    }
    for ev in &spec.events {
        let cb = swift_ident(&ev.name);
        let cb_ty = swift_event_closure_type(name, ev);
        init_params.push(format!("{cb}: ({cb_ty})? = nil"));
    }
    init_params.push(format!("controller: {name}Controller? = nil"));

    writeln!(out, "    public init(");
    for (i, param) in init_params.iter().enumerate() {
        let sep = if i + 1 == init_params.len() { "" } else { "," };
        writeln!(out, "        {param}{sep}");
    }
    writeln!(out, "    ) {{");
    for prop in &spec.props {
        let field = swift_ident(&prop.name);
        writeln!(out, "        self.{field} = {field}");
    }
    for ev in &spec.events {
        let cb = swift_ident(&ev.name);
        writeln!(out, "        self.{cb} = {cb}");
    }
    writeln!(out, "        self.controller = controller");
    writeln!(out, "    }}");
    writeln!(out);

    // Zero-boxing direct props snapshot
    writeln!(out, "    private func makeDirectProps() -> {name}DirectProps {{");
    writeln!(out, "        {name}DirectProps(");
    for (i, prop) in spec.props.iter().enumerate() {
        let field = swift_ident(&prop.name);
        let sep = if i + 1 == spec.props.len() { "" } else { "," };
        writeln!(out, "            {field}: {field}{sep}");
    }
    writeln!(out, "        )");
    writeln!(out, "    }}");
    writeln!(out);

    // Binary event router (`NveBinValueView`)
    writeln!(out, "    private func handleEvent(_ event: NveEvent) {{");
    writeln!(
        out,
        "        guard event.kind == .custom, let eventName = event.name else {{ return }}"
    );
    writeln!(out, "        switch eventName {{");
    for ev in &spec.events {
        let cb = swift_ident(&ev.name);
        let short = strip_on_prefix(&ev.name);
        writeln!(
            out,
            "        case \"{}\", \"{}\":",
            escape_c_like_string(&ev.name),
            escape_c_like_string(&short)
        );
        if ev.payload.is_empty() {
            writeln!(out, "            {cb}?()");
        } else {
            let ev_ty = swift_event_struct_name(name, ev);
            writeln!(
                out,
                "            if let decoded = (try? event.withBinValueView {{ {ev_ty}(binView: $0) }}) ?? nil {{\n                {cb}?(decoded)\n            }}"
            );
        }
    }
    writeln!(out, "        default:");
    writeln!(out, "            break");
    writeln!(out, "        }}");
    writeln!(out, "    }}");
    writeln!(out);

    // SwiftUI body using zero-boxing `NveDirectEncodable` initializer
    writeln!(out, "    public var body: some View {{");
    writeln!(out, "        NveSurfaceRepresentable(");
    writeln!(
        out,
        "            componentName: \"{}\",",
        escape_c_like_string(name)
    );
    writeln!(
        out,
        "            vtableSymbol: \"{}\",",
        escape_c_like_string(vtable_sym)
    );
    writeln!(out, "            backend: {backend_case},");
    writeln!(out, "            directProps: makeDirectProps(),");
    writeln!(out, "            controller: controller?.inner,");
    writeln!(out, "            onEvent: handleEvent");
    writeln!(out, "        )");
    writeln!(out, "    }}");
    writeln!(out, "}}");

    out.into_string()
}

fn emit_swift_direct_props_struct(out: &mut CodeWriter, spec: &NveExportSpec) {
    let name = &spec.name;
    writeln!(
        out,
        "/// Zero-boxing direct FFI prop payload encoded via `NveDirectPropsWriter` / `NveDirectPropsBuilder`."
    );
    writeln!(
        out,
        "public struct {name}DirectProps: NveDirectEncodable, Equatable, Sendable {{"
    );
    for prop in &spec.props {
        let field = swift_ident(&prop.name);
        let ty = swift_prop_type(name, prop);
        writeln!(out, "    public let {field}: {ty}");
    }
    writeln!(out);
    if spec.props.is_empty() {
        writeln!(out, "    public init() {{}}");
        writeln!(out);
        writeln!(out, "    public var directPropCount: Int {{ 0 }}");
        writeln!(out);
        writeln!(
            out,
            "    public func encodeDirect(into builder: inout NveDirectPropsBuilder) throws {{}}"
        );
    } else {
        writeln!(out, "    public init(");
        for (i, prop) in spec.props.iter().enumerate() {
            let field = swift_ident(&prop.name);
            let ty = swift_prop_type(name, prop);
            let sep = if i + 1 == spec.props.len() { "" } else { "," };
            writeln!(out, "        {field}: {ty}{sep}");
        }
        writeln!(out, "    ) {{");
        for prop in &spec.props {
            let field = swift_ident(&prop.name);
            writeln!(out, "        self.{field} = {field}");
        }
        writeln!(out, "    }}");
        writeln!(out);

        writeln!(out, "    public var directPropCount: Int {{");
        writeln!(out, "        var count = 0");
        for prop in &spec.props {
            let field = swift_ident(&prop.name);
            if swift_prop_is_optional(prop) {
                writeln!(out, "        if {field} != nil {{ count += 1 }}");
            } else {
                writeln!(out, "        count += 1");
            }
        }
        writeln!(out, "        return count");
        writeln!(out, "    }}");
        writeln!(out);

        writeln!(
            out,
            "    public func encodeDirect(into builder: inout NveDirectPropsBuilder) throws {{"
        );
        for prop in &spec.props {
            let key = escape_c_like_string(&prop.name);
            let field = swift_ident(&prop.name);
            let is_opt = swift_prop_is_optional(prop);
            if is_opt {
                writeln!(out, "        if let val = {field} {{");
                emit_swift_direct_write_stmt(out, "            ", &key, "val", prop);
                writeln!(out, "        }}");
            } else {
                emit_swift_direct_write_stmt(out, "        ", &key, &field, prop);
            }
        }
        writeln!(out, "    }}");
    }
    writeln!(out, "}}");
    writeln!(out);
}

fn emit_swift_direct_write_stmt(
    out: &mut CodeWriter,
    indent: &str,
    key: &str,
    var: &str,
    prop: &PropSpec,
) {
    match &prop.prop_type {
        PropType::Bool
        | PropType::Int32
        | PropType::Float
        | PropType::Double
        | PropType::String
        | PropType::Color
        | PropType::ImageSource
        | PropType::Dimension
        | PropType::Mixed
        | PropType::Point
        | PropType::EdgeInsets
        | PropType::Void
        | PropType::Promise { .. }
        | PropType::Callback { .. } => {
            writeln!(out, "{indent}builder.write(\"{key}\", {var})");
        }
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            writeln!(out, "{indent}builder.write(\"{key}\", {var}.rawValue)");
        }
        PropType::Object { .. } => {
            writeln!(
                out,
                "{indent}builder.write(\"{key}\", value: try builder.arena.writeValue({var}))"
            );
        }
        PropType::Array { item } => {
            let elem_expr = swift_bin_value_expr("$0", item);
            writeln!(
                out,
                "{indent}builder.write(\"{key}\", value: try builder.arena.writeValue(.array({var}.map {{ {elem_expr} }})))"
            );
        }
    }
}

fn swift_bin_value_expr(var: &str, ty: &PropType) -> String {
    match ty {
        PropType::Bool => format!(".bool({var})"),
        PropType::Int32 | PropType::IntEnum { .. } => format!(".int64(Int64({var}))"),
        PropType::Float => format!(".float64(Double({var}))"),
        PropType::Double => format!(".float64({var})"),
        PropType::Object { .. } => var.to_owned(),
        PropType::Array { item } => {
            format!(".array({var}.map {{ {} }})", swift_bin_value_expr("$0", item))
        }
        _ => format!(".string({var})"),
    }
}

fn emit_swift_aux_enum(out: &mut CodeWriter, comp_name: &str, prop: &PropSpec) {
    match &prop.prop_type {
        PropType::StringEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            writeln!(
                out,
                "public enum {enum_name}: String, Sendable, Hashable, CaseIterable {{"
            );
            for v in variants {
                writeln!(
                    out,
                    "    case {} = \"{}\"",
                    swift_ident(v),
                    escape_c_like_string(v)
                );
            }
            writeln!(out, "}}");
            writeln!(out);
        }
        PropType::IntEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            writeln!(
                out,
                "public enum {enum_name}: Int32, Sendable, Hashable, CaseIterable {{"
            );
            for v in variants {
                let vname = int_enum_variant_camel(*v);
                writeln!(out, "    case {vname} = {v}");
            }
            writeln!(out, "}}");
            writeln!(out);
        }
        _ => {}
    }
}

fn swift_event_struct_name(comp_name: &str, ev: &EventSpec) -> String {
    format!("{comp_name}{}Event", to_pascal_case(&strip_on_prefix(&ev.name)))
}

fn emit_swift_event_struct(out: &mut CodeWriter, comp_name: &str, ev: &EventSpec) {
    if ev.payload.is_empty() {
        return;
    }
    let st = swift_event_struct_name(comp_name, ev);
    writeln!(out, "public struct {st}: Sendable, Equatable {{");
    for f in &ev.payload {
        let fname = swift_ident(&f.name);
        let fty = swift_simple_type(&f.field_type);
        let q = if f.optional || f.nullable { "?" } else { "" };
        writeln!(out, "    public let {fname}: {fty}{q}");
    }
    writeln!(out);
    writeln!(out, "    public init(binView: NveBinValueView) {{");
    for f in &ev.payload {
        let fname = swift_ident(&f.name);
        let key = escape_c_like_string(&f.name);
        let expr = swift_from_bin_view_expr(&key, f);
        writeln!(out, "        self.{fname} = {expr}");
    }
    writeln!(out, "    }}");
    writeln!(out, "}}");
    writeln!(out);
}

fn swift_from_bin_view_expr(key: &str, f: &ObjectField) -> String {
    let opt = f.optional || f.nullable;
    match &f.field_type {
        PropType::Bool => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.boolValue")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.boolValue ?? false")
            }
        }
        PropType::Int32 | PropType::IntEnum { .. } => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.int64Value.map(Int32.init(truncatingIfNeeded:))")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.int64Value.map(Int32.init(truncatingIfNeeded:)) ?? 0")
            }
        }
        PropType::Float => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.numberValue.map(Float.init)")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.numberValue.map(Float.init) ?? 0.0")
            }
        }
        PropType::Double => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.numberValue")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.numberValue ?? 0.0")
            }
        }
        PropType::Object { .. } => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.toOwned()")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.toOwned() ?? .null")
            }
        }
        _ => {
            if opt {
                format!("binView.mapValue(forKey: \"{key}\")?.stringValue")
            } else {
                format!("binView.mapValue(forKey: \"{key}\")?.stringValue ?? \"\"")
            }
        }
    }
}

fn swift_event_closure_type(comp_name: &str, ev: &EventSpec) -> String {
    if ev.payload.is_empty() {
        "() -> Void".to_owned()
    } else {
        format!("({}) -> Void", swift_event_struct_name(comp_name, ev))
    }
}

fn swift_prop_is_optional(prop: &PropSpec) -> bool {
    (prop.optional || prop.nullable) && swift_default_expr("_", prop).is_none()
}

fn swift_prop_type(comp_name: &str, prop: &PropSpec) -> String {
    let base = match &prop.prop_type {
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("{comp_name}{}", to_pascal_case(&prop.name))
        }
        PropType::Color => "String".to_owned(),
        other => swift_simple_type(other),
    };
    if swift_prop_is_optional(prop) {
        format!("{base}?")
    } else {
        base
    }
}

fn swift_simple_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "Bool".to_owned(),
        PropType::Int32 | PropType::IntEnum { .. } => "Int32".to_owned(),
        PropType::Float => "Float".to_owned(),
        PropType::Double => "Double".to_owned(),
        PropType::Array { item } => format!("[{}]", swift_simple_type(item)),
        PropType::Object { .. } => "NveBinValue".to_owned(),
        _ => "String".to_owned(),
    }
}

fn swift_default_expr(comp_name: &str, prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float | PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Float | PropType::Double, DefaultValue::Float(f)) => {
            Some(format_float_literal(*f))
        }
        (PropType::String | PropType::Color, DefaultValue::String(s)) => {
            Some(format!("\"{}\"", escape_c_like_string(s)))
        }
        (PropType::StringEnum { variants }, DefaultValue::String(s)) if variants.contains(s) => {
            let _ = comp_name;
            Some(format!(".{}", swift_ident(s)))
        }
        (PropType::IntEnum { variants }, DefaultValue::Int(i))
            if variants.contains(&(*i as i32)) =>
        {
            let vname = int_enum_variant_camel(*i as i32);
            Some(format!(".{vname}"))
        }
        _ => None,
    }
}
