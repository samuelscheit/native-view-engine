//! Java target for published word tables (`generated/NveTables.java`): one nested class per
//! `TableDesc` with its key, schema hash, layout, `dev.nve.host.FieldSpec`s, default bits, and
//! word-enum variant values, so Android / Compose hosts read `NveRuntimeSceneView` tables
//! without hand-transcribed layouts.

use std::fmt::Write as _;

use nve_abi::table::{FieldDesc, FieldKind, Storage, TableDesc};

use crate::naming::{to_pascal_case, to_snake_case};
use crate::schema::export::GeneratedFile;

/// Workspace-relative path of the generated Java tables class.
pub const JAVA_TABLES_PATH: &str =
    "hosts/android-shell/android-app/src/dev/nve/android/generated/NveTables.java";

/// `GeneratedFile` for [`generate_java_tables`] at [`JAVA_TABLES_PATH`].
pub fn generate_java_tables_file(tables: &[&TableDesc]) -> GeneratedFile {
    GeneratedFile {
        relative_path: JAVA_TABLES_PATH.to_owned(),
        content: generate_java_tables(tables),
    }
}

/// Generates `NveTables.java` for `tables` (sorted by name; duplicate names panic).
pub fn generate_java_tables(tables: &[&TableDesc]) -> String {
    let mut sorted: Vec<&TableDesc> = tables.to_vec();
    sorted.sort_by_key(|t| t.name);
    for pair in sorted.windows(2) {
        assert_ne!(pair[0].name, pair[1].name, "duplicate table {}", pair[0].name);
    }
    let mut out = String::with_capacity(16 * 1024);
    out.push_str(
        "// @generated by nve-codegen (published word tables) — DO NOT EDIT MANUALLY.\n\
         package dev.nve.android.generated;\n\n\
         import dev.nve.host.FieldKind;\n\
         import dev.nve.host.FieldSpec;\n\
         import dev.nve.host.Key64;\n\n\
         /**\n * Published NVE word tables: key, schema hash, layout, field specs, default bits, and\n\
         \x20* word-enum values per table. Defaults are raw field bits ({@code Float.intBitsToFloat} for\n\
         \x20* {@code F32}); {@code STR} fields span two words and have no default.\n */\n\
         public final class NveTables {\n    private NveTables() {}\n",
    );
    for t in sorted {
        emit_table(&mut out, t);
    }
    out.push_str("}\n");
    out
}

fn class_name(table: &str) -> String {
    to_pascal_case(table.strip_prefix("nve.").unwrap_or(table))
}

fn java_kind(kind: FieldKind) -> &'static str {
    match kind {
        FieldKind::U32 => "U32",
        FieldKind::I32 => "I32",
        FieldKind::F32 => "F32",
        FieldKind::Bool => "BOOL",
        FieldKind::Enum => "ENUM",
        FieldKind::Color => "COLOR",
        FieldKind::Length => "LENGTH",
        FieldKind::Str => "STR",
        FieldKind::Resource => "RESOURCE",
        FieldKind::Node => "NODE",
    }
}

/// Java `FieldSpec` bit width (`STR` is two whole words; Java specs describe the offset word).
fn java_bits(f: &FieldDesc) -> u8 {
    if f.kind == FieldKind::Str { 32 } else { f.bits }
}

fn default_bits(t: &TableDesc, f: &FieldDesc) -> u32 {
    let word = t.defaults.get(f.word as usize).copied().unwrap_or(0);
    let bits = java_bits(f);
    let shifted = word >> f.shift;
    if bits >= 32 { shifted } else { shifted & ((1u32 << bits) - 1) }
}

fn emit_table(out: &mut String, t: &TableDesc) {
    let storage = match t.storage {
        Storage::Dense => "dense",
        Storage::Sparse => "sparse",
    };
    let class = class_name(t.name);
    let _ = write!(
        out,
        "\n    /** {{@code {name}}} ({storage}, {words} words). */\n\
         \x20   public static final class {class} {{\n\
         \x20       private {class}() {{}}\n\n\
         \x20       public static final String NAME = \"{name}\";\n\
         \x20       public static final Key64 KEY = Key64.of(0x{key:016X}L);\n\
         \x20       public static final long SCHEMA_HASH = 0x{hash:016X}L;\n\
         \x20       public static final int WORDS = {words};\n\
         \x20       public static final boolean SPARSE = {sparse};\n",
        name = t.name,
        words = t.words(),
        key = t.key.0,
        hash = t.schema_hash,
        sparse = matches!(t.storage, Storage::Sparse),
    );
    for f in t.fields {
        let field = to_snake_case(f.name).to_ascii_uppercase();
        let _ = write!(
            out,
            "\n        public static final FieldSpec {field} = new FieldSpec({}, {}, {}, FieldKind.{});\n",
            f.word,
            f.shift,
            java_bits(f),
            java_kind(f.kind)
        );
        if f.kind != FieldKind::Str {
            let _ = writeln!(
                out,
                "        public static final int {field}_DEFAULT = 0x{:08X};",
                default_bits(t, f)
            );
        }
        for v in f.variants {
            let _ = writeln!(
                out,
                "        public static final int {field}_{} = {};",
                to_snake_case(v.name).to_ascii_uppercase(),
                v.value
            );
        }
    }
    out.push_str("    }\n");
}

#[cfg(test)]
mod tests {
    use super::*;
    use nve_abi::table::EnumVariant;
    use nve_abi::Key64;

    const FIELDS: &[FieldDesc] = &[
        FieldDesc { name: "bg_color", kind: FieldKind::Color, word: 0, shift: 0, bits: 32, effects: 0, variants: &[] },
        FieldDesc { name: "label", kind: FieldKind::Str, word: 1, shift: 0, bits: 64, effects: 0, variants: &[] },
        FieldDesc {
            name: "fit",
            kind: FieldKind::Enum,
            word: 3,
            shift: 4,
            bits: 3,
            effects: 0,
            variants: &[EnumVariant { name: "Cover", value: 0 }, EnumVariant { name: "ScaleDown", value: 4 }],
        },
    ];

    const DEMO: TableDesc = TableDesc {
        key: Key64::of("nve.demo_table"),
        name: "nve.demo_table",
        schema_hash: 0xABCD,
        storage: Storage::Sparse,
        flags: 0,
        defaults: &[0xFF00_0000, 0, 0, 0x40],
        word_effects: &[0, 0, 0, 0],
        str_words: 0b10,
        resource_words: 0,
        fields: FIELDS,
    };

    #[test]
    fn emits_specs_defaults_and_variants() {
        let java = generate_java_tables(&[&DEMO]);
        assert!(java.contains("public static final class DemoTable {"));
        assert!(java.contains(&format!("Key64.of(0x{:016X}L)", Key64::of("nve.demo_table").0)));
        assert!(java.contains("public static final boolean SPARSE = true;"));
        assert!(java.contains("public static final int WORDS = 4;"));
        assert!(java.contains("BG_COLOR = new FieldSpec(0, 0, 32, FieldKind.COLOR);"));
        assert!(java.contains("BG_COLOR_DEFAULT = 0xFF000000;"));
        assert!(java.contains("LABEL = new FieldSpec(1, 0, 32, FieldKind.STR);"));
        assert!(!java.contains("LABEL_DEFAULT"), "strings have no default bits");
        assert!(java.contains("FIT = new FieldSpec(3, 4, 3, FieldKind.ENUM);"));
        assert!(java.contains("FIT_DEFAULT = 0x00000004;"), "default bits are shifted and masked");
        assert!(java.contains("FIT_COVER = 0;") && java.contains("FIT_SCALE_DOWN = 4;"));
    }

    #[test]
    fn output_is_sorted_and_deterministic() {
        const OTHER: TableDesc = TableDesc { name: "nve.alpha", key: Key64::of("nve.alpha"), ..DEMO };
        let a = generate_java_tables(&[&DEMO, &OTHER]);
        assert_eq!(a, generate_java_tables(&[&OTHER, &DEMO]));
        assert!(a.find("class Alpha").unwrap() < a.find("class DemoTable").unwrap());
    }

    #[test]
    #[should_panic(expected = "duplicate table")]
    fn duplicate_names_are_rejected() {
        let _ = generate_java_tables(&[&DEMO, &DEMO]);
    }
}
