//! Android Kotlin + C++20 JNI target emitter for NVE Hybrid FFI codegen.
//!
//! Emits:
//! 1. `<Stem>HybridSpec.generated.kt`: `enum class`, `data class` structs/props/events with
//!    `NveBinValue` codecs, `interface Hybrid<Name>Spec`, and `class <Name>HybridClient` with
//!    `external fun` bindings. The codec, `DynamicValue`, and direct-buffer helpers are the static
//!    `dev.nve.host` runtime (`packages/core/host-java`), never copied into generated code.
//! 2. `<Stem>HybridJni.generated.cpp`: C++20 JNI glue calling `NveHybrid<Name>VTable` directly over
//!    JNI primitives, borrowed direct `ByteBuffer`s (`GetDirectBufferAddress`), and `byte[]`
//!    results, reusing the static `nve::host` C++ runtime (`nve/host/jni.hpp`).

mod client_emitter;
mod jni_emitter;
mod type_helpers;

use type_helpers::{check_kotlin_supported, kotlin_long_literal};

use crate::writer::CodeWriter;
use client_emitter::{emit_kotlin_enum, emit_kotlin_module, emit_kotlin_struct, emit_kotlin_view};
use jni_emitter::emit_jni_cpp;

use crate::error::CodegenError;
use crate::schema::export::GeneratedFile;
use crate::schema::hybrid::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::naming::{
    cpp_ident, escape_kotlin_string, format_float_literal, kotlin_ident, to_camel_case,
    to_pascal_case, to_snake_case,
};

const KOTLIN_PACKAGE: &str = "dev.nve.hybrid";
const JNI_PACKAGE_PREFIX: &str = "Java_dev_nve_hybrid";

/// Emits `<Stem>HybridSpec.generated.kt` and `<Stem>HybridJni.generated.cpp`.
pub fn generate_hybrid_kotlin(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    check_kotlin_supported(spec)?;
    let stem = spec.stem_pascal();
    let kt_name = format!("{stem}HybridSpec.generated.kt");
    let jni_name = format!("{stem}HybridJni.generated.cpp");
    let hpp_name = format!("{stem}HybridSpec.generated.hpp");

    let kt = emit_kotlin_spec(spec);
    let jni = emit_jni_cpp(spec, &hpp_name);

    Ok(vec![
        GeneratedFile {
            relative_path: kt_name,
            content: kt,
        },
        GeneratedFile {
            relative_path: jni_name,
            content: jni,
        },
    ])
}

fn emit_kotlin_spec(spec: &HybridFileSpec) -> String {
    let mut out = CodeWriter::with_capacity(16 * 1024);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Android Kotlin target) — DO NOT EDIT."
    );
    writeln!(
        out,
        "// Binary direct JNI bindings over primitives & DirectByteBuffer."
    );
    writeln!(out, "package {KOTLIN_PACKAGE}");
    writeln!(out);
    writeln!(out, "import dev.nve.host.BinReader");
    writeln!(out, "import dev.nve.host.BinWriter");
    writeln!(out, "import dev.nve.host.HybridRuntime");
    writeln!(out, "import dev.nve.host.HybridRuntime.DynamicValue");
    writeln!(out, "import java.nio.ByteBuffer");
    writeln!(out);

    emit_kotlin_common(&mut out, spec);

    for e in &spec.enums {
        emit_kotlin_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_kotlin_struct(&mut out, s, spec);
    }

    for m in &spec.modules {
        emit_kotlin_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_kotlin_view(&mut out, v, spec);
    }

    out.into_string()
}

/// File-level constants, scoped per spec so several generated files share `dev.nve.hybrid`.
fn emit_kotlin_common(out: &mut CodeWriter, spec: &HybridFileSpec) {
    writeln!(out, "object {}HybridSchema {{", spec.stem_pascal());
    writeln!(out, "    const val ABI_VERSION: Int = {NVE_HYBRID_ABI_VERSION}");
    let hash = spec.file_schema_hash();
    writeln!(
        out,
        "    const val FILE_SCHEMA_HASH: Long = {} // 0x{hash:016X}",
        kotlin_long_literal(hash)
    );
    writeln!(out, "}}");
    writeln!(out);
}
