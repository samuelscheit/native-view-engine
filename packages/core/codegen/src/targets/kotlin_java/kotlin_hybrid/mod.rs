const KOTLIN_PACKAGE: &str = "dev.nve.hybrid";
const JNI_PACKAGE_PREFIX: &str = "Java_dev_nve_hybrid";

/// Emits `<Stem>HybridSpec.generated.kt` and `<Stem>HybridJni.generated.cpp`.
pub fn generate_hybrid_kotlin(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_pascal();
    let kt_name = format!("{stem}HybridSpec.generated.kt");
    let jni_name = format!("{stem}HybridJni.generated.cpp");
    let hpp_name = format!("{stem}HybridSpec.generated.hpp");

    let kt = emit_kotlin_spec(spec);
    let jni = emit_jni_cpp(spec, &hpp_name);

    Ok(vec![
        GeneratedFile {
            relative_path: kt_name,
            content: kt,
        },
        GeneratedFile {
            relative_path: jni_name,
            content: jni,
        },
    ])
}

fn emit_kotlin_spec(spec: &HybridFileSpec) -> String {
    let mut out = String::with_capacity(16 * 1024);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Android Kotlin target) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(
        out,
        "// Binary direct JNI bindings over primitives & DirectByteBuffer."
    )
    .unwrap();
    writeln!(out, "package {KOTLIN_PACKAGE}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "import java.nio.ByteBuffer").unwrap();
    writeln!(out, "import java.nio.ByteOrder").unwrap();
    writeln!(out, "import java.nio.charset.StandardCharsets").unwrap();
    writeln!(out).unwrap();

    emit_kotlin_common(&mut out, spec);

    for e in &spec.enums {
        emit_kotlin_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_kotlin_struct(&mut out, s, spec);
    }

    for m in &spec.modules {
        emit_kotlin_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_kotlin_view(&mut out, v, spec);
    }

    out
}

fn emit_kotlin_common(out: &mut String, spec: &HybridFileSpec) {
    writeln!(out, "const val NVE_HYBRID_ABI_VERSION: Int = {NVE_HYBRID_ABI_VERSION}").unwrap();
    writeln!(
        out,
        "const val NVE_HYBRID_FILE_SCHEMA_HASH: Long = 0x{:016X}UL.toLong()",
        spec.file_schema_hash()
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        r#"/** Owned dynamic value encoded in NVE's compact binary `NveBinValue` format (binary). */
data class NveHybridDynamicValue(val binBytes: ByteArray = byteArrayOf(0)) {{
    override fun equals(other: Any?): Boolean =
        other is NveHybridDynamicValue && binBytes.contentEquals(other.binBytes)

    override fun hashCode(): Int = binBytes.contentHashCode()
}}

/** Compact binary `NveBinValue` writer matching `nve_abi::encode_bin_value` byte-for-byte. */
class NveBinWriter(initialCapacity: Int = 64) {{
    private var buf = ByteArray(initialCapacity)
    private var len = 0

    fun writeNull() = pushByte(0)

    fun writeBool(v: Boolean) {{
        pushByte(1)
        pushByte(if (v) 1 else 0)
    }}

    fun writeLong(v: Long) {{
        pushByte(2)
        writeLe64(v)
    }}

    fun writeDouble(v: Double) {{
        pushByte(3)
        writeLe64(java.lang.Double.doubleToRawLongBits(v))
    }}

    fun writeString(v: String) {{
        val b = v.toByteArray(StandardCharsets.UTF_8)
        pushByte(4)
        writeLe32(b.size)
        pushBytes(b)
    }}

    fun writeBytes(b: ByteArray) {{
        pushByte(5)
        writeLe32(b.size)
        pushBytes(b)
    }}

    fun writeRaw(raw: ByteArray) = pushBytes(raw)

    fun writeArray(count: Int, block: (NveBinWriter) -> Unit) {{
        pushByte(6)
        val lenPos = len
        writeLe32(0)
        val start = len
        writeLe32(count)
        block(this)
        patchLe32(lenPos, len - start)
    }}

    fun writeMap(count: Int, block: (NveBinWriter) -> Unit) {{
        pushByte(7)
        val lenPos = len
        writeLe32(0)
        val start = len
        writeLe32(count)
        block(this)
        patchLe32(lenPos, len - start)
    }}

    fun writeMapKey(key: String) {{
        val b = key.toByteArray(StandardCharsets.UTF_8)
        writeLe32(b.size)
        pushBytes(b)
    }}

    fun toDirectByteBuffer(): ByteBuffer {{
        val direct = ByteBuffer.allocateDirect(len).order(ByteOrder.LITTLE_ENDIAN)
        direct.put(buf, 0, len)
        direct.flip()
        return direct
    }}

    fun toByteArray(): ByteArray = buf.copyOf(len)

    private fun ensure(extra: Int) {{
        if (len + extra <= buf.size) return
        var next = buf.size.coerceAtLeast(64)
        while (next < len + extra) next *= 2
        buf = buf.copyOf(next)
    }}

    private fun pushByte(b: Int) {{
        ensure(1)
        buf[len++] = b.toByte()
    }}

    private fun pushBytes(src: ByteArray) {{
        ensure(src.size)
        System.arraycopy(src, 0, buf, len, src.size)
        len += src.size
    }}

    private fun writeLe32(v: Int) {{
        ensure(4)
        buf[len++] = (v and 0xFF).toByte()
        buf[len++] = ((v ushr 8) and 0xFF).toByte()
        buf[len++] = ((v ushr 16) and 0xFF).toByte()
        buf[len++] = ((v ushr 24) and 0xFF).toByte()
    }}

    private fun patchLe32(pos: Int, v: Int) {{
        buf[pos] = (v and 0xFF).toByte()
        buf[pos + 1] = ((v ushr 8) and 0xFF).toByte()
        buf[pos + 2] = ((v ushr 16) and 0xFF).toByte()
        buf[pos + 3] = ((v ushr 24) and 0xFF).toByte()
    }}

    private fun writeLe64(v: Long) {{
        ensure(8)
        for (i in 0 until 8) {{
            buf[len++] = ((v ushr (i * 8)) and 0xFFL).toByte()
        }}
    }}
}}

/** Bounds-checked little-endian reader for compact binary `NveBinValue` payloads. */
class NveBinReader(private val buf: ByteBuffer) {{
    init {{
        buf.order(ByteOrder.LITTLE_ENDIAN)
    }}

    constructor(bytes: ByteArray) : this(ByteBuffer.wrap(bytes))

    fun peekTag(): Int = buf.get(buf.position()).toInt() and 0xFF

    fun readNullIfPresent(): Boolean {{
        if (peekTag() == 0) {{
            buf.get()
            return true
        }}
        return false
    }}

    fun readBool(): Boolean {{
        expectTag(1)
        return buf.get().toInt() != 0
    }}

    fun readLong(): Long {{
        expectTag(2)
        return buf.long
    }}

    fun readDouble(): Double {{
        return when (peekTag()) {{
            3 -> {{
                buf.get()
                buf.double
            }}
            2 -> readLong().toDouble()
            else -> throw IllegalStateException("expected NveBinValue number")
        }}
    }}

    fun readString(): String {{
        expectTag(4)
        val len = buf.int
        val bytes = ByteArray(len)
        buf.get(bytes)
        return String(bytes, StandardCharsets.UTF_8)
    }}

    fun readBytes(): ByteArray {{
        expectTag(5)
        val len = buf.int
        val bytes = ByteArray(len)
        buf.get(bytes)
        return bytes
    }}

    fun beginArray(): Int {{
        expectTag(6)
        buf.int // payload_byte_len
        return buf.int
    }}

    fun beginMap(): Int {{
        expectTag(7)
        buf.int // payload_byte_len
        return buf.int
    }}

    fun readMapKey(): String {{
        val len = buf.int
        val bytes = ByteArray(len)
        buf.get(bytes)
        return String(bytes, StandardCharsets.UTF_8)
    }}

    fun readRawValue(): ByteArray {{
        val start = buf.position()
        skipValue()
        val end = buf.position()
        val out = ByteArray(end - start)
        buf.position(start)
        buf.get(out)
        return out
    }}

    fun skipValue() {{
        when (val tag = buf.get().toInt() and 0xFF) {{
            0 -> return
            1 -> buf.position(buf.position() + 1)
            2, 3 -> buf.position(buf.position() + 8)
            4, 5, 6, 7 -> {{
                val len = buf.int
                buf.position(buf.position() + len)
            }}
            else -> throw IllegalStateException("invalid NveBinValue tag: $tag")
        }}
    }}

    private fun expectTag(expected: Int) {{
        val actual = buf.get().toInt() and 0xFF
        if (actual != expected) {{
            throw IllegalStateException("unexpected NveBinValue tag: expected $expected, got $actual")
        }}
    }}
}}
"#
    )
    .unwrap();
}

