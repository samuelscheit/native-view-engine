/// Generates `hosts/android-shell/android-app/src/dev/nve/android/generated/NveCoreAbi.java`
/// directly from `packages/core/abi/src/schema.rs`.
pub fn generate_java_core_abi() -> String {
    let spec = core_abi_spec();
    let schema_hash = crate::schema::hybrid::core_abi::core_abi_schema_hash();
    let mut out = CodeWriter::with_capacity(4 * 1024);

    writeln!(
        out,
        "// @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY."
    );
    writeln!(
        out,
        "// Single-source NVE Core ABI constants generated from packages/core/abi/src/schema.rs."
    );
    writeln!(out, "package dev.nve.android.generated;");
    writeln!(out);
    writeln!(out, "/**");
    writeln!(
        out,
        " * Generated NVE Core ABI constants, interface IDs, enums, and layout sizes."
    );
    writeln!(out, " */");
    writeln!(out, "public final class NveCoreAbi {{");
    writeln!(out, "    private NveCoreAbi() {{}}");
    writeln!(out);
    writeln!(
        out,
        "    public static final long CORE_ABI_SCHEMA_HASH = 0x{schema_hash:016X}L;"
    );
    writeln!(
        out,
        "    public static final String CORE_ABI_SCHEMA_HASH_HEX = \"0x{schema_hash:016X}\";"
    );
    writeln!(out);

    for c in &spec.consts {
        let jname = c.name.strip_prefix("NVE_").unwrap_or(&c.name);
        let is_u64 = c.ty == HybridType::U64;
        match (c.hex, is_u64) {
            (true, true) => writeln!(out, "    public static final long {jname} = 0x{:016X}L;", c.value),
            (false, true) => writeln!(out, "    public static final long {jname} = {}L;", c.value),
            (true, false) => writeln!(out, "    public static final int {jname} = 0x{:X};", c.value),
            (false, false) => writeln!(out, "    public static final int {jname} = {};", c.value),
        }
    }
    writeln!(out);

    writeln!(out, "    // Modular interface IDs (`nve_get_interface`)");
    for m in &spec.modules {
        let upper = to_snake_case(&m.name).to_ascii_uppercase();
        writeln!(
            out,
            "    public static final int IFACE_{upper} = {};",
            m.interface_id()
        );
    }
    writeln!(out);

    for e in &spec.enums {
        let prefix = format_c_enum_prefix(e);
        let jprefix = prefix.strip_prefix("NVE_").unwrap_or(&prefix);
        writeln!(out, "    // {}", e.name);
        for v in &e.variants {
            let v_upper = to_snake_case(&v.name).to_ascii_uppercase();
            writeln!(
                out,
                "    public static final int {jprefix}{v_upper} = {};",
                format_enum_value(v.value)
            );
        }
        writeln!(out);
    }

    writeln!(out, "    // NveHostStatus");
    for &(variant, code) in HOST_STATUS_VARIANTS {
        let v_upper = to_snake_case(variant).to_ascii_uppercase();
        writeln!(out, "    public static final int HOST_{v_upper} = {code};");
    }
    writeln!(out);

    writeln!(out, "    // Fixed ABI struct sizes");
    for s in &spec.structs {
        let sup = to_snake_case(&s.name).to_ascii_uppercase();
        let short = sup.strip_prefix("NVE_").unwrap_or(&sup);
        if let Some(sz) = s.expected_size {
            writeln!(out, "    public static final int SIZEOF_{short} = {sz};");
        }
        if let Some(sz64) = s.expected_size_64 {
            writeln!(
                out,
                "    public static final int SIZEOF_{short}_64 = {sz64};"
            );
        }
    }
    writeln!(out, "}}");
    out.into_string()
}


