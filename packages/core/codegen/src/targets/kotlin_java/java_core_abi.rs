/// Generates `hosts/android-shell/android-app/src/dev/nve/android/generated/NveSceneBuffer.java`
/// directly from `packages/core/abi/src/schema.rs`.
pub fn generate_java_scene_buffer() -> String {
    let spec = scene_abi_spec();
    let schema_hash = compute_scene_schema_hash(&spec);
    let ResolvedSceneAbi {
        render_node,
        node_meta,
        node_size,
        meta_size,
        ..
    } = ResolvedSceneAbi::from_spec(&spec);

    let mut out = CodeWriter::with_capacity(6144);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY."
    );
    writeln!(
        out,
        "// Single-source 64-byte NveRenderNode + NveSceneView zero-GC DirectByteBuffer reader."
    );
    writeln!(out, "package dev.nve.android.generated;");
    writeln!(out);
    writeln!(out, "import java.nio.ByteBuffer;");
    writeln!(out, "import java.nio.ByteOrder;");
    writeln!(out, "import java.nio.charset.StandardCharsets;");
    writeln!(out);
    writeln!(out, "/**");
    writeln!(
        out,
        " * Zero-copy, binary FFI reader over JNI `NewDirectByteBuffer` slabs for `NveSceneView`."
    );
    writeln!(out, " */");
    writeln!(out, "public final class NveSceneBuffer {{");
    writeln!(
        out,
        "    public static final long SCHEMA_HASH = 0x{schema_hash:016X}L;"
    );
    writeln!(out, "    public static final int NODE_STRIDE = {node_size};");
    writeln!(out, "    public static final int META_STRIDE = {meta_size};");
    writeln!(out);
    writeln!(out, "    // NveRenderNode::flags bits");
    writeln!(out, "    public static final int FLAG_LEAF_TEXT = 1 << 0;");
    writeln!(out, "    public static final int FLAG_INTERACTIVE = 1 << 1;");
    writeln!(out, "    public static final int FLAG_CLIP_BOUNDS = 1 << 2;");
    writeln!(out);
    writeln!(out, "    // Sentinel NveRenderNode::primary_slot value (plain container)");
    for c in &spec.consts {
        if c.name == "NVE_PRIMARY_SLOT_NONE" {
            writeln!(out, "    public static final int PRIMARY_SLOT_NONE = 0x{:02X};", c.value);
        }
    }
    writeln!(out);
    writeln!(out, "    // NveNodeMeta::flags bits & resize-mode shift/mask");
    for c in &spec.consts {
        if let Some(suffix) = c.name.strip_prefix("NVE_META_") {
            if c.hex {
                writeln!(out, "    public static final int META_{suffix} = 0x{:X};", c.value);
            } else {
                writeln!(out, "    public static final int META_{suffix} = {};", c.value);
            }
        }
    }
    writeln!(out);
    writeln!(out, "    // Exact byte offsets within one 64-byte NveRenderNode");
    for f in &render_node.fields {
        writeln!(
            out,
            "    public static final int OFFSET_{} = {};",
            snake_to_screaming(&f.name),
            f.offset.expect("NveRenderNode field defines offset")
        );
    }
    writeln!(out);
    writeln!(out, "    // Exact byte offsets within one 64-byte NveNodeMeta");
    for f in &node_meta.fields {
        writeln!(
            out,
            "    public static final int META_OFFSET_{} = {};",
            snake_to_screaming(&f.name),
            f.offset.expect("NveNodeMeta field defines offset")
        );
    }
    writeln!(out);
    writeln!(out, "    private long frameId;");
    writeln!(out, "    private int nodeCount;");
    writeln!(out, "    private int dirtyCount;");
    writeln!(out, "    private int removedCount;");
    writeln!(out, "    private int textSlabLen;");
    writeln!(out, "    private int childrenSlabLen;");
    writeln!(out, "    private int tableCount;");
    writeln!(out, "    private ByteBuffer nodesBuf;");
    writeln!(out, "    private ByteBuffer textSlabBuf;");
    writeln!(out, "    private ByteBuffer childrenSlabBuf;");
    writeln!(out, "    private ByteBuffer dirtyIndicesBuf;");
    writeln!(out, "    private ByteBuffer removedIdsBuf;");
    writeln!(out, "    private ByteBuffer tablesBuf;");
    writeln!(out, "    private byte[] textScratch = new byte[256];");
    writeln!(out);
    writeln!(out, "    /**");
    writeln!(
        out,
        "     * Rebinds this reusable reader to the latest frame's direct buffers without table views."
    );
    writeln!(out, "     */");
    writeln!(out, "    public void attach(");
    writeln!(out, "            long schemaHash,");
    writeln!(out, "            long frameId,");
    writeln!(out, "            int nodeCount,");
    writeln!(out, "            int dirtyCount,");
    writeln!(out, "            int removedCount,");
    writeln!(out, "            int textSlabLen,");
    writeln!(out, "            int childrenSlabLen,");
    writeln!(out, "            ByteBuffer nodesBuf,");
    writeln!(out, "            ByteBuffer textSlabBuf,");
    writeln!(out, "            ByteBuffer childrenSlabBuf,");
    writeln!(out, "            ByteBuffer dirtyIndicesBuf,");
    writeln!(out, "            ByteBuffer removedIdsBuf) {{");
    writeln!(
        out,
        "        attach(schemaHash, frameId, nodeCount, dirtyCount, removedCount, textSlabLen, childrenSlabLen, 0, nodesBuf, textSlabBuf, childrenSlabBuf, dirtyIndicesBuf, removedIdsBuf, null);"
    );
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    /**");
    writeln!(
        out,
        "     * Rebinds this reusable reader to the latest frame's direct buffers without copying."
    );
    writeln!(out, "     */");
    writeln!(out, "    public void attach(");
    writeln!(out, "            long schemaHash,");
    writeln!(out, "            long frameId,");
    writeln!(out, "            int nodeCount,");
    writeln!(out, "            int dirtyCount,");
    writeln!(out, "            int removedCount,");
    writeln!(out, "            int textSlabLen,");
    writeln!(out, "            int childrenSlabLen,");
    writeln!(out, "            int tableCount,");
    writeln!(out, "            ByteBuffer nodesBuf,");
    writeln!(out, "            ByteBuffer textSlabBuf,");
    writeln!(out, "            ByteBuffer childrenSlabBuf,");
    writeln!(out, "            ByteBuffer dirtyIndicesBuf,");
    writeln!(out, "            ByteBuffer removedIdsBuf,");
    writeln!(out, "            ByteBuffer tablesBuf) {{");
    writeln!(out, "        if (schemaHash != SCHEMA_HASH) {{");
    writeln!(
        out,
        "            throw new IllegalStateException(\"NveSceneView schema hash mismatch: expected 0x\" + Long.toHexString(SCHEMA_HASH) + \", got 0x\" + Long.toHexString(schemaHash));"
    );
    writeln!(out, "        }}");
    writeln!(out, "        this.frameId = frameId;");
    writeln!(out, "        this.nodeCount = Math.max(0, nodeCount);");
    writeln!(out, "        this.dirtyCount = Math.max(0, dirtyCount);");
    writeln!(out, "        this.removedCount = Math.max(0, removedCount);");
    writeln!(out, "        this.textSlabLen = Math.max(0, textSlabLen);");
    writeln!(out, "        this.childrenSlabLen = Math.max(0, childrenSlabLen);");
    writeln!(out, "        this.tableCount = Math.max(0, tableCount);");
    writeln!(
        out,
        "        this.nodesBuf = nodesBuf != null ? nodesBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(
        out,
        "        this.textSlabBuf = textSlabBuf != null ? textSlabBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(
        out,
        "        this.childrenSlabBuf = childrenSlabBuf != null ? childrenSlabBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(
        out,
        "        this.dirtyIndicesBuf = dirtyIndicesBuf != null ? dirtyIndicesBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(
        out,
        "        this.removedIdsBuf = removedIdsBuf != null ? removedIdsBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(
        out,
        "        this.tablesBuf = tablesBuf != null ? tablesBuf.order(ByteOrder.LITTLE_ENDIAN) : null;"
    );
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    public long frameId() {{ return frameId; }}");
    writeln!(out, "    public int nodeCount() {{ return nodeCount; }}");
    writeln!(out, "    public int dirtyCount() {{ return dirtyCount; }}");
    writeln!(out, "    public int removedCount() {{ return removedCount; }}");
    writeln!(out, "    public int textSlabLen() {{ return textSlabLen; }}");
    writeln!(out, "    public int childrenSlabLen() {{ return childrenSlabLen; }}");
    writeln!(out, "    public int tableCount() {{ return tableCount; }}");
    writeln!(out, "    public ByteBuffer tablesBuf() {{ return tablesBuf; }}");
    writeln!(out);
    writeln!(out, "    public int dirtyIndex(int i) {{");
    writeln!(out, "        return dirtyIndicesBuf.getInt(i << 2);");
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    public int removedId(int i) {{");
    writeln!(out, "        return removedIdsBuf.getInt(i << 2);");
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    public int nodeId(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_NODE_ID); }}");
    writeln!(out, "    public int primarySlot(int idx) {{ return nodesBuf.get(idx * NODE_STRIDE + OFFSET_PRIMARY_SLOT) & 0xFF; }}");
    writeln!(out, "    public int flags(int idx) {{ return nodesBuf.get(idx * NODE_STRIDE + OFFSET_FLAGS) & 0xFF; }}");
    writeln!(out, "    public int opacityU8(int idx) {{ return nodesBuf.get(idx * NODE_STRIDE + OFFSET_OPACITY_U8) & 0xFF; }}");
    writeln!(out, "    public float opacity(int idx) {{ return opacityU8(idx) / 255.0f; }}");
    writeln!(out, "    public float x(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_X); }}");
    writeln!(out, "    public float y(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_Y); }}");
    writeln!(out, "    public float width(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_WIDTH); }}");
    writeln!(out, "    public float height(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_HEIGHT); }}");
    writeln!(out, "    public int bgRgba(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_BG_RGBA); }}");
    writeln!(out, "    public int textRgba(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_TEXT_RGBA); }}");
    writeln!(out, "    public int borderRgba(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_BORDER_RGBA); }}");
    writeln!(out, "    public float borderRadius(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_BORDER_RADIUS); }}");
    writeln!(out, "    public float borderWidth(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_BORDER_WIDTH); }}");
    writeln!(out, "    public float fontSize(int idx) {{ return nodesBuf.getFloat(idx * NODE_STRIDE + OFFSET_FONT_SIZE); }}");
    writeln!(out, "    public int textOffset(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_TEXT_OFFSET); }}");
    writeln!(out, "    public int textLen(int idx) {{ return nodesBuf.getShort(idx * NODE_STRIDE + OFFSET_TEXT_LEN) & 0xFFFF; }}");
    writeln!(out, "    public int childCount(int idx) {{ return nodesBuf.getShort(idx * NODE_STRIDE + OFFSET_CHILD_COUNT) & 0xFFFF; }}");
    writeln!(out, "    public int childOffset(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_CHILD_OFFSET); }}");
    writeln!(out, "    public int zIndex(int idx) {{ return nodesBuf.getInt(idx * NODE_STRIDE + OFFSET_Z_INDEX); }}");
    writeln!(out);
    writeln!(out, "    public boolean isLeafText(int idx) {{ return (flags(idx) & FLAG_LEAF_TEXT) != 0; }}");
    writeln!(out, "    public boolean isInteractive(int idx) {{ return (flags(idx) & FLAG_INTERACTIVE) != 0; }}");
    writeln!(out, "    public boolean clipsBounds(int idx) {{ return (flags(idx) & FLAG_CLIP_BOUNDS) != 0; }}");
    writeln!(out);
    writeln!(out, "    public int childId(int nodeIdx, int childPos) {{");
    writeln!(out, "        int offset = childOffset(nodeIdx) + childPos;");
    writeln!(out, "        return childrenSlabBuf.getInt(offset << 2);");
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    public String readText(int nodeIdx) {{");
    writeln!(out, "        int len = textLen(nodeIdx);");
    writeln!(out, "        if (len == 0 || textSlabBuf == null) {{");
    writeln!(out, "            return \"\";");
    writeln!(out, "        }}");
    writeln!(out, "        int off = textOffset(nodeIdx);");
    writeln!(out, "        if (off < 0 || off + len > textSlabLen) {{");
    writeln!(out, "            return \"\";");
    writeln!(out, "        }}");
    writeln!(out, "        if (textScratch.length < len) {{");
    writeln!(out, "            textScratch = new byte[Math.max(len, textScratch.length << 1)];");
    writeln!(out, "        }}");
    writeln!(out, "        ByteBuffer dup = textSlabBuf.duplicate();");
    writeln!(out, "        dup.position(off);");
    writeln!(out, "        dup.get(textScratch, 0, len);");
    writeln!(out, "        return new String(textScratch, 0, len, StandardCharsets.UTF_8);");
    writeln!(out, "    }}");
    writeln!(out, "}}");
    out.into_string()
}

