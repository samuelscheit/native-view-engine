/// Generates `hosts/web-shell/nve_scene_view.generated.ts` directly from
/// `packages/core/abi/src/schema.rs`.
pub fn generate_ts_scene_view() -> String {
    let spec = scene_abi_spec();
    let schema_hash = compute_scene_schema_hash(&spec);
    let ResolvedSceneAbi {
        render_node,
        node_meta,
        node_size,
        meta_size,
        ..
    } = ResolvedSceneAbi::from_spec(&spec);

    let mut out = CodeWriter::with_capacity(5120);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY."
    );
    writeln!(
        out,
        "// Single-source 64-byte NveRenderNode + NveSceneView zero-copy WASM memory reader."
    );
    writeln!(out);
    writeln!(
        out,
        "export const NVE_SCENE_SCHEMA_HASH: bigint = 0x{schema_hash:016X}n;"
    );
    writeln!(
        out,
        "export const NVE_RENDER_NODE_STRIDE = {node_size} as const;"
    );
    writeln!(
        out,
        "export const NVE_NODE_META_STRIDE = {meta_size} as const;"
    );
    writeln!(out);
    writeln!(out, "export const NVE_NODE_FLAG = {{");
    writeln!(out, "  LEAF_TEXT: 1 << 0,");
    writeln!(out, "  INTERACTIVE: 1 << 1,");
    writeln!(out, "  CLIP_BOUNDS: 1 << 2,");
    writeln!(out, "}} as const;");
    writeln!(out);
    for c in &spec.consts {
        if c.name == "NVE_PRIMARY_SLOT_NONE" {
            writeln!(out, "export const NVE_PRIMARY_SLOT_NONE = 0x{:02X} as const;", c.value);
        }
    }
    writeln!(out);
    writeln!(out, "export const NVE_META_FLAG = {{");
    for c in &spec.consts {
        if let Some(suffix) = c.name.strip_prefix("NVE_META_FLAG_") {
            writeln!(out, "  {suffix}: {},", c.value);
        }
    }
    writeln!(out, "}} as const;");
    for c in &spec.consts {
        if c.name.starts_with("NVE_META_RESIZE_MODE_") {
            if c.hex {
                writeln!(out, "export const {} = 0x{:X} as const;", c.name, c.value);
            } else {
                writeln!(out, "export const {} = {} as const;", c.name, c.value);
            }
        }
    }
    writeln!(out);
    writeln!(out, "export const NVE_NODE_OFFSET = {{");
    for f in &render_node.fields {
        writeln!(
            out,
            "  {}: {},",
            snake_to_screaming(&f.name),
            f.offset.expect("NveRenderNode field defines offset")
        );
    }
    writeln!(out, "}} as const;");
    writeln!(out);
    writeln!(out, "export const NVE_META_OFFSET = {{");
    for f in &node_meta.fields {
        writeln!(
            out,
            "  {}: {},",
            snake_to_screaming(&f.name),
            f.offset.expect("NveNodeMeta field defines offset")
        );
    }
    writeln!(out, "}} as const;");
    writeln!(out);
    writeln!(
        out,
        "/** Pointer & count descriptor for a WASM `NveSceneView` inside linear memory. */"
    );
    writeln!(out, "export interface NveSceneMemoryLayout {{");
    writeln!(out, "  readonly schemaHash: bigint;");
    writeln!(out, "  readonly frameId: bigint;");
    writeln!(out, "  readonly nodeCount: number;");
    writeln!(out, "  readonly dirtyCount: number;");
    writeln!(out, "  readonly removedCount: number;");
    writeln!(out, "  readonly textSlabLen: number;");
    writeln!(out, "  readonly childrenSlabLen: number;");
    writeln!(out, "  readonly tableCount: number;");
    writeln!(out, "  readonly nodesPtr: number;");
    writeln!(out, "  readonly textSlabPtr: number;");
    writeln!(out, "  readonly childrenSlabPtr: number;");
    writeln!(out, "  readonly dirtyIndicesPtr: number;");
    writeln!(out, "  readonly removedIdsPtr: number;");
    writeln!(out, "  readonly tablesPtr: number;");
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "const sharedUtf8Decoder = new TextDecoder('utf-8', {{ fatal: true }});"
    );
    writeln!(out);
    writeln!(
        out,
        "/** Zero-copy view over an `NveSceneView` stored directly inside `WebAssembly.Memory.buffer`. */"
    );
    writeln!(out, "export class NveSceneViewReader {{");
    writeln!(out, "  readonly frameId: bigint;");
    writeln!(out, "  readonly nodeCount: number;");
    writeln!(out, "  readonly tableCount: number;");
    writeln!(out, "  readonly tablesPtr: number;");
    writeln!(out, "  readonly textSlab: Uint8Array;");
    writeln!(out, "  readonly childrenSlab: Uint32Array;");
    writeln!(out, "  readonly dirtyIndices: Uint32Array;");
    writeln!(out, "  readonly removedIds: Uint32Array;");
    writeln!(out, "  private readonly nodesView: DataView;");
    writeln!(out);
    writeln!(
        out,
        "  constructor(memoryBuffer: ArrayBuffer, layout: NveSceneMemoryLayout) {{"
    );
    writeln!(out, "    if (layout.schemaHash !== NVE_SCENE_SCHEMA_HASH) {{");
    writeln!(
        out,
        "      throw new Error(`NveSceneView schema hash mismatch: expected 0x${{NVE_SCENE_SCHEMA_HASH.toString(16)}}, got 0x${{layout.schemaHash.toString(16)}}`);"
    );
    writeln!(out, "    }}");
    writeln!(out, "    this.frameId = layout.frameId;");
    writeln!(out, "    this.nodeCount = layout.nodeCount;");
    writeln!(out, "    this.tableCount = layout.tableCount;");
    writeln!(out, "    this.tablesPtr = layout.tablesPtr;");
    writeln!(
        out,
        "    this.nodesView = new DataView(memoryBuffer, layout.nodesPtr, layout.nodeCount * NVE_RENDER_NODE_STRIDE);"
    );
    writeln!(
        out,
        "    this.textSlab = new Uint8Array(memoryBuffer, layout.textSlabPtr, layout.textSlabLen);"
    );
    writeln!(
        out,
        "    this.childrenSlab = new Uint32Array(memoryBuffer, layout.childrenSlabPtr, layout.childrenSlabLen);"
    );
    writeln!(
        out,
        "    this.dirtyIndices = new Uint32Array(memoryBuffer, layout.dirtyIndicesPtr, layout.dirtyCount);"
    );
    writeln!(
        out,
        "    this.removedIds = new Uint32Array(memoryBuffer, layout.removedIdsPtr, layout.removedCount);"
    );
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(
        out,
        "  /** Reads an `NveSceneView` header directly at `viewPtr` inside wasm32 linear memory. */"
    );
    writeln!(
        out,
        "  static fromWasm32Pointer(memoryBuffer: ArrayBuffer, viewPtr: number): NveSceneViewReader {{"
    );
    writeln!(out, "    const hdr = new DataView(memoryBuffer, viewPtr, 64);");
    writeln!(out, "    return new NveSceneViewReader(memoryBuffer, {{");
    writeln!(out, "      schemaHash: hdr.getBigUint64(0, true),");
    writeln!(out, "      frameId: hdr.getBigUint64(8, true),");
    writeln!(out, "      nodeCount: hdr.getUint32(16, true),");
    writeln!(out, "      dirtyCount: hdr.getUint32(20, true),");
    writeln!(out, "      removedCount: hdr.getUint32(24, true),");
    writeln!(out, "      textSlabLen: hdr.getUint32(28, true),");
    writeln!(out, "      childrenSlabLen: hdr.getUint32(32, true),");
    writeln!(out, "      tableCount: hdr.getUint32(36, true),");
    writeln!(out, "      nodesPtr: hdr.getUint32(40, true),");
    writeln!(out, "      textSlabPtr: hdr.getUint32(44, true),");
    writeln!(out, "      childrenSlabPtr: hdr.getUint32(48, true),");
    writeln!(out, "      dirtyIndicesPtr: hdr.getUint32(52, true),");
    writeln!(out, "      removedIdsPtr: hdr.getUint32(56, true),");
    writeln!(out, "      tablesPtr: hdr.getUint32(60, true),");
    writeln!(out, "    }});");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  nodeId(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.NODE_ID, true); }}");
    writeln!(out, "  primarySlot(idx: number): number {{ return this.nodesView.getUint8(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.PRIMARY_SLOT); }}");
    writeln!(out, "  flags(idx: number): number {{ return this.nodesView.getUint8(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.FLAGS); }}");
    writeln!(out, "  opacityU8(idx: number): number {{ return this.nodesView.getUint8(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.OPACITY_U8); }}");
    writeln!(out, "  opacity(idx: number): number {{ return this.opacityU8(idx) / 255.0; }}");
    writeln!(out, "  x(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.X, true); }}");
    writeln!(out, "  y(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.Y, true); }}");
    writeln!(out, "  width(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.WIDTH, true); }}");
    writeln!(out, "  height(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.HEIGHT, true); }}");
    writeln!(out, "  bgRgba(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.BG_RGBA, true); }}");
    writeln!(out, "  textRgba(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.TEXT_RGBA, true); }}");
    writeln!(out, "  borderRgba(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.BORDER_RGBA, true); }}");
    writeln!(out, "  borderRadius(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.BORDER_RADIUS, true); }}");
    writeln!(out, "  borderWidth(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.BORDER_WIDTH, true); }}");
    writeln!(out, "  fontSize(idx: number): number {{ return this.nodesView.getFloat32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.FONT_SIZE, true); }}");
    writeln!(out, "  textOffset(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.TEXT_OFFSET, true); }}");
    writeln!(out, "  textLen(idx: number): number {{ return this.nodesView.getUint16(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.TEXT_LEN, true); }}");
    writeln!(out, "  childCount(idx: number): number {{ return this.nodesView.getUint16(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.CHILD_COUNT, true); }}");
    writeln!(out, "  childOffset(idx: number): number {{ return this.nodesView.getUint32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.CHILD_OFFSET, true); }}");
    writeln!(out, "  zIndex(idx: number): number {{ return this.nodesView.getInt32(idx * NVE_RENDER_NODE_STRIDE + NVE_NODE_OFFSET.Z_INDEX, true); }}");
    writeln!(out);
    writeln!(out, "  isLeafText(idx: number): boolean {{ return (this.flags(idx) & NVE_NODE_FLAG.LEAF_TEXT) !== 0; }}");
    writeln!(out, "  isInteractive(idx: number): boolean {{ return (this.flags(idx) & NVE_NODE_FLAG.INTERACTIVE) !== 0; }}");
    writeln!(out, "  clipsBounds(idx: number): boolean {{ return (this.flags(idx) & NVE_NODE_FLAG.CLIP_BOUNDS) !== 0; }}");
    writeln!(out);
    writeln!(out, "  readText(idx: number): string {{");
    writeln!(out, "    const len = this.textLen(idx);");
    writeln!(out, "    if (len === 0) return '';");
    writeln!(out, "    const start = this.textOffset(idx);");
    writeln!(out, "    const end = start + len;");
    writeln!(out, "    if (end > this.textSlab.byteLength) {{");
    writeln!(out, "      throw new RangeError(`Text slice [${{start}}..${{end}}] exceeds textSlab (${{this.textSlab.byteLength}})`);");
    writeln!(out, "    }}");
    writeln!(out, "    return sharedUtf8Decoder.decode(this.textSlab.subarray(start, end));");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  childrenOf(idx: number): Uint32Array {{");
    writeln!(out, "    const count = this.childCount(idx);");
    writeln!(out, "    if (count === 0) return new Uint32Array(0);");
    writeln!(out, "    const start = this.childOffset(idx);");
    writeln!(out, "    const end = start + count;");
    writeln!(out, "    if (end > this.childrenSlab.length) {{");
    writeln!(out, "      throw new RangeError(`Children slice [${{start}}..${{end}}] exceeds childrenSlab (${{this.childrenSlab.length}})`);");
    writeln!(out, "    }}");
    writeln!(out, "    return this.childrenSlab.subarray(start, end);");
    writeln!(out, "  }}");
    writeln!(out, "}}");
    out.into_string()
}

