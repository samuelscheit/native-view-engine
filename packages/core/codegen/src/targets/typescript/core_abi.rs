/// Generates `hosts/web-shell/nve_core_abi.generated.ts` directly from
/// `packages/core/abi/src/schema.rs`.
pub fn generate_ts_core_abi() -> String {
    let spec = core_abi_spec();
    let schema_hash = crate::schema::hybrid::core_abi::core_abi_schema_hash();
    let mut out = CodeWriter::with_capacity(4 * 1024);

    writeln!(
        out,
        "// @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY."
    );
    writeln!(
        out,
        "// Single-source NVE Core ABI constants generated from packages/core/abi/src/schema.rs."
    );
    writeln!(out);
    writeln!(
        out,
        "export const NVE_CORE_ABI_SCHEMA_HASH: bigint = 0x{schema_hash:016X}n;"
    );
    for c in &spec.consts {
        if c.hex {
            writeln!(out, "export const {} = 0x{:X} as const;", c.name, c.value);
        } else {
            writeln!(out, "export const {} = {} as const;", c.name, c.value);
        }
    }
    writeln!(out);

    writeln!(out, "export const NVE_IFACE = {{");
    for m in &spec.modules {
        let upper = to_snake_case(&m.name).to_ascii_uppercase();
        writeln!(out, "  {upper}: {},", m.interface_id());
    }
    writeln!(out, "}} as const;");
    writeln!(
        out,
        "export type NveIfaceId = (typeof NVE_IFACE)[keyof typeof NVE_IFACE];"
    );
    writeln!(out);

    for e in &spec.enums {
        let obj_name = to_snake_case(&e.name).to_ascii_uppercase();
        writeln!(out, "export const {obj_name} = {{");
        for v in &e.variants {
            let v_upper = to_snake_case(&v.name).to_ascii_uppercase();
            writeln!(out, "  {v_upper}: {},", format_enum_value(v.value));
        }
        writeln!(out, "}} as const;");
        writeln!(
            out,
            "export type {} = (typeof {obj_name})[keyof typeof {obj_name}];",
            e.name
        );
        writeln!(out);
    }

    writeln!(out, "export const NVE_HOST_STATUS = {{");
    for &(variant, code) in HOST_STATUS_VARIANTS {
        let v_upper = to_snake_case(variant).to_ascii_uppercase();
        writeln!(out, "  {v_upper}: {code},");
    }
    writeln!(out, "}} as const;");
    writeln!(
        out,
        "export type NveHostStatus = (typeof NVE_HOST_STATUS)[keyof typeof NVE_HOST_STATUS];"
    );
    writeln!(out);

    out.into_string()
}


// ============================================================================
// Scene ABI Target 5: TypeScript / WASM (`hosts/web-shell/nve_scene_view.generated.ts`)
