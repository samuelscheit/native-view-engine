//! `<Name>NativeComponent.generated.ts` emitter for `export_rn`.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::naming::{
    escape_ts_single_quoted, format_float_literal, sanitize_block_comment,
    sanitize_single_line_comment, strip_on_prefix, to_pascal_case,
};
use crate::schema::export::{DefaultValue, EventBubbling, EventSpec, NveExportSpec, PropType};

pub(crate) fn emit_native_component_ts(spec: &NveExportSpec) -> String {
    let mut out = String::with_capacity(2048);
    let mut codegen_imports = BTreeSet::new();
    let mut needs_color = false;
    let mut needs_image = false;

    for p in &spec.props {
        if p.default_value.is_some() {
            codegen_imports.insert("WithDefault");
        }
        collect_ts_imports(
            &p.prop_type,
            &mut codegen_imports,
            &mut needs_color,
            &mut needs_image,
        );
    }
    for ev in &spec.events {
        match ev.bubbling {
            EventBubbling::Direct => {
                codegen_imports.insert("DirectEventHandler");
            }
            EventBubbling::Bubbling => {
                codegen_imports.insert("BubblingEventHandler");
            }
        }
        for field in &ev.payload {
            collect_ts_imports(
                &field.field_type,
                &mut codegen_imports,
                &mut needs_color,
                &mut needs_image,
            );
        }
    }
    for cmd in &spec.commands {
        for p in &cmd.params {
            collect_ts_imports(
                &p.param_type,
                &mut codegen_imports,
                &mut needs_color,
                &mut needs_image,
            );
        }
    }

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_rn`) — backend: {}",
        spec.backend.as_str()
    );
    let _ = writeln!(
        out,
        "// Drop-in React Native Fabric NativeComponent spec for `react-native-codegen` & autolinking."
    );
    let _ = writeln!(out);

    let mut rn_imports = vec!["ViewProps"];
    if needs_color {
        rn_imports.push("ColorValue");
    }
    if needs_image {
        rn_imports.push("ImageSourcePropType");
    }
    if !spec.commands.is_empty() {
        rn_imports.push("HostComponent");
    }
    let _ = writeln!(
        out,
        "import type {{ {} }} from 'react-native';",
        rn_imports.join(", ")
    );
    if !codegen_imports.is_empty() {
        let joined: Vec<&str> = codegen_imports.into_iter().collect();
        let _ = writeln!(
            out,
            "import type {{ {} }} from 'react-native/Libraries/Types/CodegenTypes';",
            joined.join(", ")
        );
    }
    if !spec.commands.is_empty() {
        let _ = writeln!(out, "import type * as React from 'react';");
        let _ = writeln!(
            out,
            "import codegenNativeCommands from 'react-native/Libraries/Utilities/codegenNativeCommands';"
        );
    }
    let _ = writeln!(
        out,
        "import codegenNativeComponent from 'react-native/Libraries/Utilities/codegenNativeComponent';"
    );
    let _ = writeln!(out);

    for ev in &spec.events {
        if !ev.payload.is_empty() {
            let payload_name = event_ts_payload_name(ev);
            let _ = writeln!(out, "export type {payload_name} = Readonly<{{");
            for f in &ev.payload {
                let opt = if f.optional { "?" } else { "" };
                let null_suffix = if f.nullable { " | null" } else { "" };
                let _ = writeln!(
                    out,
                    "  {}{opt}: {}{null_suffix};",
                    f.name,
                    ts_type(&f.field_type)
                );
            }
            let _ = writeln!(out, "}}>;");
            let _ = writeln!(out);
        }
    }

    if let Some(doc) = &spec.doc {
        let _ = writeln!(out, "/**");
        for line in sanitize_block_comment(doc).lines() {
            let _ = writeln!(out, " * {line}");
        }
        let _ = writeln!(out, " */");
    }

    let _ = writeln!(out, "export interface NativeProps extends ViewProps {{");
    for prop in &spec.props {
        if let Some(doc) = &prop.doc {
            let _ = writeln!(
                out,
                "  /** {} */",
                sanitize_single_line_comment(&sanitize_block_comment(doc))
            );
        }
        let opt = if prop.optional || prop.default_value.is_some() {
            "?"
        } else {
            ""
        };
        let base_ty = ts_type(&prop.prop_type);
        let full_ty = if let Some(def) = &prop.default_value {
            format!("WithDefault<{base_ty}, {}>", ts_default_literal(def))
        } else if prop.nullable {
            format!("{base_ty} | null")
        } else {
            base_ty
        };
        let _ = writeln!(out, "  {}{opt}: {full_ty};", prop.name);
    }

    for ev in &spec.events {
        if let Some(doc) = &ev.doc {
            let _ = writeln!(
                out,
                "  /** {} */",
                sanitize_single_line_comment(&sanitize_block_comment(doc))
            );
        }
        let handler = match ev.bubbling {
            EventBubbling::Direct => "DirectEventHandler",
            EventBubbling::Bubbling => "BubblingEventHandler",
        };
        let payload_arg = if ev.payload.is_empty() {
            "null".to_owned()
        } else {
            event_ts_payload_name(ev)
        };
        let opt = if ev.optional { "?" } else { "" };
        if let Some(paper) = &ev.paper_top_level_name {
            let _ = writeln!(
                out,
                "  {}{opt}: {handler}<{payload_arg}, '{}'>;",
                ev.name,
                escape_ts_single_quoted(paper)
            );
        } else {
            let _ = writeln!(out, "  {}{opt}: {handler}<{payload_arg}>;", ev.name);
        }
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    if !spec.commands.is_empty() {
        let _ = writeln!(out, "export type ComponentType = HostComponent<NativeProps>;");
        let _ = writeln!(out);
        let _ = writeln!(out, "export interface NativeCommands {{");
        for cmd in &spec.commands {
            let mut params = vec!["viewRef: React.ElementRef<ComponentType>".to_owned()];
            for p in &cmd.params {
                let opt = if p.optional { "?" } else { "" };
                params.push(format!("{}{opt}: {}", p.name, ts_type(&p.param_type)));
            }
            let _ = writeln!(out, "  {}: ({}) => void;", cmd.name, params.join(", "));
        }
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
        let cmd_list: Vec<String> = spec
            .commands
            .iter()
            .map(|c| format!("'{}'", escape_ts_single_quoted(&c.name)))
            .collect();
        let _ = writeln!(
            out,
            "export const Commands: NativeCommands = codegenNativeCommands<NativeCommands>({{"
        );
        let _ = writeln!(out, "  supportedCommands: [{}],", cmd_list.join(", "));
        let _ = writeln!(out, "}});");
        let _ = writeln!(out);
    }

    let _ = writeln!(
        out,
        "export default codegenNativeComponent<NativeProps>('{}');",
        escape_ts_single_quoted(&spec.name)
    );
    out
}

fn event_ts_payload_name(ev: &EventSpec) -> String {
    if let Some(explicit) = &ev.payload_type_name {
        return explicit.clone();
    }
    format!("{}Event", to_pascal_case(&strip_on_prefix(&ev.name)))
}

fn collect_ts_imports(
    ty: &PropType,
    codegen: &mut BTreeSet<&'static str>,
    needs_color: &mut bool,
    needs_image: &mut bool,
) {
    match ty {
        PropType::Int32 => {
            codegen.insert("Int32");
        }
        PropType::Float => {
            codegen.insert("Float");
        }
        PropType::Double => {
            codegen.insert("Double");
        }
        PropType::Color => {
            *needs_color = true;
        }
        PropType::ImageSource => {
            *needs_image = true;
        }
        PropType::Mixed => {
            codegen.insert("UnsafeMixed");
        }
        PropType::Array { item } => collect_ts_imports(item, codegen, needs_color, needs_image),
        PropType::Object { fields } => {
            for f in fields {
                collect_ts_imports(&f.field_type, codegen, needs_color, needs_image);
            }
        }
        _ => {}
    }
}

fn ts_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "boolean".to_owned(),
        PropType::Int32 => "Int32".to_owned(),
        PropType::Float => "Float".to_owned(),
        PropType::Double => "Double".to_owned(),
        PropType::String => "string".to_owned(),
        PropType::Color => "ColorValue".to_owned(),
        PropType::ImageSource => "ImageSourcePropType".to_owned(),
        PropType::Point => "Readonly<{ x: Float; y: Float }>".to_owned(),
        PropType::EdgeInsets => {
            "Readonly<{ top: Float; left: Float; bottom: Float; right: Float }>".to_owned()
        }
        PropType::Dimension => "string".to_owned(),
        PropType::StringEnum { variants } => variants
            .iter()
            .map(|v| format!("'{}'", escape_ts_single_quoted(v)))
            .collect::<Vec<_>>()
            .join(" | "),
        PropType::IntEnum { variants } => variants
            .iter()
            .map(|v| v.to_string())
            .collect::<Vec<_>>()
            .join(" | "),
        PropType::Array { item } => format!("ReadonlyArray<{}>", ts_type(item)),
        PropType::Object { fields } => {
            let parts: Vec<String> = fields
                .iter()
                .map(|f| {
                    let opt = if f.optional { "?" } else { "" };
                    format!("{}{opt}: {}", f.name, ts_type(&f.field_type))
                })
                .collect();
            format!("Readonly<{{ {} }}>", parts.join("; "))
        }
        PropType::Mixed => "UnsafeMixed".to_owned(),
        PropType::Void => "void".to_owned(),
        PropType::Promise { inner } => format!("Promise<{}>", ts_type(inner)),
        PropType::Callback { .. } => "() => void".to_owned(),
    }
}

fn ts_default_literal(def: &DefaultValue) -> String {
    match def {
        DefaultValue::Null => "null".to_owned(),
        DefaultValue::Bool(b) => if *b { "true" } else { "false" }.to_owned(),
        DefaultValue::Int(i) => i.to_string(),
        DefaultValue::Float(f) => format_float_literal(*f),
        DefaultValue::String(s) => format!("'{}'", escape_ts_single_quoted(s)),
    }
}
