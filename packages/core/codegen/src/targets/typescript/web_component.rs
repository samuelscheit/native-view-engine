//! `export_web_component`: `NveExportSpec` -> typed Custom Element `<nve-...>` (ES module JS)
//! + TypeScript `.d.ts` definitions wrapping `wasm-bindgen` (`nve-web-shell`).

use std::fmt::Write as _;

use crate::error::CodegenError;
use crate::schema::export::{
    DefaultValue, EventBubbling, EventSpec, ExportWebComponentOutput, GeneratedFile, NveExportSpec,
    PropSpec, PropType,
};
use crate::naming::{
    escape_ts_single_quoted, format_float_literal, sanitize_single_line_comment, strip_on_prefix,
    to_camel_case, to_kebab_case, to_pascal_case, to_snake_case, web_component_tag,
};

/// Generates a typed Custom Element `<nve-...>` (`.js`) and TypeScript `.d.ts` declaration
/// wrapping a `wasm-bindgen` NVE Web WASM module.
pub fn generate_export_web_component(
    spec: &NveExportSpec,
) -> Result<ExportWebComponentOutput, CodegenError> {
    spec.validate()?;
    let tag_name = web_component_tag(&spec.name);
    let element_js = GeneratedFile {
        relative_path: format!("{tag_name}.generated.js"),
        content: emit_web_component_js(spec, &tag_name),
    };
    let types_dts = GeneratedFile {
        relative_path: format!("{tag_name}.generated.d.ts"),
        content: emit_web_component_dts(spec, &tag_name),
    };

    Ok(ExportWebComponentOutput {
        spec: spec.clone(),
        tag_name,
        element_js,
        types_dts,
    })
}

fn emit_web_component_js(spec: &NveExportSpec, tag_name: &str) -> String {
    let name = &spec.name;
    let elem_class = format!("{name}Element");
    let wasm_pkg = format!("./pkg/{}_web.js", to_snake_case(name));
    let mut out = String::with_capacity(4096);

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_web_component`) — tag: <{}>, backend: {}",
        sanitize_single_line_comment(tag_name),
        spec.backend.as_str()
    );
    let _ = writeln!(
        out,
        "// Typed Custom Element wrapping a `wasm-bindgen` NVE surface."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "let _wasmModulePromise = null;");
    let _ = writeln!(out, "const _utf8Encoder = new TextEncoder();");
    let _ = writeln!(out, "const _utf8Decoder = new TextDecoder('utf-8', {{ fatal: true }});");
    let _ = writeln!(out);
    let _ = writeln!(out, "function _encodeNveBinValue(value, chunks = []) {{");
    let _ = writeln!(out, "  if (value === null || value === undefined) {{ chunks.push(new Uint8Array([0])); return chunks; }}");
    let _ = writeln!(out, "  if (typeof value === 'boolean') {{ chunks.push(new Uint8Array([1, value ? 1 : 0])); return chunks; }}");
    let _ = writeln!(out, "  if (typeof value === 'number') {{");
    let _ = writeln!(out, "    const buf = new ArrayBuffer(9); const dv = new DataView(buf);");
    let _ = writeln!(out, "    if (Number.isInteger(value) && Number.isSafeInteger(value)) {{ dv.setUint8(0, 2); dv.setBigInt64(1, BigInt(value), true); }}");
    let _ = writeln!(out, "    else {{ dv.setUint8(0, 3); dv.setFloat64(1, value, true); }}");
    let _ = writeln!(out, "    chunks.push(new Uint8Array(buf)); return chunks;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  if (typeof value === 'string') {{");
    let _ = writeln!(out, "    const bytes = _utf8Encoder.encode(value); const hdr = new ArrayBuffer(5); const dv = new DataView(hdr);");
    let _ = writeln!(out, "    dv.setUint8(0, 4); dv.setUint32(1, bytes.byteLength, true); chunks.push(new Uint8Array(hdr), bytes); return chunks;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  if (value instanceof Uint8Array) {{");
    let _ = writeln!(out, "    const hdr = new ArrayBuffer(5); const dv = new DataView(hdr);");
    let _ = writeln!(out, "    dv.setUint8(0, 5); dv.setUint32(1, value.byteLength, true); chunks.push(new Uint8Array(hdr), value); return chunks;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  if (Array.isArray(value)) {{");
    let _ = writeln!(out, "    const inner = []; const cnt = new ArrayBuffer(4); new DataView(cnt).setUint32(0, value.length, true); inner.push(new Uint8Array(cnt));");
    let _ = writeln!(out, "    for (const item of value) _encodeNveBinValue(item, inner);");
    let _ = writeln!(out, "    const bodyLen = inner.reduce((a, b) => a + b.byteLength, 0); const hdr = new ArrayBuffer(5); const dv = new DataView(hdr);");
    let _ = writeln!(out, "    dv.setUint8(0, 6); dv.setUint32(1, bodyLen, true); chunks.push(new Uint8Array(hdr), ...inner); return chunks;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  const entries = Object.entries(value).filter(([, v]) => v !== undefined);");
    let _ = writeln!(out, "  const inner = []; const cnt = new ArrayBuffer(4); new DataView(cnt).setUint32(0, entries.length, true); inner.push(new Uint8Array(cnt));");
    let _ = writeln!(out, "  for (const [k, v] of entries) {{");
    let _ = writeln!(out, "    const kb = _utf8Encoder.encode(k); const kl = new ArrayBuffer(4); new DataView(kl).setUint32(0, kb.byteLength, true);");
    let _ = writeln!(out, "    inner.push(new Uint8Array(kl), kb); _encodeNveBinValue(v, inner);");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  const bodyLen = inner.reduce((a, b) => a + b.byteLength, 0); const hdr = new ArrayBuffer(5); const dv = new DataView(hdr);");
    let _ = writeln!(out, "  dv.setUint8(0, 7); dv.setUint32(1, bodyLen, true); chunks.push(new Uint8Array(hdr), ...inner); return chunks;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "function encodeNveBinValue(value) {{");
    let _ = writeln!(out, "  const chunks = _encodeNveBinValue(value);");
    let _ = writeln!(out, "  const total = chunks.reduce((a, b) => a + b.byteLength, 0);");
    let _ = writeln!(out, "  const out = new Uint8Array(total); let off = 0;");
    let _ = writeln!(out, "  for (const c of chunks) {{ out.set(c, off); off += c.byteLength; }}");
    let _ = writeln!(out, "  return out;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "function decodeNveBinValue(bytes, state = {{ off: 0 }}) {{");
    let _ = writeln!(out, "  if (!(bytes instanceof Uint8Array) || state.off >= bytes.byteLength) return null;");
    let _ = writeln!(out, "  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);");
    let _ = writeln!(out, "  const tag = bytes[state.off++];");
    let _ = writeln!(out, "  if (tag === 0) return null;");
    let _ = writeln!(out, "  if (tag === 1) return bytes[state.off++] !== 0;");
    let _ = writeln!(out, "  if (tag === 2) {{ const v = Number(dv.getBigInt64(state.off, true)); state.off += 8; return v; }}");
    let _ = writeln!(out, "  if (tag === 3) {{ const v = dv.getFloat64(state.off, true); state.off += 8; return v; }}");
    let _ = writeln!(out, "  if (tag === 4) {{ const n = dv.getUint32(state.off, true); state.off += 4; const s = _utf8Decoder.decode(bytes.subarray(state.off, state.off + n)); state.off += n; return s; }}");
    let _ = writeln!(out, "  if (tag === 5) {{ const n = dv.getUint32(state.off, true); state.off += 4; const b = bytes.subarray(state.off, state.off + n); state.off += n; return b; }}");
    let _ = writeln!(out, "  if (tag === 6) {{ state.off += 4; const n = dv.getUint32(state.off, true); state.off += 4; const arr = []; for (let i = 0; i < n; i++) arr.push(decodeNveBinValue(bytes, state)); return arr; }}");
    let _ = writeln!(out, "  if (tag === 7) {{ state.off += 4; const n = dv.getUint32(state.off, true); state.off += 4; const obj = {{}}; for (let i = 0; i < n; i++) {{ const kl = dv.getUint32(state.off, true); state.off += 4; const k = _utf8Decoder.decode(bytes.subarray(state.off, state.off + kl)); state.off += kl; obj[k] = decodeNveBinValue(bytes, state); }} return obj; }}");
    let _ = writeln!(out, "  return null;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "async function loadWasmModule(moduleUrl) {{");
    let _ = writeln!(out, "  if (!_wasmModulePromise) {{");
    let _ = writeln!(out, "    _wasmModulePromise = import(moduleUrl).then(async (mod) => {{");
    let _ = writeln!(out, "      if (typeof mod.default === 'function') {{");
    let _ = writeln!(out, "        await mod.default();");
    let _ = writeln!(out, "      }}");
    let _ = writeln!(out, "      return mod;");
    let _ = writeln!(out, "    }});");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "  return _wasmModulePromise;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(out, "export class {elem_class} extends HTMLElement {{");
    let _ = writeln!(
        out,
        "  static tagName = '{}';",
        escape_ts_single_quoted(tag_name)
    );
    let _ = writeln!(
        out,
        "  static defaultWasmModuleUrl = '{}';",
        escape_ts_single_quoted(&wasm_pkg)
    );
    let _ = writeln!(out);

    // observedAttributes
    let mut attrs: Vec<String> = spec
        .props
        .iter()
        .map(|p| format!("'{}'", escape_ts_single_quoted(&to_kebab_case(&p.name))))
        .collect();
    attrs.push("'wasm-url'".to_owned());
    attrs.push("'hot-reload-url'".to_owned());
    let _ = writeln!(out, "  static get observedAttributes() {{");
    let _ = writeln!(out, "    return [{}];", attrs.join(", "));
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    // Constructor & defaults
    let _ = writeln!(out, "  constructor() {{");
    let _ = writeln!(out, "    super();");
    let _ = writeln!(out, "    this._shadow = this.attachShadow({{ mode: 'open' }});");
    let _ = writeln!(out, "    this._mountRoot = document.createElement('div');");
    let _ = writeln!(
        out,
        "    this._mountRoot.id = 'nve-root-' + Math.random().toString(36).slice(2, 10);"
    );
    let _ = writeln!(out, "    this._mountRoot.style.width = '100%';");
    let _ = writeln!(out, "    this._mountRoot.style.height = '100%';");
    let _ = writeln!(out, "    this._shadow.appendChild(this._mountRoot);");
    let _ = writeln!(out, "    this._surface = null;");
    let _ = writeln!(out, "    this._props = {{");
    for prop in &spec.props {
        if let Some(def) = js_default_literal(prop) {
            let _ = writeln!(
                out,
                "      '{}': {def},",
                escape_ts_single_quoted(&prop.name)
            );
        }
    }
    let _ = writeln!(out, "    }};");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    // Typed JS property getters/setters
    for prop in &spec.props {
        let camel = to_camel_case(&prop.name);
        let key = escape_ts_single_quoted(&prop.name);
        let _ = writeln!(out, "  get {camel}() {{");
        let _ = writeln!(out, "    return this._props['{key}'];");
        let _ = writeln!(out, "  }}");
        let _ = writeln!(out, "  set {camel}(value) {{");
        let _ = writeln!(out, "    this._props['{key}'] = value;");
        let _ = writeln!(out, "    this._syncProps();");
        let _ = writeln!(out, "  }}");
        let _ = writeln!(out);
    }

    // Lifecycle
    let _ = writeln!(out, "  async connectedCallback() {{");
    let _ = writeln!(
        out,
        "    const wasmUrl = this.getAttribute('wasm-url') || {elem_class}.defaultWasmModuleUrl;"
    );
    let _ = writeln!(
        out,
        "    const hotReloadUrl = this.getAttribute('hot-reload-url') || undefined;"
    );
    let _ = writeln!(out, "    const mod = await loadWasmModule(wasmUrl);");
    let _ = writeln!(out, "    if (typeof mod.mount_nve_component === 'function') {{");
    let _ = writeln!(out, "      this._surface = mod.mount_nve_component(");
    let _ = writeln!(out, "        '{}',", escape_ts_single_quoted(name));
    let _ = writeln!(out, "        this._mountRoot,");
    let _ = writeln!(out, "        encodeNveBinValue(this._props),");
    let _ = writeln!(out, "        (eventName, payloadBin) => this._dispatchNativeEvent(eventName, payloadBin),");
    let _ = writeln!(out, "        hotReloadUrl,");
    let _ = writeln!(out, "      );");
    let _ = writeln!(out, "    }} else if (typeof mod.start_kitchen_sink_app === 'function') {{");
    let _ = writeln!(out, "      mod.start_kitchen_sink_app(this._mountRoot.id, hotReloadUrl);");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    this._syncProps();");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    let _ = writeln!(out, "  disconnectedCallback() {{");
    let _ = writeln!(out, "    if (this._surface && typeof this._surface.free === 'function') {{");
    let _ = writeln!(out, "      this._surface.free();");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    this._surface = null;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    let _ = writeln!(out, "  attributeChangedCallback(name, _oldValue, newValue) {{");
    let _ = writeln!(out, "    switch (name) {{");
    for prop in &spec.props {
        let attr = to_kebab_case(&prop.name);
        let key = escape_ts_single_quoted(&prop.name);
        let parse_expr = js_parse_attr_expr(&prop.prop_type);
        let _ = writeln!(out, "      case '{}':", escape_ts_single_quoted(&attr));
        let _ = writeln!(out, "        this._props['{key}'] = {parse_expr};");
        let _ = writeln!(out, "        this._syncProps();");
        let _ = writeln!(out, "        break;");
    }
    let _ = writeln!(out, "      default:");
    let _ = writeln!(out, "        break;");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    // Imperative commands (compact binary `NveBinValue`)
    for cmd in &spec.commands {
        let mname = to_camel_case(&cmd.name);
        let pnames: Vec<String> = cmd.params.iter().map(|p| to_camel_case(&p.name)).collect();
        let _ = writeln!(out, "  {mname}({}) {{", pnames.join(", "));
        let _ = writeln!(
            out,
            "    if (this._surface && typeof this._surface.dispatch_command_binary === 'function') {{"
        );
        let args_obj = if cmd.params.is_empty() {
            "null".to_owned()
        } else {
            let pairs: Vec<String> = cmd
                .params
                .iter()
                .map(|p| format!("'{}': {}", escape_ts_single_quoted(&p.name), to_camel_case(&p.name)))
                .collect();
            format!("{{ {} }}", pairs.join(", "))
        };
        let _ = writeln!(
            out,
            "      this._surface.dispatch_command_binary('{}', encodeNveBinValue({args_obj}));",
            escape_ts_single_quoted(&cmd.name)
        );
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "  }}");
        let _ = writeln!(out);
    }

    // Internal binary prop sync + CustomEvent dispatcher
    let _ = writeln!(out, "  _syncProps() {{");
    let _ = writeln!(
        out,
        "    if (this._surface && typeof this._surface.set_props_binary === 'function') {{"
    );
    let _ = writeln!(
        out,
        "      this._surface.set_props_binary(encodeNveBinValue(this._props));"
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out);

    let _ = writeln!(out, "  _dispatchNativeEvent(eventName, payloadBin) {{");
    let _ = writeln!(
        out,
        "    const detail = payloadBin instanceof Uint8Array && payloadBin.byteLength > 0 ? decodeNveBinValue(payloadBin) : null;"
    );
    let _ = writeln!(out, "    switch (eventName) {{");
    for ev in &spec.events {
        let dom_ev = dom_event_name(ev);
        let short = strip_on_prefix(&ev.name);
        let bubbles = if ev.bubbling == EventBubbling::Bubbling {
            "true"
        } else {
            "false"
        };
        let _ = writeln!(
            out,
            "      case '{}':\n      case '{}':",
            escape_ts_single_quoted(&ev.name),
            escape_ts_single_quoted(&short)
        );
        let _ = writeln!(
            out,
            "        this.dispatchEvent(new CustomEvent('{}', {{ detail, bubbles: {bubbles}, composed: true }}));",
            escape_ts_single_quoted(&dom_ev)
        );
        let _ = writeln!(out, "        break;");
    }
    let _ = writeln!(out, "      default:");
    let _ = writeln!(
        out,
        "        this.dispatchEvent(new CustomEvent(eventName, {{ detail, bubbles: false, composed: true }}));"
    );
    let _ = writeln!(out, "        break;");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "export function define{name}(tagName = {elem_class}.tagName) {{"
    );
    let _ = writeln!(out, "  if (!customElements.get(tagName)) {{");
    let _ = writeln!(out, "    customElements.define(tagName, {elem_class});");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "define{name}();");

    out
}

fn emit_web_component_dts(spec: &NveExportSpec, tag_name: &str) -> String {
    let name = &spec.name;
    let elem_class = format!("{name}Element");
    let mut out = String::with_capacity(2048);

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_web_component`) — tag: <{}>",
        sanitize_single_line_comment(tag_name)
    );
    let _ = writeln!(out);

    for ev in &spec.events {
        if !ev.payload.is_empty() {
            let detail_ty = format!("{name}{}Detail", to_pascal_case(&strip_on_prefix(&ev.name)));
            let _ = writeln!(out, "export interface {detail_ty} {{");
            for f in &ev.payload {
                let opt = if f.optional { "?" } else { "" };
                let null_s = if f.nullable { " | null" } else { "" };
                let _ = writeln!(
                    out,
                    "  readonly {}{opt}: {}{null_s};",
                    f.name,
                    dts_type(&f.field_type)
                );
            }
            let _ = writeln!(out, "}}");
            let _ = writeln!(out);
        }
    }

    let _ = writeln!(out, "export interface {name}EventMap {{");
    for ev in &spec.events {
        let dom_ev = dom_event_name(ev);
        let detail_ty = if ev.payload.is_empty() {
            "null".to_owned()
        } else {
            format!("{name}{}Detail", to_pascal_case(&strip_on_prefix(&ev.name)))
        };
        let _ = writeln!(
            out,
            "  '{}': CustomEvent<{detail_ty}>;",
            escape_ts_single_quoted(&dom_ev)
        );
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(out, "export interface {name}Props {{");
    for prop in &spec.props {
        let camel = to_camel_case(&prop.name);
        let opt = if prop.optional || prop.default_value.is_some() {
            "?"
        } else {
            ""
        };
        let null_s = if prop.nullable { " | null" } else { "" };
        let _ = writeln!(
            out,
            "  {camel}{opt}: {}{null_s};",
            dts_type(&prop.prop_type)
        );
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "export declare class {elem_class} extends HTMLElement implements Partial<{name}Props> {{"
    );
    let _ = writeln!(out, "  static readonly tagName: '{}';", escape_ts_single_quoted(tag_name));
    let _ = writeln!(out, "  static readonly defaultWasmModuleUrl: string;");
    let _ = writeln!(out, "  static readonly observedAttributes: readonly string[];");
    for prop in &spec.props {
        let camel = to_camel_case(&prop.name);
        let null_s = if prop.optional || prop.nullable {
            " | undefined"
        } else {
            ""
        };
        let _ = writeln!(out, "  {camel}: {}{null_s};", dts_type(&prop.prop_type));
    }
    for cmd in &spec.commands {
        let mname = to_camel_case(&cmd.name);
        let params: Vec<String> = cmd
            .params
            .iter()
            .map(|p| {
                let opt = if p.optional { "?" } else { "" };
                format!("{}{opt}: {}", to_camel_case(&p.name), dts_type(&p.param_type))
            })
            .collect();
        let _ = writeln!(out, "  {mname}({}): void;", params.join(", "));
    }
    let _ = writeln!(
        out,
        "  addEventListener<K extends keyof {name}EventMap>(type: K, listener: (this: {elem_class}, ev: {name}EventMap[K]) => any, options?: boolean | AddEventListenerOptions): void;"
    );
    let _ = writeln!(
        out,
        "  addEventListener(type: string, listener: EventListenerOrEventListenerObject, options?: boolean | AddEventListenerOptions): void;"
    );
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(out, "export declare function define{name}(tagName?: string): void;");
    let _ = writeln!(out);

    let _ = writeln!(out, "declare global {{");
    let _ = writeln!(out, "  interface HTMLElementTagNameMap {{");
    let _ = writeln!(
        out,
        "    '{}': {elem_class};",
        escape_ts_single_quoted(tag_name)
    );
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");

    out
}

fn dom_event_name(ev: &EventSpec) -> String {
    to_kebab_case(&strip_on_prefix(&ev.name))
}

fn js_default_literal(prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match def {
        DefaultValue::Null => Some("null".to_owned()),
        DefaultValue::Bool(b) => Some(if *b { "true" } else { "false" }.to_owned()),
        DefaultValue::Int(i) => Some(i.to_string()),
        DefaultValue::Float(f) => Some(format_float_literal(*f)),
        DefaultValue::String(s) => Some(format!("'{}'", escape_ts_single_quoted(s))),
    }
}

fn js_parse_attr_expr(ty: &PropType) -> &'static str {
    match ty {
        PropType::Bool => "newValue !== null && newValue !== 'false'",
        PropType::Int32 | PropType::IntEnum { .. } => "newValue === null ? undefined : Number.parseInt(newValue, 10)",
        PropType::Float | PropType::Double => "newValue === null ? undefined : Number.parseFloat(newValue)",
        PropType::Array { .. } => "newValue === null ? undefined : newValue.split(',').map((s) => s.trim()).filter(Boolean)",
        _ => "newValue ?? undefined",
    }
}

fn dts_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "boolean".to_owned(),
        PropType::Int32 | PropType::Float | PropType::Double => "number".to_owned(),
        PropType::String | PropType::Color | PropType::ImageSource | PropType::Dimension => {
            "string".to_owned()
        }
        PropType::Point => "Readonly<{ x: number; y: number }>".to_owned(),
        PropType::EdgeInsets => {
            "Readonly<{ top: number; left: number; bottom: number; right: number }>".to_owned()
        }
        PropType::StringEnum { variants } => variants
            .iter()
            .map(|v| format!("'{}'", escape_ts_single_quoted(v)))
            .collect::<Vec<_>>()
            .join(" | "),
        PropType::IntEnum { variants } => variants
            .iter()
            .map(|v| v.to_string())
            .collect::<Vec<_>>()
            .join(" | "),
        PropType::Array { item } => format!("ReadonlyArray<{}>", dts_type(item)),
        PropType::Object { fields } => {
            let parts: Vec<String> = fields
                .iter()
                .map(|f| {
                    let opt = if f.optional { "?" } else { "" };
                    format!("{}{opt}: {}", f.name, dts_type(&f.field_type))
                })
                .collect();
            format!("Readonly<{{ {} }}>", parts.join("; "))
        }
        PropType::Mixed => "unknown".to_owned(),
        PropType::Void => "void".to_owned(),
        PropType::Promise { inner } => format!("Promise<{}>", dts_type(inner)),
        PropType::Callback { .. } => "() => void".to_owned(),
    }
}
