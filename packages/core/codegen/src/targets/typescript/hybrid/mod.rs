//! TypeScript / WASM target emitter for NVE Hybrid FFI codegen.
//!
//! Emits `<stem>_hybrid.generated.ts` built on the static `@nve/host` runtime
//! (`packages/core/host-ts`):
//! - Erasable TypeScript (`as const` enum objects + union types, explicit class fields)
//! - Exact `INTERFACE_ID` and `SCHEMA_HASH` (`Key64`) constants
//! - Bounds- and depth-checked `NveBinValue` struct encoders/decoders over `BinWriter`/`BinReader`
//! - Lossless `DynamicValue` (`HybridType::Value`) marshaling preserving true `NveValue` tags
//! - Direct WASM linear-memory client classes (`<Name>HybridClient`) calling WASM exports
//!   without `JSON.parse` / `JSON.stringify`.

mod bin_emitter;
mod client_emitter;

use std::collections::BTreeSet;

use crate::error::CodegenError;
use crate::naming::{escape_ts_single_quoted, to_camel_case, to_pascal_case, to_snake_case};
use crate::schema::export::GeneratedFile;
use crate::schema::hybrid::{
    HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec, HybridStructSpec,
    HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::writer::CodeWriter;
use client_emitter::{emit_ts_enum, emit_ts_module, emit_ts_struct, emit_ts_view};

#[derive(Default)]
pub(super) struct TsImports {
    values: BTreeSet<&'static str>,
    types: BTreeSet<&'static str>,
}

impl TsImports {
    pub(super) fn value(&mut self, name: &'static str) {
        self.values.insert(name);
    }

    pub(super) fn ty(&mut self, name: &'static str) {
        self.types.insert(name);
    }

    fn emit(&self, out: &mut CodeWriter) {
        if !self.values.is_empty() {
            let vals: Vec<&str> = self.values.iter().copied().collect();
            writeln!(out, "import {{");
            for v in vals {
                writeln!(out, "  {v},");
            }
            writeln!(out, "}} from '@nve/host';");
        }
        let type_only: Vec<&str> = self
            .types
            .iter()
            .copied()
            .filter(|t| !self.values.contains(t))
            .collect();
        if !type_only.is_empty() {
            writeln!(
                out,
                "import type {{ {} }} from '@nve/host';",
                type_only.join(", ")
            );
        }
        if !self.values.is_empty() || !type_only.is_empty() {
            writeln!(out);
        }
    }
}

/// Formats a 64-bit hash as a 53-bit-safe `new Key64(0xLO, 0xHI)` expression.
pub(super) fn format_key64(hash: u64) -> String {
    let k = nve_abi::Key64(hash);
    format!("new Key64(0x{:08X}, 0x{:08X})", k.lo(), k.hi())
}

/// Emits `<stem>_hybrid.generated.ts` with typed interfaces and direct WASM linear-memory clients
/// backed by `@nve/host`.
pub fn generate_hybrid_ts(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut imports = TsImports::default();
    let mut body = CodeWriter::with_capacity(8 * 1024);

    imports.value("Key64");
    writeln!(
        body,
        "export const NVE_HYBRID_ABI_VERSION = {NVE_HYBRID_ABI_VERSION} as const;"
    );
    writeln!(
        body,
        "export const NVE_HYBRID_FILE_SCHEMA_HASH = {};",
        format_key64(spec.file_schema_hash())
    );
    writeln!(body);

    for e in &spec.enums {
        emit_ts_enum(&mut body, &mut imports, e);
    }

    for s in spec.structs_topological() {
        emit_ts_struct(&mut body, &mut imports, s);
    }

    for m in &spec.modules {
        emit_ts_module(&mut body, &mut imports, m, spec);
    }

    for v in &spec.views {
        emit_ts_view(&mut body, &mut imports, v, spec);
    }

    let mut out = CodeWriter::with_capacity(body.len() + 512);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid TypeScript/WASM target) — DO NOT EDIT."
    );
    writeln!(
        out,
        "// Binary direct DataView / Uint8Array WASM linear-memory bridge backed by `@nve/host`."
    );
    writeln!(out);
    imports.emit(&mut out);
    out.push_str(&body);

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.generated.ts"),
        content: out.into_string(),
    }])
}
