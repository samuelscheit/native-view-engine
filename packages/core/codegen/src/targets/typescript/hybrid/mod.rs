//! TypeScript / WASM target emitter for NVE Hybrid FFI codegen.
//!
//! Emits `<stem>_hybrid.generated.ts` with:
//! - Typed TypeScript enums, interfaces, props, and event payloads
//! - Exact `INTERFACE_ID` and `SCHEMA_HASH` (`bigint`) constants
//! - Zero-JSON `DataView` / `Uint8Array` compact binary `NveBinValue` encoder & decoder
//! - Direct WASM linear-memory client classes (`<Name>HybridClient`) calling WASM exports
//!   without `JSON.parse` / `JSON.stringify`.

mod client_emitter;

use std::fmt::Write as _;
use client_emitter::{emit_ts_enum, emit_ts_module, emit_ts_struct, emit_ts_view};

use crate::error::CodegenError;
use crate::schema::export::GeneratedFile;
use crate::schema::hybrid::{
    HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec, HybridStructSpec,
    HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};
use crate::naming::{escape_ts_single_quoted, to_camel_case, to_pascal_case, to_snake_case};

/// Emits `<stem>_hybrid.generated.ts` with typed interfaces and direct `DataView`/`Uint8Array` WASM bridge.
pub fn generate_hybrid_ts(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut out = String::with_capacity(16 * 1024);

    writeln!(
        out,
        "// @generated by nve-codegen (hybrid TypeScript/WASM target) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(
        out,
        "// Zero-JSON direct DataView / Uint8Array WASM linear-memory bridge."
    )
    .unwrap();
    writeln!(out).unwrap();

    emit_ts_common(&mut out, spec);

    for e in &spec.enums {
        emit_ts_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_ts_struct(&mut out, s);
    }

    for m in &spec.modules {
        emit_ts_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_ts_view(&mut out, v, spec);
    }

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.generated.ts"),
        content: out,
    }])
}

fn emit_ts_common(out: &mut String, spec: &HybridFileSpec) {
    writeln!(out, "export const NVE_HYBRID_ABI_VERSION = {NVE_HYBRID_ABI_VERSION} as const;").unwrap();
    writeln!(
        out,
        "export const NVE_HYBRID_FILE_SCHEMA_HASH = 0x{:016X}n;",
        spec.file_schema_hash()
    )
    .unwrap();
    writeln!(out).unwrap();

    writeln!(
        out,
        r#"/** Owned dynamic value encoded in NVE's compact binary `NveBinValue` format (zero JSON). */
export interface NveHybridDynamicValue {{
  readonly binBytes: Uint8Array;
}}

const TEXT_ENCODER = new TextEncoder();
const TEXT_DECODER = new TextDecoder('utf-8', {{ fatal: true }});

/** Compact binary `NveBinValue` writer over `DataView`/`Uint8Array` (zero JSON). */
export class NveBinWriter {{
  private buf: Uint8Array;
  private view: DataView;
  private len = 0;

  constructor(initialCapacity = 64) {{
    this.buf = new Uint8Array(initialCapacity);
    this.view = new DataView(this.buf.buffer);
  }}

  writeNull(): void {{
    this.pushByte(0);
  }}

  writeBool(v: boolean): void {{
    this.pushByte(1);
    this.pushByte(v ? 1 : 0);
  }}

  writeI64(v: bigint): void {{
    this.ensure(9);
    this.buf[this.len++] = 2;
    this.view.setBigInt64(this.len, v, true);
    this.len += 8;
  }}

  writeF64(v: number): void {{
    this.ensure(9);
    this.buf[this.len++] = 3;
    this.view.setFloat64(this.len, v, true);
    this.len += 8;
  }}

  writeString(v: string): void {{
    const encoded = TEXT_ENCODER.encode(v);
    this.ensure(5 + encoded.byteLength);
    this.buf[this.len++] = 4;
    this.view.setUint32(this.len, encoded.byteLength, true);
    this.len += 4;
    this.buf.set(encoded, this.len);
    this.len += encoded.byteLength;
  }}

  writeBytes(v: Uint8Array): void {{
    this.ensure(5 + v.byteLength);
    this.buf[this.len++] = 5;
    this.view.setUint32(this.len, v.byteLength, true);
    this.len += 4;
    this.buf.set(v, this.len);
    this.len += v.byteLength;
  }}

  writeRaw(raw: Uint8Array): void {{
    this.ensure(raw.byteLength);
    this.buf.set(raw, this.len);
    this.len += raw.byteLength;
  }}

  writeArray(count: number, body: (w: NveBinWriter) => void): void {{
    this.ensure(9);
    this.buf[this.len++] = 6;
    const lenPos = this.len;
    this.view.setUint32(this.len, 0, true);
    this.len += 4;
    const start = this.len;
    this.view.setUint32(this.len, count, true);
    this.len += 4;
    body(this);
    this.view.setUint32(lenPos, this.len - start, true);
  }}

  writeMap(count: number, body: (w: NveBinWriter) => void): void {{
    this.ensure(9);
    this.buf[this.len++] = 7;
    const lenPos = this.len;
    this.view.setUint32(this.len, 0, true);
    this.len += 4;
    const start = this.len;
    this.view.setUint32(this.len, count, true);
    this.len += 4;
    body(this);
    this.view.setUint32(lenPos, this.len - start, true);
  }}

  writeMapKey(key: string): void {{
    const encoded = TEXT_ENCODER.encode(key);
    this.ensure(4 + encoded.byteLength);
    this.view.setUint32(this.len, encoded.byteLength, true);
    this.len += 4;
    this.buf.set(encoded, this.len);
    this.len += encoded.byteLength;
  }}

  toUint8Array(): Uint8Array {{
    return this.buf.subarray(0, this.len);
  }}

  private pushByte(b: number): void {{
    this.ensure(1);
    this.buf[this.len++] = b;
  }}

  private ensure(extra: number): void {{
    if (this.len + extra <= this.buf.byteLength) return;
    let next = Math.max(64, this.buf.byteLength);
    while (next < this.len + extra) next *= 2;
    const grown = new Uint8Array(next);
    grown.set(this.buf.subarray(0, this.len));
    this.buf = grown;
    this.view = new DataView(this.buf.buffer);
  }}
}}

/** Bounds-checked `DataView` reader for compact binary `NveBinValue` payloads. */
export class NveBinReader {{
  private readonly view: DataView;
  private pos = 0;

  constructor(private readonly bytes: Uint8Array) {{
    this.view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  }}

  peekTag(): number {{
    if (this.pos >= this.bytes.byteLength) throw new Error('truncated NveBinValue');
    return this.bytes[this.pos];
  }}

  readNullIfPresent(): boolean {{
    if (this.peekTag() === 0) {{
      this.pos += 1;
      return true;
    }}
    return false;
  }}

  readBool(): boolean {{
    this.expectTag(1);
    return this.bytes[this.pos++] !== 0;
  }}

  readI64(): bigint {{
    this.expectTag(2);
    const v = this.view.getBigInt64(this.pos, true);
    this.pos += 8;
    return v;
  }}

  readF64(): number {{
    const tag = this.peekTag();
    if (tag === 3) {{
      this.pos += 1;
      const v = this.view.getFloat64(this.pos, true);
      this.pos += 8;
      return v;
    }}
    if (tag === 2) return Number(this.readI64());
    throw new Error('expected NveBinValue number');
  }}

  readString(): string {{
    this.expectTag(4);
    const len = this.view.getUint32(this.pos, true);
    this.pos += 4;
    const out = TEXT_DECODER.decode(this.bytes.subarray(this.pos, this.pos + len));
    this.pos += len;
    return out;
  }}

  readBytes(): Uint8Array {{
    this.expectTag(5);
    const len = this.view.getUint32(this.pos, true);
    this.pos += 4;
    const out = this.bytes.slice(this.pos, this.pos + len);
    this.pos += len;
    return out;
  }}

  beginArray(): number {{
    this.expectTag(6);
    this.pos += 4; // payload_byte_len
    const count = this.view.getUint32(this.pos, true);
    this.pos += 4;
    return count;
  }}

  beginMap(): number {{
    this.expectTag(7);
    this.pos += 4; // payload_byte_len
    const count = this.view.getUint32(this.pos, true);
    this.pos += 4;
    return count;
  }}

  readMapKey(): string {{
    const len = this.view.getUint32(this.pos, true);
    this.pos += 4;
    const key = TEXT_DECODER.decode(this.bytes.subarray(this.pos, this.pos + len));
    this.pos += len;
    return key;
  }}

  readRawValue(): Uint8Array {{
    const start = this.pos;
    this.skipValue();
    return this.bytes.slice(start, this.pos);
  }}

  skipValue(): void {{
    const tag = this.bytes[this.pos++];
    switch (tag) {{
      case 0:
        return;
      case 1:
        this.pos += 1;
        return;
      case 2:
      case 3:
        this.pos += 8;
        return;
      case 4:
      case 5:
      case 6:
      case 7: {{
        const len = this.view.getUint32(this.pos, true);
        this.pos += 4 + len;
        return;
      }}
      default:
        throw new Error(`invalid NveBinValue tag: ${{tag}}`);
    }}
  }}

  private expectTag(expected: number): void {{
    const actual = this.bytes[this.pos++];
    if (actual !== expected) {{
      throw new Error(`unexpected NveBinValue tag: expected ${{expected}}, got ${{actual}}`);
    }}
  }}
}}

export interface NveHybridWasmBaseExports {{
  readonly memory: WebAssembly.Memory;
  nve_hybrid_alloc(len: number): number;
  nve_hybrid_free(ptr: number, len: number): void;
}}
"#
    )
    .unwrap();
}

