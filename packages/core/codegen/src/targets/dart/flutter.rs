//! `export_flutter`: `NveExportSpec` -> typed Dart `StatefulWidget` using `dart:ffi`
//! and `package:nve_flutter/nve_canvas.dart` (`NveCanvasView` / `NveCanvasController`).

use crate::writer::CodeWriter;

use crate::error::CodegenError;
use crate::schema::export::{
    DefaultValue, EventSpec, ExportFlutterOutput, GeneratedFile, NveExportSpec, ObjectField,
    PropSpec, PropType,
};
use crate::naming::{
    dart_ident, escape_dart_single_quoted_string, format_float_literal, int_enum_variant_camel,
    sanitize_single_line_comment, strip_on_prefix, to_pascal_case, to_snake_case,
};

/// Generates a typed Flutter `StatefulWidget` + `dart:ffi` binding from an `NveExportSpec`.
pub fn generate_export_flutter(spec: &NveExportSpec) -> Result<ExportFlutterOutput, CodegenError> {
    spec.validate()?;
    let file_stem = to_snake_case(&spec.name);
    let content = emit_flutter_dart(spec);

    Ok(ExportFlutterOutput {
        spec: spec.clone(),
        dart_widget: GeneratedFile {
            relative_path: format!("{file_stem}.generated.dart"),
            content,
        },
    })
}

fn emit_flutter_dart(spec: &NveExportSpec) -> String {
    let name = &spec.name;
    let vtable_sym = spec.vtable_symbol();

    let mut out = CodeWriter::with_capacity(4096);
    writeln!(
        out,
        "// @generated by nve-codegen (`export_flutter`) — backend: {}",
        spec.backend.as_str()
    );
    writeln!(
        out,
        "// Typed Flutter StatefulWidget + dart:ffi binding wrapping `package:nve_flutter/nve_canvas.dart`."
    );
    writeln!(out);
    writeln!(out, "import 'dart:ffi' as ffi;");
    writeln!(out, "import 'dart:io' show Platform;");
    writeln!(out, "import 'package:flutter/widgets.dart';");
    writeln!(out, "import 'package:nve_flutter/nve_canvas.dart';");
    writeln!(out, "import 'package:nve_flutter/nve_flutter.dart';");
    writeln!(out);

    // 1. Direct `dart:ffi` modular interface resolver (`nve_get_interface`)
    writeln!(
        out,
        "/// Direct `dart:ffi` symbol binding for `{}`'s modular interface resolver (`{}`).",
        sanitize_single_line_comment(name),
        sanitize_single_line_comment(vtable_sym)
    );
    writeln!(out, "class {name}NativeBindings {{");
    writeln!(
        out,
        "  static const String componentName = '{}';",
        escape_dart_single_quoted_string(name)
    );
    writeln!(
        out,
        "  static const String vtableSymbol = '{}';",
        escape_dart_single_quoted_string(vtable_sym)
    );
    writeln!(out);
    writeln!(out, "  final ffi.DynamicLibrary library;");
    writeln!(out, "  late final ffi.Pointer<ffi.Void> Function(int) getInterface;");
    writeln!(out);
    writeln!(out, "  {name}NativeBindings(this.library) {{");
    writeln!(
        out,
        "    getInterface = library.lookupFunction<\n        NveGetInterfaceNative,\n        ffi.Pointer<ffi.Void> Function(int)>(vtableSymbol);"
    );
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(
        out,
        "  factory {name}NativeBindings.open({{String? libraryPath}}) {{"
    );
    writeln!(out, "    if (libraryPath != null && libraryPath.isNotEmpty) {{");
    writeln!(
        out,
        "      return {name}NativeBindings(ffi.DynamicLibrary.open(libraryPath));"
    );
    writeln!(out, "    }}");
    writeln!(out, "    if (Platform.isIOS) {{");
    writeln!(
        out,
        "      return {name}NativeBindings(ffi.DynamicLibrary.process());"
    );
    writeln!(out, "    }}");
    let lib_name = to_snake_case(name);
    writeln!(
        out,
        "    final libName = Platform.isWindows ? '{lib_name}.dll' : Platform.isMacOS ? 'lib{lib_name}.dylib' : 'lib{lib_name}.so';"
    );
    writeln!(
        out,
        "    return {name}NativeBindings(ffi.DynamicLibrary.open(libName));"
    );
    writeln!(out, "  }}");
    writeln!(out, "}}");
    writeln!(out);

    // 2. Typed Dart enums for StringEnum / IntEnum props
    for prop in &spec.props {
        emit_dart_aux_enum(&mut out, name, prop);
    }

    // 3. Typed event payload classes
    for ev in &spec.events {
        emit_dart_event_class(&mut out, name, ev);
    }

    // 4. Typed imperative command controller wrapping `NveSurfaceController`
    writeln!(
        out,
        "/// Imperative controller for `{}` delegating to `NveSurfaceController`.",
        sanitize_single_line_comment(name)
    );
    writeln!(out, "class {name}Controller {{");
    writeln!(out, "  final NveSurfaceController inner;");
    writeln!(out);
    writeln!(
        out,
        "  {name}Controller([NveSurfaceController? controller])\n      : inner = controller ?? NveSurfaceController();"
    );
    for cmd in &spec.commands {
        let mname = dart_ident(&cmd.name);
        let mut sig = CodeWriter::new();
        for (i, p) in cmd.params.iter().enumerate() {
            if i > 0 {
                sig.push_str(", ");
            }
            let pty = dart_simple_type(&p.param_type);
            let pname = dart_ident(&p.name);
            if p.optional {
                write!(sig, "{pty}? {pname}");
            } else {
                write!(sig, "{pty} {pname}");
            }
        }
        writeln!(out);
        writeln!(out, "  void {mname}({sig}) {{");
        if cmd.params.is_empty() {
            writeln!(
                out,
                "    inner.dispatchCommand('{}');",
                escape_dart_single_quoted_string(&cmd.name)
            );
        } else {
            writeln!(
                out,
                "    inner.dispatchCommand('{}', <String, dynamic>{{",
                escape_dart_single_quoted_string(&cmd.name)
            );
            for p in &cmd.params {
                let pname = dart_ident(&p.name);
                writeln!(
                    out,
                    "      '{}': {pname},",
                    escape_dart_single_quoted_string(&p.name)
                );
            }
            writeln!(out, "    }});");
        }
        writeln!(out, "  }}");
    }
    writeln!(out, "}}");
    writeln!(out);

    // 5. Typed `StatefulWidget`
    if let Some(doc) = &spec.doc {
        for line in doc.lines() {
            writeln!(out, "/// {}", sanitize_single_line_comment(line));
        }
    }
    writeln!(out, "class {name} extends StatefulWidget {{");
    for prop in &spec.props {
        if let Some(doc) = &prop.doc {
            for line in doc.lines() {
                writeln!(out, "  /// {}", sanitize_single_line_comment(line));
            }
        }
        let field = dart_ident(&prop.name);
        let ty = dart_prop_type(name, prop);
        writeln!(out, "  final {ty} {field};");
    }
    for ev in &spec.events {
        let cb = dart_ident(&ev.name);
        let cb_ty = dart_event_callback_type(name, ev);
        writeln!(out, "  final {cb_ty}? {cb};");
    }
    writeln!(out, "  final {name}Controller? controller;");
    writeln!(out, "  final String? libraryPath;");
    writeln!(out, "  final int? surfaceId;");
    writeln!(out, "  final NveChannelClient? channelClient;");
    writeln!(out, "  final double? width;");
    writeln!(out, "  final double? height;");
    writeln!(out);

    // Constructor
    writeln!(out, "  const {name}({{");
    writeln!(out, "    super.key,");
    for prop in &spec.props {
        let field = dart_ident(&prop.name);
        if let Some(def_lit) = dart_default_expr(name, prop) {
            writeln!(out, "    this.{field} = {def_lit},");
        } else if prop.optional || prop.nullable {
            writeln!(out, "    this.{field},");
        } else {
            writeln!(out, "    required this.{field},");
        }
    }
    for ev in &spec.events {
        let cb = dart_ident(&ev.name);
        writeln!(out, "    this.{cb},");
    }
    writeln!(out, "    this.controller,");
    writeln!(out, "    this.libraryPath,");
    writeln!(out, "    this.surfaceId,");
    writeln!(out, "    this.channelClient,");
    writeln!(out, "    this.width,");
    writeln!(out, "    this.height,");
    writeln!(out, "  }});");
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  State<{name}> createState() => _{name}State();");
    writeln!(out, "}}");
    writeln!(out);

    // State class
    writeln!(out, "class _{name}State extends State<{name}> {{");
    writeln!(out, "  NveCanvasController? _canvas;");
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  void initState() {{");
    writeln!(out, "    super.initState();");
    writeln!(out, "    final bindings = {name}NativeBindings.open(libraryPath: widget.libraryPath);");
    writeln!(out, "    _canvas = NveCanvasController.fromInterfaceResolver(");
    writeln!(out, "      surfaceId: widget.surfaceId ?? 1,");
    writeln!(out, "      getInterface: bindings.getInterface,");
    writeln!(out, "      onEvent: _handleEvent,");
    writeln!(out, "    );");
    writeln!(out, "    _syncProps();");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  void didUpdateWidget(covariant {name} oldWidget) {{");
    writeln!(out, "    super.didUpdateWidget(oldWidget);");
    writeln!(out, "    _syncProps();");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  void dispose() {{");
    writeln!(out, "    _canvas?.dispose();");
    writeln!(out, "    super.dispose();");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  void _syncProps() {{");
    writeln!(out, "    final ctrl = _canvas;");
    writeln!(out, "    if (ctrl == null || ctrl.isDisposed) return;");
    writeln!(out, "    ctrl.instance.setPropsDirect(_encodeProps());");
    writeln!(out, "    ctrl.renderNextFrame();");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  Map<String, dynamic> _encodeProps() {{");
    writeln!(out, "    final map = <String, dynamic>{{}};");
    for prop in &spec.props {
        let key = escape_dart_single_quoted_string(&prop.name);
        let field = dart_ident(&prop.name);
        let is_nullable = dart_prop_is_nullable(prop);
        let expr = dart_encode_prop_expr(&format!("widget.{field}"), prop, is_nullable);
        if is_nullable {
            writeln!(out, "    if (widget.{field} != null) {{");
            writeln!(out, "      map['{key}'] = {expr};");
            writeln!(out, "    }}");
        } else {
            writeln!(out, "    map['{key}'] = {expr};");
        }
    }
    writeln!(out, "    return map;");
    writeln!(out, "  }}");
    writeln!(out);

    writeln!(out, "  void _handleEvent(NveEvent event) {{");
    writeln!(
        out,
        "    if (event.kind != NveEventKind.custom || event.name == null) return;"
    );
    writeln!(out, "    final binView = event.payload.parseBinValue();");
    writeln!(out, "    switch (event.name) {{");
    for ev in &spec.events {
        let cb = dart_ident(&ev.name);
        let short = strip_on_prefix(&ev.name);
        writeln!(
            out,
            "      case '{}':\n      case '{}':",
            escape_dart_single_quoted_string(&ev.name),
            escape_dart_single_quoted_string(&short)
        );
        if ev.payload.is_empty() {
            writeln!(out, "        widget.{cb}?.call();");
        } else {
            let ev_cls = dart_event_class_name(name, ev);
            writeln!(
                out,
                "        if (binView != null) {{ widget.{cb}?.call({ev_cls}.fromBinView(binView)); }}"
            );
        }
        writeln!(out, "        break;");
    }
    writeln!(out, "      default:");
    writeln!(out, "        break;");
    writeln!(out, "    }}");
    writeln!(out, "  }}");
    writeln!(out);

    writeln!(out, "  @override");
    writeln!(out, "  Widget build(BuildContext context) {{");
    writeln!(out, "    final ctrl = _canvas;");
    writeln!(out, "    if (ctrl == null) return const SizedBox.shrink();");
    writeln!(out, "    return SizedBox(");
    writeln!(out, "      width: widget.width,");
    writeln!(out, "      height: widget.height,");
    writeln!(out, "      child: NveCanvasView(");
    writeln!(out, "        controller: ctrl,");
    writeln!(out, "        onEvent: _handleEvent,");
    writeln!(out, "      ),");
    writeln!(out, "    );");
    writeln!(out, "  }}");
    writeln!(out, "}}");

    out.into_string()
}

fn emit_dart_aux_enum(out: &mut CodeWriter, comp_name: &str, prop: &PropSpec) {
    match &prop.prop_type {
        PropType::StringEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            writeln!(out, "enum {enum_name} {{");
            for (i, v) in variants.iter().enumerate() {
                let sep = if i + 1 == variants.len() { ";" } else { "," };
                writeln!(
                    out,
                    "  {}('{}'){sep}",
                    dart_ident(v),
                    escape_dart_single_quoted_string(v)
                );
            }
            writeln!(out);
            writeln!(out, "  final String wireValue;");
            writeln!(out, "  const {enum_name}(this.wireValue);");
            writeln!(out, "}}");
            writeln!(out);
        }
        PropType::IntEnum { variants } => {
            let enum_name = format!("{comp_name}{}", to_pascal_case(&prop.name));
            writeln!(out, "enum {enum_name} {{");
            for (i, v) in variants.iter().enumerate() {
                let sep = if i + 1 == variants.len() { ";" } else { "," };
                let vname = int_enum_variant_camel(*v);
                writeln!(out, "  {vname}({v}){sep}");
            }
            writeln!(out);
            writeln!(out, "  final int wireValue;");
            writeln!(out, "  const {enum_name}(this.wireValue);");
            writeln!(out, "}}");
            writeln!(out);
        }
        _ => {}
    }
}

fn dart_event_class_name(comp_name: &str, ev: &EventSpec) -> String {
    format!("{comp_name}{}Event", to_pascal_case(&strip_on_prefix(&ev.name)))
}

fn emit_dart_event_class(out: &mut CodeWriter, comp_name: &str, ev: &EventSpec) {
    if ev.payload.is_empty() {
        return;
    }
    let cls = dart_event_class_name(comp_name, ev);
    writeln!(out, "class {cls} {{");
    for f in &ev.payload {
        let fname = dart_ident(&f.name);
        let fty = dart_simple_type(&f.field_type);
        let q = if f.optional || f.nullable { "?" } else { "" };
        writeln!(out, "  final {fty}{q} {fname};");
    }
    writeln!(out);
    writeln!(out, "  const {cls}({{");
    for f in &ev.payload {
        let fname = dart_ident(&f.name);
        if f.optional || f.nullable {
            writeln!(out, "    this.{fname},");
        } else {
            writeln!(out, "    required this.{fname},");
        }
    }
    writeln!(out, "  }});");
    writeln!(out);
    writeln!(out, "  factory {cls}.fromBinView(NveBinValueView view) {{");
    writeln!(out, "    return {cls}(");
    for f in &ev.payload {
        let fname = dart_ident(&f.name);
        let key = escape_dart_single_quoted_string(&f.name);
        let expr = dart_from_bin_view_expr(&key, f);
        writeln!(out, "      {fname}: {expr},");
    }
    writeln!(out, "    );");
    writeln!(out, "  }}");
    writeln!(out, "}}");
    writeln!(out);
}

fn dart_from_bin_view_expr(key: &str, f: &ObjectField) -> String {
    let opt = f.optional || f.nullable;
    match &f.field_type {
        PropType::Bool => {
            if opt {
                format!("view.get('{key}')?.asBool()")
            } else {
                format!("view.get('{key}')?.asBool() ?? false")
            }
        }
        PropType::Int32 | PropType::IntEnum { .. } => {
            if opt {
                format!("view.get('{key}')?.asInt64()")
            } else {
                format!("view.get('{key}')?.asInt64() ?? 0")
            }
        }
        PropType::Float | PropType::Double => {
            if opt {
                format!("view.get('{key}')?.asNumber()")
            } else {
                format!("view.get('{key}')?.asNumber() ?? 0.0")
            }
        }
        _ => {
            if opt {
                format!("view.get('{key}')?.asString()")
            } else {
                format!("view.get('{key}')?.asString() ?? ''")
            }
        }
    }
}

fn dart_event_callback_type(comp_name: &str, ev: &EventSpec) -> String {
    if ev.payload.is_empty() {
        "VoidCallback".to_owned()
    } else {
        format!("ValueChanged<{}>", dart_event_class_name(comp_name, ev))
    }
}

fn dart_prop_is_nullable(prop: &PropSpec) -> bool {
    (prop.optional || prop.nullable) && dart_default_expr_exists(prop).not()
}

trait BoolNot {
    fn not(self) -> bool;
}
impl BoolNot for bool {
    fn not(self) -> bool {
        !self
    }
}

fn dart_default_expr_exists(prop: &PropSpec) -> bool {
    matches!(
        (&prop.prop_type, &prop.default_value),
        (PropType::Bool, Some(DefaultValue::Bool(_)))
            | (PropType::Int32 | PropType::IntEnum { .. }, Some(DefaultValue::Int(_)))
            | (PropType::Float | PropType::Double, Some(DefaultValue::Int(_) | DefaultValue::Float(_)))
            | (PropType::String | PropType::StringEnum { .. }, Some(DefaultValue::String(_)))
    )
}

fn dart_prop_type(comp_name: &str, prop: &PropSpec) -> String {
    let base = match &prop.prop_type {
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("{comp_name}{}", to_pascal_case(&prop.name))
        }
        PropType::Color => "Color".to_owned(),
        other => dart_simple_type(other),
    };
    if dart_prop_is_nullable(prop) {
        format!("{base}?")
    } else {
        base
    }
}

fn dart_simple_type(ty: &PropType) -> String {
    match ty {
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 | PropType::IntEnum { .. } => "int".to_owned(),
        PropType::Float | PropType::Double => "double".to_owned(),
        PropType::Color => "Color".to_owned(),
        PropType::Array { item } => format!("List<{}>", dart_simple_type(item)),
        PropType::Object { .. } => "Map<String, dynamic>".to_owned(),
        _ => "String".to_owned(),
    }
}

fn dart_default_expr(comp_name: &str, prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float | PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Float | PropType::Double, DefaultValue::Float(f)) => {
            Some(format_float_literal(*f))
        }
        (PropType::String, DefaultValue::String(s)) => {
            Some(format!("'{}'", escape_dart_single_quoted_string(s)))
        }
        (PropType::StringEnum { variants }, DefaultValue::String(s)) if variants.contains(s) => {
            Some(format!(
                "{comp_name}{}.{}",
                to_pascal_case(&prop.name),
                dart_ident(s)
            ))
        }
        (PropType::IntEnum { variants }, DefaultValue::Int(i))
            if variants.contains(&(*i as i32)) =>
        {
            let vname = int_enum_variant_camel(*i as i32);
            Some(format!("{comp_name}{}.{vname}", to_pascal_case(&prop.name)))
        }
        _ => None,
    }
}

fn dart_encode_prop_expr(access: &str, prop: &PropSpec, nullable: bool) -> String {
    let bang = if nullable { "!" } else { "" };
    match &prop.prop_type {
        PropType::Color => {
            format!(
                "'#${{{access}{bang}.toARGB32().toRadixString(16).padLeft(8, '0')}}'"
            )
        }
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("{access}{bang}.wireValue")
        }
        _ => format!("{access}{bang}"),
    }
}
