use super::core_abi::{
    dart_core_ffi_annotation, dart_core_native_type, dart_core_struct_field_type,
};
use crate::naming::{screaming_snake_to_camel_case, to_pascal_case};
use crate::schema::hybrid::core_abi::{
    compute_scene_schema_hash, scene_abi_spec, snake_to_camel_preserve_leading, ResolvedSceneAbi,
};
use crate::schema::hybrid::HybridType;
use crate::writer::CodeWriter;

// ============================================================================
// Scene ABI Target 3: Dart `dart:ffi` (`hosts/flutter-plugin/lib/src/nve_scene_abi.generated.dart`)
// ============================================================================

/// Generates `hosts/flutter-plugin/lib/src/nve_scene_abi.generated.dart` directly from
/// `packages/core/abi/src/schema.rs`.
pub fn generate_dart_scene_abi() -> String {
    let spec = scene_abi_spec();
    let schema_hash = compute_scene_schema_hash(&spec);
    let signed_hash = schema_hash as i64;
    let ResolvedSceneAbi {
        render_node,
        table_view,
        scene_view,
        node_meta,
        node_size,
        meta_size,
        ..
    } = ResolvedSceneAbi::from_spec(&spec);

    let mut out = CodeWriter::with_capacity(8192);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY."
    );
    writeln!(
        out,
        "// Single-source 64-byte NveRenderNode + NveSceneView + 64-byte NveNodeMeta `dart:ffi` bindings."
    );
    writeln!(out);
    writeln!(out, "import 'dart:convert';");
    writeln!(out, "import 'dart:ffi' as ffi;");
    writeln!(out, "import 'dart:typed_data';");
    writeln!(out);
    writeln!(
        out,
        "/// Deterministic XXH64 schema hash (`0x{schema_hash:016X}`)."
    );
    writeln!(
        out,
        "/// Stored as 64-bit two's-complement `int` matching `@ffi.Uint64()` bit pattern on native VM."
    );
    writeln!(out, "const int nveSceneSchemaHash = {signed_hash};");
    writeln!(
        out,
        "const String nveSceneSchemaHashHex = '0x{schema_hash:016X}';"
    );
    writeln!(out, "const int nveRenderNodeStride = {node_size};");
    writeln!(out, "const int nveNodeMetaStride = {meta_size};");
    writeln!(out);
    writeln!(out, "// NveRenderNode::flags bit constants");
    writeln!(out, "const int nveNodeLeafText = 1 << 0;");
    writeln!(out, "const int nveNodeInteractive = 1 << 1;");
    writeln!(out, "const int nveNodeClipBounds = 1 << 2;");
    writeln!(out);
    writeln!(out, "// Sentinel NveRenderNode::primary_slot value (plain container)");
    for c in &spec.consts {
        if c.name == "NVE_PRIMARY_SLOT_NONE" {
            let dart_name = screaming_snake_to_camel_case(&c.name);
            writeln!(out, "const int {dart_name} = 0x{:02X};", c.value);
        }
    }
    writeln!(out);
    writeln!(out, "// NveNodeMeta::flags bits & resize-mode shift/mask");
    for c in &spec.consts {
        if c.name.starts_with("NVE_META_") {
            let dart_name = screaming_snake_to_camel_case(&c.name);
            if c.hex {
                writeln!(out, "const int {dart_name} = 0x{:X};", c.value);
            } else {
                writeln!(out, "const int {dart_name} = {};", c.value);
            }
        }
    }
    writeln!(out);
    writeln!(out, "// Exact byte offsets within one 64-byte NveRenderNode");
    for f in &render_node.fields {
        let const_name = format!(
            "nveNodeOffset{}",
            to_pascal_case(f.name.trim_start_matches('_'))
        );
        writeln!(
            out,
            "const int {const_name} = {};",
            f.offset.expect("NveRenderNode field defines offset")
        );
    }
    writeln!(out);
    writeln!(out, "// Exact byte offsets within one 64-byte NveNodeMeta");
    for f in &node_meta.fields {
        let const_name = format!(
            "nveMetaOffset{}",
            to_pascal_case(f.name.trim_start_matches('_'))
        );
        writeln!(
            out,
            "const int {const_name} = {};",
            f.offset.expect("NveNodeMeta field defines offset")
        );
    }
    writeln!(out);
    writeln!(
        out,
        "/// 64-byte zero-decode render node (`NveRenderNode` in `nve_scene_abi.generated.h`)."
    );
    writeln!(out, "final class NveRenderNode extends ffi.Struct {{");
    for f in &render_node.fields {
        let dart_name = if f.name == "_pad0" {
            "pad0".to_owned()
        } else {
            snake_to_camel_preserve_leading(&f.name)
        };
        if let Some(ann) = dart_core_ffi_annotation(&f.ty, &spec.aliases) {
            writeln!(out, "  {ann}");
        }
        writeln!(
            out,
            "  external {} {dart_name}; // offset {}",
            dart_core_struct_field_type(&f.ty, &spec.aliases),
            f.offset.expect("NveRenderNode field defines offset")
        );
    }
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "/// Fixed-stride 64-byte per-node metadata record (`NveNodeMeta` in `nve_scene_abi.generated.h`)."
    );
    writeln!(out, "final class NveNodeMeta extends ffi.Struct {{");
    for f in &node_meta.fields {
        let dart_name = if f.name == "_reserved" {
            "reserved".to_owned()
        } else {
            snake_to_camel_preserve_leading(&f.name)
        };
        match &f.ty {
            HybridType::FixedArray { elem, len } => {
                writeln!(out, "  @ffi.Array({len})");
                writeln!(
                    out,
                    "  external ffi.Array<{}> {dart_name}; // offset {}",
                    dart_core_native_type(elem, &spec.aliases),
                    f.offset.expect("NveNodeMeta field defines offset")
                );
            }
            _ => {
                if let Some(ann) = dart_core_ffi_annotation(&f.ty, &spec.aliases) {
                    writeln!(out, "  {ann}");
                }
                writeln!(
                    out,
                    "  external {} {dart_name}; // offset {}",
                    dart_core_struct_field_type(&f.ty, &spec.aliases),
                    f.offset.expect("NveNodeMeta field defines offset")
                );
            }
        }
    }
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "/// Zero-copy view of one published NodeStore word table (`NveTableView` in `nve_scene_abi.generated.h`)."
    );
    writeln!(out, "final class NveTableView extends ffi.Struct {{");
    for f in &table_view.fields {
        let dart_name = snake_to_camel_preserve_leading(&f.name);
        if let Some(ann) = dart_core_ffi_annotation(&f.ty, &spec.aliases) {
            writeln!(out, "  {ann}");
        }
        writeln!(
            out,
            "  external {} {dart_name};",
            dart_core_struct_field_type(&f.ty, &spec.aliases)
        );
    }
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "/// Zero-decode scene snapshot header + slab pointers (`NveSceneView` in `nve_scene_abi.generated.h`)."
    );
    writeln!(out, "final class NveSceneView extends ffi.Struct {{");
    for f in &scene_view.fields {
        let dart_name = if f.name == "_pad" {
            "pad".to_owned()
        } else {
            snake_to_camel_preserve_leading(&f.name)
        };
        if let Some(ann) = dart_core_ffi_annotation(&f.ty, &spec.aliases) {
            writeln!(out, "  {ann}");
        }
        writeln!(
            out,
            "  external {} {dart_name};",
            dart_core_struct_field_type(&f.ty, &spec.aliases)
        );
    }
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "/// Error thrown when an `NveSceneView` fails schema or bounds validation."
    );
    writeln!(out, "class NveSceneAbiException implements Exception {{");
    writeln!(out, "  const NveSceneAbiException(this.message);");
    writeln!(out, "  final String message;");
    writeln!(out, "  @override");
    writeln!(out, "  String toString() => 'NveSceneAbiException: $message';");
    writeln!(out, "}}");
    writeln!(out);
    writeln!(
        out,
        "/// Zero-copy, zero-decode reader over a native `Pointer<NveSceneView>`."
    );
    writeln!(out, "class NveSceneReader {{");
    writeln!(out, "  NveSceneReader._({{");
    writeln!(out, "    required this.frameId,");
    writeln!(out, "    required this.nodeCount,");
    writeln!(out, "    required this.tableCount,");
    writeln!(out, "    required ffi.Pointer<NveRenderNode> nodesPtr,");
    writeln!(out, "    required this.tables,");
    writeln!(out, "    required this.textSlab,");
    writeln!(out, "    required this.childrenSlab,");
    writeln!(out, "    required this.dirtyIndices,");
    writeln!(out, "    required this.removedIds,");
    writeln!(out, "  }}) : _nodesPtr = nodesPtr;");
    writeln!(out);
    writeln!(
        out,
        "  /// Validates `schemaHash` and non-null pointer invariants with zero data copies."
    );
    writeln!(
        out,
        "  factory NveSceneReader.fromPointer(ffi.Pointer<NveSceneView> viewPtr) {{"
    );
    writeln!(out, "    if (viewPtr == ffi.nullptr) {{");
    writeln!(
        out,
        "      throw const NveSceneAbiException('NveSceneView pointer is null');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final NveSceneView view = viewPtr.ref;");
    writeln!(out, "    if (view.schemaHash != nveSceneSchemaHash) {{");
    writeln!(
        out,
        "      throw NveSceneAbiException('Schema hash mismatch: expected $nveSceneSchemaHashHex, got 0x${{view.schemaHash.toUnsigned(64).toRadixString(16).toUpperCase()}}');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int nodeCount = view.nodeCount;");
    writeln!(out, "    if (nodeCount > 0 && view.nodes == ffi.nullptr) {{");
    writeln!(
        out,
        "      throw const NveSceneAbiException('nodes pointer is null with non-zero nodeCount');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int textLen = view.textSlabLen;");
    writeln!(out, "    if (textLen > 0 && view.textSlab == ffi.nullptr) {{");
    writeln!(
        out,
        "      throw const NveSceneAbiException('textSlab pointer is null with non-zero textSlabLen');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int childrenLen = view.childrenSlabLen;");
    writeln!(
        out,
        "    if (childrenLen > 0 && view.childrenSlab == ffi.nullptr) {{"
    );
    writeln!(
        out,
        "      throw const NveSceneAbiException('childrenSlab pointer is null with non-zero childrenSlabLen');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int dirtyCount = view.dirtyCount;");
    writeln!(
        out,
        "    if (dirtyCount > 0 && view.dirtyIndices == ffi.nullptr) {{"
    );
    writeln!(
        out,
        "      throw const NveSceneAbiException('dirtyIndices pointer is null with non-zero dirtyCount');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int removedCount = view.removedCount;");
    writeln!(
        out,
        "    if (removedCount > 0 && view.removedIds == ffi.nullptr) {{"
    );
    writeln!(
        out,
        "      throw const NveSceneAbiException('removedIds pointer is null with non-zero removedCount');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    final int tableCount = view.tableCount;");
    writeln!(
        out,
        "    if (tableCount > 0 && view.tables == ffi.nullptr) {{"
    );
    writeln!(
        out,
        "      throw const NveSceneAbiException('tables pointer is null with non-zero tableCount');"
    );
    writeln!(out, "    }}");
    writeln!(out);
    writeln!(out, "    return NveSceneReader._(");
    writeln!(out, "      frameId: view.frameId,");
    writeln!(out, "      nodeCount: nodeCount,");
    writeln!(out, "      tableCount: tableCount,");
    writeln!(out, "      nodesPtr: view.nodes,");
    writeln!(out, "      tables: view.tables,");
    writeln!(
        out,
        "      textSlab: textLen == 0 ? Uint8List(0) : view.textSlab.asTypedList(textLen),"
    );
    writeln!(
        out,
        "      childrenSlab: childrenLen == 0 ? Uint32List(0) : view.childrenSlab.asTypedList(childrenLen),"
    );
    writeln!(
        out,
        "      dirtyIndices: dirtyCount == 0 ? Uint32List(0) : view.dirtyIndices.asTypedList(dirtyCount),"
    );
    writeln!(
        out,
        "      removedIds: removedCount == 0 ? Uint32List(0) : view.removedIds.asTypedList(removedCount),"
    );
    writeln!(out, "    );");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  final int frameId;");
    writeln!(out, "  final int nodeCount;");
    writeln!(out, "  final int tableCount;");
    writeln!(out, "  final ffi.Pointer<NveRenderNode> _nodesPtr;");
    writeln!(out, "  final ffi.Pointer<NveTableView> tables;");
    writeln!(out, "  final Uint8List textSlab;");
    writeln!(out, "  final Uint32List childrenSlab;");
    writeln!(out, "  final Uint32List dirtyIndices;");
    writeln!(out, "  final Uint32List removedIds;");
    writeln!(out);
    writeln!(out, "  /// Zero-copy indexed access to a published `NveTableView`.");
    writeln!(out, "  NveTableView tableAt(int index) {{");
    writeln!(out, "    if (index < 0 || index >= tableCount) {{");
    writeln!(
        out,
        "      throw RangeError.index(index, this, 'index', null, tableCount);"
    );
    writeln!(out, "    }}");
    writeln!(out, "    return tables[index];");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  /// Zero-copy indexed access to a 64-byte `NveRenderNode`.");
    writeln!(out, "  NveRenderNode nodeAt(int index) {{");
    writeln!(out, "    if (index < 0 || index >= nodeCount) {{");
    writeln!(
        out,
        "      throw RangeError.index(index, this, 'index', null, nodeCount);"
    );
    writeln!(out, "    }}");
    writeln!(out, "    return _nodesPtr[index];");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  /// Zero-copy UTF-8 byte slice for `node` inside `textSlab`.");
    writeln!(out, "  Uint8List textBytesFor(NveRenderNode node) {{");
    writeln!(out, "    final int len = node.textLen;");
    writeln!(out, "    if (len == 0) {{");
    writeln!(out, "      return Uint8List(0);");
    writeln!(out, "    }}");
    writeln!(out, "    final int start = node.textOffset;");
    writeln!(out, "    final int end = start + len;");
    writeln!(out, "    if (start < 0 || end > textSlab.length) {{");
    writeln!(
        out,
        "      throw NveSceneAbiException('Node ${{node.nodeId}} text slice [$start..$end] out of bounds (${{textSlab.length}})');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    return Uint8List.sublistView(textSlab, start, end);");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  /// Decodes `node`'s UTF-8 text directly from `textSlab`.");
    writeln!(out, "  String textFor(NveRenderNode node) {{");
    writeln!(out, "    final Uint8List slice = textBytesFor(node);");
    writeln!(out, "    if (slice.isEmpty) {{");
    writeln!(out, "      return '';");
    writeln!(out, "    }}");
    writeln!(out, "    return utf8.decode(slice, allowMalformed: false);");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(
        out,
        "  /// Zero-copy `Uint32List` view over `node`'s children in `childrenSlab`."
    );
    writeln!(out, "  Uint32List childrenFor(NveRenderNode node) {{");
    writeln!(out, "    final int count = node.childCount;");
    writeln!(out, "    if (count == 0) {{");
    writeln!(out, "      return Uint32List(0);");
    writeln!(out, "    }}");
    writeln!(out, "    final int start = node.childOffset;");
    writeln!(out, "    final int end = start + count;");
    writeln!(out, "    if (start < 0 || end > childrenSlab.length) {{");
    writeln!(
        out,
        "      throw NveSceneAbiException('Node ${{node.nodeId}} children slice [$start..$end] out of bounds (${{childrenSlab.length}})');"
    );
    writeln!(out, "    }}");
    writeln!(out, "    return Uint32List.sublistView(childrenSlab, start, end);");
    writeln!(out, "  }}");
    writeln!(out);
    writeln!(out, "  /// Iterates only dirty nodes in `O(dirtyCount)`.");
    writeln!(
        out,
        "  void forEachDirty(void Function(int index, NveRenderNode node) visit) {{"
    );
    writeln!(out, "    for (int i = 0; i < dirtyIndices.length; i++) {{");
    writeln!(out, "      final int idx = dirtyIndices[i];");
    writeln!(out, "      if (idx < nodeCount) {{");
    writeln!(out, "        visit(idx, _nodesPtr[idx]);");
    writeln!(out, "      }}");
    writeln!(out, "    }}");
    writeln!(out, "  }}");
    writeln!(out, "}}");
    out.into_string()
}
