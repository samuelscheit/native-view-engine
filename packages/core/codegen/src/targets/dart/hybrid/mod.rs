//! Flutter / Dart (`dart:ffi`) target emitter for NVE Hybrid FFI codegen.
//!
//! Emits a standalone, binary FFI, zero-external-package Dart file (`<stem>_hybrid.generated.dart`):
//! - Uses only Dart SDK (`dart:convert` UTF-8, `dart:ffi`, `dart:typed_data`)
//! - Exact `ffi.Struct` definitions for `NveStrSlice`, `NveBufferSlice`, `NveHybridOwnedBytes`,
//!   `NveValue`, `NveMapEntry`, POD structs, POD `NveHybridOpt*`, and `NveHybrid<Name>VTable`
//! - `abstract interface class Hybrid<Name>Spec`
//! - `class <Name>HybridClient` resolving `nve_get_interface`, verifying `schemaHash`,
//!   and managing transient scratch buffers via the vtable's `allocBytes` / `freeBytes`.

mod client_emitter;
mod type_helpers;

use crate::writer::CodeWriter;
use client_emitter::{emit_dart_client, emit_dart_direct_prop_write};
use type_helpers::*;

use crate::error::CodegenError;
use crate::naming::{
    dart_ident, escape_dart_single_quoted_string, format_float_literal, to_camel_case,
    to_pascal_case,
};
use crate::schema::export::GeneratedFile;
use crate::schema::hybrid::{
    HybridDefaultValue, HybridEnumSpec, HybridFileSpec, HybridMethodSpec, HybridModuleSpec,
    HybridStructSpec, HybridType, HybridViewSpec, NVE_HYBRID_ABI_VERSION,
};

/// Emits `<stem>_hybrid.generated.dart` using `dart:ffi` and the shared `package:nve_flutter/nve_hybrid_runtime.dart`.
pub fn generate_hybrid_dart(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut body = CodeWriter::with_capacity(16 * 1024);

    emit_dart_common(&mut body, spec);

    for e in &spec.enums {
        emit_dart_enum(&mut body, e);
    }

    for s in spec.structs_topological() {
        emit_dart_struct(&mut body, s, spec);
    }

    // POD Option FFI structs
    for (suffix, inner) in spec.collect_pod_option_types() {
        writeln!(
            body,
            "final class NveHybridOpt{suffix} extends ffi.Struct {{"
        );
        writeln!(body, "  @ffi.Bool()");
        writeln!(body, "  external bool isSome;");
        if let Some(ann) = dart_ffi_field_annotation(&inner) {
            writeln!(body, "  {ann}");
        }
        writeln!(
            body,
            "  external {} value;",
            dart_ffi_struct_field_type(&inner)
        );
        writeln!(body, "}}");
        writeln!(body);
    }

    for m in &spec.modules {
        emit_dart_module(&mut body, m, spec);
    }

    for v in &spec.views {
        emit_dart_view(&mut body, v, spec);
    }

    let mut out = CodeWriter::with_capacity(body.len() + 512);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Flutter/Dart dart:ffi target) — DO NOT EDIT."
    );
    writeln!(
        out,
        "// Binary direct dart:ffi vtable bindings sharing `package:nve_flutter/nve_hybrid_runtime.dart`."
    );
    writeln!(out);
    if body.contains("utf8.") {
        writeln!(out, "import 'dart:convert' show utf8;");
    }
    writeln!(out, "import 'dart:ffi' as ffi;");
    if body.contains("Uint8List") {
        writeln!(out, "import 'dart:typed_data';");
    }
    writeln!(out);
    writeln!(out, "import 'package:nve_flutter/nve_hybrid_runtime.dart';");
    writeln!(out);
    out.push_str(&body);

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.generated.dart"),
        content: out.into_string(),
    }])
}

fn emit_dart_common(out: &mut CodeWriter, spec: &HybridFileSpec) {
    writeln!(
        out,
        "const int nveHybridAbiVersion = {NVE_HYBRID_ABI_VERSION};"
    );
    writeln!(
        out,
        "const int nveHybridFileSchemaHash = {};",
        dart_u64_const(spec.file_schema_hash())
    );
    writeln!(out, "const int nveHybridOk = 0;");
    writeln!(out);

    writeln!(
        out,
        r#"typedef _NveGetInterfaceNative = ffi.Pointer<ffi.Void> Function(ffi.Uint32);
typedef _NveGetInterfaceDart = ffi.Pointer<ffi.Void> Function(int);
typedef _NveCreateNative = ffi.Pointer<ffi.Void> Function();
typedef _NveCreateDart = ffi.Pointer<ffi.Void> Function();
typedef _NveDestroyNative = ffi.Void Function(ffi.Pointer<ffi.Void>);
typedef _NveDestroyDart = void Function(ffi.Pointer<ffi.Void>);
typedef _NveAllocBytesNative = NveHybridOwnedBytes Function(ffi.Size);
typedef _NveAllocBytesDart = NveHybridOwnedBytes Function(int);
typedef _NveFreeBytesNative = ffi.Void Function(NveHybridOwnedBytes);
typedef _NveFreeBytesDart = void Function(NveHybridOwnedBytes);
typedef _NveSetPropsDirectNative = ffi.Int32 Function(
  ffi.Pointer<ffi.Void>,
  ffi.Pointer<NveMapEntry>,
  ffi.Uint32,
);
typedef _NveSetPropsDirectDart = int Function(
  ffi.Pointer<ffi.Void>,
  ffi.Pointer<NveMapEntry>,
  int,
);
"#
    );
}

fn emit_dart_enum(out: &mut CodeWriter, e: &HybridEnumSpec) {
    writeln!(out, "enum {} {{", e.name);
    for (idx, v) in e.variants.iter().enumerate() {
        let vname = dart_ident(&v.name);
        let sep = if idx + 1 == e.variants.len() {
            ";"
        } else {
            ","
        };
        writeln!(out, "  {vname}({}){sep}", v.value);
    }
    writeln!(out, "  final int rawValue;");
    writeln!(out, "  const {}(this.rawValue);", e.name);
    writeln!(
        out,
        "  static {} fromRaw(int raw) => switch (raw) {{",
        e.name
    );
    for v in &e.variants {
        writeln!(
            out,
            "    {} => {}.{},",
            v.value,
            e.name,
            dart_ident(&v.name)
        );
    }
    writeln!(
        out,
        "    _ => throw ArgumentError('invalid {} discriminant: $raw'),",
        e.name
    );
    writeln!(out, "  }};");
    writeln!(out, "}}");
    writeln!(out);
}

fn emit_dart_struct(out: &mut CodeWriter, s: &HybridStructSpec, spec: &HybridFileSpec) {
    if s.is_pod(spec) {
        writeln!(out, "final class NveHybrid{} extends ffi.Struct {{", s.name);
        for f in &s.fields {
            if let Some(ann) = dart_ffi_field_annotation(&f.ty) {
                writeln!(out, "  {ann}");
            }
            let fname = dart_ident(&f.name);
            writeln!(
                out,
                "  external {} {fname};",
                dart_ffi_struct_field_type(&f.ty)
            );
        }
        writeln!(out, "}}");
        writeln!(out);
    }

    writeln!(out, "class {} {{", s.name);
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        writeln!(out, "  final {} {fname};", dart_type(&f.ty));
    }
    writeln!(out);
    write!(out, "  const {}({{", s.name);
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        write!(out, "required this.{fname}, ");
    }
    writeln!(out, "}});");

    if s.is_pod(spec) {
        writeln!(out);
        writeln!(out, "  NveHybrid{} toAbi() {{", s.name);
        writeln!(
            out,
            "    final raw = ffi.Struct.create<NveHybrid{}>();",
            s.name
        );
        for f in &s.fields {
            let fname = dart_ident(&f.name);
            match &f.ty {
                HybridType::Enum(_) => writeln!(out, "    raw.{fname} = {fname}.rawValue;"),
                HybridType::Struct(_) => writeln!(out, "    raw.{fname} = {fname}.toAbi();"),
                _ => writeln!(out, "    raw.{fname} = {fname};"),
            }
        }
        writeln!(out, "    return raw;");
        writeln!(out, "  }}");
        writeln!(out);
        writeln!(
            out,
            "  factory {}.fromAbi(NveHybrid{} raw) => {}(",
            s.name, s.name, s.name
        );
        for f in &s.fields {
            let fname = dart_ident(&f.name);
            match &f.ty {
                HybridType::Enum(e) => writeln!(out, "    {fname}: {e}.fromRaw(raw.{fname}),"),
                HybridType::Struct(st) => writeln!(out, "    {fname}: {st}.fromAbi(raw.{fname}),"),
                _ => writeln!(out, "    {fname}: raw.{fname},"),
            }
        }
        writeln!(out, "  );");
    }

    writeln!(out);
    writeln!(out, "  void encodeBin(NveBinWriter w) {{");
    writeln!(out, "    w.writeMap({}, (mw) {{", s.fields.len());
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let key_lit = escape_dart_single_quoted_string(&f.name);
        writeln!(out, "      mw.writeMapKey('{key_lit}');");
        // `this.`: a field named like the writer (`w`, `mw`) must not resolve to it.
        emit_dart_bin_write(out, "      ", "mw", &format!("this.{fname}"), &f.ty);
    }
    writeln!(out, "    }});");
    writeln!(out, "  }}");
    writeln!(out);

    writeln!(out, "  factory {}.decodeBin(NveBinReader r) {{", s.name);
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let def = dart_default_value(&f.ty, None, spec);
        writeln!(out, "    {} _{fname} = {def};", dart_type(&f.ty));
    }
    writeln!(out, "    final count = r.beginMap();");
    writeln!(out, "    for (var i = 0; i < count; i++) {{");
    writeln!(out, "      switch (r.readMapKey()) {{");
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        let key_lit = escape_dart_single_quoted_string(&f.name);
        writeln!(out, "        case '{key_lit}':");
        emit_dart_bin_read(out, "          ", "r", &format!("_{fname}"), &f.ty);
    }
    writeln!(out, "        default:");
    writeln!(out, "          r.skipValue();");
    writeln!(out, "      }}");
    writeln!(out, "    }}");
    writeln!(out, "    return {}(", s.name);
    for f in &s.fields {
        let fname = dart_ident(&f.name);
        writeln!(out, "      {fname}: _{fname},");
    }
    writeln!(out, "    );");
    writeln!(out, "  }}");
    writeln!(out, "}}");
    writeln!(out);
}

fn emit_dart_module(out: &mut CodeWriter, m: &HybridModuleSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&m.name);
    emit_dart_vtable_struct(out, &pascal, &m.methods, false, spec);

    writeln!(out, "abstract interface class Hybrid{pascal}Spec {{");
    for method in &m.methods {
        writeln!(out, "  {};", dart_method_sig(method));
    }
    writeln!(out, "}}");
    writeln!(out);

    emit_dart_client(
        out,
        &pascal,
        m.interface_id(),
        m.schema_hash(spec),
        &m.methods,
        None,
        spec,
    );
}

fn emit_dart_view(out: &mut CodeWriter, v: &HybridViewSpec, spec: &HybridFileSpec) {
    let pascal = to_pascal_case(&v.name);

    writeln!(out, "class {pascal}Props implements NveDirectEncodable {{");
    for p in &v.props {
        let pname = dart_ident(&p.name);
        writeln!(out, "  final {} {pname};", dart_type(&p.ty));
    }
    writeln!(out);
    write!(out, "  {pascal}Props({{");
    for p in &v.props {
        let pname = dart_ident(&p.name);
        let def = dart_default_value(&p.ty, p.default_value.as_ref(), spec);
        if dart_is_const_expr(&p.ty, p.default_value.as_ref()) {
            write!(out, "this.{pname} = {def}, ");
        } else {
            write!(out, "{}? {pname}, ", dart_type_non_nullable(&p.ty));
        }
    }
    writeln!(out, "}})");
    let non_const_inits: Vec<String> = v
        .props
        .iter()
        .filter(|p| !dart_is_const_expr(&p.ty, p.default_value.as_ref()))
        .map(|p| {
            let pname = dart_ident(&p.name);
            let def = dart_default_value(&p.ty, p.default_value.as_ref(), spec);
            format!("{pname} = {pname} ?? {def}")
        })
        .collect();
    if !non_const_inits.is_empty() {
        writeln!(out, "      : {};", non_const_inits.join(",\n        "));
    } else {
        writeln!(out, "      ;");
    }
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  int get directPropCount => {};", v.props.len());
    writeln!(out);
    writeln!(out, "  @override");
    writeln!(out, "  void encodeDirect(NveDirectPropsBuilder builder) {{");
    for p in &v.props {
        let pname = dart_ident(&p.name);
        let key_lit = escape_dart_single_quoted_string(&p.name);
        emit_dart_direct_prop_write(out, &key_lit, &pname, &p.ty);
    }
    writeln!(out, "  }}");
    writeln!(out, "}}");
    writeln!(out);

    for ev in &v.events {
        let ev_pascal = to_pascal_case(&ev.name);
        writeln!(out, "class {pascal}{ev_pascal}Event {{");
        for param in &ev.params {
            let pname = dart_ident(&param.name);
            writeln!(out, "  final {} {pname};", dart_type(&param.ty));
        }
        writeln!(out);
        write!(out, "  const {pascal}{ev_pascal}Event({{");
        for param in &ev.params {
            let pname = dart_ident(&param.name);
            write!(out, "required this.{pname}, ");
        }
        writeln!(out, "}});");
        writeln!(out, "}}");
        writeln!(out);
    }

    emit_dart_vtable_struct(out, &pascal, &v.methods, true, spec);

    writeln!(out, "abstract interface class Hybrid{pascal}Spec {{");
    writeln!(out, "  void setProps({pascal}Props props);");
    for method in &v.methods {
        writeln!(out, "  {};", dart_method_sig(method));
    }
    writeln!(out, "}}");
    writeln!(out);

    emit_dart_client(
        out,
        &pascal,
        v.interface_id(),
        v.schema_hash(spec),
        &v.methods,
        Some(v),
        spec,
    );
}

fn emit_dart_vtable_struct(
    out: &mut CodeWriter,
    pascal: &str,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    for m in methods {
        let mp = to_pascal_case(&m.name);
        let native_ret = dart_native_return_type(&m.return_type, spec);
        let dart_ret = dart_ffi_call_return_type(&m.return_type, spec);
        let mut native_params = vec!["ffi.Pointer<ffi.Void>".to_string()];
        let mut dart_params = vec!["ffi.Pointer<ffi.Void>".to_string()];
        for p in &m.params {
            native_params.push(dart_native_param_type(&p.ty, spec));
            dart_params.push(dart_ffi_call_param_type(&p.ty, spec));
        }
        if let HybridType::Result { ok, .. } = &m.return_type {
            if !matches!(ok.as_ref(), HybridType::Void) {
                let ptr_ty = format!("ffi.Pointer<{}>", dart_native_value_type(ok, spec));
                native_params.push(ptr_ty.clone());
                dart_params.push(ptr_ty);
            }
            native_params.push("ffi.Pointer<NveHybridOwnedBytes>".to_string());
            dart_params.push("ffi.Pointer<NveHybridOwnedBytes>".to_string());
        }
        writeln!(
            out,
            "typedef _{pascal}{mp}Native = {native_ret} Function({});",
            native_params.join(", ")
        );
        writeln!(
            out,
            "typedef _{pascal}{mp}Dart = {dart_ret} Function({});",
            dart_params.join(", ")
        );
    }
    writeln!(out);

    writeln!(
        out,
        "final class NveHybrid{pascal}VTable extends ffi.Struct {{"
    );
    writeln!(out, "  @ffi.Uint32()");
    writeln!(out, "  external int abiVersion;");
    writeln!(out, "  @ffi.Uint32()");
    writeln!(out, "  external int interfaceId;");
    writeln!(out, "  @ffi.Uint64()");
    writeln!(out, "  external int schemaHash;");
    writeln!(
        out,
        "  external ffi.Pointer<ffi.NativeFunction<_NveCreateNative>> create;"
    );
    writeln!(
        out,
        "  external ffi.Pointer<ffi.NativeFunction<_NveDestroyNative>> destroy;"
    );
    writeln!(
        out,
        "  external ffi.Pointer<ffi.NativeFunction<_NveAllocBytesNative>> allocBytes;"
    );
    writeln!(
        out,
        "  external ffi.Pointer<ffi.NativeFunction<_NveFreeBytesNative>> freeBytes;"
    );
    if is_view {
        writeln!(
            out,
            "  external ffi.Pointer<ffi.NativeFunction<_NveSetPropsDirectNative>> setPropsDirect;"
        );
    }
    for m in methods {
        let mp = to_pascal_case(&m.name);
        let mfield = dart_ident(&m.name);
        writeln!(
            out,
            "  external ffi.Pointer<ffi.NativeFunction<_{pascal}{mp}Native>> {mfield};"
        );
    }
    writeln!(out, "}}");
    writeln!(out);
}
