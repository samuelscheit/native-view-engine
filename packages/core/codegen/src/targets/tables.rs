//! Host mirrors of the core `#[derive(NveTable)]` word tables (`nve_components::tables`):
//! table keys, storage, row width, per-word defaults, every field's `{word, shift, bits, kind}`
//! spec, the word enums those fields hold, and flag-bit sets. Hosts decode published
//! `NveTableView` rows from these instead of hand-written layouts.
//!
//! - `packages/core/host-cxx/include/nve/host/nve_tables.generated.h` (C11 / C++20, `table_word.h`)
//! - `hosts/swiftui-kit/Sources/NveSwiftUI/NveTables.generated.swift` (`NveHost.FieldSpec`)

use nve_abi::table::{FieldDesc, FieldKind, Storage, TableDesc};
use nve_components::tables as t;

use crate::naming::{to_camel_case, to_pascal_case, to_snake_case};
use crate::schema::export::GeneratedFile;
use crate::writer::CodeWriter;

/// One generated word enum: `(type name, variant names, variant values)`.
struct WordEnum {
    name: &'static str,
    names: &'static [&'static str],
    values: Vec<u32>,
}

macro_rules! word_enums {
    ($($ty:ident),+ $(,)?) => {
        vec![$(WordEnum {
            name: stringify!($ty),
            names: t::$ty::NAMES,
            values: t::$ty::ALL.iter().map(|v| v.to_word()).collect(),
        }),+]
    };
}

fn word_enums() -> Vec<WordEnum> {
    word_enums![
        Overflow, Visibility, FontStyle, TextAlign, WhiteSpace, WordBreak, OverflowWrap,
        VerticalAlign, ScrollAxes, Scrollbars, ImageFit, InputKind, LinkTarget, AriaRole,
        AriaTriState, AriaLive, AriaOrientation, AriaAutoComplete, Display, Position,
        FlexDirection, FlexWrap, AlignItems, AlignSelf, AlignContent, JustifyContent,
    ]
}

/// Named flag-bit sets stored in `u32`/bit fields: `(set name, [(flag, bit value)])`.
fn flag_sets() -> Vec<(&'static str, Vec<(&'static str, u32)>)> {
    use t::text_decoration as td;
    use t::Typography as ty;
    vec![
        (
            "TypographySet",
            vec![
                ("Color", ty::SET_COLOR),
                ("FontSize", ty::SET_FONT_SIZE),
                ("LineHeight", ty::SET_LINE_HEIGHT),
                ("LetterSpacing", ty::SET_LETTER_SPACING),
                ("FontFamily", ty::SET_FONT_FAMILY),
                ("MaxLines", ty::SET_MAX_LINES),
                ("FontWeight", ty::SET_FONT_WEIGHT),
                ("FontStyle", ty::SET_FONT_STYLE),
                ("WhiteSpace", ty::SET_WHITE_SPACE),
                ("WordBreak", ty::SET_WORD_BREAK),
                ("OverflowWrap", ty::SET_OVERFLOW_WRAP),
                ("TextAlign", ty::SET_TEXT_ALIGN),
                ("TextDecoration", ty::SET_TEXT_DECORATION),
                ("VerticalAlign", ty::SET_VERTICAL_ALIGN),
            ],
        ),
        (
            "TextDecoration",
            vec![
                ("Underline", u32::from(td::UNDERLINE)),
                ("Overline", u32::from(td::OVERLINE)),
                ("LineThrough", u32::from(td::LINE_THROUGH)),
            ],
        ),
    ]
}

/// `nve.text_input` → `TextInput`.
fn table_type_name(desc: &TableDesc) -> String {
    to_pascal_case(desc.name.trim_start_matches("nve."))
}

/// Bit width as the host `FieldSpec` stores it (`Str` spans two whole words: 32 per word).
fn spec_bits(f: &FieldDesc) -> u8 {
    if f.kind == FieldKind::Str { 32 } else { f.bits }
}

fn c_kind(kind: FieldKind) -> &'static str {
    match kind {
        FieldKind::U32 => "NVE_FIELD_U32",
        FieldKind::I32 => "NVE_FIELD_I32",
        FieldKind::F32 => "NVE_FIELD_F32",
        FieldKind::Bool => "NVE_FIELD_BOOL",
        FieldKind::Enum => "NVE_FIELD_ENUM",
        FieldKind::Color => "NVE_FIELD_COLOR",
        FieldKind::Length => "NVE_FIELD_LENGTH",
        FieldKind::Str => "NVE_FIELD_STR",
        FieldKind::Resource => "NVE_FIELD_RESOURCE",
        FieldKind::Node => "NVE_FIELD_NODE",
    }
}

fn swift_kind(kind: FieldKind) -> &'static str {
    match kind {
        FieldKind::U32 => ".u32",
        FieldKind::I32 => ".i32",
        FieldKind::F32 => ".f32",
        FieldKind::Bool => ".bool",
        FieldKind::Enum => ".enumeration",
        FieldKind::Color => ".color",
        FieldKind::Length => ".length",
        FieldKind::Str => ".str",
        FieldKind::Resource => ".resource",
        FieldKind::Node => ".node",
    }
}

/// Swift identifiers that collide with keywords get a trailing underscore.
fn swift_ident(name: &str) -> String {
    let ident = to_camel_case(name.trim_end_matches('_'));
    match ident.as_str() {
        "self" | "default" | "none" | "static" | "true" | "false" => format!("{ident}_"),
        _ => ident,
    }
}

fn c_upper(name: &str) -> String {
    to_snake_case(name.trim_end_matches('_')).to_ascii_uppercase()
}

/// Generates `nve_tables.generated.h`.
pub fn generate_c_tables_h() -> String {
    let mut out = CodeWriter::with_capacity(32 * 1024);
    writeln!(out, "/* @generated by nve-codegen (core table mirror generator) — DO NOT EDIT MANUALLY. */");
    writeln!(out, "/* Core `#[derive(NveTable)]` keys, word layouts, defaults, field specs, and enums. */");
    writeln!(out, "#ifndef NVE_TABLES_GENERATED_H");
    writeln!(out, "#define NVE_TABLES_GENERATED_H");
    writeln!(out);
    writeln!(out, "#include \"table_word.h\"");
    writeln!(out);
    for desc in t::CORE_TABLE_DESCS {
        let upper = c_upper(&table_type_name(desc));
        writeln!(out, "/* `{}` ({:?}) */", desc.name, desc.storage);
        writeln!(out, "#define NVE_TABLE_{upper}_KEY UINT64_C(0x{:016X})", desc.key.0);
        writeln!(out, "#define NVE_TABLE_{upper}_WORDS {}u", desc.defaults.len());
        writeln!(out, "#define NVE_TABLE_{upper}_SPARSE {}u", u8::from(desc.storage == Storage::Sparse));
        let defaults: Vec<String> = desc.defaults.iter().map(|w| format!("0x{w:08X}u")).collect();
        writeln!(
            out,
            "static const uint32_t NVE_TABLE_{upper}_DEFAULTS[{}] = {{{}}};",
            defaults.len(),
            defaults.join(", ")
        );
        for f in desc.fields {
            writeln!(
                out,
                "static const NveFieldSpec NVE_{upper}_{} = {{{}u, {}u, {}u, {}}};",
                c_upper(f.name),
                f.word,
                f.shift,
                spec_bits(f),
                c_kind(f.kind)
            );
        }
        writeln!(out);
    }
    for e in word_enums() {
        let upper = c_upper(e.name);
        for (name, value) in e.names.iter().zip(&e.values) {
            writeln!(out, "#define NVE_{upper}_{} {value}u", c_upper(name));
        }
        writeln!(out);
    }
    for (set, flags) in flag_sets() {
        let upper = c_upper(set);
        for (name, bit) in flags {
            writeln!(out, "#define NVE_{upper}_{} 0x{bit:X}u", c_upper(name));
        }
        writeln!(out);
    }
    writeln!(out, "#endif /* NVE_TABLES_GENERATED_H */");
    out.into_string()
}

/// Generates `NveTables.generated.swift`.
pub fn generate_swift_tables() -> String {
    let mut out = CodeWriter::with_capacity(32 * 1024);
    writeln!(out, "// @generated by nve-codegen (core table mirror generator) — DO NOT EDIT MANUALLY.");
    writeln!(out, "// Core `#[derive(NveTable)]` keys, word layouts, defaults, field specs, and enums.");
    writeln!(out);
    writeln!(out, "import NveHost");
    writeln!(out);
    writeln!(out, "/// Field specs are validated by `nve-codegen`; `try!` can never trap.");
    writeln!(out, "private func spec(_ word: UInt8, _ shift: UInt8, _ bits: UInt8, _ kind: FieldKind) -> FieldSpec {{");
    writeln!(out, "    try! FieldSpec(word: word, shift: shift, bits: bits, kind: kind)");
    writeln!(out, "}}");
    writeln!(out);
    writeln!(out, "public enum NveTables {{");
    for desc in t::CORE_TABLE_DESCS {
        writeln!(out, "    /// `{}` ({:?}).", desc.name, desc.storage);
        writeln!(out, "    public enum {} {{", table_type_name(desc));
        writeln!(out, "        public static let key = Key64(0x{:016X})", desc.key.0);
        writeln!(out, "        public static let words = {}", desc.defaults.len());
        writeln!(out, "        public static let isSparse = {}", desc.storage == Storage::Sparse);
        let defaults: Vec<String> = desc.defaults.iter().map(|w| format!("0x{w:08X}")).collect();
        writeln!(out, "        public static let defaults: [UInt32] = [{}]", defaults.join(", "));
        for f in desc.fields {
            writeln!(
                out,
                "        public static let {} = spec({}, {}, {}, {})",
                swift_ident(f.name),
                f.word,
                f.shift,
                spec_bits(f),
                swift_kind(f.kind)
            );
        }
        writeln!(out, "    }}");
    }
    writeln!(out, "}}");
    for e in word_enums() {
        writeln!(out);
        writeln!(out, "public enum Nve{}: UInt32, Sendable, CaseIterable {{", e.name);
        for (name, value) in e.names.iter().zip(&e.values) {
            writeln!(out, "    case {} = {value}", swift_ident(name));
        }
        writeln!(out, "}}");
    }
    for (set, flags) in flag_sets() {
        writeln!(out);
        writeln!(out, "public enum Nve{set} {{");
        for (name, bit) in flags {
            writeln!(out, "    public static let {}: UInt32 = 0x{bit:X}", swift_ident(name));
        }
        writeln!(out, "}}");
    }
    out.into_string()
}

/// Generates every core table mirror keyed by workspace-relative path.
pub fn generate_all_table_files() -> Vec<GeneratedFile> {
    vec![
        GeneratedFile {
            relative_path: "packages/core/host-cxx/include/nve/host/nve_tables.generated.h".to_owned(),
            content: generate_c_tables_h(),
        },
        GeneratedFile {
            relative_path: "hosts/swiftui-kit/Sources/NveSwiftUI/NveTables.generated.swift".to_owned(),
            content: generate_swift_tables(),
        },
    ]
}
