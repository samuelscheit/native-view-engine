//! Single-source **XXH64** host mirrors (`nve_hash.generated.*`) of the canonical Rust `nve-hash`
//! crate: C11, constexpr C++20, Swift, Java, and 53-bit-safe Dart / TypeScript (digests as
//! `(lo, hi)` `u32` halves, never `BigInt`). Every file embeds the same golden vectors, computed
//! here by `nve_hash::xxh64`, plus a self-check (`verify…TestVectors`) covering one-shot and
//! chunked streaming digests.

mod c;
mod dart;
mod java;
mod swift;
mod typescript;

use nve_hash::{xxh64, PRIME1};

use crate::schema::export::GeneratedFile;

/// `NveWireFrame` v2 trailer seed (`"NVEWIRE2"`), the seed every pairing host uses.
pub const WIRE_XXH64_SEED: u64 = 0x4E56_4557_4952_4532;

const SEQ_LEN: usize = 101;

/// 101 bytes: three full 32-byte stripes plus an 8 + 4 + 1 byte tail, so every branch runs.
const SEQ: [u8; SEQ_LEN] = {
    let mut out = [0u8; SEQ_LEN];
    let mut i = 0;
    while i < SEQ_LEN {
        out[i] = (i * 31 + 7) as u8;
        i += 1;
    }
    out
};

/// One golden vector shared by every host mirror.
#[derive(Debug, Clone, Copy)]
pub struct HashVector {
    pub label: &'static str,
    pub bytes: &'static [u8],
    pub seed: u64,
}

impl HashVector {
    pub const fn expected(&self) -> u64 {
        xxh64(self.bytes, self.seed)
    }
}

/// Golden vectors: empty input, short tails, a reverse-DNS key, high-bit bytes, multi-stripe
/// input, and seeds with the high bit set (wire seed, `PRIME1`).
pub const HASH_VECTORS: &[HashVector] = &[
    HashVector { label: "empty", bytes: b"", seed: 0 },
    HashVector { label: "a", bytes: b"a", seed: 0 },
    HashVector { label: "abc", bytes: b"abc", seed: 0 },
    HashVector { label: "nve_visual", bytes: b"nve.visual", seed: 0 },
    HashVector { label: "high_bits", bytes: &[0x00, 0x01, 0x7F, 0x80, 0xFF], seed: 0 },
    HashVector { label: "seq101", bytes: &SEQ, seed: 0 },
    HashVector { label: "seq101_wire_seed", bytes: &SEQ, seed: WIRE_XXH64_SEED },
    HashVector { label: "seq37_prime1_seed", bytes: SEQ.split_at(37).0, seed: PRIME1 },
];

/// Chunk boundaries every self-check streams each vector through (clamped to its length).
pub const STREAM_SPLITS: [usize; 3] = [1, 7, 33];

/// Generates every `nve_hash.generated.*` host mirror keyed by workspace-relative path.
pub fn generate_all_hash_files() -> Vec<GeneratedFile> {
    [
        ("cxx/nve-fabric-bridge/include/nve_hash.generated.h", c::generate_c_hash()),
        ("cxx/nve-fabric-bridge/include/nve_hash.generated.hpp", c::generate_cpp_hash()),
        ("hosts/swiftui-kit/Sources/NveSwiftUI/NveHash.generated.swift", swift::generate_swift_hash()),
        ("hosts/flutter-plugin/lib/src/nve_hash.generated.dart", dart::generate_dart_hash()),
        ("hosts/web-shell/nve_hash.generated.ts", typescript::generate_ts_hash()),
        (
            "hosts/android-shell/android-app/src/dev/nve/android/generated/NveHash.java",
            java::generate_java_hash(),
        ),
    ]
    .into_iter()
    .map(|(path, content)| GeneratedFile { relative_path: path.to_owned(), content })
    .collect()
}

/// `// @generated` banner shared by every C-family mirror (C, C++, Swift, Dart, TS, Java).
fn banner() -> String {
    format!(
        "// @generated by nve-codegen (packages/core/codegen/src/targets/hash) — DO NOT EDIT MANUALLY.\n\
         // Canonical XXH64 mirror of the Rust `nve-hash` crate ({} golden vectors).\n",
        HASH_VECTORS.len()
    )
}

/// Comma-separated byte list with a per-byte formatter (`0x7Fu`, `0x7F`, `(byte) 0x7F`, ...).
fn byte_list(bytes: &[u8], fmt: impl Fn(u8) -> String) -> String {
    bytes.iter().map(|&b| fmt(b)).collect::<Vec<_>>().join(", ")
}

/// Splits `v` into `(lo, hi)` `u32` halves.
const fn halves(v: u64) -> (u32, u32) {
    (v as u32, (v >> 32) as u32)
}
