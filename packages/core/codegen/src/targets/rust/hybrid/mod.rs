//! Rust target emitter for NVE Hybrid FFI codegen.
//!
//! Emits a self-contained Rust module (`<stem>_hybrid.generated.rs`) with no JSON dependencies:
//! - `#[repr(u32)]` enums with safe `from_u32` / `to_u32`
//! - `#[repr(C)]` POD structs (passed directly by value) and idiomatic owned Rust structs
//! - Direct C-ABI `NveHybridOwnedBytes`, `NveHybridStatus`, and POD `NveHybridOpt*` structs
//! - Strict `pub trait <Name>Hybrid` contracts
//! - `#[repr(C)] pub struct NveHybrid<Name>VTable` with `abi_version`, `interface_id`,
//!   `schema_hash`, `create`, `destroy`, `alloc_bytes`, `free_bytes`, and direct `extern "C"`
//!   trampolines (`build_<snake>_vtable::<Impl>()`)
//! - For `HybridView`: typed `<Name>Props`, zero-copy `decode_props_direct(&[NveMapEntry])`,
//!   typed event payload structs, uniform 64-byte `EventBatchBuf` emitters, and compact binary
//!   `NveBinValue` encoders (`encode_bin`).

