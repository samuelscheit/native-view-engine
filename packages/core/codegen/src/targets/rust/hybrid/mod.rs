//! Rust target of NVE hybrid FFI codegen.
//!
//! Emits `<stem>_hybrid.generated.rs` holding only what a spec decides: `#[repr(u32)]` enums,
//! `#[repr(C)]` POD and owned structs, POD `NveHybridOpt*` options, `<Name>Hybrid` traits,
//! `#[repr(C)]` vtables with `extern "C"` trampolines (`build_<name>_vtable::<Impl>()`), and typed
//! view props / events. Everything static (owned C buffers, status codes, the `NveBinValue` codec
//! of every type, trampoline error plumbing) is the checked-in `nve_abi::hybrid` runtime.
//!
//! Generated code names every `nve_abi` item by its path and imports nothing, so no spec can make
//! it emit an unused (or shadowed) import.

mod type_map;
mod types_emitter;
mod view_emitter;
mod vtable_emitter;

use crate::error::CodegenError;
use crate::naming::sanitize_single_line_comment;
use crate::schema::export::GeneratedFile;
use crate::schema::hybrid::HybridFileSpec;
use crate::writer::CodeWriter;

use type_map::CodecSupport;
use types_emitter::{emit_pod_option_structs, emit_rust_enum, emit_rust_struct};
use view_emitter::{emit_rust_module, emit_rust_view};

/// Emits the Rust hybrid bindings of `spec` over the `nve_abi::hybrid` runtime.
pub fn generate_hybrid_rust(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let codec = CodecSupport::new(spec);
    codec.check_members(spec)?;

    let mut body = CodeWriter::with_capacity(16 * 1024);
    writeln!(
        body,
        "/// File-wide deterministic XXH64 schema hash across all declared hybrid items."
    );
    writeln!(
        body,
        "pub const NVE_HYBRID_FILE_SCHEMA_HASH: u64 = 0x{:016X};",
        spec.file_schema_hash()
    );
    writeln!(body);
    for e in &spec.enums {
        emit_rust_enum(&mut body, e);
    }
    for s in spec.structs_topological() {
        emit_rust_struct(&mut body, s, spec, &codec);
    }
    emit_pod_option_structs(&mut body, spec);
    for m in &spec.modules {
        emit_rust_module(&mut body, m, spec);
    }
    for v in &spec.views {
        emit_rust_view(&mut body, v, spec);
    }

    let mut out = CodeWriter::with_capacity(body.len() + 1024);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid Rust target) — DO NOT EDIT."
    );
    writeln!(
        out,
        "// Spec-specific bindings over the static `nve_abi::hybrid` runtime. Trampolines rely on the"
    );
    writeln!(
        out,
        "// vtable's C contract (live handles, valid slices) rather than per-block safety comments."
    );
    writeln!(
        out,
        "#![allow(clippy::too_many_arguments, clippy::undocumented_unsafe_blocks)]"
    );
    writeln!(out);
    writeln!(out, "pub use nve_abi::hybrid::{{");
    writeln!(
        out,
        "    NveHybridOwnedBytes, NveHybridStatus, NveHybridValue, NVE_HYBRID_ABI_VERSION,"
    );
    writeln!(out, "}};");
    writeln!(out);
    out.push_str(&body);

    Ok(vec![GeneratedFile {
        relative_path: format!("{}_hybrid.generated.rs", spec.stem_snake()),
        content: out.into_string(),
    }])
}

fn emit_doc_comments(out: &mut CodeWriter, indent: &str, doc: Option<&str>) {
    for line in doc.into_iter().flat_map(str::lines) {
        writeln!(out, "{indent}/// {}", sanitize_single_line_comment(line));
    }
}
