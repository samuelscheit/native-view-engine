/// Emits the Rust Hybrid FFI contract, direct C-ABI vtables, and zero-copy prop/event helpers.
pub fn generate_hybrid_rust(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_snake();
    let mut body = CodeWriter::with_capacity(16 * 1024);
    emit_common_rust_abi(&mut body, spec);

    for e in &spec.enums {
        emit_rust_enum(&mut body, e);
    }

    for s in spec.structs_topological() {
        emit_rust_struct(&mut body, s, spec);
    }

    emit_pod_option_structs(&mut body, spec);

    for m in &spec.modules {
        emit_rust_module(&mut body, m, spec);
    }

    for v in &spec.views {
        emit_rust_view(&mut body, v, spec);
    }

    let mut out = CodeWriter::with_capacity(body.len() + 512);
    writeln!(out, "// @generated by nve-codegen (hybrid Rust target) — DO NOT EDIT.");
    writeln!(out, "// Binary, direct C-ABI vtable bindings backed by `nve_abi`.");
    writeln!(out, "#![allow(clippy::too_many_arguments)]");
    writeln!(out);
    const NVE_ABI_IMPORTS: &[&str] = &[
        "BinValueView",
        "DecodeError",
        "EventBatchBuf",
        "NveAppHandle",
        "NveBufferSlice",
        "NveMapEntry",
        "NveMapRef",
        "NveStrSlice",
        "NveValue",
        "NveValueRef",
        "NveValueTag",
    ];
    let used_imports: Vec<&str> = NVE_ABI_IMPORTS
        .iter()
        .copied()
        .filter(|sym| contains_rust_ident(&body, sym))
        .collect();
    if !used_imports.is_empty() {
        writeln!(out, "use nve_abi::{{\n    {},\n}};", used_imports.join(", "));
        writeln!(out);
    }
    out.push_str(&body);

    Ok(vec![GeneratedFile {
        relative_path: format!("{stem}_hybrid.generated.rs"),
        content: out.into_string(),
    }])
}

fn emit_common_rust_abi(out: &mut CodeWriter, spec: &HybridFileSpec) {
    writeln!(out, "/// Current Hybrid FFI vtable ABI version.");
    writeln!(out, "pub const NVE_HYBRID_ABI_VERSION: u32 = {NVE_HYBRID_ABI_VERSION};");
    writeln!(
        out,
        "/// File-wide deterministic XXH64 schema hash across all declared hybrid items."
    );
    writeln!(
        out,
        "pub const NVE_HYBRID_FILE_SCHEMA_HASH: u64 = 0x{:016X};",
        spec.file_schema_hash()
    );
    writeln!(out);

    writeln!(
        out,
        r#"/// Status code returned by fallible Hybrid FFI trampolines.
#[repr(i32)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NveHybridStatus {{
    Ok = 0,
    Err = 1,
    InvalidArg = 2,
    SchemaMismatch = 3,
    NullHandle = 4,
}}

/// Rust-allocated owned byte buffer returned across the C ABI.
/// Foreign callers MUST release non-null buffers via the vtable's `free_bytes`.
#[repr(C)]
#[derive(Debug, Clone, Copy)]
pub struct NveHybridOwnedBytes {{
    pub ptr: *mut u8,
    pub len: usize,
    pub cap: usize,
}}

impl NveHybridOwnedBytes {{
    pub const EMPTY: Self = Self {{
        ptr: std::ptr::null_mut(),
        len: 0,
        cap: 0,
    }};

    #[inline]
    pub fn from_vec(mut v: Vec<u8>) -> Self {{
        if v.is_empty() {{
            return Self::EMPTY;
        }}
        let ptr = v.as_mut_ptr();
        let len = v.len();
        let cap = v.capacity();
        std::mem::forget(v);
        Self {{ ptr, len, cap }}
    }}

    #[inline]
    pub fn from_string(s: String) -> Self {{
        Self::from_vec(s.into_bytes())
    }}

    /// # Safety
    /// Must only be called once on a buffer previously allocated by `alloc_bytes` / `from_vec`.
    #[inline]
    pub unsafe fn free(self) {{
        if !self.ptr.is_null() && self.cap > 0 {{
            let _ = unsafe {{ Vec::from_raw_parts(self.ptr, self.len, self.cap) }};
        }}
    }}
}}

/// Owned dynamic value crossing Hybrid FFI as compact binary `NveBinValue` (binary).
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct NveHybridValue {{
    pub bin_bytes: Vec<u8>,
}}

impl NveHybridValue {{
    #[inline]
    pub fn null() -> Self {{
        Self {{
            bin_bytes: vec![NveValueTag::Null as u8],
        }}
    }}

    #[inline]
    pub fn from_ffi_ref(value: NveValueRef<'_>) -> Result<Self, DecodeError> {{
        Ok(Self {{
            bin_bytes: nve_abi::encode_bin_value_to_vec(value)?,
        }})
    }}

    #[inline]
    pub fn as_view(&self) -> Result<BinValueView<'_>, DecodeError> {{
        BinValueView::parse(&self.bin_bytes)
    }}
}}

#[inline]
pub unsafe extern "C" fn nve_hybrid_alloc_bytes(len: usize) -> NveHybridOwnedBytes {{
    if len == 0 {{
        return NveHybridOwnedBytes::EMPTY;
    }}
    let buf = vec![0u8; len];
    NveHybridOwnedBytes::from_vec(buf)
}}

#[inline]
pub unsafe extern "C" fn nve_hybrid_free_bytes(buf: NveHybridOwnedBytes) {{
    unsafe {{ buf.free() }};
}}

/// Compact binary `NveBinValue` writer helpers matching `nve_abi::encode_bin_value` byte-for-byte.
pub mod nve_bin_codec {{
    use nve_abi::{{BinValueView, DecodeError, NveValueTag}};

    #[inline]
    pub fn write_null(out: &mut Vec<u8>) {{
        out.push(NveValueTag::Null as u8);
    }}

    #[inline]
    pub fn write_bool(out: &mut Vec<u8>, v: bool) {{
        out.push(NveValueTag::Bool as u8);
        out.push(u8::from(v));
    }}

    #[inline]
    pub fn write_i64(out: &mut Vec<u8>, v: i64) {{
        out.push(NveValueTag::I64 as u8);
        out.extend_from_slice(&v.to_le_bytes());
    }}

    #[inline]
    pub fn write_f64(out: &mut Vec<u8>, v: f64) {{
        out.push(NveValueTag::F64 as u8);
        out.extend_from_slice(&v.to_le_bytes());
    }}

    #[inline]
    pub fn write_str(out: &mut Vec<u8>, s: &str) {{
        let b = s.as_bytes();
        out.push(NveValueTag::Str as u8);
        out.extend_from_slice(&(b.len() as u32).to_le_bytes());
        out.extend_from_slice(b);
    }}

    #[inline]
    pub fn write_bytes(out: &mut Vec<u8>, b: &[u8]) {{
        out.push(NveValueTag::Bytes as u8);
        out.extend_from_slice(&(b.len() as u32).to_le_bytes());
        out.extend_from_slice(b);
    }}

    #[inline]
    pub fn write_array<F: FnOnce(&mut Vec<u8>)>(out: &mut Vec<u8>, count: usize, f: F) {{
        out.push(NveValueTag::Array as u8);
        let len_pos = out.len();
        out.extend_from_slice(&0u32.to_le_bytes());
        let start = out.len();
        out.extend_from_slice(&(count as u32).to_le_bytes());
        f(out);
        let payload_len = (out.len() - start) as u32;
        out[len_pos..len_pos + 4].copy_from_slice(&payload_len.to_le_bytes());
    }}

    #[inline]
    pub fn write_map<F: FnOnce(&mut Vec<u8>)>(out: &mut Vec<u8>, count: usize, f: F) {{
        out.push(NveValueTag::Map as u8);
        let len_pos = out.len();
        out.extend_from_slice(&0u32.to_le_bytes());
        let start = out.len();
        out.extend_from_slice(&(count as u32).to_le_bytes());
        f(out);
        let payload_len = (out.len() - start) as u32;
        out[len_pos..len_pos + 4].copy_from_slice(&payload_len.to_le_bytes());
    }}

    #[inline]
    pub fn write_map_key(out: &mut Vec<u8>, key: &str) {{
        let kb = key.as_bytes();
        out.extend_from_slice(&(kb.len() as u32).to_le_bytes());
        out.extend_from_slice(kb);
    }}

    #[inline]
    pub fn parse_view(bytes: &[u8]) -> Result<BinValueView<'_>, DecodeError> {{
        BinValueView::parse(bytes)
    }}
}}
"#
    );
}

fn emit_doc_comments(out: &mut CodeWriter, indent: &str, doc: Option<&str>) {
    if let Some(d) = doc {
        for line in d.lines() {
            writeln!(out, "{indent}/// {}", sanitize_single_line_comment(line));
        }
    }
}

fn contains_rust_ident(haystack: &str, ident: &str) -> bool {
    let bytes = haystack.as_bytes();
    let mut start = 0;
    while let Some(pos) = haystack[start..].find(ident) {
        let abs = start + pos;
        let end = abs + ident.len();
        let before_ok = abs == 0 || !(bytes[abs - 1].is_ascii_alphanumeric() || bytes[abs - 1] == b'_');
        let after_ok = end == bytes.len() || !(bytes[end].is_ascii_alphanumeric() || bytes[end] == b'_');
        if before_ok && after_ok {
            return true;
        }
        start = abs + 1;
    }
    false
}

