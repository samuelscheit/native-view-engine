//! Standalone zero-dependency Rust emitter for NVE's zero-copy `RelocSlice` binary slab schema.
//!
//! Emits a self-contained Rust 2024 module (`<snake>_reloc.generated.rs`) containing:
//! - `RelocHeader` (32 bytes, 8-byte aligned), `RelocSlice<T>` (8 bytes), `RelocStr` (8 bytes)
//! - `VerifyMode::{Full, HeaderOnly, Unchecked}` + `RelocError`
//! - `view_full`, `view_header_only`, `view_unchecked` (0 runtime checks!), and `view`
//! - `#[repr(u8/u16/u32)]` enums and `#[repr(C)]` structs with `as_bytes()` for zero-padding PODs
//! - Compile-time `size_of!` / `offset_of!` assertions and safe `SlabBuilder` + `AlignedSlab`.

use std::fmt::Write as _;

use super::reloc_runtime::{emit_core_primitives, emit_slab_builder};
use crate::error::CodegenError;
use crate::naming::to_snake_case;
use crate::schema::export::GeneratedFile;
use crate::schema::reloc::ir::{
    RelocEnum, RelocEnumRepr, RelocSchema, RelocStruct, RelocType, StructLayout,
    RELOC_HEADER_ALIGN, RELOC_HEADER_SIZE, RELOC_MAX_VERIFY_DEPTH,
};

/// Generates a standalone Rust 2024 zero-copy reloc module (`<snake>_reloc.generated.rs`).
pub fn generate_reloc_rust(schema: &RelocSchema) -> Result<GeneratedFile, CodegenError> {
    let layouts = schema.compute_layouts()?;
    let schema_hash = schema.schema_hash_with_layouts(&layouts);
    let slab_align = schema.slab_align(&layouts);
    let snake = to_snake_case(&schema.name);

    let mut out = String::with_capacity(16 * 1024);
    emit_preamble(&mut out, schema, schema_hash, slab_align);
    emit_core_primitives(&mut out);

    for e in &schema.enums {
        emit_enum(&mut out, e);
    }

    for s in schema.structs_topological() {
        emit_struct(&mut out, s, &layouts[&s.name]);
    }

    emit_view_entrypoints(&mut out, schema, &layouts[&schema.root]);
    emit_slab_builder(&mut out, schema, slab_align);

    Ok(GeneratedFile {
        relative_path: format!("{snake}_reloc.generated.rs"),
        content: out,
    })
}

fn emit_preamble(out: &mut String, schema: &RelocSchema, schema_hash: u64, slab_align: usize) {
    let magic_bytes: Vec<String> = schema.magic.iter().map(|b| format!("0x{b:02X}")).collect();
    writeln!(
        out,
        "// @generated by nve-codegen (zero-copy RelocSlice Rust emitter) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(out, "#![allow(dead_code)]").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "use core::fmt;").unwrap();
    writeln!(out, "use core::marker::PhantomData;").unwrap();
    writeln!(out, "use core::mem::{{align_of, offset_of, size_of}};").unwrap();
    writeln!(out, "use core::slice;").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "/// 8-byte binary slab magic for schema `{}`.",
        schema.name
    )
    .unwrap();
    writeln!(
        out,
        "pub const SCHEMA_MAGIC: [u8; 8] = [{}];",
        magic_bytes.join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "/// Deterministic FNV-1a64 schema hash (changes on any layout or variant mutation)."
    )
    .unwrap();
    writeln!(out, "pub const SCHEMA_HASH: u64 = 0x{schema_hash:016X};").unwrap();
    writeln!(out, "pub const HEADER_SIZE: usize = {RELOC_HEADER_SIZE};").unwrap();
    writeln!(out, "pub const HEADER_ALIGN: usize = {RELOC_HEADER_ALIGN};").unwrap();
    writeln!(out, "pub const SLAB_ALIGN: usize = {slab_align};").unwrap();
    writeln!(
        out,
        "pub const MAX_VERIFY_DEPTH: usize = {RELOC_MAX_VERIFY_DEPTH};"
    )
    .unwrap();
    writeln!(out).unwrap();
}

fn emit_enum(out: &mut String, e: &RelocEnum) {
    let repr = e.repr.rust_type();
    if let Some(doc) = &e.doc {
        for line in doc.lines() {
            writeln!(out, "/// {line}").unwrap();
        }
    }
    writeln!(out, "#[repr({repr})]").unwrap();
    writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]").unwrap();
    writeln!(out, "pub enum {} {{", e.name).unwrap();
    for v in &e.variants {
        if let Some(doc) = &v.doc {
            for line in doc.lines() {
                writeln!(out, "    /// {line}").unwrap();
            }
        }
        writeln!(out, "    {} = {},", v.name, v.value).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "impl {} {{", e.name).unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    pub const fn to_raw(self) -> {repr} {{").unwrap();
    writeln!(out, "        self as {repr}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    pub const fn from_raw(raw: {repr}) -> Option<Self> {{").unwrap();
    writeln!(out, "        match raw {{").unwrap();
    for v in &e.variants {
        writeln!(out, "            {} => Some(Self::{}),", v.value, v.name).unwrap();
    }
    writeln!(out, "            _ => None,").unwrap();
    writeln!(out, "        }}").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    let raw_read = match e.repr {
        RelocEnumRepr::U8 => "slab[base]".to_string(),
        RelocEnumRepr::U16 => "u16::from_le_bytes([slab[base], slab[base + 1]])".to_string(),
        RelocEnumRepr::U32 => "read_u32_le(slab, base)".to_string(),
    };
    writeln!(out, "impl RelocVerify for {} {{", e.name).unwrap();
    writeln!(out, "    const NEEDS_VERIFY: bool = true;").unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(
        out,
        "    fn verify_bytes(slab: &[u8], _total_len: usize, base: usize, _depth: usize) -> Result<(), RelocError> {{"
    )
    .unwrap();
    writeln!(out, "        let raw = {raw_read};").unwrap();
    writeln!(
        out,
        "        Self::from_raw(raw).map(|_| ()).ok_or(RelocError::InvalidEnumDiscriminant)"
    )
    .unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "    #[inline]").unwrap();
    writeln!(out, "    fn write_le_bytes(&self, dst: &mut [u8]) {{").unwrap();
    writeln!(
        out,
        "        dst[..size_of::<{repr}>()].copy_from_slice(&self.to_raw().to_le_bytes());"
    )
    .unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();
}

fn emit_struct(out: &mut String, s: &RelocStruct, layout: &StructLayout) {
    if let Some(doc) = &s.doc {
        for line in doc.lines() {
            writeln!(out, "/// {line}").unwrap();
        }
    }
    if let Some(align) = s.align {
        writeln!(out, "#[repr(C, align({align}))]").unwrap();
    } else {
        writeln!(out, "#[repr(C)]").unwrap();
    }
    writeln!(out, "#[derive(Debug, Clone, Copy, PartialEq)]").unwrap();
    writeln!(out, "pub struct {} {{", s.name).unwrap();
    for f in &s.fields {
        if let Some(doc) = &f.doc {
            for line in doc.lines() {
                writeln!(out, "    /// {line}").unwrap();
            }
        }
        let fname = reloc_rust_ident(&f.name);
        writeln!(out, "    pub {fname}: {},", rust_type(&f.ty)).unwrap();
    }
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    if layout.is_pure_pod {
        writeln!(out, "impl {} {{", s.name).unwrap();
        writeln!(
            out,
            "    /// Zero-copy view as raw bytes (verified zero implicit padding at compile time)."
        )
        .unwrap();
        writeln!(out, "    #[inline]").unwrap();
        writeln!(out, "    pub fn as_bytes(&self) -> &[u8] {{").unwrap();
        writeln!(
            out,
            "        unsafe {{ slice::from_raw_parts((self as *const Self).cast::<u8>(), size_of::<Self>()) }}"
        )
        .unwrap();
        writeln!(out, "    }}").unwrap();
        writeln!(out, "}}").unwrap();
        writeln!(out).unwrap();
    }

    writeln!(out, "impl RelocVerify for {} {{", s.name).unwrap();
    writeln!(
        out,
        "    const NEEDS_VERIFY: bool = {};",
        layout.needs_value_verify
    )
    .unwrap();
    if layout.needs_value_verify {
        writeln!(
            out,
            "    fn verify_bytes(slab: &[u8], total_len: usize, base: usize, depth: usize) -> Result<(), RelocError> {{"
        )
        .unwrap();
        for (f, fl) in s.fields.iter().zip(layout.fields.iter()) {
            let ty_str = rust_type(&f.ty);
            writeln!(
                out,
                "        if <{ty_str} as RelocVerify>::NEEDS_VERIFY {{"
            )
            .unwrap();
            writeln!(
                out,
                "            <{ty_str} as RelocVerify>::verify_bytes(slab, total_len, base + {}, depth)?;",
                fl.offset
            )
            .unwrap();
            writeln!(out, "        }}").unwrap();
        }
        writeln!(out, "        Ok(())").unwrap();
        writeln!(out, "    }}").unwrap();
    } else {
        writeln!(
            out,
            "    #[inline]\n    fn verify_bytes(_slab: &[u8], _total_len: usize, _base: usize, _depth: usize) -> Result<(), RelocError> {{ Ok(()) }}"
        )
        .unwrap();
    }
    writeln!(out, "    fn write_le_bytes(&self, dst: &mut [u8]) {{").unwrap();
    writeln!(out, "        dst[..{}].fill(0);", layout.size).unwrap();
    for (f, fl) in s.fields.iter().zip(layout.fields.iter()) {
        let fname = reloc_rust_ident(&f.name);
        let end = fl.offset + fl.size;
        writeln!(
            out,
            "        self.{fname}.write_le_bytes(&mut dst[{}..{end}]);",
            fl.offset
        )
        .unwrap();
    }
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "const _: () = {{").unwrap();
    writeln!(
        out,
        "    assert!(size_of::<{}>() == {});",
        s.name, layout.size
    )
    .unwrap();
    writeln!(
        out,
        "    assert!(align_of::<{}>() == {});",
        s.name, layout.align
    )
    .unwrap();
    for fl in &layout.fields {
        let fname = reloc_rust_ident(&fl.name);
        writeln!(
            out,
            "    assert!(offset_of!({}, {fname}) == {});",
            s.name, fl.offset
        )
        .unwrap();
    }
    if layout.is_pure_pod {
        let field_sum: usize = layout.fields.iter().map(|f| f.size).sum();
        writeln!(out, "    assert!(size_of::<{}>() == {field_sum});", s.name).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();
}

fn emit_view_entrypoints(out: &mut String, schema: &RelocSchema, root_layout: &StructLayout) {
    let root = &schema.root;
    let root_size = root_layout.size;
    let root_align = root_layout.align;
    writeln!(
        out,
        r#"fn verify_header_common(buf: &[u8]) -> Result<(usize, usize), RelocError> {{
    if buf.len() < HEADER_SIZE {{
        return Err(RelocError::Truncated);
    }}
    let base_addr = buf.as_ptr() as usize;
    if !base_addr.is_multiple_of(SLAB_ALIGN) {{
        return Err(RelocError::Misaligned);
    }}
    if buf[0..8] != SCHEMA_MAGIC {{
        return Err(RelocError::InvalidMagic);
    }}
    if read_u64_le(buf, 8) != SCHEMA_HASH {{
        return Err(RelocError::SchemaHashMismatch);
    }}
    let total_len = read_u32_le(buf, 16) as usize;
    if total_len < HEADER_SIZE || total_len > buf.len() {{
        return Err(RelocError::Truncated);
    }}
    let root_offset = read_u32_le(buf, 24) as usize;
    if root_offset < HEADER_SIZE {{
        return Err(RelocError::OutOfBounds);
    }}
    if !root_offset.is_multiple_of({root_align}) || !base_addr.wrapping_add(root_offset).is_multiple_of({root_align}) {{
        return Err(RelocError::Misaligned);
    }}
    let root_end = root_offset.checked_add({root_size}).ok_or(RelocError::LengthOverflow)?;
    if root_end > total_len {{
        return Err(RelocError::OutOfBounds);
    }}
    Ok((total_len, root_offset))
}}

/// Safe, full recursive zero-copy verification (`VerifyMode::Full`) for untrusted slabs.
pub fn view_full<'a>(buf: &'a [u8]) -> Result<&'a {root}, RelocError> {{
    let (total_len, root_offset) = verify_header_common(buf)?;
    <{root} as RelocVerify>::verify_bytes(buf, total_len, root_offset, 0)?;
    Ok(unsafe {{ &*(buf.as_ptr().add(root_offset).cast::<{root}>()) }})
}}

/// O(1) header-only zero-copy verification (`VerifyMode::HeaderOnly`) for trusted local `mmap`
/// caches or compiled-in static assets.
///
/// # Safety
/// Caller guarantees all internal slice bounds, UTF-8 strings, booleans, and enum discriminants
/// inside `buf` are valid.
pub unsafe fn view_header_only<'a>(buf: &'a [u8]) -> Result<&'a {root}, RelocError> {{
    let (_total_len, root_offset) = verify_header_common(buf)?;
    Ok(unsafe {{ &*(buf.as_ptr().add(root_offset).cast::<{root}>()) }})
}}

/// Zero-check raw pointer cast (`VerifyMode::Unchecked`). Literally 0 runtime checks.
///
/// # Safety
/// Caller guarantees `buf` is aligned to `SLAB_ALIGN`, holds a valid `RelocHeader` and `{root}`
/// at `header.root_offset`, and satisfies all Rust validity invariants.
#[inline]
pub unsafe fn view_unchecked<'a>(buf: &'a [u8]) -> &'a {root} {{
    unsafe {{
        let hdr = &*(buf.as_ptr().cast::<RelocHeader>());
        &*(buf.as_ptr().add(hdr.root_offset as usize).cast::<{root}>())
    }}
}}

/// Unified zero-copy view entry point dispatching on [`VerifyMode`].
///
/// # Safety
/// When `mode` is [`VerifyMode::HeaderOnly`] or [`VerifyMode::Unchecked`], caller must uphold
/// the corresponding safety preconditions of [`view_header_only`] / [`view_unchecked`].
/// When `mode` is [`VerifyMode::Full`], this function performs complete verification and is safe
/// for untrusted inputs.
pub unsafe fn view<'a>(buf: &'a [u8], mode: VerifyMode) -> Result<&'a {root}, RelocError> {{
    match mode {{
        VerifyMode::Full => view_full(buf),
        VerifyMode::HeaderOnly => unsafe {{ view_header_only(buf) }},
        VerifyMode::Unchecked => Ok(unsafe {{ view_unchecked(buf) }}),
    }}
}}
"#
    )
    .unwrap();
}

fn reloc_rust_ident(name: &str) -> String {
    match name {
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false"
        | "fn" | "for" | "if" | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move"
        | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct" | "super"
        | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await"
        | "dyn" => format!("r#{name}"),
        _ => name.to_string(),
    }
}

fn rust_type(ty: &RelocType) -> String {
    match ty {
        RelocType::Bool => "bool".to_string(),
        RelocType::U8 => "u8".to_string(),
        RelocType::I8 => "i8".to_string(),
        RelocType::U16 => "u16".to_string(),
        RelocType::I16 => "i16".to_string(),
        RelocType::U32 => "u32".to_string(),
        RelocType::I32 => "i32".to_string(),
        RelocType::F32 => "f32".to_string(),
        RelocType::U64 => "u64".to_string(),
        RelocType::I64 => "i64".to_string(),
        RelocType::F64 => "f64".to_string(),
        RelocType::FixedArray { elem, len } => format!("[{}; {len}]", rust_type(elem)),
        RelocType::Enum(name) | RelocType::Struct(name) => name.clone(),
        RelocType::RelocSlice(elem) => format!("RelocSlice<{}>", rust_type(elem)),
        RelocType::RelocStr => "RelocStr".to_string(),
    }
}
