use super::core_abi::c_core_type;
use crate::schema::hybrid::core_abi::{
    compute_scene_schema_hash, scene_abi_spec, ResolvedSceneAbi,
};
use crate::schema::hybrid::HybridType;
use crate::writer::CodeWriter;

// ============================================================================
// Scene ABI Target 1 & 2: C11 / C++20 / Swift (`nve_scene_abi.generated.h`)
// ============================================================================

/// Generates `nve_scene_abi.generated.h` (used identically by
/// `cxx/nve-fabric-bridge/include/nve_scene_abi.generated.h` and
/// `hosts/swiftui-kit/Sources/CNveAbi/include/nve_scene_abi.generated.h`) directly from
/// `packages/core/abi/src/schema.rs`.
pub fn generate_c_scene_abi_h() -> String {
    let spec = scene_abi_spec();
    let schema_hash = compute_scene_schema_hash(&spec);
    let ResolvedSceneAbi {
        render_node,
        table_view,
        scene_view,
        node_meta,
        node_size,
        node_align,
        meta_size,
        meta_align,
    } = ResolvedSceneAbi::from_spec(&spec);

    let mut out = CodeWriter::with_capacity(6144);
    writeln!(
        out,
        "/* @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY. */"
    );
    writeln!(
        out,
        "/* Single-source 64-byte NveRenderNode + NveSceneView + 64-byte NveNodeMeta ABI. */"
    );
    writeln!(out, "#ifndef NVE_SCENE_ABI_H");
    writeln!(out, "#define NVE_SCENE_ABI_H");
    writeln!(out);
    writeln!(out, "#include <stddef.h>");
    writeln!(out, "#include <stdint.h>");
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "extern \"C\" {{");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#ifndef NVE_STATIC_ASSERT");
    writeln!(out, "#if defined(__cplusplus)");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg) static_assert((cond), msg)");
    writeln!(
        out,
        "#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L"
    );
    writeln!(
        out,
        "#define NVE_STATIC_ASSERT(cond, msg) _Static_assert((cond), msg)"
    );
    writeln!(out, "#else");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg)");
    writeln!(out, "#endif");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#define NVE_SCENE_SCHEMA_HASH 0x{schema_hash:016X}ULL");
    writeln!(out, "#define NVE_RENDER_NODE_SIZE {node_size}u");
    writeln!(out, "#define NVE_RENDER_NODE_ALIGN {node_align}u");
    writeln!(out, "#define NVE_NODE_META_SIZE {meta_size}u");
    writeln!(out, "#define NVE_NODE_META_ALIGN {meta_align}u");
    writeln!(out);
    writeln!(out, "/* NveRenderNode::flags bits */");
    for c in &spec.consts {
        if matches!(
            c.name.as_str(),
            "NVE_NODE_LEAF_TEXT" | "NVE_NODE_INTERACTIVE" | "NVE_NODE_CLIP_BOUNDS"
        ) {
            writeln!(out, "#define {} {}u", c.name, c.value);
        }
    }
    writeln!(out);
    writeln!(out, "/* Sentinel NveRenderNode::primary_slot value (plain container) */");
    for c in &spec.consts {
        if c.name == "NVE_PRIMARY_SLOT_NONE" {
            writeln!(out, "#define {} 0x{:02X}u", c.name, c.value);
        }
    }
    writeln!(out);
    writeln!(out, "/* NveNodeMeta::flags bits & resize-mode shift/mask */");
    for c in &spec.consts {
        if c.name.starts_with("NVE_META_") {
            if c.hex {
                writeln!(out, "#define {} 0x{:X}u", c.name, c.value);
            } else {
                writeln!(out, "#define {} {}u", c.name, c.value);
            }
        }
    }
    writeln!(out);
    writeln!(
        out,
        "/* Naturally 4-byte aligned in C so Swift's ClangImporter imports it directly as a value type;"
    );
    writeln!(
        out,
        " * exact size is 64 bytes (1 cache line) and Rust aligns backing slabs to 64 bytes. */"
    );
    writeln!(out, "typedef struct NveRenderNode {{");
    for f in &render_node.fields {
        writeln!(
            out,
            "  {} {}; /* offset {} */",
            c_core_type(&f.ty),
            f.name,
            f.offset.expect("NveRenderNode field defines offset")
        );
    }
    writeln!(out, "}} NveRenderNode;");
    writeln!(out);
    writeln!(out, "/* Zero-copy view of one published NodeStore word table. */");
    writeln!(out, "#ifndef NVE_TYPE_TABLE_VIEW_DEFINED");
    writeln!(out, "#define NVE_TYPE_TABLE_VIEW_DEFINED");
    writeln!(out, "typedef struct NveTableView {{");
    for f in &table_view.fields {
        writeln!(out, "  {} {};", c_core_type(&f.ty), f.name);
    }
    writeln!(out, "}} NveTableView;");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "typedef struct NveSceneView {{");
    for f in &scene_view.fields {
        writeln!(out, "  {} {};", c_core_type(&f.ty), f.name);
    }
    writeln!(out, "}} NveSceneView;");
    writeln!(out);
    writeln!(
        out,
        "/* Fixed-stride 64-byte per-node metadata record indexing into a flat companion blob slab. */"
    );
    writeln!(out, "typedef struct NveNodeMeta {{");
    for f in &node_meta.fields {
        match &f.ty {
            HybridType::FixedArray { elem, len } => {
                writeln!(
                    out,
                    "  {} {}[{len}]; /* offset {} */",
                    c_core_type(elem),
                    f.name,
                    f.offset.expect("NveNodeMeta field defines offset")
                );
            }
            _ => {
                writeln!(
                    out,
                    "  {} {}; /* offset {} */",
                    c_core_type(&f.ty),
                    f.name,
                    f.offset.expect("NveNodeMeta field defines offset")
                );
            }
        }
    }
    writeln!(out, "}} NveNodeMeta;");
    writeln!(out);
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(NveRenderNode) == {node_size}u, \"NveRenderNode must be 64 bytes\");"
    );
    for f in &render_node.fields {
        let off = f.offset.expect("NveRenderNode field defines offset");
        writeln!(
            out,
            "NVE_STATIC_ASSERT(offsetof(NveRenderNode, {}) == {off}u, \"NveRenderNode.{} offset mismatch\");",
            f.name, f.name
        );
    }
    let mut ptr_slot = 0usize;
    for f in &scene_view.fields {
        if let Some(off) = f.offset {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveSceneView, {}) == {off}u, \"NveSceneView.{} offset mismatch\");",
                f.name, f.name
            );
        } else {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveSceneView, {}) == 40u + {ptr_slot}u * sizeof(void*), \"NveSceneView.{} offset mismatch\");",
                f.name, f.name
            );
            ptr_slot += 1;
        }
    }
    let mut tv_ptr_slot = 0usize;
    for f in &table_view.fields {
        if let Some(off) = f.offset {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveTableView, {}) == {off}u, \"NveTableView.{} offset mismatch\");",
                f.name, f.name
            );
        } else {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveTableView, {}) == 24u + {tv_ptr_slot}u * sizeof(void*), \"NveTableView.{} offset mismatch\");",
                f.name, f.name
            );
            tv_ptr_slot += 1;
        }
    }
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveTableView) == 48u, \"NveTableView size must be 48 on 64-bit\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveSceneView) == 88u, \"NveSceneView size must be 88 on 64-bit\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(NveNodeMeta) == {meta_size}u, \"NveNodeMeta must be 64 bytes\");"
    );
    for f in &node_meta.fields {
        let off = f.offset.expect("NveNodeMeta field defines offset");
        writeln!(
            out,
            "NVE_STATIC_ASSERT(offsetof(NveNodeMeta, {}) == {off}u, \"NveNodeMeta.{} offset mismatch\");",
            f.name, f.name
        );
    }
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "}} /* extern \"C\" */");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#endif /* NVE_SCENE_ABI_H */");
    out.into_string()
}
