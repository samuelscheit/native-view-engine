//! C11 / C++20 emitter for `nve_runtime_abi.generated.h` derived directly from
//! `nve_abi::schema::runtime_abi_descriptor()`.

use super::core_abi::c_core_type;
use crate::schema::hybrid::schema_bridge::from_abi_descriptor;
use crate::schema::hybrid::HybridType;
use crate::writer::CodeWriter;

/// Generates `nve_runtime_abi.generated.h` directly from `packages/core/abi/src/runtime.rs`.
pub fn generate_c_runtime_abi_h() -> String {
    let spec = from_abi_descriptor(&nve_abi::schema::runtime_abi_descriptor());
    let schema_hash = nve_abi::NVE_RUNTIME_SCHEMA_HASH;

    let layout_rect = spec
        .find_struct("NveLayoutRect")
        .expect("runtime_abi_descriptor must declare NveLayoutRect");
    let scroll_offset = spec
        .find_struct("NveScrollOffset")
        .expect("runtime_abi_descriptor must declare NveScrollOffset");
    let node_row = spec
        .find_struct("NveNodeRow")
        .expect("runtime_abi_descriptor must declare NveNodeRow");
    let config = spec
        .find_struct("NveRuntimeConfig")
        .expect("runtime_abi_descriptor must declare NveRuntimeConfig");
    let metrics = spec
        .find_struct("NveRuntimeMetrics")
        .expect("runtime_abi_descriptor must declare NveRuntimeMetrics");
    let table_view = spec
        .find_struct("NveTableView")
        .expect("runtime_abi_descriptor must declare NveTableView");
    let scene_view = spec
        .find_struct("NveRuntimeSceneView")
        .expect("runtime_abi_descriptor must declare NveRuntimeSceneView");
    let status_enum = spec
        .enums
        .iter()
        .find(|e| e.name == "NveRuntimeStatus")
        .expect("runtime_abi_descriptor must declare NveRuntimeStatus");

    let mut out = CodeWriter::with_capacity(8192);
    writeln!(
        out,
        "/* @generated by nve-codegen (runtime C ABI generator) — DO NOT EDIT MANUALLY. */"
    );
    writeln!(
        out,
        "/* Zero-copy NveRuntimeSceneView, NveNodeRow, NveLayoutRect, and NveRuntimeApi vtable. */"
    );
    writeln!(out, "#ifndef NVE_RUNTIME_ABI_H");
    writeln!(out, "#define NVE_RUNTIME_ABI_H");
    writeln!(out);
    writeln!(out, "#include <stddef.h>");
    writeln!(out, "#include <stdint.h>");
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "extern \"C\" {{");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#ifndef NVE_RUNTIME_API");
    writeln!(out, "#if defined(NVE_RUNTIME_SHARED)");
    writeln!(out, "#if defined(_WIN32)");
    writeln!(out, "#if defined(NVE_BUILDING_RUNTIME)");
    writeln!(out, "#define NVE_RUNTIME_API __declspec(dllexport)");
    writeln!(out, "#else");
    writeln!(out, "#define NVE_RUNTIME_API __declspec(dllimport)");
    writeln!(out, "#endif");
    writeln!(out, "#elif defined(__GNUC__) || defined(__clang__)");
    writeln!(out, "#define NVE_RUNTIME_API __attribute__((visibility(\"default\")))");
    writeln!(out, "#else");
    writeln!(out, "#define NVE_RUNTIME_API");
    writeln!(out, "#endif");
    writeln!(out, "#else");
    writeln!(out, "#define NVE_RUNTIME_API");
    writeln!(out, "#endif");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#ifndef NVE_STATIC_ASSERT");
    writeln!(out, "#if defined(__cplusplus)");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg) static_assert((cond), msg)");
    writeln!(
        out,
        "#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L"
    );
    writeln!(
        out,
        "#define NVE_STATIC_ASSERT(cond, msg) _Static_assert((cond), msg)"
    );
    writeln!(out, "#else");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg)");
    writeln!(out, "#endif");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#define NVE_RUNTIME_SCHEMA_HASH 0x{schema_hash:016X}ULL");
    for c in &spec.consts {
        writeln!(out, "#define {} {}u", c.name, c.value);
    }
    writeln!(out);

    // Guarded shared POD definitions so this header works standalone AND alongside
    // `nve_abi.generated.h` / `nve_scene_abi.generated.h` in any include order.
    writeln!(out, "#ifndef NVE_TYPE_BUFFER_SLICE_DEFINED");
    writeln!(out, "#define NVE_TYPE_BUFFER_SLICE_DEFINED");
    writeln!(out, "typedef struct NveBufferSlice {{");
    writeln!(out, "  const uint8_t* ptr;");
    writeln!(out, "  size_t len;");
    writeln!(out, "}} NveBufferSlice;");
    writeln!(out, "#endif");
    writeln!(out, "#ifndef NVE_TYPE_STR_SLICE_DEFINED");
    writeln!(out, "#define NVE_TYPE_STR_SLICE_DEFINED");
    writeln!(out, "typedef struct NveStrSlice {{");
    writeln!(out, "  const uint8_t* ptr;");
    writeln!(out, "  size_t len;");
    writeln!(out, "}} NveStrSlice;");
    writeln!(out, "#endif");
    writeln!(out, "#ifndef NVE_TYPE_EVENT_BATCH_DEFINED");
    writeln!(out, "#define NVE_TYPE_EVENT_BATCH_DEFINED");
    writeln!(out, "struct NveDirectEvent;");
    writeln!(out, "typedef struct NveEventBatch {{");
    writeln!(out, "  const struct NveDirectEvent* ptr;");
    writeln!(out, "  uint32_t len;");
    writeln!(out, "  uint32_t _pad;");
    writeln!(out, "}} NveEventBatch;");
    writeln!(out, "#endif");
    writeln!(out, "#ifndef NVE_TYPE_GET_INTERFACE_FN_DEFINED");
    writeln!(out, "#define NVE_TYPE_GET_INTERFACE_FN_DEFINED");
    writeln!(
        out,
        "typedef const void* (*NveGetInterfaceFn)(uint32_t interface_id);"
    );
    writeln!(out, "#endif");
    writeln!(out, "#ifndef NVE_TYPE_TABLE_VIEW_DEFINED");
    writeln!(out, "#define NVE_TYPE_TABLE_VIEW_DEFINED");
    writeln!(out, "typedef struct NveTableView {{");
    for f in &table_view.fields {
        writeln!(out, "  {} {};", c_core_type(&f.ty), f.name);
    }
    writeln!(out, "}} NveTableView;");
    writeln!(out, "#endif");
    writeln!(out);

    writeln!(out, "typedef void* NveRuntimeHandle;");
    writeln!(out, "typedef void (*NveRuntimeWakeFn)(void* ctx);");
    writeln!(out);

    writeln!(out, "typedef enum NveRuntimeStatus {{");
    let prefix = status_enum.c_prefix.as_deref().unwrap_or("NVE_RUNTIME_");
    for v in &status_enum.variants {
        writeln!(
            out,
            "  {}{} = {},",
            prefix,
            crate::naming::to_snake_case(&v.name).to_ascii_uppercase(),
            v.value
        );
    }
    writeln!(out, "}} NveRuntimeStatus;");
    writeln!(out);

    emit_c_struct(&mut out, layout_rect);
    emit_c_struct(&mut out, scroll_offset);
    emit_c_struct(&mut out, node_row);
    emit_c_struct(&mut out, config);
    emit_c_struct(&mut out, metrics);
    emit_c_struct(&mut out, scene_view);

    writeln!(out, "typedef struct NveRuntimeApi {{");
    writeln!(out, "  uint32_t abi_version;");
    writeln!(out, "  uint32_t struct_size;");
    writeln!(out, "  uint64_t schema_hash;");
    writeln!(
        out,
        "  NveRuntimeHandle (*create)(const NveRuntimeConfig* config);"
    );
    writeln!(out, "  void (*destroy)(NveRuntimeHandle handle);");
    writeln!(
        out,
        "  int32_t (*set_wake_callback)(NveRuntimeHandle handle, NveRuntimeWakeFn cb, void* ctx);"
    );
    writeln!(
        out,
        "  int32_t (*set_viewport)(NveRuntimeHandle handle, float width, float height, float scale_factor);"
    );
    writeln!(
        out,
        "  int32_t (*attach_app_interface)(NveRuntimeHandle handle, NveGetInterfaceFn get_iface);"
    );
    writeln!(
        out,
        "  int32_t (*submit_nve2)(NveRuntimeHandle handle, NveBufferSlice frame);"
    );
    writeln!(
        out,
        "  int32_t (*tick)(NveRuntimeHandle handle, float dt_s, uint32_t* out_changed);"
    );
    writeln!(
        out,
        "  int32_t (*dispatch_events)(NveRuntimeHandle handle, NveEventBatch batch, uint32_t* out_changed);"
    );
    writeln!(
        out,
        "  int32_t (*hit_test)(NveRuntimeHandle handle, float x, float y, uint32_t* out_node_id);"
    );
    writeln!(
        out,
        "  int32_t (*scroll_by)(NveRuntimeHandle handle, uint32_t node_id, float dx, float dy, float* out_x, float* out_y);"
    );
    writeln!(
        out,
        "  int32_t (*scene_acquire)(NveRuntimeHandle handle, NveRuntimeSceneView* out_view);"
    );
    writeln!(out, "  int32_t (*scene_release)(NveRuntimeHandle handle);");
    writeln!(
        out,
        "  int32_t (*get_metrics)(NveRuntimeHandle handle, NveRuntimeMetrics* out_metrics);"
    );
    writeln!(
        out,
        "  int32_t (*pair_connect)(NveRuntimeHandle handle, NveStrSlice uri, NveStrSlice token);"
    );
    writeln!(out, "  int32_t (*pair_disconnect)(NveRuntimeHandle handle);");
    writeln!(
        out,
        "  uint32_t (*pair_is_connected)(NveRuntimeHandle handle);"
    );
    writeln!(
        out,
        "  size_t (*last_error)(uint8_t* out_buf, size_t cap);"
    );
    writeln!(out, "}} NveRuntimeApi;");
    writeln!(out);
    writeln!(out, "/*");
    writeln!(out, " * Threading, wake-callback, and scene-view lifetime contracts:");
    writeln!(out, " * - Owner thread affinity: `create` binds the surface to its creating thread.");
    writeln!(out, " *   All mutating, layout, and app-touching calls (`destroy`, `set_viewport`,");
    writeln!(out, " *   `attach_app_interface`, `submit_nve2`, `tick`, `dispatch_events`, `hit_test`,");
    writeln!(out, " *   `scroll_by`, `pair_connect`, `pair_disconnect`) MUST be invoked on that");
    writeln!(out, " *   owner thread (wrong-thread calls return `NVE_RUNTIME_INVALID_ARG` with");
    writeln!(out, " *   diagnostic text in `last_error`). No thread may concurrently access the");
    writeln!(out, " *   handle during or after `destroy(h)`.");
    writeln!(out, " * - Cross-thread safe calls: `scene_acquire`, `scene_release`, `get_metrics`,");
    writeln!(out, " *   `pair_is_connected`, `set_wake_callback`, and `last_error`.");
    writeln!(out, " * - Borrowed `NveRuntimeSceneView`: all pointers remain valid and immutable ONLY");
    writeln!(out, " *   between a successful `scene_acquire` and its matching `scene_release`.");
    writeln!(out, " *   While any reader holds `scene_acquire`, writes fail with `NVE_RUNTIME_BUSY`;");
    writeln!(out, " *   a `Busy` `tick` retains its pending wake latch without re-firing the wake");
    writeln!(out, " *   callback (retry `tick` after releasing `scene_acquire`).");
    writeln!(out, " * - `NveRuntimeWakeFn(ctx)`: may be invoked on ANY thread (including the owner");
    writeln!(out, " *   thread during `tick`, `dispatch_events`, or `set_wake_callback`). It MUST be");
    writeln!(out, " *   lightweight, strictly non-re-entrant, and MUST NEVER block waiting on the");
    writeln!(out, " *   owner thread (post a message or signal a semaphore; NEVER call");
    writeln!(out, " *   `set_wake_callback`, `destroy`, or mutating `NveRuntimeApi` methods inside it).");
    writeln!(out, " *   `set_wake_callback(h, NULL, NULL)` and `destroy(h)` drain all in-flight");
    writeln!(out, " *   invocations before returning so the host may safely free `ctx` afterward.");
    writeln!(out, " */");
    writeln!(
        out,
        "NVE_RUNTIME_API const NveRuntimeApi* nve_runtime_get_interface(uint32_t abi_version);"
    );
    writeln!(out);

    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveBufferSlice, ptr) == 0u, \"NveBufferSlice.ptr @0\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveBufferSlice, len) == sizeof(void*), \"NveBufferSlice.len offset\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveBufferSlice) == 16u, \"NveBufferSlice must be 16 bytes on 64-bit\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveStrSlice, ptr) == 0u, \"NveStrSlice.ptr @0\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveStrSlice, len) == sizeof(void*), \"NveStrSlice.len offset\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveStrSlice) == 16u, \"NveStrSlice must be 16 bytes on 64-bit\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveEventBatch, ptr) == 0u, \"NveEventBatch.ptr @0\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveEventBatch, len) == sizeof(void*), \"NveEventBatch.len offset\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveEventBatch, _pad) == sizeof(void*) + 4u, \"NveEventBatch._pad offset\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveEventBatch) == 16u, \"NveEventBatch must be 16 bytes on 64-bit\");"
    );

    let mut tv_ptr_slot = 0usize;
    for f in &table_view.fields {
        if let Some(off) = f.offset {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveTableView, {}) == {off}u, \"NveTableView.{} offset mismatch\");",
                f.name, f.name
            );
        } else {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveTableView, {}) == 24u + {tv_ptr_slot}u * sizeof(void*), \"NveTableView.{} offset mismatch\");",
                f.name, f.name
            );
            tv_ptr_slot += 1;
        }
    }
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveTableView) == 48u, \"NveTableView must be 48 bytes on 64-bit\");"
    );

    emit_fixed_asserts(&mut out, layout_rect, 16);
    emit_fixed_asserts(&mut out, scroll_offset, nve_abi::NVE_SCROLL_OFFSET_SIZE);
    emit_fixed_asserts(&mut out, node_row, 32);
    emit_fixed_asserts(&mut out, config, 24);
    emit_fixed_asserts(&mut out, metrics, 64);

    // Fixed-width header first, then pointers: the pointer base and 64-bit size come straight
    // from the compiled Rust layout (the header is pointer-aligned on every target).
    let ptr_base = core::mem::offset_of!(nve_abi::NveRuntimeSceneView, rows);
    let view_size = core::mem::size_of::<nve_abi::NveRuntimeSceneView>();
    let mut ptr_slot = 0usize;
    for f in &scene_view.fields {
        if let Some(off) = f.offset {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveRuntimeSceneView, {}) == {off}u, \"NveRuntimeSceneView.{} offset mismatch\");",
                f.name, f.name
            );
        } else {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof(NveRuntimeSceneView, {}) == {ptr_base}u + {ptr_slot}u * sizeof(void*), \"NveRuntimeSceneView.{} offset mismatch\");",
                f.name, f.name
            );
            ptr_slot += 1;
        }
    }
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveRuntimeSceneView) == {view_size}u, \"NveRuntimeSceneView must be {view_size} bytes on 64-bit\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveRuntimeApi, abi_version) == 0u, \"NveRuntimeApi.abi_version @0\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveRuntimeApi, struct_size) == 4u, \"NveRuntimeApi.struct_size @4\");"
    );
    writeln!(
        out,
        "NVE_STATIC_ASSERT(offsetof(NveRuntimeApi, schema_hash) == 8u, \"NveRuntimeApi.schema_hash @8\");"
    );
    for (slot_idx, fn_name) in [
        "create",
        "destroy",
        "set_wake_callback",
        "set_viewport",
        "attach_app_interface",
        "submit_nve2",
        "tick",
        "dispatch_events",
        "hit_test",
        "scroll_by",
        "scene_acquire",
        "scene_release",
        "get_metrics",
        "pair_connect",
        "pair_disconnect",
        "pair_is_connected",
        "last_error",
    ]
    .iter()
    .enumerate()
    {
        writeln!(
            out,
            "NVE_STATIC_ASSERT(offsetof(NveRuntimeApi, {fn_name}) == 16u + {slot_idx}u * sizeof(void*), \"NveRuntimeApi.{fn_name} offset\");"
        );
    }
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveRuntimeApi) == 152u, \"NveRuntimeApi must be 152 bytes on 64-bit\");"
    );
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "}} /* extern \"C\" */");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#endif /* NVE_RUNTIME_ABI_H */");
    out.into_string()
}

fn emit_c_struct(out: &mut CodeWriter, s: &crate::schema::hybrid::HybridStructSpec) {
    writeln!(out, "typedef struct {} {{", s.name);
    for f in &s.fields {
        match &f.ty {
            HybridType::FixedArray { elem, len } => {
                writeln!(out, "  {} {}[{len}];", c_core_type(elem), f.name);
            }
            _ => {
                writeln!(out, "  {} {};", c_core_type(&f.ty), f.name);
            }
        }
    }
    writeln!(out, "}} {};", s.name);
    writeln!(out);
}

fn emit_fixed_asserts(
    out: &mut CodeWriter,
    s: &crate::schema::hybrid::HybridStructSpec,
    expected_size: usize,
) {
    writeln!(
        out,
        "NVE_STATIC_ASSERT(sizeof({}) == {expected_size}u, \"{} must be {expected_size} bytes\");",
        s.name, s.name
    );
    for f in &s.fields {
        let off = f.offset.expect("fixed runtime ABI field defines offset");
        writeln!(
            out,
            "NVE_STATIC_ASSERT(offsetof({}, {}) == {off}u, \"{}.{} offset mismatch\");",
            s.name, f.name, s.name, f.name
        );
    }
}
