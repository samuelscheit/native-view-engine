//! Binary `<Name>NveBridge.generated.hpp` & `.cpp` emitter for `export_rn`.

use std::fmt::Write as _;

use crate::naming::{
    cpp_ident, escape_c_like_string, format_float_literal, sanitize_single_line_comment,
    strip_on_prefix,
};
use crate::schema::export::{DefaultValue, NveExportSpec, PropSpec, PropType};

pub(crate) fn emit_cpp_bridge_hpp(spec: &NveExportSpec) -> String {
    let name = &spec.name;
    let vtable_sym = spec.vtable_symbol();
    let mut out = String::with_capacity(3072);

    let _ = writeln!(out, "#pragma once");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_rn`) — backend: {}",
        spec.backend.as_str()
    );
    let _ = writeln!(
        out,
        "// Binary C++20 bridge connecting RN Fabric `{}` Props/EventEmitter <-> `nve::NveRnComponentBridge`.",
        sanitize_single_line_comment(name)
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "#include \"nve_abi.generated.h\"");
    let _ = writeln!(out, "#include \"nve_rn_component.hpp\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <array>");
    let _ = writeln!(out, "#include <cstdint>");
    let _ = writeln!(out, "#include <functional>");
    let _ = writeln!(out, "#include <memory>");
    let _ = writeln!(out, "#include <optional>");
    let _ = writeln!(out, "#include <string>");
    let _ = writeln!(out, "#include <string_view>");
    let _ = writeln!(out, "#include <vector>");
    let _ = writeln!(out);
    let _ = writeln!(out, "extern \"C\" {{");
    let _ = writeln!(out, "const void* {vtable_sym}(uint32_t interface_id);");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace nve::exported {{");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "inline constexpr std::string_view k{name}Name = \"{}\";",
        escape_c_like_string(name)
    );
    let _ = writeln!(
        out,
        "inline constexpr std::string_view k{name}Backend = \"{}\";",
        spec.backend.as_str()
    );
    let _ = writeln!(out);

    let _ = writeln!(out, "struct {name}Props {{");
    for prop in &spec.props {
        let field = cpp_ident(&prop.name);
        let cty = export_cpp_prop_type(&prop.prop_type);
        let def = export_cpp_default(prop);
        if prop.optional && def.is_none() {
            let _ = writeln!(out, "  std::optional<{cty}> {field};");
        } else if let Some(d) = def {
            let _ = writeln!(out, "  {cty} {field}{{{d}}};");
        } else {
            let _ = writeln!(out, "  {cty} {field}{{}};");
        }
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);

    // Typed outbound binary `NveBinValue` event callbacks matching RN Fabric EventEmitter
    let _ = writeln!(out, "struct {name}EventCallbacks {{");
    for ev in &spec.events {
        let cb_name = cpp_ident(&ev.name);
        let _ = writeln!(
            out,
            "  std::function<void(NveBufferSlice payload_bin)> {cb_name};"
        );
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);

    let _ = writeln!(out, "class {name}NveBridge {{");
    let _ = writeln!(out, " public:");
    let _ = writeln!(
        out,
        "  {name}NveBridge(\n      NveSurfaceConfig config,\n      {name}EventCallbacks callbacks = {{}},\n      NveGetInterfaceFn interface_override = nullptr);"
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "  static bool apply_props(\n      nve::NveRnComponentBridge& bridge,\n      const {name}Props& props,\n      bool auto_render = true);"
    );
    let _ = writeln!(
        out,
        "  bool update_props(const {name}Props& props, bool auto_render = true);"
    );
    let _ = writeln!(
        out,
        "  bool update_props(const NveMapEntry* entries, uint32_t count, bool auto_render = true);"
    );
    let _ = writeln!(
        out,
        "  void set_surface_size(float width, float height, float scale_factor = 0.0f);"
    );
    let _ = writeln!(out, "  int32_t render(NveFrameStats* out_stats = nullptr);");
    let _ = writeln!(
        out,
        "  std::vector<nve::DecodedEvent> drain_and_dispatch_events();"
    );
    let _ = writeln!(out, "  void set_callbacks({name}EventCallbacks callbacks);");
    let _ = writeln!(
        out,
        "  nve::NveRnComponentBridge& inner() noexcept {{ return *bridge_; }}"
    );
    let _ = writeln!(
        out,
        "  const nve::NveRnComponentBridge& inner() const noexcept {{ return *bridge_; }}"
    );
    let _ = writeln!(out, "  bool is_valid() const noexcept;");
    let _ = writeln!(out);
    let _ = writeln!(out, " private:");
    let _ = writeln!(out, "  void dispatch_decoded_event(const nve::DecodedEvent& ev);");
    let _ = writeln!(out);
    let _ = writeln!(out, "  {name}EventCallbacks callbacks_;");
    let _ = writeln!(out, "  std::unique_ptr<nve::NveRnComponentBridge> bridge_;");
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace nve::exported");
    out
}

pub(crate) fn emit_cpp_bridge_cpp(spec: &NveExportSpec) -> String {
    let name = &spec.name;
    let vtable_sym = spec.vtable_symbol();
    let mut out = String::with_capacity(3072);

    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`export_rn`) — backend: {}",
        spec.backend.as_str()
    );
    let _ = writeln!(out, "#include \"{name}NveBridge.generated.hpp\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <utility>");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace nve::exported {{");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "{name}NveBridge::{name}NveBridge(\n    NveSurfaceConfig config,\n    {name}EventCallbacks callbacks,\n    NveGetInterfaceFn interface_override)\n    : callbacks_(std::move(callbacks)) {{"
    );
    let _ = writeln!(
        out,
        "  NveGetInterfaceFn get_iface = interface_override != nullptr ? interface_override : &{vtable_sym};"
    );
    let _ = writeln!(out, "  if (get_iface != nullptr) {{");
    let _ = writeln!(
        out,
        "    bridge_ = std::make_unique<nve::NveRnComponentBridge>(\n        get_iface,\n        config,\n        [this](const nve::DecodedEvent& ev) {{ dispatch_decoded_event(ev); }});"
    );
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    if spec.props.is_empty() {
        let _ = writeln!(
            out,
            "bool {name}NveBridge::apply_props(\n    nve::NveRnComponentBridge& bridge,\n    const {name}Props& /*props*/,\n    bool auto_render) {{"
        );
        let _ = writeln!(out, "  return bridge.update_props(nullptr, 0u, auto_render);");
        let _ = writeln!(out, "}}");
    } else {
        let _ = writeln!(
            out,
            "bool {name}NveBridge::apply_props(\n    nve::NveRnComponentBridge& bridge,\n    const {name}Props& props,\n    bool auto_render) {{"
        );
        let _ = writeln!(
            out,
            "  std::array<NveMapEntry, {}u> entries{{}};",
            spec.props.len()
        );
        let _ = writeln!(out, "  uint32_t count = 0u;");
        for prop in &spec.props {
            let key = escape_c_like_string(&prop.name);
            let field = cpp_ident(&prop.name);
            let is_opt = prop.optional && export_cpp_default(prop).is_none();
            if is_opt {
                let _ = writeln!(out, "  if (props.{field}.has_value()) {{");
                let val_expr = cpp_prop_to_nve_value(&format!("*props.{field}"), &prop.prop_type);
                let _ = writeln!(
                    out,
                    "    entries[count++] = NveMapEntry{{nve::make_str_slice(\"{key}\"), {val_expr}}};"
                );
                let _ = writeln!(out, "  }}");
            } else {
                let val_expr = cpp_prop_to_nve_value(&format!("props.{field}"), &prop.prop_type);
                let _ = writeln!(
                    out,
                    "  entries[count++] = NveMapEntry{{nve::make_str_slice(\"{key}\"), {val_expr}}};"
                );
            }
        }
        let _ = writeln!(
            out,
            "  return bridge.update_props(entries.data(), count, auto_render);"
        );
        let _ = writeln!(out, "}}");
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "bool {name}NveBridge::update_props(const {name}Props& props, bool auto_render) {{"
    );
    let _ = writeln!(out, "  if (!bridge_) return false;");
    let _ = writeln!(
        out,
        "  const bool dirty = apply_props(*bridge_, props, auto_render);"
    );
    let _ = writeln!(out, "  (void)bridge_->drain_emitted_events();");
    let _ = writeln!(out, "  return dirty;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "bool {name}NveBridge::update_props(const NveMapEntry* entries, uint32_t count, bool auto_render) {{"
    );
    let _ = writeln!(out, "  if (!bridge_) return false;");
    let _ = writeln!(
        out,
        "  const bool dirty = bridge_->update_props(entries, count, auto_render);"
    );
    let _ = writeln!(out, "  (void)drain_and_dispatch_events();");
    let _ = writeln!(out, "  return dirty;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "void {name}NveBridge::set_surface_size(float width, float height, float scale_factor) {{"
    );
    let _ = writeln!(out, "  if (bridge_) {{");
    let _ = writeln!(
        out,
        "    bridge_->set_surface_size(width, height, scale_factor);"
    );
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "int32_t {name}NveBridge::render(NveFrameStats* out_stats) {{"
    );
    let _ = writeln!(out, "  if (!bridge_) return -1;");
    let _ = writeln!(out, "  const int32_t rc = bridge_->render(out_stats);");
    let _ = writeln!(out, "  (void)drain_and_dispatch_events();");
    let _ = writeln!(out, "  return rc;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "std::vector<nve::DecodedEvent> {name}NveBridge::drain_and_dispatch_events() {{"
    );
    let _ = writeln!(out, "  if (!bridge_) return {{}};");
    let _ = writeln!(out, "  return bridge_->drain_emitted_events();");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "void {name}NveBridge::set_callbacks({name}EventCallbacks callbacks) {{"
    );
    let _ = writeln!(out, "  callbacks_ = std::move(callbacks);");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "bool {name}NveBridge::is_valid() const noexcept {{");
    let _ = writeln!(out, "  return bridge_ != nullptr && bridge_->is_valid();");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "void {name}NveBridge::dispatch_decoded_event(const nve::DecodedEvent& ev) {{"
    );
    let _ = writeln!(
        out,
        "  const NveBufferSlice payload_bin{{ev.payload_bytes.empty() ? nullptr : ev.payload_bytes.data(), ev.payload_bytes.size()}};"
    );
    for (idx, ev) in spec.events.iter().enumerate() {
        let cb_name = cpp_ident(&ev.name);
        let short_name = strip_on_prefix(&ev.name);
        let kw = if idx == 0 { "if" } else { "else if" };
        let _ = writeln!(
            out,
            "  {kw} (ev.name == \"{}\" || ev.name == \"{}\") {{",
            escape_c_like_string(&ev.name),
            escape_c_like_string(&short_name)
        );
        let _ = writeln!(out, "    if (callbacks_.{cb_name}) {{");
        let _ = writeln!(out, "      callbacks_.{cb_name}(payload_bin);");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "  }}");
    }
    let _ = writeln!(out, "  (void)payload_bin;");
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace nve::exported");
    out
}

fn export_cpp_prop_type(ty: &PropType) -> &'static str {
    match ty {
        PropType::Bool => "bool",
        PropType::Int32 | PropType::IntEnum { .. } => "int32_t",
        PropType::Float => "float",
        PropType::Double => "double",
        PropType::String
        | PropType::Color
        | PropType::ImageSource
        | PropType::Point
        | PropType::EdgeInsets
        | PropType::Dimension
        | PropType::StringEnum { .. }
        | PropType::Array { .. }
        | PropType::Object { .. }
        | PropType::Mixed
        | PropType::Void
        | PropType::Promise { .. }
        | PropType::Callback { .. } => "std::string",
    }
}

fn export_cpp_default(prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32 | PropType::IntEnum { .. }, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float, DefaultValue::Int(i)) => Some(format!("{i}.0f")),
        (PropType::Float, DefaultValue::Float(f)) => {
            Some(format!("{}f", format_float_literal(*f)))
        }
        (PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Double, DefaultValue::Float(f)) => Some(format_float_literal(*f)),
        (PropType::String | PropType::StringEnum { .. } | PropType::Color, DefaultValue::String(s)) => {
            Some(format!("\"{}\"", escape_c_like_string(s)))
        }
        _ => None,
    }
}

fn cpp_prop_to_nve_value(expr: &str, ty: &PropType) -> String {
    match ty {
        PropType::Bool => format!("nve::make_bool_value({expr})"),
        PropType::Int32 | PropType::IntEnum { .. } => {
            format!("nve::make_i64_value(static_cast<int64_t>({expr}))")
        }
        PropType::Float | PropType::Double => {
            format!("nve::make_f64_value(static_cast<double>({expr}))")
        }
        _ => format!("nve::make_str_value({expr})"),
    }
}
