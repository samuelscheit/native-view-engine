use crate::writer::CodeWriter;

use crate::naming::to_snake_case;
pub use super::scene_abi::generate_c_scene_abi_h;
use crate::schema::hybrid::core_abi::{
    core_abi_spec, format_c_enum_prefix, format_enum_value, module_c_struct_name,
    HOST_STATUS_VARIANTS,
};
use crate::schema::hybrid::{HybridMethodSpec, HybridStructSpec, HybridType};

pub(super) fn c_core_type(ty: &HybridType) -> String {
    match ty {
        HybridType::Void => "void".to_string(),
        HybridType::Bool => "bool".to_string(),
        HybridType::U8 => "uint8_t".to_string(),
        HybridType::U16 => "uint16_t".to_string(),
        HybridType::Usize => "size_t".to_string(),
        HybridType::I32 => "int32_t".to_string(),
        HybridType::U32 => "uint32_t".to_string(),
        HybridType::I64 => "int64_t".to_string(),
        HybridType::U64 => "uint64_t".to_string(),
        HybridType::F32 => "float".to_string(),
        HybridType::F64 => "double".to_string(),
        HybridType::Value => "NveValue".to_string(),
        HybridType::Struct(name) | HybridType::Enum(name) | HybridType::Handle(name) => {
            name.clone()
        }
        HybridType::ConstPtr(inner) => format!("const {}*", c_core_type(inner)),
        HybridType::MutPtr(inner) => format!("{}*", c_core_type(inner)),
        other => unreachable!("unsupported core ABI C type: {other:?}"),
    }
}

// ============================================================================
// Core ABI Target 1 & 2: C11 / C++20 / Swift (`nve_abi.generated.h`)
// ============================================================================

/// Generates `nve_abi.generated.h` (used identically by `cxx/nve-fabric-bridge/include/nve_abi.generated.h`
/// and `hosts/swiftui-kit/Sources/CNveAbi/include/nve_abi.generated.h`) directly from
/// `packages/core/abi/src/schema.rs`.
pub fn generate_c_core_abi_h() -> String {
    let spec = core_abi_spec();
    let schema_hash = crate::schema::hybrid::core_abi::core_abi_schema_hash();
    let mut out = CodeWriter::with_capacity(8 * 1024);

    writeln!(
        out,
        "/* @generated by nve-codegen (hybrid unified ABI generator) — DO NOT EDIT MANUALLY. */"
    );
    writeln!(
        out,
        "/* Single-source NVE Core C ABI generated from packages/core/abi/src/schema.rs. */"
    );
    writeln!(out, "#pragma once");
    writeln!(out, "#ifndef NVE_ABI_GENERATED_H");
    writeln!(out, "#define NVE_ABI_GENERATED_H");
    writeln!(out);
    writeln!(out, "#include <stddef.h>");
    writeln!(out, "#include <stdint.h>");
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "extern \"C\" {{");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#ifndef NVE_API");
    writeln!(out, "#if defined(NVE_BUILD_SHARED_LIB)");
    writeln!(out, "#if defined(_WIN32)");
    writeln!(out, "#define NVE_API __declspec(dllexport)");
    writeln!(out, "#elif defined(__GNUC__) || defined(__clang__)");
    writeln!(out, "#define NVE_API __attribute__((visibility(\"default\")))");
    writeln!(out, "#else");
    writeln!(out, "#define NVE_API");
    writeln!(out, "#endif");
    writeln!(out, "#else");
    writeln!(out, "#define NVE_API");
    writeln!(out, "#endif");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(
        out,
        "#define NVE_CORE_ABI_SCHEMA_HASH 0x{schema_hash:016X}ULL"
    );
    for c in &spec.consts {
        if c.name == "NVE_BIN_VALUE_MAX_DEPTH" {
            continue;
        }
        if c.hex {
            writeln!(out, "#define {} 0x{:X}u", c.name, c.value);
        } else {
            writeln!(out, "#define {} {}u", c.name, c.value);
        }
    }
    writeln!(out);
    writeln!(
        out,
        "/* Modular interface IDs resolved once via `nve_get_interface(uint32_t)`. */"
    );
    for m in &spec.modules {
        let upper = to_snake_case(&m.name).to_ascii_uppercase();
        let c_name = module_c_struct_name(m);
        writeln!(
            out,
            "#define NVE_IFACE_{upper} {}u /* const {c_name}* */",
            m.interface_id()
        );
    }
    writeln!(out);

    // Core enums
    for e in &spec.enums {
        let prefix = format_c_enum_prefix(e);
        writeln!(out, "typedef enum {} {{", e.name);
        for v in &e.variants {
            let v_upper = to_snake_case(&v.name).to_ascii_uppercase();
            writeln!(
                out,
                "  {prefix}{v_upper} = {},",
                format_enum_value(v.value)
            );
        }
        writeln!(out, "}} {};", e.name);
        writeln!(out);
    }

    // Signed host-capability status enum (`NVE_IFACE_HOST = 5`)
    writeln!(out, "typedef enum NveHostStatus {{");
    for &(variant, code) in HOST_STATUS_VARIANTS {
        let v_upper = to_snake_case(variant).to_ascii_uppercase();
        writeln!(out, "  NVE_HOST_{v_upper} = {code},");
    }
    writeln!(out, "}} NveHostStatus;");
    writeln!(out);

    if let Some(depth_const) = spec.consts.iter().find(|c| c.name == "NVE_BIN_VALUE_MAX_DEPTH") {
        writeln!(
            out,
            "#define {} {}u",
            depth_const.name, depth_const.value
        );
        writeln!(out);
    }

    // Forward declarations for mutually referencing value structs
    writeln!(out, "typedef struct NveValue NveValue;");
    writeln!(out, "typedef struct NveMapEntry NveMapEntry;");
    writeln!(out);

    // Structs and unions in declaration order
    for s in &spec.structs {
        if s.name == "NveHostCallbacks" {
            writeln!(
                out,
                "typedef int32_t (*NveHostInvokeFn)(void* host_ctx, uint32_t service_id, uint32_t method_id, uint64_t request_id, NveBufferSlice request, uint8_t* out_buf, size_t out_cap, size_t* out_len);"
            );
            writeln!(
                out,
                "typedef int32_t (*NveHostChannelPublishFn)(void* host_ctx, uint32_t channel_id, uint32_t flags, NveBufferSlice payload);"
            );
            writeln!(out);
        }
        emit_c_core_struct_or_union(&mut out, s);
    }

    // Compile-time layout & offset assertions
    writeln!(out, "#ifndef NVE_STATIC_ASSERT");
    writeln!(out, "#if defined(__cplusplus)");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg) static_assert((cond), msg)");
    writeln!(
        out,
        "#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L"
    );
    writeln!(
        out,
        "#define NVE_STATIC_ASSERT(cond, msg) _Static_assert((cond), msg)"
    );
    writeln!(out, "#else");
    writeln!(out, "#define NVE_STATIC_ASSERT(cond, msg)");
    writeln!(out, "#endif");
    writeln!(out, "#endif");
    writeln!(out);

    for s in &spec.structs {
        if let Some(sz) = s.expected_size {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof({}) == {sz}u, \"{} size must be {sz}\");",
                s.name, s.name
            );
        }
        if let Some(sz64) = s.expected_size_64 {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof({}) == {sz64}u, \"{} size must be {sz64} on 64-bit\");",
                s.name, s.name
            );
        }
        // Emit pointer-size-aware layout checks for slice/pointer/value structs that work on 32-bit & 64-bit.
        match s.name.as_str() {
            "NveBufferSlice" | "NveStrSlice" | "NveValueArray" | "NveValueMap" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof({}) == 2u * sizeof(void*), \"{} size must be 2 pointers\");",
                    s.name, s.name
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof({}, ptr) == 0u, \"{}::ptr offset must be 0\");",
                    s.name, s.name
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof({}, len) == sizeof(void*), \"{}::len offset must be sizeof(void*)\");",
                    s.name, s.name
                );
            }
            "NveValue" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveValue, tag) == 0u, \"NveValue::tag offset must be 0\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 8 || offsetof(NveValue, data) == 8u, \"NveValue::data offset must be 8 on 64-bit\");"
                );
            }
            "NveMapEntry" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveMapEntry, key) == 0u, \"NveMapEntry::key offset must be 0\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 8 || offsetof(NveMapEntry, value) == 16u, \"NveMapEntry::value offset must be 16 on 64-bit\");"
                );
            }
            "NveDirectEvent" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 4 || sizeof(NveDirectEvent) == 72u, \"NveDirectEvent size must be 72 on 32-bit\");"
                );
            }
            "NveEventBatch" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(NveEventBatch) == sizeof(void*) + 8u, \"NveEventBatch size must be sizeof(void*) + 8\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveEventBatch, ptr) == 0u, \"NveEventBatch::ptr offset must be 0\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveEventBatch, len) == sizeof(void*), \"NveEventBatch::len offset must be sizeof(void*)\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveEventBatch, _pad) == sizeof(void*) + 4u, \"NveEventBatch::_pad offset must be sizeof(void*) + 4\");"
                );
            }
            "NvePropEntry" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(NvePropEntry) == 8u + sizeof(NveValue), \"NvePropEntry size must be 8 + sizeof(NveValue)\");"
                );
            }
            "NvePropSlice" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(NvePropSlice) == sizeof(void*) + 8u, \"NvePropSlice size must be sizeof(void*) + 8\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NvePropSlice, len) == sizeof(void*), \"NvePropSlice::len offset must be sizeof(void*)\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NvePropSlice, _pad) == sizeof(void*) + 4u, \"NvePropSlice::_pad offset must be sizeof(void*) + 4\");"
                );
            }
            "NveCommandSlice" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(NveCommandSlice) == 8u + sizeof(void*), \"NveCommandSlice size must be 8 + sizeof(void*)\");"
                );
            }
            "NveHostCallbacks" => {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(NveHostCallbacks) == 3u * sizeof(void*), \"NveHostCallbacks size must be 3 pointers\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveHostCallbacks, host_ctx) == 0u, \"NveHostCallbacks::host_ctx offset must be 0\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveHostCallbacks, invoke) == sizeof(void*), \"NveHostCallbacks::invoke offset must be sizeof(void*)\");"
                );
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveHostCallbacks, channel_publish) == 2u * sizeof(void*), \"NveHostCallbacks::channel_publish offset must be 2 * sizeof(void*)\");"
                );
            }
            _ => {}
        }
        for f in &s.fields {
            if let Some(off) = f.offset {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof({}, {}) == {off}u, \"{}::{} offset must be {off}\");",
                    s.name, f.name, s.name, f.name
                );
            }
            if let Some(off64) = f.offset_64
                && s.name != "NveHostCallbacks"
            {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 8 || offsetof({}, {}) == {off64}u, \"{}::{} offset must be {off64}\");",
                    s.name, f.name, s.name, f.name
                );
            }
        }
    }
    writeln!(out);

    // Handle aliases
    for a in &spec.aliases {
        if matches!(
            a.name.as_str(),
            "NveHostInvokeFn" | "NveHostChannelPublishFn"
        ) {
            continue;
        }
        writeln!(out, "typedef {} {};", c_core_type(&a.target), a.name);
    }
    writeln!(out);

    // Modular interface vtables
    for m in &spec.modules {
        let c_name = module_c_struct_name(m);
        if let Some(doc) = &m.doc {
            writeln!(out, "/* {} */", doc.replace('\n', " "));
        }
        writeln!(out, "typedef struct {c_name} {{");
        for method in &m.methods {
            if let Some(doc) = &method.doc {
                writeln!(out, "  /* {} */", doc.replace('\n', " "));
            }
            let ret = c_core_type(&method.return_type);
            let mut params = Vec::new();
            if method.has_self {
                params.push("NveAppHandle handle".to_string());
            }
            for p in &method.params {
                params.push(format!("{} {}", c_core_type(&p.ty), p.name));
            }
            let param_list = if params.is_empty() {
                "void".to_string()
            } else {
                params.join(", ")
            };
            writeln!(out, "  {ret} (*{})({param_list});", method.name);
        }
        writeln!(out, "}} {c_name};");
        writeln!(out);
    }

    // Pointer-size-aware compile-time layout assertions for every modular vtable struct
    for m in &spec.modules {
        let c_name = module_c_struct_name(m);
        let slot_count = m.methods.len();
        writeln!(
            out,
            "NVE_STATIC_ASSERT(sizeof({c_name}) == {slot_count}u * sizeof(void*), \"{c_name} size must be {slot_count} function pointers\");"
        );
        for (idx, method) in m.methods.iter().enumerate() {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(offsetof({c_name}, {}) == {idx}u * sizeof(void*), \"{c_name}::{} offset must be slot {idx}\");",
                method.name, method.name
            );
        }
    }
    writeln!(out);

    // Single exported symbol + NveModule resolver
    writeln!(
        out,
        "/* Single exported symbol per NVE module (`nve_get_interface`). */"
    );
    writeln!(
        out,
        "typedef const void* (*NveGetInterfaceFn)(uint32_t interface_id);"
    );
    writeln!(out, "NVE_API const void* nve_get_interface(uint32_t interface_id);");
    writeln!(out);
    writeln!(
        out,
        "/* Host-side resolved cache of modular interface pointers (not an ABI struct). */"
    );
    writeln!(out, "typedef struct NveModule {{");
    for m in &spec.modules {
        let c_name = module_c_struct_name(m);
        let field = to_snake_case(&m.name);
        writeln!(out, "  const {c_name}* {field};");
    }
    writeln!(out, "}} NveModule;");
    writeln!(out);
    writeln!(
        out,
        "static inline NveModule nve_resolve_module(NveGetInterfaceFn get_iface) {{"
    );
    let nulls = vec!["NULL"; spec.modules.len()].join(", ");
    writeln!(out, "  NveModule m = {{{nulls}}};");
    writeln!(out, "  if (!get_iface) {{");
    writeln!(out, "    return m;");
    writeln!(out, "  }}");
    for m in &spec.modules {
        let c_name = module_c_struct_name(m);
        let field = to_snake_case(&m.name);
        let upper = field.to_ascii_uppercase();
        writeln!(
            out,
            "  m.{field} = (const {c_name}*)get_iface(NVE_IFACE_{upper});"
        );
    }
    writeln!(out, "  return m;");
    writeln!(out, "}}");
    writeln!(out);

    // Host C API functions (cxx/nve-fabric-bridge)
    writeln!(
        out,
        "/* C API implemented by cxx/nve-fabric-bridge for iOS, macOS, Android, and headless Fabric tests. */"
    );
    for f in &spec.c_functions {
        emit_c_function_decl(&mut out, f);
    }
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "}}");
    writeln!(out, "#endif");
    writeln!(out);
    writeln!(out, "#endif /* NVE_ABI_GENERATED_H */");
    out.into_string()
}

fn emit_c_core_struct_or_union(out: &mut CodeWriter, s: &HybridStructSpec) {
    let is_forward_typedef = matches!(s.name.as_str(), "NveValue" | "NveMapEntry");
    if s.is_union {
        writeln!(out, "typedef union {} {{", s.name);
    } else if is_forward_typedef {
        writeln!(out, "struct {} {{", s.name);
    } else {
        writeln!(out, "typedef struct {} {{", s.name);
    }
    for f in &s.fields {
        match &f.ty {
            HybridType::FixedArray { elem, len } => {
                writeln!(out, "  {} {}[{len}];", c_core_type(elem), f.name);
            }
            _ => {
                writeln!(out, "  {} {};", c_core_type(&f.ty), f.name);
            }
        }
    }
    if is_forward_typedef {
        writeln!(out, "}};");
    } else {
        writeln!(out, "}} {};", s.name);
    }
    writeln!(out);
}

fn emit_c_function_decl(out: &mut CodeWriter, f: &HybridMethodSpec) {
    let ret = c_core_type(&f.return_type);
    let params: Vec<String> = f
        .params
        .iter()
        .map(|p| format!("{} {}", c_core_type(&p.ty), p.name))
        .collect();
    let param_list = if params.is_empty() {
        "void".to_string()
    } else {
        params.join(", ")
    };
    writeln!(out, "{ret} {}({param_list});", f.name);
}



