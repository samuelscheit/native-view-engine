//! C++20 TurboModule host interface emitter for `import_rn`: a pure-virtual class over std types
//! that a native host implements for each React Native TurboModule method.

use crate::writer::CodeWriter;

use crate::naming::{cpp_ident, escape_c_like_string, sanitize_single_line_comment, to_pascal_case};
use crate::schema::export::{PropType, TurboModuleSpec};

pub(crate) fn emit_turbomodule_cpp(spec: &TurboModuleSpec) -> String {
    let pascal = to_pascal_case(&spec.module_name);
    let mut out = CodeWriter::with_capacity(2048);

    writeln!(out, "#pragma once");
    writeln!(out);
    writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native TurboModule `{}`.",
        sanitize_single_line_comment(&spec.module_name)
    );
    writeln!(out);
    writeln!(out, "#include <cstdint>");
    writeln!(out, "#include <optional>");
    writeln!(out, "#include <string>");
    writeln!(out, "#include <string_view>");
    writeln!(out, "#include <vector>");
    writeln!(out);
    writeln!(out, "namespace nve::generated {{");
    writeln!(out);
    writeln!(
        out,
        "inline constexpr std::string_view k{pascal}ModuleName = \"{}\";",
        escape_c_like_string(&spec.module_name)
    );
    writeln!(out);
    writeln!(out, "class {pascal}TurboModuleHost {{");
    writeln!(out, " public:");
    writeln!(out, "  virtual ~{pascal}TurboModuleHost() = default;");
    for method in &spec.methods {
        let mname = cpp_ident(&method.name);
        let ret = cpp_tm_type(&method.return_type);
        let mut params = CodeWriter::new();
        for (i, p) in method.params.iter().enumerate() {
            if i > 0 {
                params.push_str(", ");
            }
            let pty = cpp_tm_type(&p.param_type);
            let pname = cpp_ident(&p.name);
            if p.optional {
                write!(params, "std::optional<{pty}> {pname}");
            } else {
                write!(params, "{pty} {pname}");
            }
        }
        writeln!(out, "  virtual {ret} {mname}({params}) = 0;");
    }
    writeln!(out, "}};");
    writeln!(out);
    writeln!(out, "}} // namespace nve::generated");
    out.into_string()
}

fn cpp_tm_type(ty: &PropType) -> String {
    match ty {
        PropType::Void => "void".to_owned(),
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 => "int32_t".to_owned(),
        PropType::Float => "float".to_owned(),
        PropType::Double => "double".to_owned(),
        PropType::String | PropType::StringEnum { .. } | PropType::Mixed => {
            "std::string".to_owned()
        }
        PropType::IntEnum { .. } => "int32_t".to_owned(),
        PropType::Array { item } => format!("std::vector<{}>", cpp_tm_type(item)),
        PropType::Promise { inner } => cpp_tm_type(inner),
        _ => "std::string".to_owned(),
    }
}
