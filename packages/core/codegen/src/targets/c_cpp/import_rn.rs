//! Binary C++20 Fabric adapter emitter for `import_rn`.

use std::fmt::Write as _;

use crate::naming::{
    cpp_ident, escape_c_like_string, format_float_literal, int_enum_variant_pascal,
    sanitize_single_line_comment, to_pascal_case, to_snake_case,
};
use crate::schema::export::{
    DefaultValue, EventBubbling, PropSpec, PropType, RnComponentSpec, TurboModuleSpec,
};

pub(crate) fn emit_component_cpp(spec: &RnComponentSpec) -> String {
    let pascal = to_pascal_case(&spec.component_name);
    let mut out = String::with_capacity(4096);

    let _ = writeln!(out, "#pragma once");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native Fabric component `{}`.",
        sanitize_single_line_comment(&spec.component_name)
    );
    let _ = writeln!(
        out,
        "// Binary thin C++20 Fabric prop/event adapter compatible with `cxx/nve-fabric-bridge`."
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "#include \"nve_abi.generated.h\"");
    let _ = writeln!(out, "#include \"nve_rn_component.hpp\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <cstdint>");
    let _ = writeln!(out, "#include <optional>");
    let _ = writeln!(out, "#include <span>");
    let _ = writeln!(out, "#include <string>");
    let _ = writeln!(out, "#include <string_view>");
    let _ = writeln!(out, "#include <utility>");
    let _ = writeln!(out, "#include <variant>");
    let _ = writeln!(out, "#include <vector>");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace nve::generated {{");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "inline constexpr std::string_view k{pascal}ComponentName = \"{}\";",
        escape_c_like_string(&spec.component_name)
    );
    let _ = writeln!(out);

    for prop in &spec.props {
        emit_cpp_aux_enum(&mut out, &pascal, &prop.name, &prop.prop_type);
    }

    let _ = writeln!(out, "struct {pascal}Props {{");
    for prop in &spec.props {
        let field = cpp_ident(&prop.name);
        let cpp_ty = cpp_prop_type(&pascal, &prop.name, &prop.prop_type);
        let default_init = cpp_default_initializer(&pascal, prop);
        if prop.optional && default_init.is_none() {
            let _ = writeln!(out, "  std::optional<{cpp_ty}> {field};");
        } else if let Some(init) = default_init {
            let _ = writeln!(out, "  {cpp_ty} {field}{{{init}}};");
        } else {
            let _ = writeln!(out, "  {cpp_ty} {field}{{}};");
        }
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "inline void decode_{snake}_props(const nve::RawPropMap& raw, {pascal}Props& out) {{",
        snake = to_snake_case(&spec.component_name)
    );
    for prop in &spec.props {
        let key = escape_c_like_string(&prop.name);
        let field = cpp_ident(&prop.name);
        let _ = writeln!(out, "  if (auto it = raw.find(\"{key}\"); it != raw.end()) {{");
        emit_cpp_raw_prop_extract(&mut out, &pascal, prop, &field);
        let _ = writeln!(out, "  }}");
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);

    if !spec.events.is_empty() {
        let _ = writeln!(out, "struct {pascal}EventBridge {{");
        let _ = writeln!(out, "  NveFabricHostHandle host{{nullptr}};");
        let _ = writeln!(out, "  uint32_t node_id{{0}};");
        for ev in &spec.events {
            let method = format!("emit_{}", to_snake_case(&ev.name));
            let bubbling_comment = match ev.bubbling {
                EventBubbling::Direct => "direct",
                EventBubbling::Bubbling => "bubbling",
            };
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "  // Forwards RN Fabric `{}` ({bubbling_comment}) binary `NveBinValue` payload into NVE EventRing.",
                sanitize_single_line_comment(&ev.name)
            );
            let _ = writeln!(
                out,
                "  void {method}(uint64_t timestamp_us, std::span<const uint8_t> payload_bin = {{}}) const {{"
            );
            let _ = writeln!(
                out,
                "    nve::fabric_host_enqueue_custom_event(\n        host,\n        node_id,\n        timestamp_us,\n        \"{}\",\n        payload_bin.data(),\n        payload_bin.size());",
                escape_c_like_string(&ev.name)
            );
            let _ = writeln!(out, "  }}");
        }
        let _ = writeln!(out, "}};");
        let _ = writeln!(out);
    }

    let _ = writeln!(
        out,
        "template <typename OnPropsFn, typename OnCommandFn = std::nullptr_t>"
    );
    let _ = writeln!(
        out,
        "inline void register_{snake}_adapter(\n    NveFabricHostHandle host,\n    OnPropsFn&& on_props,\n    OnCommandFn&& on_command = nullptr) {{",
        snake = to_snake_case(&spec.component_name)
    );
    let _ = writeln!(out, "  nve::CustomComponentDescriptor desc{{}};");
    let _ = writeln!(
        out,
        "  desc.component_name = std::string(k{pascal}ComponentName);"
    );
    let _ = writeln!(
        out,
        "  desc.on_update_props = [cb = std::forward<OnPropsFn>(on_props)](uint32_t node_id, const nve::RawPropMap& raw) {{"
    );
    let _ = writeln!(out, "    {pascal}Props typed{{}};");
    let _ = writeln!(
        out,
        "    decode_{snake}_props(raw, typed);",
        snake = to_snake_case(&spec.component_name)
    );
    let _ = writeln!(out, "    cb(node_id, typed);");
    let _ = writeln!(out, "  }};");
    let _ = writeln!(
        out,
        "  if constexpr (!std::is_same_v<std::decay_t<OnCommandFn>, std::nullptr_t>) {{"
    );
    let _ = writeln!(
        out,
        "    desc.on_dispatch_command = std::forward<OnCommandFn>(on_command);"
    );
    let _ = writeln!(out, "  }}");
    let _ = writeln!(
        out,
        "  nve::fabric_host_register_custom_component(host, std::move(desc));"
    );
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace nve::generated");
    out
}

pub(crate) fn emit_turbomodule_cpp(spec: &TurboModuleSpec) -> String {
    let pascal = to_pascal_case(&spec.module_name);
    let mut out = String::with_capacity(2048);

    let _ = writeln!(out, "#pragma once");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "// @generated by nve-codegen (`import_rn`) from React Native TurboModule `{}`.",
        sanitize_single_line_comment(&spec.module_name)
    );
    let _ = writeln!(out, "#include \"nve_abi.generated.h\"");
    let _ = writeln!(out, "#include \"nve_rn_component.hpp\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "#include <cstdint>");
    let _ = writeln!(out, "#include <optional>");
    let _ = writeln!(out, "#include <string>");
    let _ = writeln!(out, "#include <string_view>");
    let _ = writeln!(out, "#include <vector>");
    let _ = writeln!(out);
    let _ = writeln!(out, "namespace nve::generated {{");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "inline constexpr std::string_view k{pascal}ModuleName = \"{}\";",
        escape_c_like_string(&spec.module_name)
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "class {pascal}TurboModuleHost {{");
    let _ = writeln!(out, " public:");
    let _ = writeln!(out, "  virtual ~{pascal}TurboModuleHost() = default;");
    for method in &spec.methods {
        let mname = cpp_ident(&method.name);
        let ret = cpp_tm_type(&method.return_type);
        let mut params = String::new();
        for (i, p) in method.params.iter().enumerate() {
            if i > 0 {
                params.push_str(", ");
            }
            let pty = cpp_tm_type(&p.param_type);
            let pname = cpp_ident(&p.name);
            if p.optional {
                let _ = write!(params, "std::optional<{pty}> {pname}");
            } else {
                let _ = write!(params, "{pty} {pname}");
            }
        }
        let _ = writeln!(out, "  virtual {ret} {mname}({params}) = 0;");
    }
    let _ = writeln!(out, "}};");
    let _ = writeln!(out);
    let _ = writeln!(out, "}} // namespace nve::generated");
    out
}

fn emit_cpp_aux_enum(out: &mut String, comp_pascal: &str, prop_name: &str, prop_type: &PropType) {
    match prop_type {
        PropType::StringEnum { variants } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(prop_name));
            let _ = writeln!(out, "enum class {enum_name} {{");
            for v in variants {
                let _ = writeln!(out, "  {},", to_pascal_case(v));
            }
            let _ = writeln!(out, "}};");
            let _ = writeln!(out);
            let _ = writeln!(
                out,
                "inline std::optional<{enum_name}> parse_{snake}(std::string_view s) {{",
                snake = to_snake_case(&enum_name)
            );
            for v in variants {
                let _ = writeln!(
                    out,
                    "  if (s == \"{}\") return {enum_name}::{};",
                    escape_c_like_string(v),
                    to_pascal_case(v)
                );
            }
            let _ = writeln!(out, "  return std::nullopt;");
            let _ = writeln!(out, "}}");
            let _ = writeln!(out);
        }
        PropType::IntEnum { variants } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(prop_name));
            let _ = writeln!(out, "enum class {enum_name} : int32_t {{");
            for v in variants {
                let _ = writeln!(out, "  {} = {v},", int_enum_variant_pascal(*v));
            }
            let _ = writeln!(out, "}};");
            let _ = writeln!(out);
        }
        PropType::Array { item } => {
            emit_cpp_aux_enum(out, comp_pascal, &format!("{prop_name}Item"), item);
        }
        _ => {}
    }
}

fn cpp_prop_type(comp_pascal: &str, prop_name: &str, ty: &PropType) -> String {
    match ty {
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 => "int32_t".to_owned(),
        PropType::Float => "float".to_owned(),
        PropType::Double => "double".to_owned(),
        PropType::String | PropType::ImageSource | PropType::Dimension | PropType::Mixed => {
            "std::string".to_owned()
        }
        PropType::Color => "uint32_t".to_owned(),
        PropType::Point | PropType::EdgeInsets | PropType::Object { .. } | PropType::Array { .. } => {
            "std::vector<uint8_t>".to_owned()
        }
        PropType::StringEnum { .. } | PropType::IntEnum { .. } => {
            format!("{comp_pascal}{}", to_pascal_case(prop_name))
        }
        PropType::Void | PropType::Promise { .. } | PropType::Callback { .. } => {
            "std::string".to_owned()
        }
    }
}

fn cpp_default_initializer(comp_pascal: &str, prop: &PropSpec) -> Option<String> {
    let def = prop.default_value.as_ref()?;
    match (&prop.prop_type, def) {
        (PropType::Bool, DefaultValue::Bool(b)) => Some(if *b { "true" } else { "false" }.into()),
        (PropType::Int32, DefaultValue::Int(i)) => Some(i.to_string()),
        (PropType::Float, DefaultValue::Int(i)) => Some(format!("{i}.0f")),
        (PropType::Float, DefaultValue::Float(f)) => {
            Some(format!("{}f", format_float_literal(*f)))
        }
        (PropType::Double, DefaultValue::Int(i)) => Some(format!("{i}.0")),
        (PropType::Double, DefaultValue::Float(f)) => Some(format_float_literal(*f)),
        (PropType::String, DefaultValue::String(s)) => {
            Some(format!("\"{}\"", escape_c_like_string(s)))
        }
        (PropType::StringEnum { variants }, DefaultValue::String(s)) if variants.contains(s) => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(&prop.name));
            Some(format!("{enum_name}::{}", to_pascal_case(s)))
        }
        (PropType::IntEnum { variants }, DefaultValue::Int(i))
            if variants.contains(&(*i as i32)) =>
        {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(&prop.name));
            Some(format!(
                "{enum_name}::{}",
                int_enum_variant_pascal(*i as i32)
            ))
        }
        _ => None,
    }
}

fn emit_cpp_raw_prop_extract(
    out: &mut String,
    comp_pascal: &str,
    prop: &PropSpec,
    field: &str,
) {
    match &prop.prop_type {
        PropType::Bool => {
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<bool>(&it->second)) out.{field} = *v;"
            );
        }
        PropType::Int32 => {
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<int64_t>(&it->second)) out.{field} = static_cast<int32_t>(*v);"
            );
        }
        PropType::Float => {
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<double>(&it->second)) out.{field} = static_cast<float>(*v);"
            );
            let _ = writeln!(
                out,
                "    else if (const auto* iv = std::get_if<int64_t>(&it->second)) out.{field} = static_cast<float>(*iv);"
            );
        }
        PropType::Double => {
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<double>(&it->second)) out.{field} = *v;"
            );
            let _ = writeln!(
                out,
                "    else if (const auto* iv = std::get_if<int64_t>(&it->second)) out.{field} = static_cast<double>(*iv);"
            );
        }
        PropType::Color => {
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<int64_t>(&it->second)) out.{field} = static_cast<uint32_t>(*v);"
            );
        }
        PropType::StringEnum { .. } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(&prop.name));
            let _ = writeln!(
                out,
                "    if (const auto* s = std::get_if<std::string>(&it->second)) {{\n      if (auto parsed = parse_{snake}(*s)) out.{field} = *parsed;\n    }}",
                snake = to_snake_case(&enum_name)
            );
        }
        PropType::IntEnum { .. } => {
            let enum_name = format!("{comp_pascal}{}", to_pascal_case(&prop.name));
            let _ = writeln!(
                out,
                "    if (const auto* v = std::get_if<int64_t>(&it->second)) out.{field} = static_cast<{enum_name}>(*v);"
            );
        }
        PropType::Array { .. }
        | PropType::Object { .. }
        | PropType::Point
        | PropType::EdgeInsets => {
            let _ = writeln!(
                out,
                "    if (const auto* b = std::get_if<std::vector<uint8_t>>(&it->second)) out.{field} = *b;"
            );
        }
        _ => {
            let _ = writeln!(
                out,
                "    if (const auto* s = std::get_if<std::string>(&it->second)) out.{field} = *s;"
            );
        }
    }
}

fn cpp_tm_type(ty: &PropType) -> String {
    match ty {
        PropType::Void => "void".to_owned(),
        PropType::Bool => "bool".to_owned(),
        PropType::Int32 => "int32_t".to_owned(),
        PropType::Float => "float".to_owned(),
        PropType::Double => "double".to_owned(),
        PropType::String | PropType::StringEnum { .. } | PropType::Mixed => {
            "std::string".to_owned()
        }
        PropType::IntEnum { .. } => "int32_t".to_owned(),
        PropType::Array { item } => format!("std::vector<{}>", cpp_tm_type(item)),
        PropType::Promise { inner } => cpp_tm_type(inner),
        _ => "std::string".to_owned(),
    }
}
