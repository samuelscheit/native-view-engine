use std::fmt::Write as _;

use super::*;
use super::client_emitter::{emit_cpp_enum, emit_cpp_module, emit_cpp_struct, emit_cpp_view};

pub(super) fn emit_cpp20_spec(spec: &HybridFileSpec, abi_header: &str) -> String {
    let mut out = String::with_capacity(16 * 1024);
    writeln!(out, "// @generated by nve-codegen (hybrid C++20 Spec & Client) — DO NOT EDIT.").unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <array>").unwrap();
    writeln!(out, "#include <cstddef>").unwrap();
    writeln!(out, "#include <cstdint>").unwrap();
    writeln!(out, "#include <cstring>").unwrap();
    writeln!(out, "#include <optional>").unwrap();
    writeln!(out, "#include <span>").unwrap();
    writeln!(out, "#include <stdexcept>").unwrap();
    writeln!(out, "#include <string>").unwrap();
    writeln!(out, "#include <string_view>").unwrap();
    writeln!(out, "#include <utility>").unwrap();
    writeln!(out, "#include <vector>").unwrap();
    writeln!(out, "#include \"{abi_header}\"").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace nve::hybrid {{").unwrap();
    writeln!(out).unwrap();

    emit_cpp_bin_codec(&mut out);

    for e in &spec.enums {
        emit_cpp_enum(&mut out, e);
    }

    for s in spec.structs_topological() {
        emit_cpp_struct(&mut out, s, spec);
    }

    for m in &spec.modules {
        emit_cpp_module(&mut out, m, spec);
    }

    for v in &spec.views {
        emit_cpp_view(&mut out, v, spec);
    }

    writeln!(out, "}} // namespace nve::hybrid").unwrap();
    out
}

pub(super) fn emit_cpp_bin_codec(out: &mut String) {
    writeln!(
        out,
        r#"#ifndef NVE_HYBRID_CPP_COMMON_DEFINED
#define NVE_HYBRID_CPP_COMMON_DEFINED 1

/// Owned dynamic value encoded in NVE's compact binary `NveBinValue` format (binary).
struct DynamicValue {{
  std::vector<uint8_t> bin_bytes;
}};

/// Compact binary `NveBinValue` encoder matching `nve_abi::encode_bin_value` byte-for-byte.
class BinWriter {{
 public:
  void write_null() {{ buf_.push_back(static_cast<uint8_t>(NVE_VAL_NULL)); }}

  void write_bool(bool v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_BOOL));
    buf_.push_back(v ? 1u : 0u);
  }}

  void write_i64(int64_t v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_I64));
    write_le64(static_cast<uint64_t>(v));
  }}

  void write_f64(double v) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_F64));
    uint64_t bits = 0;
    std::memcpy(&bits, &v, sizeof(bits));
    write_le64(bits);
  }}

  void write_str(std::string_view s) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_STR));
    write_le32(static_cast<uint32_t>(s.size()));
    const auto* p = reinterpret_cast<const uint8_t*>(s.data());
    buf_.insert(buf_.end(), p, p + s.size());
  }}

  void write_bytes(std::span<const uint8_t> b) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_BYTES));
    write_le32(static_cast<uint32_t>(b.size()));
    buf_.insert(buf_.end(), b.begin(), b.end());
  }}

  void write_raw(std::span<const uint8_t> raw) {{
    buf_.insert(buf_.end(), raw.begin(), raw.end());
  }}

  template <typename Fn>
  void write_array(uint32_t count, Fn&& fn) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_ARRAY));
    const size_t len_pos = buf_.size();
    write_le32(0);
    const size_t start = buf_.size();
    write_le32(count);
    fn(*this);
    patch_le32(len_pos, static_cast<uint32_t>(buf_.size() - start));
  }}

  template <typename Fn>
  void write_map(uint32_t count, Fn&& fn) {{
    buf_.push_back(static_cast<uint8_t>(NVE_VAL_MAP));
    const size_t len_pos = buf_.size();
    write_le32(0);
    const size_t start = buf_.size();
    write_le32(count);
    fn(*this);
    patch_le32(len_pos, static_cast<uint32_t>(buf_.size() - start));
  }}

  void write_map_key(std::string_view key) {{
    write_le32(static_cast<uint32_t>(key.size()));
    const auto* p = reinterpret_cast<const uint8_t*>(key.data());
    buf_.insert(buf_.end(), p, p + key.size());
  }}

  const std::vector<uint8_t>& bytes() const noexcept {{ return buf_; }}
  NveBufferSlice slice() const noexcept {{ return NveBufferSlice{{buf_.data(), buf_.size()}}; }}

 private:
  void write_le32(uint32_t v) {{
    buf_.push_back(static_cast<uint8_t>(v & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 8) & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 16) & 0xFFu));
    buf_.push_back(static_cast<uint8_t>((v >> 24) & 0xFFu));
  }}

  void patch_le32(size_t pos, uint32_t v) {{
    buf_[pos] = static_cast<uint8_t>(v & 0xFFu);
    buf_[pos + 1] = static_cast<uint8_t>((v >> 8) & 0xFFu);
    buf_[pos + 2] = static_cast<uint8_t>((v >> 16) & 0xFFu);
    buf_[pos + 3] = static_cast<uint8_t>((v >> 24) & 0xFFu);
  }}

  void write_le64(uint64_t v) {{
    for (int i = 0; i < 8; ++i) {{
      buf_.push_back(static_cast<uint8_t>((v >> (i * 8)) & 0xFFu));
    }}
  }}

  std::vector<uint8_t> buf_;
}};

/// Bounds-checked zero-copy reader for compact binary `NveBinValue` payloads.
class BinReader {{
 public:
  explicit BinReader(std::span<const uint8_t> data) noexcept : data_(data) {{}}

  uint8_t peek_tag() const {{
    if (pos_ >= data_.size()) {{
      throw std::runtime_error("truncated NveBinValue");
    }}
    return data_[pos_];
  }}

  bool read_null_if_present() {{
    if (peek_tag() == static_cast<uint8_t>(NVE_VAL_NULL)) {{
      ++pos_;
      return true;
    }}
    return false;
  }}

  bool read_bool() {{
    expect_tag(NVE_VAL_BOOL);
    require(1);
    return data_[pos_++] != 0;
  }}

  int64_t read_i64() {{
    expect_tag(NVE_VAL_I64);
    return static_cast<int64_t>(read_le64());
  }}

  double read_f64() {{
    const uint8_t tag = peek_tag();
    if (tag == static_cast<uint8_t>(NVE_VAL_F64)) {{
      ++pos_;
      const uint64_t bits = read_le64();
      double out = 0.0;
      std::memcpy(&out, &bits, sizeof(out));
      return out;
    }}
    if (tag == static_cast<uint8_t>(NVE_VAL_I64)) {{
      return static_cast<double>(read_i64());
    }}
    throw std::runtime_error("expected NveBinValue number");
  }}

  std::string read_str() {{
    expect_tag(NVE_VAL_STR);
    const uint32_t len = read_le32();
    require(len);
    std::string out(reinterpret_cast<const char*>(data_.data() + pos_), len);
    pos_ += len;
    return out;
  }}

  std::vector<uint8_t> read_bytes() {{
    expect_tag(NVE_VAL_BYTES);
    const uint32_t len = read_le32();
    require(len);
    std::vector<uint8_t> out(data_.begin() + static_cast<std::ptrdiff_t>(pos_),
                             data_.begin() + static_cast<std::ptrdiff_t>(pos_ + len));
    pos_ += len;
    return out;
  }}

  uint32_t begin_array() {{
    expect_tag(NVE_VAL_ARRAY);
    const uint32_t byte_len = read_le32();
    require(byte_len);
    return read_le32();
  }}

  uint32_t begin_map() {{
    expect_tag(NVE_VAL_MAP);
    const uint32_t byte_len = read_le32();
    require(byte_len);
    return read_le32();
  }}

  std::string_view read_map_key() {{
    const uint32_t len = read_le32();
    require(len);
    std::string_view key(reinterpret_cast<const char*>(data_.data() + pos_), len);
    pos_ += len;
    return key;
  }}

  std::vector<uint8_t> read_raw_value() {{
    const size_t start = pos_;
    skip_value();
    return std::vector<uint8_t>(data_.begin() + static_cast<std::ptrdiff_t>(start),
                                data_.begin() + static_cast<std::ptrdiff_t>(pos_));
  }}

  void skip_value() {{
    const uint8_t tag = peek_tag();
    ++pos_;
    switch (tag) {{
      case NVE_VAL_NULL:
        return;
      case NVE_VAL_BOOL:
        require(1);
        pos_ += 1;
        return;
      case NVE_VAL_I64:
      case NVE_VAL_F64:
        require(8);
        pos_ += 8;
        return;
      case NVE_VAL_STR:
      case NVE_VAL_BYTES:
      case NVE_VAL_ARRAY:
      case NVE_VAL_MAP: {{
        const uint32_t len = read_le32();
        require(len);
        pos_ += len;
        return;
      }}
      default:
        throw std::runtime_error("invalid NveBinValue tag");
    }}
  }}

 private:
  void require(size_t n) const {{
    if (n > data_.size() - pos_) {{
      throw std::runtime_error("truncated NveBinValue");
    }}
  }}

  void expect_tag(NveValueTag tag) {{
    if (peek_tag() != static_cast<uint8_t>(tag)) {{
      throw std::runtime_error("unexpected NveBinValue tag");
    }}
    ++pos_;
  }}

  uint32_t read_le32() {{
    require(4);
    const uint32_t v = static_cast<uint32_t>(data_[pos_]) |
                       (static_cast<uint32_t>(data_[pos_ + 1]) << 8) |
                       (static_cast<uint32_t>(data_[pos_ + 2]) << 16) |
                       (static_cast<uint32_t>(data_[pos_ + 3]) << 24);
    pos_ += 4;
    return v;
  }}

  uint64_t read_le64() {{
    require(8);
    uint64_t v = 0;
    for (int i = 0; i < 8; ++i) {{
      v |= static_cast<uint64_t>(data_[pos_ + static_cast<size_t>(i)]) << (i * 8);
    }}
    pos_ += 8;
    return v;
  }}

  std::span<const uint8_t> data_;
  size_t pos_ = 0;
}};

#endif // NVE_HYBRID_CPP_COMMON_DEFINED
"#
    )
    .unwrap();
}

