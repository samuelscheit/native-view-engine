/// Emits `<Stem>HybridAbi.generated.h` (pure C11) and `<Stem>HybridSpec.generated.hpp` (C++20).
pub fn generate_hybrid_cpp(spec: &HybridFileSpec) -> Result<Vec<GeneratedFile>, CodegenError> {
    spec.validate()?;
    let stem = spec.stem_pascal();
    let header_name = format!("{stem}HybridAbi.generated.h");
    let hpp_name = format!("{stem}HybridSpec.generated.hpp");

    let c_header = emit_c11_header(spec)?;
    let cpp_header = emit_cpp20_spec(spec, &header_name);

    Ok(vec![
        GeneratedFile {
            relative_path: header_name,
            content: c_header,
        },
        GeneratedFile {
            relative_path: hpp_name,
            content: cpp_header,
        },
    ])
}

fn emit_c11_header(spec: &HybridFileSpec) -> Result<String, CodegenError> {
    let mut out = CodeWriter::with_capacity(8 * 1024);
    writeln!(
        out,
        "// @generated by nve-codegen (hybrid C11 ABI header) — DO NOT EDIT."
    );
    writeln!(out, "#pragma once");
    writeln!(out);
    writeln!(out, "#include <stdbool.h>");
    writeln!(out, "#include <stddef.h>");
    writeln!(out, "#include <stdint.h>");
    writeln!(out, "#include <nve/generated/nve_abi.generated.h>");
    writeln!(out);
    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "extern \"C\" {{");
    writeln!(out, "#endif");
    writeln!(out);

    writeln!(out, "#ifndef NVE_HYBRID_ABI_COMMON_DEFINED");
    writeln!(out, "#define NVE_HYBRID_ABI_COMMON_DEFINED 1");
    writeln!(
        out,
        "#define NVE_HYBRID_ABI_VERSION {NVE_HYBRID_ABI_VERSION}u"
    );
    writeln!(out);
    writeln!(out, "typedef enum NveHybridStatus {{");
    writeln!(out, "  NVE_HYBRID_OK = 0,");
    writeln!(out, "  NVE_HYBRID_ERR = 1,");
    writeln!(out, "  NVE_HYBRID_ERR_INVALID_ARG = 2,");
    writeln!(out, "  NVE_HYBRID_ERR_SCHEMA_MISMATCH = 3,");
    writeln!(out, "  NVE_HYBRID_ERR_NULL_HANDLE = 4,");
    writeln!(out, "}} NveHybridStatus;");
    writeln!(out);
    writeln!(out, "typedef struct NveHybridOwnedBytes {{");
    writeln!(out, "  uint8_t* ptr;");
    writeln!(out, "  size_t len;");
    writeln!(out, "  size_t cap;");
    writeln!(out, "}} NveHybridOwnedBytes;");
    writeln!(out, "#endif /* NVE_HYBRID_ABI_COMMON_DEFINED */");
    writeln!(out);

    writeln!(
        out,
        "#define NVE_HYBRID_{}_FILE_SCHEMA_HASH UINT64_C(0x{:016X})",
        to_snake_case(&spec.stem_pascal()).to_ascii_uppercase(),
        spec.file_schema_hash()
    );
    writeln!(out);

    // Enums (`typedef uint32_t` guarantees exact 4-byte unsigned ABI across C11/C++/Swift/Rust/Dart)
    for e in &spec.enums {
        let e_upper = to_snake_case(&e.name).to_ascii_uppercase();
        writeln!(out, "typedef uint32_t NveHybrid{};", e.name);
        writeln!(out, "enum {{");
        for v in &e.variants {
            let v_upper = to_snake_case(&v.name).to_ascii_uppercase();
            writeln!(out, "  NVE_HYBRID_{e_upper}_{v_upper} = {}u,", v.value);
        }
        writeln!(out, "}};");
        writeln!(out);
    }

    // POD & direct C-ABI view structs (topological order so embedded POD fields are always complete)
    for s in spec.structs_topological() {
        let Some(decls) = c_abi_struct_fields(s, spec) else {
            continue;
        };
        writeln!(out, "typedef struct NveHybrid{} {{", s.name);
        for decl in decls {
            writeln!(out, "  {decl};");
        }
        writeln!(out, "}} NveHybrid{};", s.name);
        if let Some(sz) = s.expected_size {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof(NveHybrid{}) == {sz}u, \"NveHybrid{} size must be {sz}\");",
                s.name, s.name
            );
        }
        if let Some(sz64) = s.expected_size_64 {
            writeln!(
                out,
                "NVE_STATIC_ASSERT(sizeof(void*) != 8 || sizeof(NveHybrid{}) == {sz64}u, \"NveHybrid{} size must be {sz64} on 64-bit\");",
                s.name, s.name
            );
        }
        for f in &s.fields {
            let fname = c_field_ident(&f.name);
            if let Some(off) = f.offset {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(offsetof(NveHybrid{}, {fname}) == {off}u, \"NveHybrid{}::{fname} offset must be {off}\");",
                    s.name, s.name
                );
            }
            if let Some(off64) = f.offset_64 {
                writeln!(
                    out,
                    "NVE_STATIC_ASSERT(sizeof(void*) != 8 || offsetof(NveHybrid{}, {fname}) == {off64}u, \"NveHybrid{}::{fname} offset must be {off64} on 64-bit\");",
                    s.name, s.name
                );
            }
        }
        writeln!(out);
    }

    // POD Optional<T> structs
    for (suffix, inner) in spec.collect_pod_option_types() {
        writeln!(out, "typedef struct NveHybridOpt{suffix} {{");
        writeln!(out, "  bool is_some;");
        writeln!(out, "  {} value;", require_c_value_type(&inner, spec)?);
        writeln!(out, "}} NveHybridOpt{suffix};");
        writeln!(out);
    }

    // Direct static `extern "C"` functions (default for statically linked builds; zero vtable, LTO-inlinable)
    if !spec.c_functions.is_empty() {
        for f in &spec.c_functions {
            let ret = c_fn_type(&f.return_type, spec)?;
            let params = f
                .params
                .iter()
                .map(|p| {
                    Ok(format!(
                        "{} {}",
                        c_fn_type(&p.ty, spec)?,
                        c_field_ident(&p.name)
                    ))
                })
                .collect::<Result<Vec<String>, CodegenError>>()?;
            let param_list = if params.is_empty() {
                "void".to_string()
            } else {
                params.join(", ")
            };
            writeln!(
                out,
                "NVE_API {ret} {}({param_list});",
                c_field_ident(&f.name)
            );
        }
        writeln!(out);
    }

    // Optional module vtables (for dynamic `dlopen`/`LoadLibrary` `cdylib` hot-reload boundaries)
    for m in &spec.modules {
        emit_c11_vtable(
            &mut out,
            &m.name,
            m.interface_id(),
            m.schema_hash(spec),
            &m.methods,
            false,
            spec,
        );
    }

    // View vtables
    for v in &spec.views {
        emit_c11_vtable(
            &mut out,
            &v.name,
            v.interface_id(),
            v.schema_hash(spec),
            &v.methods,
            true,
            spec,
        );
    }

    writeln!(out, "#ifdef __cplusplus");
    writeln!(out, "}}");
    writeln!(out, "#endif");
    Ok(out.into_string())
}

fn emit_c11_vtable(
    out: &mut CodeWriter,
    name: &str,
    interface_id: u32,
    schema_hash: u64,
    methods: &[HybridMethodSpec],
    is_view: bool,
    spec: &HybridFileSpec,
) {
    let pascal = to_pascal_case(name);
    let upper = to_snake_case(name).to_ascii_uppercase();

    writeln!(
        out,
        "#define NVE_HYBRID_{upper}_INTERFACE_ID UINT32_C(0x{interface_id:08X})"
    );
    writeln!(
        out,
        "#define NVE_HYBRID_{upper}_SCHEMA_HASH UINT64_C(0x{schema_hash:016X})"
    );
    writeln!(out);
    writeln!(out, "typedef struct NveHybrid{pascal}VTable {{");
    writeln!(out, "  uint32_t abi_version;");
    writeln!(out, "  uint32_t interface_id;");
    writeln!(out, "  uint64_t schema_hash;");
    writeln!(out, "  NveAppHandle (*create)(void);");
    writeln!(out, "  void (*destroy)(NveAppHandle handle);");
    writeln!(out, "  NveHybridOwnedBytes (*alloc_bytes)(size_t len);");
    writeln!(out, "  void (*free_bytes)(NveHybridOwnedBytes buf);");
    if is_view {
        writeln!(
            out,
            "  int32_t (*set_props_direct)(NveAppHandle handle, const NveMapEntry* entries, uint32_t count);"
        );
    }
    for m in methods {
        let mname = c_field_ident(&m.name);
        let ret_ty = match &m.return_type {
            HybridType::Result { .. } => "int32_t".to_string(),
            HybridType::Void => "void".to_string(),
            other => c_return_type(other, spec),
        };
        write!(out, "  {ret_ty} (*{mname})(NveAppHandle _nve_handle");
        for p in &m.params {
            let pname = c_field_ident(&p.name);
            write!(out, ", {} {pname}", c_param_type(&p.ty, spec));
        }
        if let HybridType::Result { ok, .. } = &m.return_type {
            if !matches!(ok.as_ref(), HybridType::Void) {
                write!(out, ", {}* _nve_out_ok", c_return_type(ok, spec));
            }
            write!(out, ", NveHybridOwnedBytes* _nve_out_err");
        }
        writeln!(out, ");");
    }
    writeln!(out, "}} NveHybrid{pascal}VTable;");
    writeln!(out);
}
