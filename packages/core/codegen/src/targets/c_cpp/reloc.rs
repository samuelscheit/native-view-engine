//! Standalone zero-dependency C++20 header emitter for NVE's zero-copy `RelocSlice` schema.
//!
//! Emits `<Pascal>Reloc.generated.hpp` with:
//! - `RelocHeader` (32 bytes), `RelocSlice<T>` (8 bytes), `RelocStr` (8 bytes)
//! - `VerifyMode::{Full, HeaderOnly, Unchecked}`, `RelocError`, `RelocResult<T>`
//! - Strict RFC 3629 UTF-8 validation, overflow-safe slice bounds/alignment checks, enum & bool
//!   validation, and depth limiting under `VerifyMode::Full`
//! - `view_unchecked(const uint8_t* ptr)` with literally 0 runtime checks
//! - `static_assert(sizeof(...))` and `static_assert(offsetof(...))` for every generated struct.

use std::fmt::Write as _;

use super::reloc_runtime::emit_core_primitives;
use crate::error::CodegenError;
use crate::naming::{c_field_ident, to_pascal_case, to_snake_case};
use crate::schema::export::GeneratedFile;
use crate::schema::reloc::ir::{
    RelocEnum, RelocEnumRepr, RelocSchema, RelocStruct, RelocType, StructLayout,
    RELOC_HEADER_ALIGN, RELOC_HEADER_SIZE, RELOC_MAX_VERIFY_DEPTH,
};

/// Generates a standalone C++20 zero-copy reloc header (`<Pascal>Reloc.generated.hpp`).
pub fn generate_reloc_cpp(schema: &RelocSchema) -> Result<GeneratedFile, CodegenError> {
    let layouts = schema.compute_layouts()?;
    let schema_hash = schema.schema_hash_with_layouts(&layouts);
    let slab_align = schema.slab_align(&layouts);
    let pascal = to_pascal_case(&schema.name);
    let ns = to_snake_case(&schema.name);

    let mut out = String::with_capacity(16 * 1024);
    emit_preamble(&mut out, schema, &ns, schema_hash, slab_align);
    emit_core_primitives(&mut out);

    for e in &schema.enums {
        emit_enum(&mut out, e);
    }

    for s in schema.structs_topological() {
        writeln!(out, "struct {};", s.name).unwrap();
    }
    writeln!(out).unwrap();

    for s in schema.structs_topological() {
        emit_struct(&mut out, s, &layouts[&s.name]);
    }

    for s in schema.structs_topological() {
        emit_struct_traits(&mut out, s, &layouts[&s.name]);
    }

    emit_view_entrypoints(&mut out, schema, &layouts[&schema.root]);

    writeln!(out, "}} // namespace nve::reloc::{ns}").unwrap();

    Ok(GeneratedFile {
        relative_path: format!("{pascal}Reloc.generated.hpp"),
        content: out,
    })
}

fn emit_preamble(
    out: &mut String,
    schema: &RelocSchema,
    ns: &str,
    schema_hash: u64,
    slab_align: usize,
) {
    let magic_bytes: Vec<String> = schema.magic.iter().map(|b| format!("0x{b:02X}u")).collect();
    writeln!(
        out,
        "// @generated by nve-codegen (zero-copy RelocSlice C++20 emitter) — DO NOT EDIT."
    )
    .unwrap();
    writeln!(out, "#pragma once").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "#include <array>").unwrap();
    writeln!(out, "#include <cstddef>").unwrap();
    writeln!(out, "#include <cstdint>").unwrap();
    writeln!(out, "#include <cstring>").unwrap();
    writeln!(out, "#include <limits>").unwrap();
    writeln!(out, "#include <span>").unwrap();
    writeln!(out, "#include <string_view>").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "namespace nve::reloc::{ns} {{").unwrap();
    writeln!(out).unwrap();
    writeln!(
        out,
        "inline constexpr std::array<uint8_t, 8> kSchemaMagic = {{{}}};",
        magic_bytes.join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "inline constexpr uint64_t kSchemaHash = UINT64_C(0x{schema_hash:016X});"
    )
    .unwrap();
    writeln!(
        out,
        "inline constexpr size_t kHeaderSize = {RELOC_HEADER_SIZE}u;"
    )
    .unwrap();
    writeln!(
        out,
        "inline constexpr size_t kHeaderAlign = {RELOC_HEADER_ALIGN}u;"
    )
    .unwrap();
    writeln!(out, "inline constexpr size_t kSlabAlign = {slab_align}u;").unwrap();
    writeln!(
        out,
        "inline constexpr size_t kMaxVerifyDepth = {RELOC_MAX_VERIFY_DEPTH}u;"
    )
    .unwrap();
    writeln!(out).unwrap();
}

fn emit_enum(out: &mut String, e: &RelocEnum) {
    let cpp_repr = e.repr.cpp_type();
    writeln!(out, "enum class {} : {cpp_repr} {{", e.name).unwrap();
    for v in &e.variants {
        writeln!(out, "  {} = {}u,", v.name, v.value).unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out).unwrap();

    let raw_read = match e.repr {
        RelocEnumRepr::U8 => "slab[base]",
        RelocEnumRepr::U16 => "read_u16_le(slab + base)",
        RelocEnumRepr::U32 => "read_u32_le(slab + base)",
    };

    writeln!(out, "namespace detail {{").unwrap();
    writeln!(out, "template <>").unwrap();
    writeln!(out, "struct RelocTraits<{}> {{", e.name).unwrap();
    writeln!(out, "  static constexpr bool kNeedsVerify = true;").unwrap();
    writeln!(
        out,
        "  static RelocError verify_bytes(const uint8_t* slab, size_t, size_t base, size_t) noexcept {{"
    )
    .unwrap();
    writeln!(out, "    const {cpp_repr} raw = {raw_read};").unwrap();
    writeln!(out, "    switch (raw) {{").unwrap();
    for v in &e.variants {
        writeln!(out, "      case {}u:", v.value).unwrap();
    }
    writeln!(out, "        return RelocError::Ok;").unwrap();
    writeln!(out, "      default:").unwrap();
    writeln!(out, "        return RelocError::InvalidEnumDiscriminant;").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "  }}").unwrap();
    writeln!(out, "}};").unwrap();
    writeln!(out, "}} // namespace detail").unwrap();
    writeln!(out).unwrap();
}

fn emit_struct(out: &mut String, s: &RelocStruct, layout: &StructLayout) {
    if let Some(align) = s.align {
        writeln!(out, "struct alignas({align}) {} {{", s.name).unwrap();
    } else {
        writeln!(out, "struct {} {{", s.name).unwrap();
    }
    for f in &s.fields {
        let fname = c_field_ident(&f.name);
        writeln!(out, "  {} {fname};", cpp_type(&f.ty)).unwrap();
    }
    if layout.is_pure_pod {
        writeln!(out).unwrap();
        writeln!(
            out,
            "  [[nodiscard]] std::span<const uint8_t> as_bytes() const noexcept {{"
        )
        .unwrap();
        writeln!(
            out,
            "    return std::span<const uint8_t>(reinterpret_cast<const uint8_t*>(this), sizeof({}));",
            s.name
        )
        .unwrap();
        writeln!(out, "  }}").unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out, "static_assert(sizeof({}) == {}u);", s.name, layout.size).unwrap();
    writeln!(
        out,
        "static_assert(alignof({}) == {}u);",
        s.name, layout.align
    )
    .unwrap();
    for fl in &layout.fields {
        let fname = c_field_ident(&fl.name);
        writeln!(
            out,
            "static_assert(offsetof({}, {fname}) == {}u);",
            s.name, fl.offset
        )
        .unwrap();
    }
    writeln!(out).unwrap();
}

fn emit_struct_traits(out: &mut String, s: &RelocStruct, layout: &StructLayout) {
    writeln!(out, "namespace detail {{").unwrap();
    writeln!(out, "template <>").unwrap();
    writeln!(out, "struct RelocTraits<{}> {{", s.name).unwrap();
    writeln!(
        out,
        "  static constexpr bool kNeedsVerify = {};",
        layout.needs_value_verify
    )
    .unwrap();
    if layout.needs_value_verify {
        writeln!(
            out,
            "  static RelocError verify_bytes(const uint8_t* slab, size_t total_len, size_t base, size_t depth) noexcept {{"
        )
        .unwrap();
        for (f, fl) in s.fields.iter().zip(layout.fields.iter()) {
            let fty = cpp_type(&f.ty);
            writeln!(out, "    if constexpr (RelocTraits<{fty}>::kNeedsVerify) {{").unwrap();
            writeln!(
                out,
                "      const RelocError err = RelocTraits<{fty}>::verify_bytes(slab, total_len, base + {}u, depth);",
                fl.offset
            )
            .unwrap();
            writeln!(out, "      if (err != RelocError::Ok) return err;").unwrap();
            writeln!(out, "    }}").unwrap();
        }
        writeln!(out, "    return RelocError::Ok;").unwrap();
        writeln!(out, "  }}").unwrap();
    } else {
        writeln!(
            out,
            "  static RelocError verify_bytes(const uint8_t*, size_t, size_t, size_t) noexcept {{ return RelocError::Ok; }}"
        )
        .unwrap();
    }
    writeln!(out, "}};").unwrap();
    writeln!(out, "}} // namespace detail").unwrap();
    writeln!(out).unwrap();
}

fn emit_view_entrypoints(out: &mut String, schema: &RelocSchema, root_layout: &StructLayout) {
    let root = &schema.root;
    let root_size = root_layout.size;
    let root_align = root_layout.align;
    writeln!(
        out,
        r#"namespace detail {{

[[nodiscard]] inline RelocError verify_header_common(const uint8_t* ptr, size_t len,
                                                     size_t& out_total_len,
                                                     size_t& out_root_offset) noexcept {{
  if (!ptr || len < kHeaderSize) {{
    return RelocError::Truncated;
  }}
  const uintptr_t base_addr = reinterpret_cast<uintptr_t>(ptr);
  if ((base_addr % kSlabAlign) != 0u) {{
    return RelocError::Misaligned;
  }}
  if (std::memcmp(ptr, kSchemaMagic.data(), kSchemaMagic.size()) != 0) {{
    return RelocError::InvalidMagic;
  }}
  if (read_u64_le(ptr + 8u) != kSchemaHash) {{
    return RelocError::SchemaHashMismatch;
  }}
  const size_t total_len = static_cast<size_t>(read_u32_le(ptr + 16u));
  if (total_len < kHeaderSize || total_len > len) {{
    return RelocError::Truncated;
  }}
  const size_t root_offset = static_cast<size_t>(read_u32_le(ptr + 24u));
  if (root_offset < kHeaderSize) {{
    return RelocError::OutOfBounds;
  }}
  if ((root_offset % {root_align}u) != 0u || ((base_addr + root_offset) % {root_align}u) != 0u) {{
    return RelocError::Misaligned;
  }}
  if ({root_size}u > total_len || root_offset > total_len - {root_size}u) {{
    return RelocError::OutOfBounds;
  }}
  out_total_len = total_len;
  out_root_offset = root_offset;
  return RelocError::Ok;
}}

}} // namespace detail

/// Zero-check raw pointer cast (`VerifyMode::Unchecked`). Literally 0 runtime checks.
[[nodiscard]] inline const {root}* view_unchecked(const uint8_t* ptr) noexcept {{
  const auto* hdr = reinterpret_cast<const RelocHeader*>(ptr);
  return reinterpret_cast<const {root}*>(ptr + hdr->root_offset);
}}

/// O(1) header-only zero-copy verification (`VerifyMode::HeaderOnly`).
[[nodiscard]] inline RelocResult<const {root}*> view_header_only(const uint8_t* ptr,
                                                                 size_t len) noexcept {{
  size_t total_len = 0;
  size_t root_offset = 0;
  const RelocError err = detail::verify_header_common(ptr, len, total_len, root_offset);
  if (err != RelocError::Ok) return RelocResult<const {root}*>::failure(err);
  return RelocResult<const {root}*>::success(reinterpret_cast<const {root}*>(ptr + root_offset));
}}

/// Full recursive zero-copy verification (`VerifyMode::Full`) for untrusted slabs.
[[nodiscard]] inline RelocResult<const {root}*> view_full(const uint8_t* ptr,
                                                          size_t len) noexcept {{
  size_t total_len = 0;
  size_t root_offset = 0;
  const RelocError hdr_err = detail::verify_header_common(ptr, len, total_len, root_offset);
  if (hdr_err != RelocError::Ok) return RelocResult<const {root}*>::failure(hdr_err);
  const RelocError body_err =
      detail::RelocTraits<{root}>::verify_bytes(ptr, total_len, root_offset, 0u);
  if (body_err != RelocError::Ok) return RelocResult<const {root}*>::failure(body_err);
  return RelocResult<const {root}*>::success(reinterpret_cast<const {root}*>(ptr + root_offset));
}}

/// Unified zero-copy view entry point dispatching on `VerifyMode`.
[[nodiscard]] inline RelocResult<const {root}*> view(const uint8_t* ptr, size_t len,
                                                     VerifyMode mode) noexcept {{
  switch (mode) {{
    case VerifyMode::Full:
      return view_full(ptr, len);
    case VerifyMode::HeaderOnly:
      return view_header_only(ptr, len);
    case VerifyMode::Unchecked:
      return RelocResult<const {root}*>::success(view_unchecked(ptr));
  }}
  return RelocResult<const {root}*>::failure(RelocError::InvalidEnumDiscriminant);
}}

[[nodiscard]] inline RelocResult<const {root}*> view(std::span<const uint8_t> buf,
                                                     VerifyMode mode) noexcept {{
  return view(buf.data(), buf.size(), mode);
}}
"#
    )
    .unwrap();
}

fn cpp_type(ty: &RelocType) -> String {
    match ty {
        RelocType::Bool => "bool".to_string(),
        RelocType::U8 => "uint8_t".to_string(),
        RelocType::I8 => "int8_t".to_string(),
        RelocType::U16 => "uint16_t".to_string(),
        RelocType::I16 => "int16_t".to_string(),
        RelocType::U32 => "uint32_t".to_string(),
        RelocType::I32 => "int32_t".to_string(),
        RelocType::F32 => "float".to_string(),
        RelocType::U64 => "uint64_t".to_string(),
        RelocType::I64 => "int64_t".to_string(),
        RelocType::F64 => "double".to_string(),
        RelocType::FixedArray { elem, len } => format!("std::array<{}, {len}u>", cpp_type(elem)),
        RelocType::Enum(name) | RelocType::Struct(name) => name.clone(),
        RelocType::RelocSlice(elem) => format!("RelocSlice<{}>", cpp_type(elem)),
        RelocType::RelocStr => "RelocStr".to_string(),
    }
}
