//! Java host constants the shared templates do not cover: the runtime ABI (`STATUS_*`, schema
//! hash, record sizes and flags), named table bit sets (`EventMask`, `Typography::SET_*`), and the
//! golden `EventRing` test vector (`nve_abi::encode_events`).

use std::fmt::Write as _;

use nve_abi::table::{FieldKind, Storage, TableDesc};
use nve_abi::{EventPayload, NativeEvent, NativeEventKind, encode_events};

use super::spell;
use crate::schema::export::GeneratedFile;

/// Named bit constants of one table (`(table name, [(NAME, value)])`) its `TableDesc` cannot
/// express, e.g. `Typography::SET_*`.
pub type TableBits = (&'static str, &'static [(&'static str, u32)]);

const MAIN: &str = "packages/core/host-java/src/main/java/dev/nve/host/generated";
const TEST: &str = "packages/core/host-java/src/test/java/dev/nve/host/generated";

fn header(out: &mut String, doc: &str, class: &str) {
    let _ = write!(
        out,
        "// @generated by nve-codegen (abi/java_host.rs). DO NOT EDIT.\npackage dev.nve.host.generated;\n\n/** {doc} */\npublic final class {class} {{\n    private {class}() {{}}\n"
    );
}

/// `NveRuntimeAbi.java`: `RUNTIME_SCHEMA_HASH`, runtime constants, and `STATUS_*`.
pub fn java_runtime_abi() -> GeneratedFile {
    let rt = nve_abi::schema::runtime_abi_descriptor();
    let mut out = String::with_capacity(2048);
    header(&mut out, "Embedding-host runtime ABI constants ({@code nve_runtime_get_interface}).", "NveRuntimeAbi");
    let _ = writeln!(
        out,
        "\n    public static final long RUNTIME_SCHEMA_HASH = 0x{:016X}L;",
        nve_abi::NVE_RUNTIME_SCHEMA_HASH
    );
    for c in rt.consts {
        let name = c.name.strip_prefix("NVE_").unwrap_or(c.name);
        let _ = writeln!(out, "    public static final int {name} = {};", c.value);
    }
    for e in rt.enums {
        let _ = writeln!(out, "\n    // {}", e.name);
        for v in e.variants {
            let _ = writeln!(out, "    public static final int STATUS_{} = {};", spell::screaming(v.name), v.value);
        }
    }
    out.push_str("}\n");
    GeneratedFile { relative_path: format!("{MAIN}/NveRuntimeAbi.java"), content: out }
}

/// `NveTableBits.java`: `INTERACTION_EVENT_MASK_*` plus every `bits` set (e.g. `TYPOGRAPHY_SET_*`).
pub fn java_table_bits(bits: &[TableBits]) -> GeneratedFile {
    let mut out = String::with_capacity(2048);
    header(&mut out, "Named bit sets of published table fields.", "NveTableBits");
    out.push_str("\n    // nve.interaction event_mask (`EventMask`)\n");
    for &(name, bit) in nve_abi::EventMask::ALL {
        let _ = writeln!(out, "    public static final int INTERACTION_EVENT_MASK_{name} = 0x{bit:X};");
    }
    for &(table, set) in bits {
        let prefix = table.strip_prefix("nve.").unwrap_or(table).replace('.', "_").to_ascii_uppercase();
        let _ = writeln!(out, "\n    // {table}");
        for &(name, value) in set {
            let _ = writeln!(out, "    public static final int {prefix}_{name} = 0x{value:X};");
        }
    }
    out.push_str("}\n");
    GeneratedFile { relative_path: format!("{MAIN}/NveTableBits.java"), content: out }
}

/// Surface id of every golden event.
pub const VECTOR_SURFACE: u32 = 7;

/// One event per payload kind; host suites write the same list and compare bytes.
pub fn golden_events() -> Vec<NativeEvent> {
    let ev = |node, ts, kind, payload| NativeEvent { surface_id: VECTOR_SURFACE, node_id: node, timestamp_us: ts, kind, payload };
    vec![
        ev(1, 10, NativeEventKind::Focus, EventPayload::Empty),
        ev(2, 11, NativeEventKind::Press, EventPayload::Point { x: 1.5, y: -2.0 }),
        ev(3, 12, NativeEventKind::Scroll, EventPayload::Scroll { x: 0.0, y: 30.0, content_width: 300.0, content_height: 900.0 }),
        ev(4, 13, NativeEventKind::TextChange, EventPayload::Text("h\u{e9}\u{1F680}".into())),
        ev(5, 14, NativeEventKind::Layout, EventPayload::Layout { x: 1.0, y: 2.0, width: 3.0, height: 4.0 }),
        ev(6, 15, NativeEventKind::Custom, EventPayload::Custom { name: "submit".into(), data: vec![9, 8, 7] }),
        ev(
            7,
            16,
            NativeEventKind::KeyDown,
            EventPayload::Key { key: "\u{e9}".into(), code: "KeyE".into(), modifiers: 0x05, key_code: 69, is_composing: true },
        ),
        ev(8, 17, NativeEventKind::PointerDown, EventPayload::Pointer { x: 3.0, y: 4.0, modifiers: 0x02, flags: 0x09 }),
        ev(9, 18, NativeEventKind::Wheel, EventPayload::Wheel { delta_x: 0.0, delta_y: -12.5, modifiers: 0x01 }),
        ev(
            0x8100_0002,
            19,
            NativeEventKind::TableEvent,
            EventPayload::TableEvent { table_key: 0x1122_3344_5566_7788, event_id: 42, payload: vec![1, 2] },
        ),
    ]
}

/// `EventRingVectors.java` (test sources): `ring()` = `encode_events(golden_events())`.
pub fn java_event_ring_vectors() -> GeneratedFile {
    let ring = encode_events(&golden_events());
    let mut out = String::with_capacity(ring.len() * 6 + 1024);
    header(
        &mut out,
        "{@code nve_abi::encode_events} of one event per payload kind (surface 7): Focus/Empty, Press/Point, Scroll, \
         TextChange/Text, Layout, Custom, KeyDown/Key, PointerDown/Pointer, Wheel, TableEvent (see abi/java_host.rs).",
        "EventRingVectors",
    );
    let _ = writeln!(out, "\n    public static final int SURFACE = {VECTOR_SURFACE};");
    out.push_str("\n    /** Encoded ring bytes. */\n    public static byte[] ring() {\n        return new byte[] {");
    for (i, b) in ring.iter().enumerate() {
        if i % 16 == 0 {
            out.push_str("\n            ");
        }
        let _ = write!(out, "{}, ", *b as i8);
    }
    out.push_str("\n        };\n    }\n}\n");
    GeneratedFile { relative_path: format!("{TEST}/EventRingVectors.java"), content: out }
}

fn java_kind(kind: FieldKind) -> &'static str {
    match kind {
        FieldKind::U32 => "U32",
        FieldKind::I32 => "I32",
        FieldKind::F32 => "F32",
        FieldKind::Bool => "BOOL",
        FieldKind::Enum => "ENUM",
        FieldKind::Color => "COLOR",
        FieldKind::Length => "LENGTH",
        FieldKind::Str => "STR",
        FieldKind::Resource => "RESOURCE",
        FieldKind::Node => "NODE",
    }
}

/// `NveModuleTables.java`: key, layout, and field specs (+ enum values) of capability-module
/// tables (`nve.canvas`, ...) that core `NveTables` cannot list without a core → module edge.
pub fn java_module_tables(tables: &[&TableDesc]) -> GeneratedFile {
    let mut out = String::with_capacity(2048);
    out.push_str("// @generated by nve-codegen (abi/java_host.rs). DO NOT EDIT.\npackage dev.nve.host.generated;\n\nimport dev.nve.host.FieldKind;\nimport dev.nve.host.FieldSpec;\nimport dev.nve.host.Key64;\n\n/** Published capability-module word tables (same shape as {@code NveTables}). */\npublic final class NveModuleTables {\n    private NveModuleTables() {}\n");
    for t in tables {
        let ident = spell::pascal(t.name.strip_prefix("nve.").unwrap_or(t.name));
        let _ = write!(
            out,
            "\n    /** {{@code {}}}: {}, {} word(s). */\n    public static final class {ident} {{\n        private {ident}() {{}}\n\n        public static final Key64 KEY = Key64.of(0x{:016X}L);\n        public static final Key64 SCHEMA_HASH = Key64.of(0x{:016X}L);\n        public static final int WORDS = {};\n        public static final boolean DENSE = {};\n",
            t.name,
            if t.storage == Storage::Dense { "dense" } else { "sparse" },
            t.words(),
            t.key.0,
            t.schema_hash,
            t.words(),
            t.storage == Storage::Dense,
        );
        for f in t.fields {
            let field = spell::screaming(f.name);
            let bits = if f.kind == FieldKind::Str { 32 } else { f.bits };
            let _ = writeln!(
                out,
                "        public static final FieldSpec {field} = new FieldSpec({}, {}, {bits}, FieldKind.{});",
                f.word,
                f.shift,
                java_kind(f.kind)
            );
            for v in f.variants {
                let _ = writeln!(out, "        public static final int {field}_{} = {};", spell::screaming(v.name), v.value);
            }
        }
        out.push_str("    }\n");
    }
    out.push_str("}\n");
    GeneratedFile { relative_path: format!("{MAIN}/NveModuleTables.java"), content: out }
}

/// Every file of this module.
pub fn generate_java_host_files(module_tables: &[&TableDesc], bits: &[TableBits]) -> Vec<GeneratedFile> {
    vec![java_runtime_abi(), java_table_bits(bits), java_module_tables(module_tables), java_event_ring_vectors()]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn golden_ring_round_trips_and_covers_every_payload() {
        let events = golden_events();
        assert_eq!(nve_abi::decode_events(&encode_events(&events)).unwrap(), events);
        assert_eq!(events.len(), 10);
    }

    #[test]
    fn files_live_in_the_generated_package_with_expected_constants() {
        let files = generate_java_host_files(&[], &[("nve.typography", &[("SET_COLOR", 1)])]);
        for f in &files {
            assert!(f.relative_path.contains("/dev/nve/host/generated/"), "{}", f.relative_path);
            assert!(f.content.contains("package dev.nve.host.generated;"));
        }
        assert!(files[0].content.contains("public static final int STATUS_BUSY = 3;"));
        assert!(files[0].content.contains(&format!("RUNTIME_SCHEMA_HASH = 0x{:016X}L", nve_abi::NVE_RUNTIME_SCHEMA_HASH)));
        assert!(files[1].content.contains("INTERACTION_EVENT_MASK_PRESS = 0x1;"));
        assert!(files[1].content.contains("TYPOGRAPHY_SET_COLOR = 0x1;"));
        assert!(files[2].content.contains("public final class NveModuleTables"));
        assert!(files[3].content.contains("public static byte[] ring()"));
    }
}
