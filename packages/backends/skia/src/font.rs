//! Embedded crisp 5x7 ASCII bitmap font with zero external dependencies.
//!
//! Covers printable ASCII `0x20..=0x7E` (95 glyphs) plus graceful fallbacks for common Unicode
//! punctuation (em-dash, curly quotes, ellipsis, bullets).

pub const GLYPH_WIDTH: usize = 5;
pub const GLYPH_HEIGHT: usize = 7;

/// Derived pixel metrics for the embedded 5x7 bitmap font at a given logical `font_size`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BitmapFontMetrics {
    pub glyph_w: f32,
    pub glyph_h: f32,
    pub advance_x: f32,
    pub line_height: f32,
}

/// Computes consistent metrics shared between [`BitmapFontTextMeasurer`] and the software rasterizer.
#[inline]
pub fn bitmap_font_metrics(font_size: f32) -> BitmapFontMetrics {
    let fs = if font_size.is_finite() && font_size > 0.0 {
        font_size
    } else {
        16.0
    };
    let glyph_h = fs.max(GLYPH_HEIGHT as f32);
    let glyph_w = (fs * 0.48).max(GLYPH_WIDTH as f32);
    let advance_x = (fs * 0.58).max((GLYPH_WIDTH + 1) as f32);
    let line_height = (fs * 1.35).max(glyph_h + 2.0);
    BitmapFontMetrics {
        glyph_w,
        glyph_h,
        advance_x,
        line_height,
    }
}

/// Shared 5x7 bitmap text layout & faux-bold pass iterator used by both the software rasterizer
/// (`raster::text_blend`) and the Skia canvas fallback (`gpu::skia_primitives`) so fontless output
/// has identical alignment, vertical padding, and faux-bold (`+1.0` logical px) geometry.
pub(crate) fn for_each_bitmap_glyph_pass(
    rect: nve_engine::LayoutRect,
    text: &str,
    font_size: f32,
    font_weight: u16,
    text_align: crate::text::TextAlign,
    mut emit_glyph: impl FnMut(f32, f32, f32, f32, &[u8; GLYPH_HEIGHT]),
) {
    if text.is_empty() || !font_size.is_finite() || font_size <= 0.0 {
        return;
    }
    let metrics = bitmap_font_metrics(font_size);
    let faux_bold = font_weight >= 600;
    let vertical_pad = if !text.contains('\n') && rect.height > metrics.glyph_h {
        ((rect.height - metrics.glyph_h) * 0.5)
            .min(font_size * 0.25)
            .floor()
    } else {
        0.0
    };
    let passes: &[f32] = if faux_bold { &[0.0, 1.0] } else { &[0.0] };
    let mut cursor_y = rect.y + vertical_pad;

    for line in text.split('\n') {
        let char_count = line.chars().count();
        let line_w = if char_count == 0 {
            0.0
        } else {
            (char_count as f32) * metrics.advance_x - (metrics.advance_x - metrics.glyph_w).max(0.0)
        };
        let align_offset =
            crate::text_cache::line_align_offset_logical(text_align, rect.width, line_w);
        let mut cursor_x = rect.x + align_offset;
        for ch in line.chars() {
            if ch != ' ' {
                let bitmap = glyph_bitmap(ch);
                for &dx in passes {
                    emit_glyph(cursor_x + dx, cursor_y, metrics.glyph_w, metrics.glyph_h, &bitmap);
                }
            }
            cursor_x += metrics.advance_x;
        }
        cursor_y += metrics.line_height;
    }
}

/// Emits every lit `(x, y, cell_w, cell_h)` cell rectangle of a 5x7 glyph bitmap.
#[cfg(feature = "skia")]
pub(crate) fn for_each_bitmap_cell_in_glyph(
    gx: f32,
    gy: f32,
    glyph_w: f32,
    glyph_h: f32,
    bitmap: &[u8; GLYPH_HEIGHT],
    mut emit_cell: impl FnMut(f32, f32, f32, f32),
) {
    let cell_w = glyph_w / GLYPH_WIDTH as f32;
    let cell_h = glyph_h / GLYPH_HEIGHT as f32;
    for (row_idx, &row_bits) in bitmap.iter().enumerate() {
        if row_bits == 0 {
            continue;
        }
        let ry = gy + row_idx as f32 * cell_h;
        for col_idx in 0..GLYPH_WIDTH {
            if ((row_bits >> (GLYPH_WIDTH - 1 - col_idx)) & 1) != 0 {
                let rx = gx + col_idx as f32 * cell_w;
                emit_cell(rx, ry, cell_w, cell_h);
            }
        }
    }
}

/// [`nve_layout::TextMeasurer`] backed by the embedded 5x7 bitmap font metrics.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct BitmapFontTextMeasurer;

impl nve_layout::TextMeasurer for BitmapFontTextMeasurer {
    fn measure(
        &self,
        text: &str,
        style: &nve_layout::TextStyle<&str>,
        max_width: Option<f32>,
    ) -> (f32, f32) {
        self.measure_text(text, style.font_size, max_width.filter(|_| style.wraps()))
    }
}

impl BitmapFontTextMeasurer {
    /// Measures `text` at `font_size` under an optional `max_width` wrapping bound.
    pub fn measure_text(&self, text: &str, font_size: f32, max_width: Option<f32>) -> (f32, f32) {
        if text.is_empty() {
            return (0.0, 0.0);
        }
        let metrics = bitmap_font_metrics(font_size);
        let mut max_line_w = 0.0f32;
        let mut total_lines = 0.0f32;

        match max_width {
            Some(mw) if !mw.is_finite() || mw <= 0.0 => {
                let explicit_lines = text.split('\n').count().max(1) as f32;
                (0.0, explicit_lines * metrics.line_height)
            }
            Some(mw) => {
                for line in text.split('\n') {
                    let raw_w = line.chars().count() as f32 * metrics.advance_x;
                    if raw_w > mw + 1e-3 {
                        let wrapped = (raw_w / mw).ceil().max(1.0);
                        max_line_w = max_line_w.max(mw);
                        total_lines += wrapped;
                    } else {
                        max_line_w = max_line_w.max(raw_w);
                        total_lines += 1.0;
                    }
                }
                (
                    max_line_w.max(1.0).min(mw),
                    total_lines.max(1.0) * metrics.line_height,
                )
            }
            None => {
                for line in text.split('\n') {
                    let raw_w = line.chars().count() as f32 * metrics.advance_x;
                    max_line_w = max_line_w.max(raw_w);
                    total_lines += 1.0;
                }
                (max_line_w.max(1.0), total_lines.max(1.0) * metrics.line_height)
            }
        }
    }
}

