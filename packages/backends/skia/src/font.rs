/// Returns the 5x7 bitmap rows for `ch`. Bit 4 is the leftmost column, bit 0 is the rightmost.
#[inline]
pub fn glyph_bitmap(ch: char) -> [u8; GLYPH_HEIGHT] {
    let mapped = match ch {
        '\u{2013}' | '\u{2014}' | '\u{2212}' => '-',
        '\u{2018}' | '\u{2019}' => '\'',
        '\u{201C}' | '\u{201D}' => '"',
        '\u{2022}' => '*',
        '\u{2026}' => '.',
        '\u{00A0}' => ' ',
        other => other,
    };
    let code = mapped as u32;
    if (0x20..=0x7E).contains(&code) {
        ASCII_FONT_5X7[(code - 0x20) as usize]
    } else {
        FALLBACK_GLYPH
    }
}
