//! Zero-dependency build script that discovers every `.md`, `.mdx`, and `_meta.toml` under
//! `docs/content/` and emits `embedded_docs_content.generated.rs` into `OUT_DIR`.
//!
//! This ensures `nve-docs-site` runs with zero runtime filesystem I/O on WASM, iOS, Android,
//! and standalone native desktop builds.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let content_root = manifest_dir
        .join("..")
        .join("..")
        .join("docs")
        .join("content");

    println!("cargo:rerun-if-changed={}", content_root.display());

    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect_docs_files(&content_root, &content_root, &mut files);
    files.sort_by(|a, b| a.0.cmp(&b.0));

    let mut generated = String::with_capacity(files.len() * 128 + 256);
    generated.push_str("// @generated by examples/nve-docs-site/build.rs — DO NOT EDIT.\n");
    generated.push_str("pub const EMBEDDED_DOCS_FILES: &[(&str, &str)] = &[\n");
    for (rel, abs) in &files {
        println!("cargo:rerun-if-changed={}", abs.display());
        let canonical = fs::canonicalize(abs).unwrap_or_else(|_| abs.clone());
        let abs_str = canonical.to_string_lossy().replace('\\', "/");
        let _ = writeln!(
            generated,
            "    ({rel:?}, include_str!({abs_str:?})),"
        );
    }
    generated.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let out_path = out_dir.join("embedded_docs_content.generated.rs");
    fs::write(&out_path, generated).expect("write embedded_docs_content.generated.rs");
}

fn collect_docs_files(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries.filter_map(|e| e.ok().map(|e| e.path())).collect();
    paths.sort();

    for path in paths {
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if name.starts_with('.') {
            continue;
        }
        if path.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            collect_docs_files(root, &path, out);
        } else if name == "_meta.toml" || name.ends_with(".mdx") || name.ends_with(".md") {
            let rel = path
                .strip_prefix(root)
                .unwrap_or(&path)
                .to_string_lossy()
                .replace('\\', "/");
            out.push((rel, path));
        }
    }
}
